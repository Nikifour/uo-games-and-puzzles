/**
 * Мозаика — те самые пятнашки, только из вашей картинки.
 *
 * Фреска, карта или портрет режется на клетки, одна вынимается, остальные
 * тасуются. Игроки двигают куски в пустоту и собирают изображение обратно.
 *
 * Тайны у этой загадки нет вовсе: ответ — сама картинка, и он на столе
 * с самого начала. Поэтому и хранить у ведущего нечего, и другой ведущий
 * подхватит начатое без единой оговорки.
 *
 * Тасуется не случайной перестановкой, а сотней случайных **ходов** от
 * собранного состояния. Разница принципиальная: половина случайных
 * перестановок пятнашек не собирается вовсе, и игроки бились бы над заведомо
 * невозможным.
 */

