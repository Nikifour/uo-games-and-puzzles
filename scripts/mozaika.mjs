/**
 * Соотношение сторон картинки.
 *
 * Поле мозаики должно повторять форму изображения, иначе широкая фреска
 * сплющится в квадрат и станет неузнаваемой — а узнавание тут и есть игра.
 * Меряем один раз, при выкладывании, и запоминаем в столе: у игроков картинка
 * та же, и мерить её заново каждому незачем.
 */
function соотношениеКартинки(путь) {
  if (typeof Image === "undefined") return Promise.resolve(1);      // вне браузера, в проверке правил
  return new Promise(resolve => {
    const проба = new Image();
    проба.onload = () => resolve(проба.naturalWidth && проба.naturalHeight
      ? проба.naturalWidth / проба.naturalHeight : 1);
    проба.onerror = () => resolve(1);
    проба.src = путь;
  });
}

/**
 * Собранная картинка: каждый кусок на своём месте, а на месте дыры — пусто.
 *
 * Дыра не обязана быть в правом нижнем углу. Так её ставят по традиции,
 * и на этой традиции держится классический способ сборки: верхний ряд,
 * левый столбец, остаток свести к углу. Дыра посреди фрески отнимает
 * готовый рецепт — и выглядит разбитым, а не аккуратно недостающим.
 */
const собранная = (сторона, дыраВ) => {
  const всего = сторона * сторона;
  const место = Number.isInteger(дыраВ) ? дыраВ : всего - 1;
  return Array.from({ length: всего }, (_, i) => (i === место ? null : i));
};

/** Где вынимать кусок: как выбрано в диалоге, но с оглядкой на размер поля. */
function выбратьДыру(сторона, как) {
  const всего = сторона * сторона;
  if (как === "ugol") return всего - 1;
  if (как === "centr") {
    const середина = Math.floor(сторона / 2);
    return середина * сторона + середина;
  }
  return Math.floor(Math.random() * всего);
}

/** Куда можно сдвинуть: соседняя клетка по стороне, не по углу. */
const рядом = (a, b, сторона) => {
  const [ра, ка] = [Math.floor(a / сторона), a % сторона];
  const [рб, кб] = [Math.floor(b / сторона), b % сторона];
  return Math.abs(ра - рб) + Math.abs(ка - кб) === 1;
};

function перемешать(плитки, сторона, ходов) {
  const кучка = [...плитки];
  let дыра = кучка.indexOf(null);
  let прежняя = -1;

  for (let i = 0; i < ходов; i++) {
    const соседи = кучка
      .map((_, к) => к)
      .filter(к => рядом(к, дыра, сторона) && к !== прежняя);
    const куда = соседи[Math.floor(Math.random() * соседи.length)];
    кучка[дыра] = кучка[куда];
    кучка[куда] = null;
    прежняя = дыра;
    дыра = куда;
  }
  return кучка;
}

const собрана = (плитки, дыраВ) =>
  плитки.every((к, i) => (i === дыраВ ? к === null : к === i));

export async function выложить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const картинка = конфиг.картинка?.trim();
  if (!картинка) { ui.notifications.error(Т("Не выбрана картинка.")); return null; }

  const сторона = Math.min(6, Math.max(2, Number(конфиг.сторона) || 3));
  const соотношение = await соотношениеКартинки(картинка);
  const дыраВ = выбратьДыру(сторона, конфиг.дыра);
  let плитки = перемешать(собранная(сторона, дыраВ), сторона, 60 * сторона * сторона);
  if (собрана(плитки, дыраВ)) плитки = перемешать(плитки, сторона, 7);   // редчайший случай, но обидный

  await прибрать();

  const стол = {
    id: foundry.utils.randomID(),
    тип: "mozaika",
    название: конфиг.название?.trim() || Т("Мозаика"),
    подпись: конфиг.подпись?.trim() || "",
    тема: (конфиг.тема in ТЕМЫ) ? конфиг.тема : "kamen",
    картинка,
    соотношение,
    сторона,
    дыраВ,
    плитки,
    ходов: 0,
    предел: Math.max(0, Number(конфиг.предел) || 0),
    образец: !!конфиг.образец,
    двигают: конфиг.двигают?.length ? конфиг.двигают : "все",
    макрос: конфиг.макрос?.trim() || null,
    собрана: false,
    заклинило: false,
    завершён: false,
    показан: true,
  };

  await записать(стол);
  return стол;
}

export async function прибрать() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "mozaika" && с.завершён) await убрать(id);
  }
}

/* ─────────────────────────────── правила ─────────────────────────────── */

const можетДвигать = (стол, пользователь) =>
  !!пользователь && !стол.собрана && !стол.заклинило &&
  (пользователь.isGM || стол.двигают === "все" || (стол.двигают ?? []).includes(пользователь.id));

// Сдвиги идут чаще, чем стоит писать в базу: пишем, когда рука отдохнёт.
const отложитьЗапись = foundry.utils.debounce(async id => {
  const сырой = столПоId(id);
  if (!сырой) return;
  const живой = собрать(сырой);
  await записать({ ...сырой, плитки: живой.плитки, ходов: живой.ходов });
}, 4000);

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!можетДвигать(стол, пользователь)) return;
  if (запрос.что !== "сдвинуть") return;

  const клетка = Number(запрос.клетка);
  const дыра = стол.плитки.indexOf(null);
  if (!Number.isInteger(клетка) || клетка < 0 || клетка >= стол.плитки.length) return;
  if (!рядом(клетка, дыра, стол.сторона)) return;

  const плитки = [...стол.плитки];
  плитки[дыра] = плитки[клетка];
  плитки[клетка] = null;
  const ходов = стол.ходов + 1;

  if (собрана(плитки, стол.дыраВ)) {
    const свежий = { ...столПоId(стол.id), плитки, ходов, собрана: true, завершён: true };
    await записать(свежий);
    await объявить(
      Т(`<p><strong>{название}</strong> — сложена за {ходов} {ходов3}.</p>`, { название: экранировать(свежий.название), ходов: ходов, ходов3: 
        числом(ходов, М("ход"), М("хода"), М("ходов")) }), свежий.название);
    событие("решено", свежий);
    await запуститьМакрос(свежий.макрос, свежий);
    return;
  }

  if (стол.предел && ходов >= стол.предел) {
    await записать({ ...столПоId(стол.id), плитки, ходов, заклинило: true, завершён: true });
    await объявить(
      Т(`<p><strong>{название}</strong> — ходы кончились, куски замерли.</p>`, { название: экранировать(стол.название) }), стол.название);
    return;
  }

  разослать(стол.id, { плитки, ходов });
  отложитьЗапись(стол.id);
}

/* ─────────────────── рычаги ведущего (нажимает он сам) ─────────────────── */

export async function засчитать(id) {
  const стол = столПоId(id);
  if (!стол) return;
  const полный = {
    ...собрать(стол),
    плитки: собранная(стол.сторона, стол.дыраВ),
    собрана: true, заклинило: false, завершён: true,
  };
  await записать(полный);
  await объявить(Т(`<p><strong>{название}</strong> — сложена волей ведущего.</p>`, { название: экранировать(полный.название) }), полный.название);
  событие("решено", полный);
  await запуститьМакрос(полный.макрос, полный);
}

export async function сбросить(id) {
  const стол = столПоId(id);
  if (!стол) return;
  await записать({
    ...стол,
    плитки: перемешать(собранная(стол.сторона, стол.дыраВ), стол.сторона, 60 * стол.сторона * стол.сторона),
    ходов: 0,
    собрана: false,
    заклинило: false,
    завершён: false,
  });
}

