class ОкноМозаики extends ApplicationV2 {
  constructor(options = {}) {
    super(options);
    this.стол = options.стол;
  }

  static DEFAULT_OPTIONS = {
    classes: ["uo-igry", "uo-mozaika-okno"],
    tag: "div",
    window: { title: М("Мозаика"), icon: "fa-solid fa-puzzle-piece", resizable: false },
    position: { width: 460, height: "auto" },
    actions: {
      сдвинуть: ОкноМозаики.#сдвинуть,
      образец: ОкноМозаики.#образец,
      засчитать: ОкноМозаики.#засчитать,
      сброс: ОкноМозаики.#сброс,
      снять: ОкноМозаики.#снять,
    },
  };

  get title() { return this.стол?.название ?? Т("Мозаика"); }

  static #сдвинуть(event, target) {
    просить({ id: this.стол.id, что: "сдвинуть", клетка: target.dataset.kletka });
  }

  static #образец() {
    new foundry.applications.apps.ImagePopout({
      src: this.стол.картинка,
      window: { title: Т("{название} — образец", { название: this.стол.название }) },
    }).render(true);
  }

  static #засчитать() { засчитать(this.стол.id); }
  static #сброс() { сбросить(this.стол.id); }
  static #снять() { убрать(this.стол.id); }

  _onClose() {
    забытьОкно(this.стол.id);
    if (this.закрываемСами) return;
    if (game.user.isGM) спрятать(this.стол.id);
    else спрятатьУСебя(this.стол.id);
  }

  async _renderHTML() {
    const с = this.стол;
    const n = с.сторона;
    const двигает = можетДвигать(с, game.user);
    const дыра = с.плитки.indexOf(null);

    const клетки = с.плитки.map((кусок, клетка) => {
      if (кусок === null) return `<div class="uo-kusok uo-dyra"></div>`;

      // Кусок k живёт в строке k/n и столбце k%n исходной картинки.
      const строка = Math.floor(кусок / n);
      const столбец = кусок % n;
      const можно = двигает && рядом(клетка, дыра, n);

      return `
        <button type="button" class="uo-kusok ${можно ? "uo-hodit" : ""}"
                ${можно ? `data-action="сдвинуть" data-kletka="${клетка}"` : "disabled"}
                style="background-image: url(&quot;${с.картинка}&quot;);
                       background-size: ${n * 100}% ${n * 100}%;
                       background-position: ${столбец * 100 / (n - 1)}% ${строка * 100 / (n - 1)}%;"></button>`;
    }).join("");

    const счёт = с.предел
      ? Т("Ход {номер} из {предел}", { номер: Math.min(с.ходов + 1, с.предел), предел: с.предел })
      : Т("Ходов сделано: {ходов}", { ходов: с.ходов });

    const итог = с.собрана
      ? `<p class="uo-itog uo-otkryt">${Т("Сложена.")}</p>`
      : с.заклинило
        ? `<p class="uo-itog uo-zaklinilo">${Т("Ходы кончились. Ведущий может перетасовать заново.")}</p>`
        : "";

    const образец = (с.образец || game.user.isGM)
      ? `<button type="button" class="uo-pravila-knopka" data-action="образец">${Т("Образец")}</button>`
      : "";

    const гм = game.user.isGM ? `
      <section class="uo-gm">
        <div class="uo-gm-knopki">
          <button type="button" data-action="засчитать">${Т("Засчитать")}</button>
          <button type="button" data-action="сброс">${Т("Перетасовать")}</button>
          <button type="button" data-action="снять">${Т("Убрать со стола")}</button>
        </div>
      </section>` : "";

    return `
      <div class="uo-mozaika-telo uo-tema-${экранировать(с.тема)}">
        ${с.подпись ? `<p class="uo-podpis">${экранировать(с.подпись)}</p>` : ""}
        <div class="uo-mozaika" style="--storona: ${n}; aspect-ratio: ${с.соотношение || 1}">${клетки}</div>
        <div class="uo-stroka-schet">
          <span class="uo-schet">${счёт}</span>
          ${образец}
        </div>
        ${итог}
        ${гм}
      </div>`;
  }

  _replaceHTML(result, content) { content.innerHTML = result; }
}

