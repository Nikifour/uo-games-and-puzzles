class ОкноЗеркал extends ApplicationV2 {
  constructor(options = {}) {
    super(options);
    this.стол = options.стол;
  }

  static DEFAULT_OPTIONS = {
    classes: ["uo-igry", "uo-zerkala-okno"],
    tag: "div",
    window: { title: Т("Зал зеркал"), icon: "fa-solid fa-gem", resizable: false },
    position: { width: 480, height: "auto" },
    actions: {
      повернуть: ОкноЗеркал.#повернуть,
      засчитать: ОкноЗеркал.#засчитать,
      сброс: ОкноЗеркал.#сброс,
      снять: ОкноЗеркал.#снять,
    },
  };

  get title() { return this.стол?.название ?? Т("Зал зеркал"); }

  static #повернуть(event, target) {
    просить({ id: this.стол.id, что: "повернуть", клетка: target.dataset.kletka });
  }

  static #засчитать() { засчитать(this.стол.id); }
  static #сброс() { сбросить(this.стол.id); }
  static #снять() { убрать(this.стол.id); }

  _onClose() {
    забытьОкно(this.стол.id);
    if (this.закрываемСами) return;
    if (game.user.isGM) спрятать(this.стол.id);
    else спрятатьУСебя(this.стол.id);
  }

  async _renderHTML() {
    const с = this.стол;
    const крутит = можетКрутить(с, game.user);
    const { путь } = провестиЛучБезопасно(с);
    const светло = new Set(путь);
    const начало = с.источник.y * с.ширина + с.источник.x;

    const клетки = Array.from({ length: с.ширина * с.высота }, (_, к) => {
      const зеркало = с.зеркала[к];
      const классы = [
        "uo-zerkalo-kletka",
        светло.has(к) ? "uo-svetlo" : "",
        к === с.приёмник ? "uo-priemnik" : "",
        к === начало ? "uo-istochnik" : "",
        зеркало ? "uo-est-zerkalo" : "",
      ].filter(Boolean).join(" ");

      const знак = к === с.приёмник ? "◈" : зеркало ? (зеркало === "/" ? "╱" : "╲") : "";
      return `<button type="button" class="${классы}" ${
        зеркало && крутит ? `data-action="повернуть" data-kletka="${к}"` : "disabled"}>${знак}</button>`;
    }).join("");

    const счёт = с.предел
      ? `Поворот ${Math.min(с.поворотов + 1, с.предел)} из ${с.предел}`
      : `Поворотов: ${с.поворотов}`;

    const итог = с.зажжён
      ? `<p class="uo-itog uo-otkryt">${Т("Кристалл занялся светом.")}</p>`
      : с.заклинило
        ? `<p class="uo-itog uo-zaklinilo">${Т("Зеркала застыли. Ведущий может разрешить ещё.")}</p>`
        : "";

    const гм = game.user.isGM ? `
      <section class="uo-gm">
        ${с.глубина ? `<p class="uo-podskazka">${Т(`Загадано на {глубина} поворот(ов) — столько нужно самое малое.`, { глубина: с.глубина })}</p>` : ""}
        <div class="uo-gm-knopki">
          <button type="button" data-action="засчитать">${Т("Засчитать")}</button>
          <button type="button" data-action="сброс">${Т("Сбросить счёт")}</button>
          <button type="button" data-action="снять">${Т("Убрать со стола")}</button>
        </div>
      </section>` : "";

    const откуда = ["слева", "сверху", "справа", "снизу"][(с.источник.куда + 2) % 4];

    return `
      <div class="uo-zerkala-telo uo-tema-${экранировать(с.тема)}">
        ${с.подпись ? `<p class="uo-podpis">${экранировать(с.подпись)}</p>` : ""}
        <p class="uo-podskazka">${Т(`Луч входит {откуда}, ряд {источник}. Кристалл — ◈.`, { откуда: откуда, источник: с.источник.y + 1 })}</p>
        <div class="uo-zerkala" style="--shirina: ${с.ширина}">${клетки}</div>
        <div class="uo-stroka"><span class="uo-schet">${счёт}</span></div>
        ${итог}
        ${гм}
      </div>`;
  }

  _replaceHTML(result, content) { content.innerHTML = result; }
}

/** Луч рисуем даже у испорченного стола: окно не должно падать из-за данных. */
function провестиЛучБезопасно(стол) {
  try { return провестиЛуч(стол); } catch { return { путь: [], дошёл: false }; }
}

