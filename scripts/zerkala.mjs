/* ─────────────────────────── ход луча ─────────────────────────── */

// 0 — вправо, 1 — вниз, 2 — влево, 3 — вверх
const ШАГИ = [[1, 0], [0, 1], [-1, 0], [0, -1]];
const КОСАЯ = { "/": [3, 2, 1, 0], "\\": [1, 0, 3, 2] };   // куда повернёт луч на зеркале

/**
 * Пройти лучом по залу.
 * @returns {{путь: number[], дошёл: boolean}} клетки, через которые прошёл луч
 */
export function провестиЛуч(зал) {
  const { ширина, высота, зеркала, источник, приёмник } = зал;
  let [x, y] = [источник.x, источник.y];
  let куда = источник.куда;
  const путь = [];

  for (let шаг = 0; шаг < ширина * высота * 4; шаг++) {
    if (x < 0 || y < 0 || x >= ширина || y >= высота) return { путь, дошёл: false };

    const клетка = y * ширина + x;
    путь.push(клетка);
    if (клетка === приёмник) return { путь, дошёл: true };

    const зеркало = зеркала[клетка];
    if (зеркало) куда = КОСАЯ[зеркало][куда];

    x += ШАГИ[куда][0];
    y += ШАГИ[куда][1];
  }
  return { путь, дошёл: false };   // закольцевался между зеркалами
}

/* ─────────────────────────── постройка зала ─────────────────────────── */

const наугад = н => Math.floor(Math.random() * н);

/**
 * Построить зал от решения: ломаная из `изломов` поворотов, зеркало на каждом.
 *
 * Число изломов и есть заказанная сложность: щёлкнуть придётся по каждому
 * зеркалу тропы, иначе луч уйдёт не туда. Ломаная не пересекает саму себя —
 * иначе луч наткнулся бы на чужое зеркало и свернул раньше времени, и зал
 * оказался бы не тем, что задуман.
 *
 * Возвращает null, если ломаная упёрлась в собственный хвост: проще выбросить
 * попытку и начать заново, чем подгонять.
 */
function построить(ширина, высота, лишних, изломов) {
  const сторона = наугад(4);
  let x, y, куда;
  if (сторона === 0) { x = 0; y = наугад(высота); куда = 0; }
  else if (сторона === 1) { x = ширина - 1; y = наугад(высота); куда = 2; }
  else if (сторона === 2) { x = наугад(ширина); y = 0; куда = 1; }
  else { x = наугад(ширина); y = высота - 1; куда = 3; }

  const источник = { x, y, куда };
  const зеркала = {};
  const тропа = new Set([y * ширина + x]);

  /** Сколько клеток впереди свободно до стены или до собственной тропы. */
  const впереди = () => {
    let [пx, пy] = [x, y], сколько = 0;
    while (true) {
      const нx = пx + ШАГИ[куда][0], нy = пy + ШАГИ[куда][1];
      if (нx < 0 || нy < 0 || нx >= ширина || нy >= высота) break;
      if (тропа.has(нy * ширина + нx)) break;
      пx = нx; пy = нy; сколько++;
    }
    return сколько;
  };

  for (let и = 0; и < изломов; и++) {
    const свободно = впереди();
    if (свободно < 1) return null;
    // Последний излом оставляем не вплотную к стене: за ним ещё идти к кристаллу.
    const длина = 1 + наугад(свободно);
    for (let ш = 0; ш < длина; ш++) {
      x += ШАГИ[куда][0]; y += ШАГИ[куда][1];
      тропа.add(y * ширина + x);
    }
    const клетка = y * ширина + x;
    const новое = (куда === 0 || куда === 2) ? (наугад(2) ? 1 : 3) : (наугад(2) ? 0 : 2);
    зеркала[клетка] = Object.entries(КОСАЯ).find(([, к]) => к[куда] === новое)?.[0] ?? "/";
    куда = новое;
  }

  // После последнего зеркала луч идёт до стены — там и стоит кристалл.
  const добежать = впереди();
  if (добежать < 1) return null;
  for (let ш = 0; ш < добежать; ш++) {
    x += ШАГИ[куда][0]; y += ШАГИ[куда][1];
    тропа.add(y * ширина + x);
  }
  const приёмник = y * ширина + x;

  // Лишние зеркала — только в стороне от тропы, иначе они меняют саму загадку.
  for (let и = 0; и < лишних; и++) {
    const клетка = наугад(ширина * высота);
    if (зеркала[клетка] || тропа.has(клетка)) continue;
    зеркала[клетка] = наугад(2) ? "/" : "\\";
  }

  return { ширина, высота, источник, приёмник, зеркала };
}

/**
 * Разложить все развороты зеркал по глубине: сколько щелчков до ближайшего
 * решения. Считает razvoroty.mjs, здесь только подставляется ход луча.
 */
export function разложить(зал) {
  return разбор(Object.keys(зал.зеркала ?? {}),
    где => провестиЛуч({ ...зал, зеркала: где }).дошёл);
}

/** Решается ли зал вообще. Обещание стоит ровно столько, сколько проверка. */
export function решается(зал) {
  return (разложить(зал)?.решающих ?? 0) > 0;
}

/* ─────────────────────────── выложить на стол ─────────────────────────── */

export async function выложить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const ширина = Math.min(12, Math.max(4, Number(конфиг.ширина) || 8));
  const высота = Math.min(12, Math.max(4, Number(конфиг.высота) || 8));
  const лишних = Math.max(0, Math.min(8, Number(конфиг.лишних ?? 2)));
  const ходов = Math.max(1, Math.min(8, Number(конфиг.ходов) || 4));

  // Строим, пока не выйдет зал, до решения которого не меньше заказанного числа
  // поворотов. Глубина считается перебором, так что это не оценка, а факт.
  let зал = null, старт = null;
  for (let попытка = 0; попытка < 300 && !зал; попытка++) {
    const пробный = построить(ширина, высота, лишних, ходов);
    if (!пробный) continue;
    const разложенный = разложить(пробный);
    if (!разложенный?.решающих) continue;          // не обещаем того, что не проверили
    const начальное = начало(разложенный, ходов);
    if (!начальное || начальное.глубина < ходов) continue;
    зал = пробный;
    старт = начальное;
  }

  // Не вышло ровно как заказано — берём лучшее из достижимого и говорим об этом.
  if (!зал) {
    for (let попытка = 0; попытка < 300 && !зал; попытка++) {
      const пробный = построить(ширина, высота, лишних, ходов);
      if (!пробный) continue;
      const разложенный = разложить(пробный);
      if (!разложенный?.решающих) continue;
      const начальное = начало(разложенный, 1);
      if (!начальное) continue;
      зал = пробный;
      старт = начальное;
    }
    if (зал) ui.notifications.warn(
      `Зал вышел на ${старт.глубина} поворот(ов) вместо ${ходов} — на таком поле длиннее не легло.`);
  }
  if (!зал) { ui.notifications.error(Т("Не вышло сложить зал — попробуйте поле побольше.")); return null; }

  const перепутанные = старт.зеркала;

  await прибрать();

  const стол = {
    id: foundry.utils.randomID(),
    тип: "zerkala",
    название: конфиг.название?.trim() || Т("Зал зеркал"),
    подпись: конфиг.подпись?.trim() || "",
    тема: (конфиг.тема in ТЕМЫ) ? конфиг.тема : "orden",
    ширина: зал.ширина,
    высота: зал.высота,
    источник: зал.источник,
    приёмник: зал.приёмник,
    зеркала: перепутанные,
    поворотов: 0,
    глубина: старт.глубина,                        // сколько поворотов нужно минимум
    предел: Math.max(0, Number(конфиг.предел) || 0),
    крутят: конфиг.крутят?.length ? конфиг.крутят : "все",
    макрос: конфиг.макрос?.trim() || null,
    зажжён: false,
    заклинило: false,
    завершён: false,
    показан: true,
  };

  if (стол.предел && стол.предел < старт.глубина) ui.notifications.warn(
    `Предел ${стол.предел} меньше, чем нужно поворотов (${старт.глубина}) — зал не открыть.`);

  await записать(стол);
  return стол;
}

export async function прибрать() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "zerkala" && с.завершён) await убрать(id);
  }
}

/* ─────────────────────────────── правила ─────────────────────────────── */

const можетКрутить = (стол, пользователь) =>
  !!пользователь && !стол.зажжён && !стол.заклинило &&
  (пользователь.isGM || стол.крутят === "все" || (стол.крутят ?? []).includes(пользователь.id));

const отложитьЗапись = foundry.utils.debounce(async id => {
  const сырой = столПоId(id);
  if (!сырой) return;
  const живой = собрать(сырой);
  await записать({ ...сырой, зеркала: живой.зеркала, поворотов: живой.поворотов });
}, 3000);

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!можетКрутить(стол, пользователь)) return;
  if (запрос.что !== "повернуть") return;

  const клетка = String(Number(запрос.клетка));
  if (!стол.зеркала[клетка]) return;

  const зеркала = { ...стол.зеркала, [клетка]: стол.зеркала[клетка] === "/" ? "\\" : "/" };
  const поворотов = стол.поворотов + 1;
  const { дошёл } = провестиЛуч({ ...стол, зеркала });

  if (дошёл) return зажглось(стол, зеркала, поворотов, запрос.кто);

  if (стол.предел && поворотов >= стол.предел) {
    await записать({ ...столПоId(стол.id), зеркала, поворотов, заклинило: true, завершён: true });
    await объявить(Т(`<p><strong>{название}</strong> — зеркала застыли, поворотов больше нет.</p>`, { название: экранировать(стол.название) }),
      стол.название);
    return;
  }

  разослать(стол.id, { зеркала, поворотов });
  отложитьЗапись(стол.id);
}

async function зажглось(стол, зеркала, поворотов, ктоId) {
  const свежий = { ...столПоId(стол.id), зеркала, поворотов, зажжён: true, завершён: true };
  await записать(свежий);
  await объявить(
    Т(`<p><strong>{название}</strong> — луч дошёл, кристалл занялся светом.</p>
     <p><em>{ктоId} довернул последнее зеркало; всего поворотов {поворотов}.</em></p>`, { название: экранировать(свежий.название), ктоId: экранировать(имяИгрока(ктоId)), поворотов: поворотов }),
    свежий.название);
  событие("решено", свежий);
  await запуститьМакрос(свежий.макрос, свежий);
}

/* ─────────────────── рычаги ведущего ─────────────────── */

export async function засчитать(id) {
  const стол = столПоId(id);
  if (!стол) return;
  const полный = { ...собрать(стол), зажжён: true, заклинило: false, завершён: true };
  await записать(полный);
  await объявить(Т(`<p><strong>{название}</strong> — зажжён волей ведущего.</p>`, { название: экранировать(полный.название) }), полный.название);
  событие("решено", полный);
  await запуститьМакрос(полный.макрос, полный);
}

export async function сбросить(id) {
  const стол = столПоId(id);
  if (!стол) return;
  await записать({ ...стол, поворотов: 0, зажжён: false, заклинило: false, завершён: false });
}

