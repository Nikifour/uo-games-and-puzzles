/**
 * Свет и зеркала — довести луч до кристалла.
 *
 * Луч входит с края, идёт прямо и поворачивает на зеркалах. Зеркала стоят
 * косо, «╱» или «╲», и поворачиваются щелчком. Дошёл до приёмника — открыто.
 *
 * Зал не выдумывается наугад, а строится от решения: сперва прокладывается
 * ломаная от источника до приёмника, зеркала ставятся на её изломах, и только
 * потом их разворачивают как попало и подсыпают лишних. Так зал заведомо
 * решается — а зал, который не решается, игроки будут ковырять весь вечер
 * и справедливо возненавидят.
 */

