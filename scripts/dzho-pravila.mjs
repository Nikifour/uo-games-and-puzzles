/**
 * «Счастливчик Джо» — правила и счёт. Ни одной связи с Foundry.
 *
 * Шесть раз бросают 2к6 и оставляют одну кость на выбор. Оставленные кости
 * ложатся в ряд, и в каждом окне из трёх подряд считается комбинация; окна
 * перекрываются, поэтому длинный ряд считается несколько раз: 1-2-3-4-5-6 —
 * это четыре окна по 300.
 *
 * Джо — шесть одинаковых. Он и есть безусловная победа, и его нельзя
 * вымучить: расчёт показывает, что нарочная погоня за ним прибавляет
 * две сотых процента к вероятности. Джо случается, а не добывается —
 * потому воры и держат его за руку судьбы.
 */

export const ЦЕНА_ЛЕСЕНКИ = 300;
export const ЦЕНА_ОДИНАКОВЫХ = 300;
export const ЦЕНА_ЧЁТА = 500;      // 1-3-5 и 2-4-6 тупиковые: продолжения им нет

const лесенка = (a, b, c) => (b === a + 1 && c === b + 1) || (b === a - 1 && c === b - 1);
const нечёт = (a, b, c) => (a === 1 && b === 3 && c === 5) || (a === 5 && b === 3 && c === 1);
const чёт = (a, b, c) => (a === 2 && b === 4 && c === 6) || (a === 6 && b === 4 && c === 2);
const одинаковые = (a, b, c) => a === b && b === c;

/** Что стоит окно из трёх подряд. */
export function ценаОкна(a, b, c) {
  if (!a || !b || !c) return 0;
  if (нечёт(a, b, c) || чёт(a, b, c)) return ЦЕНА_ЧЁТА;
  if (лесенка(a, b, c) || одинаковые(a, b, c)) return ЦЕНА_ЛЕСЕНКИ;
  return 0;
}

/** Как называется то, что вышло в окне. Для журнала и объявлений. */
export function имяОкна(a, b, c) {
  if (нечёт(a, b, c)) return "нечёт";
  if (чёт(a, b, c)) return "чёт";
  if (одинаковые(a, b, c)) return "одинаковые";
  if (лесенка(a, b, c)) return "лесенка";
  return null;
}

/** Все окна ряда: [{с, по, имя, очки}]. */
export function окна(кости) {
  const найдено = [];
  for (let i = 0; i + 2 < кости.length; i++) {
    const [a, b, c] = [кости[i], кости[i + 1], кости[i + 2]];
    const цена = ценаОкна(a, b, c);
    if (цена) найдено.push({ с: i, по: i + 2, имя: имяОкна(a, b, c), очки: цена });
  }
  return найдено;
}

export const очкиРяда = кости => окна(кости).reduce((с, о) => с + о.очки, 0);

/** Джо — шесть одинаковых. Ни лесенка, ни что-либо ещё им не считается. */
export const джо = кости => кости.length === 6 && кости.every(к => к === кости[0]);

/* ────────────────────── как играет умелый ────────────────────── */

/**
 * V[сколькоОставлено][предпоследняя][последняя] — сколько очков ещё возьмёт
 * умелый игрок. Считается один раз при загрузке: 6 × 7 × 7 × 36 действий,
 * то есть мгновенно.
 */
const V = Array.from({ length: 7 }, () => Array.from({ length: 7 }, () => new Array(7).fill(0)));
for (let оставлено = 5; оставлено >= 0; оставлено--) {
  for (let a = 0; a <= 6; a++) {
    for (let b = 0; b <= 6; b++) {
      let сумма = 0;
      for (let к1 = 1; к1 <= 6; к1++) {
        for (let к2 = 1; к2 <= 6; к2++) {
          const взять = x => ценаОкна(a, b, x) + V[оставлено + 1][b][x];
          сумма += Math.max(взять(к1), взять(к2));
        }
      }
      V[оставлено][a][b] = сумма / 36;
    }
  }
}

/** Во сколько умелый игрок оценивает это положение. */
export const ценаПоложения = (кости, ещёКость) => {
  const после = [...кости, ещёКость];
  const a = после.at(-3) ?? 0;
  const b = после.at(-2) ?? 0;
  return ценаОкна(a, b, ещёКость) + V[Math.min(6, после.length)][b][ещёКость];
};

/**
 * Какую из двух костей оставить.
 *
 * @param мастерство 1 — играет верно всегда, 0.5 — половину ходов наугад.
 */
export function лучшая(кости, бросок, мастерство = 1, случай = Math.random) {
  const [к1, к2] = бросок;
  if (к1 === к2) return к1;
  if (случай() > мастерство) return случай() < 0.5 ? к1 : к2;
  return ценаПоложения(кости, к1) >= ценаПоложения(кости, к2) ? к1 : к2;
}

/** Бросок 2к6. Случайность приходит снаружи: в игре её даёт Foundry. */
export const бросить2к6 = (случай = Math.random) =>
  [1 + Math.floor(случай() * 6), 1 + Math.floor(случай() * 6)];
