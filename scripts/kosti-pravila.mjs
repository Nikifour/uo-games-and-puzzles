/**
 * Кости — правила и счёт. Ни одной связи с Foundry: только кости и числа.
 *
 * Отделено нарочно. Подсчёт очков в Костях — то самое место, где ошибку
 * за столом не заметят, а деньги посчитают: «четыре единицы» бывают 2000,
 * а бывают 1000, и разницу видно только на длинной дистанции. Раз правила
 * чистые, их можно прогнать тысячей партий двух ботов, не поднимая мир.
 *
 * Счёт взят из трактирной версии Kingdom Come, и всё, что в разных домах
 * считают по-разному, вынесено в правила: три пары, порог входа, цель партии,
 * множитель за кости сверх тройки.
 */

import { М } from "./yazyk.mjs";

export const ПРАВИЛА = {
  цель: 4000,           // до скольки играем
  порогВхода: 0,        // сколько нужно набрать, чтобы открыть счёт (0 — сразу)
  единица: 100,
  пятёрка: 50,
  тройкаЕдиниц: 1000,   // три единицы; прочие тройки — номинал × 100
  стрит6: 1500,         // 1-2-3-4-5-6
  стрит15: 500,         // 1-2-3-4-5
  стрит26: 750,         // 2-3-4-5-6
  триПары: 0,           // 0 — не считаются, как в трактире Kingdom Come
  множительСверхТройки: 2,   // четыре одинаковых — вдвое от тройки, пять — вчетверо
};

const ключ = кости => [...кости].sort().join("");
const счётчик = кости => кости.reduce((с, к) => (с[к] = (с[к] ?? 0) + 1, с), {});

/** Убрать из набора ровно перечисленные кости (по одной штуке за каждую). */
function вычесть(кости, беру) {
  const остаток = [...кости];
  for (const к of беру) {
    const i = остаток.indexOf(к);
    if (i >= 0) остаток.splice(i, 1);
  }
  return остаток;
}

const базоваяТройка = (номинал, п) => номинал === 1 ? п.тройкаЕдиниц : номинал * 100;
const множитель = (сколько, п) => Math.pow(п.множительСверхТройки, сколько - 3);

/**
 * Все комбинации, которые можно взять из набора одним куском.
 * Пустой список означает пусто: брать нечего.
 */
export function комбинации(кости, правила = ПРАВИЛА) {
  const п = { ...ПРАВИЛА, ...правила };
  const с = счётчик(кости);
  const есть = н => (с[н] ?? 0) > 0;
  const выбор = [];

  // стриты
  if ([1, 2, 3, 4, 5, 6].every(есть)) выбор.push({ беру: [1, 2, 3, 4, 5, 6], очки: п.стрит6, имя: М("стрит 1–6") });
  if ([1, 2, 3, 4, 5].every(есть)) выбор.push({ беру: [1, 2, 3, 4, 5], очки: п.стрит15, имя: М("стрит 1–5") });
  if ([2, 3, 4, 5, 6].every(есть)) выбор.push({ беру: [2, 3, 4, 5, 6], очки: п.стрит26, имя: М("стрит 2–6") });

  // три пары
  if (п.триПары > 0 && кости.length === 6) {
    const пары = Object.entries(с).filter(([, n]) => n === 2 || n === 4 || n === 6);
    const всего = пары.reduce((n, [, c]) => n + c, 0);
    if (всего === 6) выбор.push({ беру: [...кости], очки: п.триПары, имя: М("три пары") });
  }

  // одинаковые, от тройки и выше
  for (const [номиналСтрока, сколько] of Object.entries(с)) {
    const номинал = Number(номиналСтрока);
    for (let k = 3; k <= сколько; k++) {
      выбор.push({
        беру: Array(k).fill(номинал),
        очки: Math.round(базоваяТройка(номинал, п) * множитель(k, п)),
        имя: `${k}×${номинал}`,
      });
    }
  }

  // одиночные
  if (есть(1)) выбор.push({ беру: [1], очки: п.единица, имя: М("единица") });
  if (есть(5)) выбор.push({ беру: [5], очки: п.пятёрка, имя: М("пятёрка") });

  return выбор;
}

/** Есть ли вообще что откладывать. Нет — это «пусто», и ход сгорает. */
export const естьХод = (кости, правила = ПРАВИЛА) => комбинации(кости, правила).length > 0;

/**
 * Оценить отобранное.
 *
 * Годным считается только тот отбор, где **каждая** кость участвует
 * в комбинации: отложить пару троек «за компанию» нельзя.
 */
export function оценить(отбор, правила = ПРАВИЛА) {
  const п = { ...ПРАВИЛА, ...правила };
  const память = new Map();

  const лучшее = кости => {
    if (!кости.length) return 0;
    const к = ключ(кости);
    if (память.has(к)) return память.get(к);

    let итог = -1;
    for (const { беру, очки } of комбинации(кости, п)) {
      const дальше = лучшее(вычесть(кости, беру));
      if (дальше >= 0) итог = Math.max(итог, очки + дальше);
    }
    память.set(к, итог);
    return итог;
  };

  const очки = лучшее([...отбор]);
  return { очки: Math.max(очки, 0), годен: очки >= 0 };
}

/**
 * Все годные отборы из броска, от дорогих к дешёвым.
 *
 * Шесть костей — это 63 непустых подмножества, перебор мгновенный,
 * зато боту и человеку видно всё поле выбора целиком.
 */
export function отборы(кости, правила = ПРАВИЛА) {
  const п = { ...ПРАВИЛА, ...правила };
  const найдено = new Map();

  for (let маска = 1; маска < (1 << кости.length); маска++) {
    const набор = кости.filter((_, i) => маска & (1 << i));
    const { очки, годен } = оценить(набор, п);
    if (!годен || !очки) continue;
    const к = ключ(набор);
    if (!найдено.has(к)) найдено.set(к, { набор, очки, осталось: кости.length - набор.length });
  }

  return [...найдено.values()].sort((a, b) => b.очки - a.очки || a.набор.length - b.набор.length);
}

/** Бросок. Случайность передаётся снаружи: в игре её даёт Foundry, в проверке — свой генератор. */
export const бросить = (сколько, случай = Math.random) =>
  Array.from({ length: сколько }, () => 1 + Math.floor(случай() * 6));
