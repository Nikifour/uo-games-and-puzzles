/** Строки вида «+ текст» — правда, «- текст» — ложь. Знак съедается. */
export function разобратьСтроки(текст) {
  return String(текст ?? "").split(/\r?\n/)
    .map(с => с.trim())
    .filter(Boolean)
    .map(с => {
      const правда = с.startsWith("+");
      const голая = с.replace(/^[+-]\s*/, "").trim();
      return { текст: голая, правда };
    })
    .filter(с => с.текст);
}

/* ─────────────────────────── выложить на стол ─────────────────────────── */

export async function выложить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const створки = разобратьСтроки(конфиг.створки);
  const надписи = разобратьСтроки(конфиг.надписи);

  if (створки.length < 2) { ui.notifications.error(Т("Нужно хотя бы две створки.")); return null; }
  if (!надписи.length) { ui.notifications.error(Т("Нужна хотя бы одна надпись.")); return null; }

  const верная = створки.findIndex(с => с.правда);
  if (верная < 0) { ui.notifications.error(Т("Ни одна створка не помечена «+» как верная.")); return null; }

  await прибрать();

  const id = foundry.utils.randomID();
  const стол = {
    id,
    тип: "vrata",
    название: конфиг.название?.trim() || Т("Врата"),
    подпись: конфиг.подпись?.trim() || "",
    тема: (конфиг.тема in ТЕМЫ) ? конфиг.тема : "kamen",
    створки: створки.map(с => ({ имя: с.текст })),
    надписи: надписи.map(н => ({ текст: н.текст })),
    пометки: {},
    попытки: { сделано: 0, предел: Math.max(0, Number(конфиг.предел) || 0) },
    выбирают: конфиг.выбирают?.length ? конфиг.выбирают : "все",
    макрос: конфиг.макрос?.trim() || null,
    макросЛовушки: конфиг.макросЛовушки?.trim() || null,
    журнал: [],
    открыта: null,
    провал: false,
    завершён: false,
    показан: true,
  };

  await тайнуЗапомнить(id, {
    верная,
    правдивы: надписи.map((н, i) => (н.правда ? i : -1)).filter(i => i >= 0),
  });
  await записать(стол);
  return стол;
}

export async function прибрать() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "vrata" && с.завершён) await убрать(id);
  }
}

/* ─────────────────────────────── правила ─────────────────────────────── */

const можетВыбирать = (стол, пользователь) =>
  !!пользователь && стол.открыта === null && !стол.провал &&
  (пользователь.isGM || стол.выбирают === "все" || (стол.выбирают ?? []).includes(пользователь.id));

const ПОМЕТКИ = [null, "правда", "ложь"];

// Пометки — доска для спора, их пишем в базу не чаще, чем нужно.
const отложитьЗапись = foundry.utils.debounce(async id => {
  const сырой = столПоId(id);
  if (!сырой) return;
  await записать({ ...сырой, пометки: собрать(сырой).пометки });
}, 3000);

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!можетВыбирать(стол, пользователь)) return;

  if (запрос.что === "пометить") {
    const какая = Number(запрос.надпись);
    if (!Number.isInteger(какая) || какая < 0 || какая >= стол.надписи.length) return;
    const было = (стол.пометки ?? {})[какая] ?? null;
    const стало = ПОМЕТКИ[(ПОМЕТКИ.indexOf(было) + 1) % ПОМЕТКИ.length];
    разослать(стол.id, { пометки: { ...(стол.пометки ?? {}), [какая]: стало } });
    отложитьЗапись(стол.id);
    return;
  }

  if (запрос.что === "открыть") await открыть(стол, Number(запрос.створка), запрос.кто);
}

async function открыть(стол, какая, ктоId) {
  if (!Number.isInteger(какая) || какая < 0 || какая >= стол.створки.length) return;

  const верная = тайна(стол.id)?.верная;
  if (верная === undefined) {
    ui.notifications.error(
      `Разгадка врат «${стол.название}» не найдена в этом браузере. Засчитайте вручную или выложите заново.`);
    return;
  }

  const угадали = какая === верная;
  const обновлённый = {
    ...столПоId(стол.id),
    пометки: стол.пометки,
    попытки: { ...стол.попытки, сделано: стол.попытки.сделано + 1 },
    журнал: [...(стол.журнал ?? []), {
      кто: имяИгрока(ктоId), створка: стол.створки[какая].имя, удача: угадали,
    }].slice(-8),
    открыта: угадали ? какая : null,
    завершён: угадали,
  };

  if (!угадали && обновлённый.попытки.предел &&
      обновлённый.попытки.сделано >= обновлённый.попытки.предел) {
    обновлённый.провал = true;
    обновлённый.завершён = true;
  }

  await записать(обновлённый);

  if (угадали) {
    await объявить(
      Т(`<p><strong>{название}</strong>: {ктоId} толкает створку «{имя}» — и она поддаётся.</p>`, { название: экранировать(обновлённый.название), ктоId: 
        экранировать(имяИгрока(ктоId)), имя: 
        экранировать(обновлённый.створки[какая].имя) }), обновлённый.название);
    событие("решено", обновлённый);
    await запуститьМакрос(обновлённый.макрос, обновлённый);
    return;
  }

  await объявить(
    Т(`<p><strong>{название}</strong>: створка «{имя}» не та.</p>`, { название: экранировать(стол.название), имя: 
      экранировать(стол.створки[какая].имя) }) +
    (обновлённый.провал ? `<p>${Т("Врата больше не отзываются.")}</p>` : ""), стол.название);
  событие("ловушка", обновлённый);
  await запуститьМакрос(стол.макросЛовушки, обновлённый);
}

/* ─────────────────── рычаги ведущего ─────────────────── */

export async function засчитать(id) {
  const стол = столПоId(id);
  if (!стол) return;
  const верная = тайна(id)?.верная ?? 0;
  const полный = { ...собрать(стол), открыта: верная, провал: false, завершён: true };
  await записать(полный);
  await объявить(Т(`<p><strong>{название}</strong> — открыты волей ведущего.</p>`, { название: экранировать(полный.название) }), полный.название);
  событие("решено", полный);
  await запуститьМакрос(полный.макрос, полный);
}

export async function сбросить(id) {
  const стол = столПоId(id);
  if (!стол) return;
  await записать({
    ...стол,
    пометки: {},
    попытки: { ...стол.попытки, сделано: 0 },
    журнал: [],
    открыта: null,
    провал: false,
    завершён: false,
  });
}

/* ──────────────────────────────── окно ──────────────────────────────── */

class ОкноВрат extends ApplicationV2 {
  constructor(options = {}) {
    super(options);
    this.стол = options.стол;
    this.ответВидно = false;
  }

  static DEFAULT_OPTIONS = {
    classes: ["uo-igry", "uo-vrata-okno"],
    tag: "div",
    window: { title: Т("Врата"), icon: "fa-solid fa-dungeon", resizable: false },
    position: { width: 520, height: "auto" },
    actions: {
      пометить: ОкноВрат.#пометить,
      открыть: ОкноВрат.#открыть,
      ответВидно: ОкноВрат.#ответВидно,
      засчитать: ОкноВрат.#засчитать,
      сброс: ОкноВрат.#сброс,
      снять: ОкноВрат.#снять,
    },
  };

  get title() { return this.стол?.название ?? Т("Врата"); }

  static #пометить(event, target) {
    просить({ id: this.стол.id, что: "пометить", надпись: target.dataset.nadpis });
  }

  static #открыть(event, target) {
    просить({ id: this.стол.id, что: "открыть", створка: target.dataset.stvorka });
  }

  static #ответВидно() { this.ответВидно = !this.ответВидно; this.render(); }
  static #засчитать() { засчитать(this.стол.id); }
  static #сброс() { сбросить(this.стол.id); }
  static #снять() { убрать(this.стол.id); }

  _onClose() {
    забытьОкно(this.стол.id);
    if (this.закрываемСами) return;
    if (game.user.isGM) спрятать(this.стол.id);
    else спрятатьУСебя(this.стол.id);
  }

  async _renderHTML() {
    const с = this.стол;
    const выбирает = можетВыбирать(с, game.user);
    const пометки = с.пометки ?? {};

    const надписи = с.надписи.map((н, i) => {
      const метка = пометки[i] ?? null;
      return `
        <li class="uo-nadpis-stroka uo-metka-${метка ?? "net"}">
          <button type="button" class="uo-metka" ${выбирает ? `data-action="пометить" data-nadpis="${i}"` : "disabled"}
                  title="${Т("правда, ложь или без пометки")}">${метка === "правда" ? "✓" : метка === "ложь" ? "✕" : "?"}</button>
          <span>«${экранировать(н.текст)}»</span>
        </li>`;
    }).join("");

    const створки = с.створки.map((ств, i) => `
      <button type="button" class="uo-stvorka ${с.открыта === i ? "uo-otkryta" : ""}"
              ${выбирает ? `data-action="открыть" data-stvorka="${i}"` : "disabled"}>
        ${экранировать(ств.имя)}
      </button>`).join("");

    const счёт = с.попытки.предел
      ? `Попытка ${Math.min(с.попытки.сделано + 1, с.попытки.предел)} из ${с.попытки.предел}`
      : `Попыток сделано: ${с.попытки.сделано}`;

    const журнал = (с.журнал ?? []).length ? `
      <ol class="uo-zhurnal">
        ${[...с.журнал].reverse().map(з => `
          <li class="${з.удача ? "uo-udacha" : ""}">
            <span class="uo-kto">${экранировать(з.кто)}</span>
            <span class="uo-podskazka">${экранировать(з.створка)}</span>
          </li>`).join("")}
      </ol>` : "";

    const итог = с.открыта !== null
      ? `<p class="uo-itog uo-otkryt">${Т("Врата открыты.")}</p>`
      : с.провал
        ? `<p class="uo-itog uo-zaklinilo">${Т("Врата больше не отзываются. Ведущий может дать ещё попытку.")}</p>`
        : "";

    const тайное = тайна(с.id);
    const гм = game.user.isGM ? `
      <section class="uo-gm">
        <div class="uo-gm-kod">
          <button type="button" data-action="ответВидно">${this.ответВидно ? "Скрыть" : Т("Показать ответ")}</button>
          ${this.ответВидно && тайное ? `<code>${
            экранировать(с.створки[тайное.верная]?.имя ?? "?")} · правдивы: ${
            (тайное.правдивы ?? []).map(i => i + 1).join("), ") || Т("ни одна")}</code>` : ""}
        </div>
        <div class="uo-gm-knopki">
          <button type="button" data-action="засчитать">${Т("Засчитать")}</button>
          <button type="button" data-action="сброс">${Т("Сбросить")}</button>
          <button type="button" data-action="снять">${Т("Убрать со стола")}</button>
        </div>
      </section>` : "";

    return `
      <div class="uo-vrata-telo uo-tema-${экранировать(с.тема)}">
        ${с.подпись ? `<p class="uo-podpis">${экранировать(с.подпись)}</p>` : ""}
        <ol class="uo-nadpisi">${надписи}</ol>
        <p class="uo-podskazka">${Т("Пометки общие: их видят все, и ни на что, кроме спора, они не влияют.")}</p>
        <div class="uo-stvorki">${створки}</div>
        <div class="uo-stroka"><span class="uo-schet">${счёт}</span></div>
        ${итог}
        ${журнал}
        ${гм}
      </div>`;
  }

  _replaceHTML(result, content) { content.innerHTML = result; }
}

/* ──────────────────────────── диалог создания ──────────────────────────── */

