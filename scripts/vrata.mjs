/**
 * Врата с надписями — испытание, а не механизм.
 *
 * Несколько створок, на них высказывания. Часть надписей лжёт, и какие
 * именно — знает только ведущий. Игроки помечают надписи «правда» и «ложь»
 * сообща, спорят вслух и в конце называют створку.
 *
 * Пометки здесь — не игра в угадайку, а общая доска: их видят все, они не
 * проверяются и ни на что не влияют механически. Это память стола, чтобы
 * спор о третьей надписи не начинался заново каждые пять минут.
 *
 * Всё сочиняется прямо в диалоге: ведущий и так пишет текст, а склад
 * заготовок для такого — лишнее звено.
 */

