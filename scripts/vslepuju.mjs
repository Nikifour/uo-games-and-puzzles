/**
 * Раздельное управление: видит один, делают другие.
 *
 * Любую загадку, где что-то крутят или двигают, можно разложить на двоих и
 * больше. Штурман видит поле, но руками его не трогает. Остальные поля не
 * видят вовсе — у них пульт: рычаги, подписанные ведущим. Рычаг
 * привязан к одной детали поля (зеркалу, шару, диску), и какой к какой —
 * знает только штурман, и то лишь там, где ведущий пометил деталь номером
 * рычага. Непомеченное штурман «прозванивает» сам: «дёрни третий — ага,
 * это верхнее». Дальше разговор: «третий дважды», «первый — нет, верни».
 *
 * Рычаги можно разбить на несколько пультов и отдать каждый своему игроку:
 * номера рычагов при этом сквозные — штурман говорит «пятый», и тот, у кого
 * пятый, тянет. Пульт без хозяина открыт любому, кто допущен к рычагам.
 *
 * Здесь только общее: роли, рычаги и пульт. Что делает рычаг, решает сам
 * вид загадки — для призм это поворот зеркала. Окно выкладки — у устройства
 * (shturman.mjs), в отделе «Устройства».
 *
 * Прятать поле от рычажных — договорённость, а не замок: стол лежит в
 * настройках мира, и F12 его покажет. Ответа там нет, только положение
 * деталей, так что подглядевший увидит то же, что видит штурман.
 */

import { Т } from "./yazyk.mjs";

const экранировать = s => foundry.utils.escapeHTML(String(s ?? ""));

/** Перемешать по месту: номера рычагов не должны идти по порядку клеток. */
export function перемешать(список) {
  for (let i = список.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [список[i], список[j]] = [список[j], список[i]];
  }
  return список;
}

/**
 * Поле `вслепую` для стола.
 *
 * `детали` — ключи того, чем управляют рычаги (номера клеток с зеркалами).
 * `рычаги` — разложенные в подготовке `[{деталь, подпись}]`; нет их —
 * детали перемешиваются, подписи пустые (на пульте тогда только номер).
 * `пометки` — детали, на которых штурман увидит номер рычага.
 * `подсказка` — слова ведущего штурману; своих подсказок стол не даёт.
 */
export function разложить({ штурман, детали, рычаги = null, пометки = [], подсказка = "", пульты = null }) {
  if (!штурман) return null;
  const свои = new Set([...детали].map(String));
  const хозяева = Array.isArray(пульты) && пульты.length ? пульты.map(к => String(к ?? "")) : [""];
  const пульт = п => (Number.isInteger(Number(п)) && Number(п) >= 0 && Number(п) < хозяева.length ? Number(п) : 0);
  const готовые = Array.isArray(рычаги) && рычаги.length && рычаги.every(р => свои.has(String(р.деталь)))
    ? рычаги.map(р => ({ деталь: String(р.деталь), подпись: String(р.подпись ?? "").trim(), пульт: пульт(р.пульт) }))
    : перемешать([...свои]).map(деталь => ({ деталь, подпись: "", пульт: 0 }));
  return {
    штурман,
    рычаги: готовые,
    пульты: хозяева,
    пометки: (пометки ?? []).map(String).filter(д => свои.has(д)),
    подсказка: String(подсказка ?? "").trim(),
  };
}

/**
 * Пульты, за которые человек может встать: ведущему — все, штурману — ни
 * одного, прочим — свои и бесхозные (если допущен к рычагам вообще).
 */
export function пультыЧеловека(стол, пользователь, допущен) {
  const в = стол.вслепую;
  if (!в || !пользователь) return [];
  const хозяева = в.пульты?.length ? в.пульты : [""];
  if (пользователь.isGM) return хозяева.map((_, i) => i);
  if (пользователь.id === в.штурман) return [];
  return хозяева.map((кто, i) => (кто === пользователь.id || (!кто && допущен) ? i : -1)).filter(i => i >= 0);
}

/** Может ли человек тянуть этот рычаг: рычаг на его пульте. */
export function можноТянуть(стол, пользователь, номер, допущен) {
  const р = стол.вслепую?.рычаги?.[Number(номер)];
  return !!р && пультыЧеловека(стол, пользователь, допущен).includes(р.пульт ?? 0);
}

/** Помечена ли деталь номером рычага для штурмана. */
export const помечена = (стол, деталь) => (стол.вслепую?.пометки ?? []).includes(String(деталь));

/**
 * Кем стол видит этого человека.
 *
 * - «ведущий» — видит всё и может всё;
 * - «штурман» — видит поле с номерами рычагов, трогать не может;
 * - «рычаги» — видит только пульт;
 * - «зритель» — рычагов ему не дали: видит, что загадка идёт, и только.
 */
export function роль(стол, пользователь, допущен) {
  if (!стол.вслепую) return null;
  if (пользователь?.isGM) return "ведущий";
  if (пользователь?.id === стол.вслепую.штурман) return "штурман";
  return пультыЧеловека(стол, пользователь, допущен).length ? "рычаги" : "зритель";
}

/** Номер рычага для детали (с единицы) — его рисуют на поле штурману. */
export function номерДетали(стол, деталь) {
  const i = (стол.вслепую?.рычаги ?? []).findIndex(р => р.деталь === String(деталь));
  return i < 0 ? null : i + 1;
}

/** Деталь под рычагом; ход проверяет номер, прежде чем что-то делать. */
export function детальРычага(стол, номер) {
  return стол.вслепую?.рычаги?.[Number(номер)]?.деталь ?? null;
}

/**
 * Пульты человека: только свои. `можно` — разрешено ли нажимать сейчас
 * (зал не решён, время не вышло). Пультов несколько — у каждого заголовок.
 */
export function пульт(стол, пользователь, можно, допущен) {
  const в = стол.вслепую;
  const хозяева = в?.пульты?.length ? в.пульты : [""];
  const свои = пультыЧеловека(стол, пользователь, допущен);
  const блоки = свои.map(п => {
    const рычаги = (в?.рычаги ?? []).map((р, i) => ((р.пульт ?? 0) === п ? `
      <button type="button" class="uo-rychag" ${можно ? `data-action="рычаг" data-rychag="${i}"` : "disabled"}>
        <span class="uo-rychag-nomer">${i + 1}</span>
        ${р.подпись ? `<span class="uo-rychag-podpis">${экранировать(р.подпись)}</span>` : ""}
      </button>` : "")).join("");
    const заголовок = хозяева.length > 1 ? `<h4 class="uo-pult-imya">${Т("Пульт {номер}", { номер: п + 1 })}</h4>` : "";
    return `${заголовок}<div class="uo-pult">${рычаги}</div>`;
  }).join("");
  const штурман = game.users.get(в?.штурман)?.name ?? Т("кто-то");
  return `
    <p class="uo-podskazka">${Т("Поле видит {штурман}. Слушайте его и тяните рычаги.", { штурман: экранировать(штурман) })}</p>
    ${блоки}`;
}

/* ───────────────────────── пересадка по ходу игры ───────────────────────── */

/*
 * Игрок вылетел, двое поменялись местами, кто-то ушёл со стола — роли
 * приходится менять, когда устройство уже на столе. Переигрывать выкладку
 * ради этого нельзя: механизм соберётся заново, и разгаданное пропадёт.
 *
 * Поэтому здесь только рассадка: кто штурман и кто за каким пультом.
 * Рычаги, пометки и подсказка не трогаются вовсе.
 */

/** Где сидит человек: "штурман", номер пульта или null. */
export function местоЧеловека(в, ктоId) {
  if (!в || !ктоId) return null;
  if (в.штурман === ктоId) return "штурман";
  const п = (в.пульты ?? []).indexOf(ктоId);
  return п >= 0 ? п : null;
}

/**
 * Посадить человека на место — с обменом.
 *
 * Если он уже сидит в другом месте, прежний хозяин нового места садится
 * на его старое: так «поменять местами» выходит само, в любую сторону —
 * пульт с пультом, штурман с пультом. Пустое место в обмене — это «любой
 * игрок», и штурманом никто стать не может, поэтому пустого штурмана нет.
 *
 * Возвращает новое «вслепую» или null, если менять нечего.
 */
export function посадить(в, куда, ктоId) {
  if (!в) return null;
  const пульты = [...(в.пульты ?? [""])];
  const штурман = в.штурман;
  const кто = String(ктоId ?? "");
  if (куда === "штурман" && !кто) return null;          // поле должен видеть кто-то

  const было = куда === "штурман" ? штурман : (пульты[куда] ?? "");
  if (было === кто) return null;
  const откуда = местоЧеловека(в, кто);                  // где он сидел раньше

  const посадка = (место, id) => {
    if (место === "штурман") return { ...в, штурман: id, пульты };
    пульты[место] = id;
    return { ...в, штурман, пульты };
  };

  let итог = посадка(куда, кто);
  // Прежний хозяин уходит на освободившееся место — если оно было.
  if (откуда !== null && откуда !== куда) {
    итог = откуда === "штурман"
      ? { ...итог, штурман: было }
      : (() => { пульты[откуда] = было; return { ...итог, пульты }; })();
  }
  // Штурмана без человека не бывает: обмен с бесхозным пультом его бы оставил.
  if (!итог.штурман) return null;
  return итог;
}

/**
 * Убрать пульт, отдав его рычаги другому.
 *
 * Номера рычагов сквозные и не меняются: штурман говорит «пятый», и пятый
 * остаётся пятым, просто теперь он у другого человека.
 */
export function убратьПульт(в, п, куда = 0) {
  if (!в) return null;
  const пульты = [...(в.пульты ?? [""])];
  if (пульты.length < 2 || п < 0 || п >= пульты.length) return null;
  const принял = Math.min(Math.max(0, Number(куда) || 0), пульты.length - 1);
  const целевой = принял === п ? (п === 0 ? 1 : 0) : принял;

  const рычаги = (в.рычаги ?? []).map(р => {
    const был = Number(р.пульт) || 0;
    const стал = был === п ? целевой : был;
    return { ...р, пульт: стал > п ? стал - 1 : стал };   // номера пультов сдвинулись
  });
  пульты.splice(п, 1);
  return { ...в, пульты, рычаги };
}
