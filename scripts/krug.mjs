/**
 * Круглый стол для игр в кости: сукно посередине, места по кругу.
 *
 * Игра в кости — это стол, за которым сидят, а не таблица с фамилиями.
 * Поэтому все три игры рисуются одинаково: в центре сукно, куда летят кости,
 * вокруг места, и своё место у каждого внизу, ближе к себе, — как за настоящим
 * столом, где себя видишь с краю, а соперников напротив.
 *
 * Здесь только облик. Чей ход, что считается и что можно нажать, решает
 * сама игра и приносит сюда готовые куски разметки.
 */

import { Т } from "./yazyk.mjs";

const экранировать = s => foundry.utils.escapeHTML(String(s ?? ""));

/* ─────────────────────────────── кость ─────────────────────────────── */

/** Где на грани точки: клетки сетки 3×3, счёт слева направо и сверху вниз. */
const ТОЧКИ = {
  1: [5],
  2: [3, 7],
  3: [3, 5, 7],
  4: [1, 3, 7, 9],
  5: [1, 3, 5, 7, 9],
  6: [1, 3, 4, 6, 7, 9],
};

/**
 * Кость с точками.
 *
 * Значки ⚀–⚅ хороши в строке журнала, но на сукне они мелкие, а в части
 * шрифтов их нет вовсе. Точки рисуются сами и читаются через весь стол.
 */
export function грань(значение) {
  const точки = (ТОЧКИ[значение] ?? []).map(к =>
    `<i style="grid-area: ${Math.ceil(к / 3)} / ${((к - 1) % 3) + 1}"></i>`).join("");
  return `<span class="uo-gran" data-g="${значение}" aria-label="${значение}">${точки}</span>`;
}

/**
 * Многогранник с выпавшим числом: к4 треугольником, к8 ромбом и так далее.
 * Вид кубика читается по силуэту, а не по подписи мелким шрифтом.
 */
export const многогранник = (грань, значение) =>
  `<span class="uo-mnogogrannik" data-d="${грань}" title="${Т("к{грань}", { грань })}"><b>${значение ?? ""}</b></span>`;

/** Ряд маленьких костей — отложенное, оставленное, сыгранное. */
export const рядКостей = (значения, класс = "") =>
  `<span class="uo-ryad-kostej ${класс}">${значения.map(грань).join("")}</span>`;

/* ───────────────────────────── разброс ───────────────────────────── */

/** Детская, но устойчивая мешалка: те же кости ложатся так же при каждой перерисовке. */
function зерно(строка) {
  let h = 2166136261;
  for (const ч of строка) h = Math.imul(h ^ ч.codePointAt(0), 16777619);
  return () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    h ^= h >>> 16;
    return (h >>> 0) / 4294967296;
  };
}

/**
 * Как легла каждая кость: небольшой поворот и сдвиг.
 *
 * Ровный ряд на сукне выглядит кнопками, а не костями. Но и разбрасывать их
 * по-настоящему нельзя: при каждом ходе окно рисуется заново, и прыгающие
 * кости сбивают взгляд. Поэтому разброс считается от самого броска — пока
 * бросок тот же, кости лежат на месте.
 */
export function разброс(ключ, сколько) {
  const случай = зерно(ключ);
  return Array.from({ length: сколько }, () => ({
    поворот: Math.round((случай() - 0.5) * 50),
    x: Math.round((случай() - 0.5) * 14),
    y: Math.round((случай() - 0.5) * 18),
  }));
}

/* ───────────────────────────── места ───────────────────────────── */

/**
 * Где сидит место: угол по кругу и сдвиг от центра в долях стола.
 *
 * Своё место всегда внизу. Остальные идут по часовой стрелке, как если
 * смотреть на стол сверху: сосед слева сидит слева.
 */
export function посадка(сколько, своё = 0) {
  return Array.from({ length: сколько }, (_, i) => {
    const k = (i - своё + сколько) % сколько;
    const угол = (k / сколько) * 2 * Math.PI;
    return {
      x: -Math.sin(угол) * 41,          // доли меньшей стороны стола: круг остаётся кругом
      y: Math.cos(угол) * 41,
    };
  });
}

/** Чьё место у этого человека. Ведущий без места смотрит с первого. */
export function своёМесто(места, пользователь = game.user) {
  const i = места.findIndex(м => м.кто && м.кто === пользователь?.id);
  return i >= 0 ? i : 0;
}

/**
 * Карточка места.
 *
 * @param {object} о
 * @param {string} о.имя
 * @param {boolean} [о.бот]
 * @param {string} [о.счёт]       — справа от имени: очки, победы
 * @param {string} [о.низ]        — под именем: кости, ряд, сумма
 * @param {boolean} [о.ходит]
 * @param {boolean} [о.моё]
 * @param {string} [о.реплика]    — что место только что решило, облачком
 * @param {string} [о.класс]
 */
export function место(о) {
  const думает = о.ходит && о.бот && !о.реплика && !о.итог;
  return `
    <div class="uo-krug-mesto ${о.ходит ? "uo-hodit" : ""} ${о.моё ? "uo-moe" : ""} ${о.y < -10 ? "uo-sverhu" : ""} ${о.класс ?? ""}"
         style="--x: ${о.x.toFixed(2)}; --y: ${о.y.toFixed(2)}">
      ${о.реплика ? `<div class="uo-replika">${о.реплика}</div>` : ""}
      <div class="uo-krug-imya">
        <span class="uo-imya">${о.бот ? `<i class="fa-solid fa-robot" title="${Т("бот")}"></i> ` : ""}${экранировать(о.имя)}</span>
        ${о.счёт !== undefined ? `<span class="uo-ochki">${о.счёт}</span>` : ""}
      </div>
      ${о.низ ? `<div class="uo-krug-niz">${о.низ}</div>` : ""}
      ${о.ходит && о.моё && !о.итог ? `<div class="uo-tvoj-hod-metka">${Т("Ваш ход")}</div>` : ""}
      ${думает ? `<div class="uo-dumaet"><i></i><i></i><i></i></div>` : ""}
    </div>`;
}

/**
 * Стол целиком.
 *
 * @param {string[]} места   — готовые карточки
 * @param {string} сукно     — что лежит посередине
 */
export function стол(места, сукно, класс = "") {
  return `
    <div class="uo-krug ${класс}">
      <div class="uo-krug-sukno">${сукно}</div>
      <div class="uo-mesta">${места.join("")}</div>
    </div>`;
}

/**
 * Брошенные кости на сукне.
 *
 * @param {object} о
 * @param {number[]} о.кости
 * @param {string} о.ключ        — чем этот бросок отличается от прошлого
 * @param {boolean} о.летят      — бросок свежий: кости летят от места бросавшего
 * @param {{x:number,y:number}} [о.откуда]
 * @param {(i:number)=>string} [о.действие]  — data-атрибуты кнопки, если кость можно взять
 * @param {(i:number)=>string} [о.класс]
 * @param {(к:any)=>string} [о.лицо]       — как рисовать кость; по умолчанию к6 точками
 * @param {number} [о.летятС]              — летят только кости с этого номера: прежние уже лежат
 */
export function брошенные(о) {
  const лёг = разброс(о.ключ, о.кости.length);
  const откуда = о.откуда ?? { x: 0, y: 41 };
  return `
    <div class="uo-na-sukne" style="--ot-x: ${откуда.x.toFixed(2)}; --ot-y: ${откуда.y.toFixed(2)}">
      ${о.кости.map((к, i) => {
        const д = о.действие?.(i) ?? "";
        const летит = о.летят && i >= (о.летятС ?? 0);
        const стиль = `--r: ${лёг[i].поворот}deg; --dx: ${лёг[i].x}px; --dy: ${лёг[i].y}px; --zaderzhka: ${(i - (о.летятС ?? 0)) * 45}ms`;
        const класс = `uo-kost-sukno ${летит ? "uo-letit" : ""} ${о.класс?.(i) ?? ""}`;
        const лицо = о.лицо ? о.лицо(к) : грань(к);
        return д
          ? `<button type="button" class="${класс}" style="${стиль}" ${д}>${лицо}</button>`
          : `<span class="${класс}" style="${стиль}">${лицо}</span>`;
      }).join("")}
    </div>`;
}

/**
 * Свежий ли бросок. Окно помнит, что видело в прошлый раз, и пускает кости
 * в полёт только тогда, когда на сукне правда новое, а не когда соседу
 * понадобилось перерисовать выбор.
 */
export function свежийБросок(окно, ключ) {
  if (!ключ) { окно._прежнийБросок = null; return false; }
  const свежий = окно._прежнийБросок !== ключ;
  окно._прежнийБросок = ключ;
  return свежий;
}
