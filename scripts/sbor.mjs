/**
 * Между раундами и посреди партии: готовность и подсадка.
 *
 * Два обычая игорного стола, общих для всех игр в кости.
 *
 * **Перерыв.** Раунд кончился — стол не сметают сразу. Руки лежат, где лежали,
 * победитель виден, и следующий раунд начинается, когда все живые игроки
 * сказали «готов». Боты готовы всегда; ведущий может не ждать и начать сам.
 *
 * **Подсадка.** Кто-то подошёл к столу, когда партия уже идёт. Ведущий сажает
 * его — человека или бота — со своим счётом с нуля. Куда именно и с какого
 * момента он вступает, решает сама игра: в Кости садятся сразу, в раунд,
 * который уже разыгрывается, — нет.
 */

import { имяИгрока, объявить } from "./stol.mjs";
import { ХАРАКТЕРЫ } from "./kosti-bot.mjs";
import * as боты from "./boty.mjs";
import { актёрМеста, изменитьКошелёк, монетами } from "./stavki.mjs";
import { Т } from "./yazyk.mjs";

const { DialogV2 } = foundry.applications.api;
const экранировать = s => foundry.utils.escapeHTML(String(s ?? ""));

/* ─────────────────────────────── перерыв ─────────────────────────────── */

/** Перерыв между раундами: боты готовы сразу, люди — когда скажут. */
export const перерыв = (места, поля = {}) => ({
  ...поля,
  готовы: места.map((м, i) => (м.бот ? i : -1)).filter(i => i >= 0),
});

/** Все ли живые за столом сказали «готов». */
export const всеГотовы = стол =>
  !!стол.перерыв && стол.места.every((м, i) => м.бот || стол.перерыв.готовы.includes(i));

/** Есть ли за столом хоть один человек. Стол одних ботов ждать некого. */
export const естьЛюди = стол => стол.места.some(м => !м.бот);

/** Отметить место человека готовым. Вернёт новый перерыв или null, если отмечать некого. */
export function отметитьГотов(стол, пользователь) {
  if (!стол.перерыв) return null;
  const i = стол.места.findIndex(м => м.кто && м.кто === пользователь.id);
  if (i < 0 || стол.перерыв.готовы.includes(i)) return null;
  return { ...стол.перерыв, готовы: [...стол.перерыв.готовы, i] };
}

/** Место ушло из-за стола — номера правее съезжают и в списке готовых. */
export const сдвинутьГотовых = (перерыв, индекс) => перерыв && ({
  ...перерыв,
  готовы: перерыв.готовы.filter(i => i !== индекс).map(i => (i > индекс ? i - 1 : i)),
});

/** Сколько готово из скольких — только люди, ботов считать незачем. */
export function счётГотовых(стол) {
  const люди = стол.места.map((м, i) => (м.бот ? -1 : i)).filter(i => i >= 0);
  return { готово: люди.filter(i => стол.перерыв?.готовы.includes(i)).length, всего: люди.length };
}

/**
 * Что показать в перерыве: строка «готовы 1 из 3» и кнопка для своего места.
 * Ведущему — ещё «начать, не дожидаясь».
 */
export function готовность(стол, дальше) {
  const { готово, всего } = счётГотовых(стол);
  const моё = стол.места.findIndex(м => м.кто && м.кто === game.user.id);
  const уже = моё >= 0 && стол.перерыв.готовы.includes(моё);
  return {
    строка: `<span class="uo-gotovy">${Т("Готовы: {готово} из {всего}", { готово, всего })}</span>`,
    кнопки: `
      <div class="uo-knopki">
        ${моё >= 0
          ? `<button type="button" data-action="готов" ${уже ? "disabled" : `class="uo-zhdet"`}>${уже ? Т("Готов ✓") : дальше}</button>`
          : ""}
        ${game.user.isGM ? `<button type="button" data-action="начать">${Т("Начать, не дожидаясь")}</button>` : ""}
      </div>`,
  };
}

/** Метка на карточке места: этот уже готов. */
export const меткаГотов = (стол, i) =>
  (стол.перерыв && !стол.места[i]?.бот && стол.перерыв.готовы.includes(i)
    ? `<span class="uo-metka-gotov">${Т("готов")}</span>` : "");

/* ─────────────────────────────── подсадка ─────────────────────────────── */

/** Тёзок за столом быть не должно: по имени игроки зовут друг друга вслух. */
export function свободноеИмя(имя, места) {
  if (!места.some(м => м.имя === имя)) return имя;
  let n = 2;
  while (места.some(м => м.имя === `${имя} ${n}`)) n++;
  return `${имя} ${n}`;
}

/**
 * Ставка с подсевшего: банк растёт на одну ставку, с листа снимается,
 * если лист есть и монет хватает, — так же, как при посадке.
 */
export async function ставкаСНового(стол, индекс) {
  const ставка = стол.ставка ?? {};
  if (!ставка.сколько) return ставка;
  const актёр = ставка.слисты ? актёрМеста(стол.места[индекс]) : null;
  const снято = !!актёр && await изменитьКошелёк(актёр, ставка.монета, -ставка.сколько);
  return {
    ...ставка,
    банк: (ставка.банк ?? 0) + ставка.сколько,
    внесли: снято ? [...(ставка.внесли ?? []), индекс] : (ставка.внесли ?? []),
  };
}

/** Объявить о подсевших одной строкой в чат. */
export async function объявитьПодсадку(стол, имена, сразу) {
  const кто = имена.map(экранировать).join(", ");
  await объявить(сразу
    ? Т(`<p>За стол подсаживается: <strong>{кто}</strong>.</p>`, { кто })
    : Т(`<p>К столу подошёл: <strong>{кто}</strong> — сядет со следующего раунда.</p>`, { кто }),
  стол.название);
  if (стол.ставка?.сколько) {
    await объявить(Т(`<p>Ставка с каждого подсевшего, в банке теперь {банк}.</p>`,
      { банк: монетами(стол.ставка.банк, стол.ставка.монета) }), стол.название);
  }
}

/**
 * Кого ведущий подсаживает: люди, которых ещё нет за столом, соперники
 * из пула и безымянные боты.
 *
 * @param {object} стол
 * @param {string} [заметка] — когда новенький вступит в этой игре
 * @returns {Promise<{кто:string|null, имя:string, бот:object|null}[]>}
 */
export async function диалогПодсадки(стол, заметка = "") {
  if (!game.user.isGM) return [];
  const сидят = new Set([...стол.места, ...(стол.ждут ?? [])].map(м => м.кто).filter(Boolean));
  const заняты = new Set([...стол.места, ...(стол.ждут ?? [])].map(м => м.имя));

  const люди = game.users.filter(u => !сидят.has(u.id) && (u.active || !u.isGM)).map(u =>
    `<label class="uo-igrok"><input type="checkbox" name="игрок" value="${u.id}"> ${экранировать(u.name)}${
      u.isGM ? ` (${Т("ведущий")})` : ""}</label>`).join("");
  const пул = боты.пул();
  const изПула = пул.map((б, i) => (заняты.has(б.имя) ? "" : `
    <label class="uo-igrok"><input type="checkbox" name="изПула" value="${i}">
      ${экранировать(б.имя)} <span class="uo-podskazka">— ${экранировать(боты.подписьХарактера(б.характер))}</span></label>`)).join("");

  let выбор = [];
  await DialogV2.wait({
    window: { title: Т("Подсадить за стол"), icon: "fa-solid fa-chair" },
    position: { width: 440 },
    content: `
      <div class="uo-forma">
        ${заметка ? `<p class="uo-podskazka">${заметка}</p>` : ""}
        <fieldset>
          <legend>${Т("Игроки")}</legend>
          ${люди || `<p class="uo-podskazka">${Т("Все, кого можно посадить, уже за столом.")}</p>`}
        </fieldset>
        <fieldset>
          <legend>${Т("Соперники-боты")}</legend>
          ${изПула}
          <label>${Т("Ещё безымянных")} <input type="number" name="ботов" value="0" min="0" max="4" step="1"></label>
          <label>${Т("Их нрав")} <select name="характер">${боты.выборХарактера()}</select></label>
        </fieldset>
        ${стол.ставка?.сколько ? `<p class="uo-podskazka">${Т("С каждого подсевшего берётся та же ставка: {ставка}.", {
          ставка: монетами(стол.ставка.сколько, стол.ставка.монета) })}</p>` : ""}
      </div>`,
    buttons: [
      {
        action: "подсадить", label: Т("Подсадить"), default: true,
        callback: (event, кнопка, диалог) => {
          const э = диалог.element;
          const уже = [...стол.места, ...(стол.ждут ?? [])];
          for (const в of э.querySelectorAll(`[name="игрок"]:checked`)) {
            выбор.push({ кто: в.value, имя: свободноеИмя(имяИгрока(в.value), [...уже, ...выбор]), бот: null });
          }
          for (const в of э.querySelectorAll(`[name="изПула"]:checked`)) {
            const б = пул[Number(в.value)];
            if (б) выбор.push({ кто: null, имя: свободноеИмя(б.имя, [...уже, ...выбор]), бот: { характер: б.характер } });
          }
          const сколько = Math.max(0, Math.min(4, Number(э.querySelector(`[name="ботов"]`)?.value) || 0));
          const характер = э.querySelector(`[name="характер"]`)?.value;
          for (let i = 0; i < сколько; i++) {
            const х = ХАРАКТЕРЫ[характер] ? характер : Object.keys(ХАРАКТЕРЫ)[0];
            выбор.push({ кто: null, имя: свободноеИмя(Т(ХАРАКТЕРЫ[х].имя), [...уже, ...выбор]), бот: { характер: х } });
          }
        },
      },
      { action: "отмена", label: Т("Отмена") },
    ],
  });
  return выбор;
}
