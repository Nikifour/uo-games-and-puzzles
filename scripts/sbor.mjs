/** Тёзок за столом быть не должно: по имени игроки зовут друг друга вслух. */
export function свободноеИмя(имя, места) {
  if (!места.some(м => м.имя === имя)) return имя;
  let n = 2;
  while (места.some(м => м.имя === `${имя} ${n}`)) n++;
  return `${имя} ${n}`;
}

/* ─────────────────────────── жетоны со сцены ─────────────────────────── */
/*
 * За стол садятся и жетоны: завсегдатаи, что стоят на сцене трактира, или
 * герои игроков. У жетона есть лист — ставка снимается с него, выигрыш
 * ложится туда же, — а на месте за столом виден его портрет.
 *
 * Кто играет за жетон, ведущий решает строкой у жетона: игрок-владелец
 * (если у листа он есть), сам ведущий или бот выбранного нрава. Человек
 * сидит за столом одним местом: его жетон и он сам из списка игроков —
 * одно и то же место.
 */

/** Игрок, который ведёт этот лист: чей это персонаж, иначе любой владелец, лучше тот, кто в игре. */
function владелецЛиста(лист) {
  const владельцы = game.users.filter(u => !u.isGM && лист.testUserPermission(u, "OWNER"));
  return владельцы.find(u => u.character?.id === лист.id)
    ?? владельцы.find(u => u.active) ?? владельцы[0] ?? null;
}

/** Портрет места. Живой жетон (видео) в карточке не нарисовать — тогда портрет листа. */
const образЖетона = (жетон, лист) => {
  const src = жетон.texture?.src ?? "";
  return src && !/\.(webm|mp4|m4v|ogv)$/i.test(src) ? src : (лист.img ?? null);
};

/**
 * Жетоны текущей сцены, у которых есть лист. Связанные с одним листом —
 * одной строкой: это один и тот же человек, сколько бы его жетонов ни стояло.
 */
export function жетоныСцены() {
  const сцена = canvas?.scene;
  if (!сцена) return [];
  const выделены = new Set((canvas.tokens?.controlled ?? []).map(т => т.document?.id));
  const видели = new Set();
  const список = [];
  for (const жетон of сцена.tokens) {
    const лист = жетон.actor;
    if (!лист) continue;
    const ссылка = жетон.actorLink ? лист.uuid : жетон.uuid;
    if (видели.has(ссылка)) continue;
    видели.add(ссылка);
    список.push({
      ссылка,
      имя: жетон.name || лист.name,
      образ: образЖетона(жетон, лист),
      игрок: владелецЛиста(лист),
      выделен: выделены.has(жетон.id),
    });
  }
  return список.sort((а, б) => (б.выделен - а.выделен) || а.имя.localeCompare(б.имя, game.i18n?.lang));
}

/** Кто играет за жетон: значения строки выбора. */
const ИГРОК = "igrok";
const ВЕДУЩИЙ = "vedushchij";
const БОТ = "bot:";

/** Кто играет за жетон, если ведущий не выбирал: игрок, иначе бот, иначе сам ведущий. */
const кемПоУмолчанию = (ж, ботРазрешён) =>
  (ж.игрок ? ИГРОК : ботРазрешён ? БОТ + ХАРАКТЕР_ПО_УМОЛЧАНИЮ : ВЕДУЩИЙ);

/** Выбор «кто играет» у жетона: игрок-владелец, ведущий, боты по нравам. */
function выборИгрокаЖетона(ж, ботРазрешён) {
  const выбран = кемПоУмолчанию(ж, ботРазрешён);
  const пункт = (значение, подпись) =>
    `<option value="${значение}" ${значение === выбран ? "selected" : ""}>${подпись}</option>`;
  return [
    ж.игрок ? пункт(ИГРОК, Т("Играет {имя}", { имя: экранировать(ж.игрок.name) })) : "",
    пункт(ВЕДУЩИЙ, Т("Играет ведущий")),
    ...(ботРазрешён ? Object.entries(ХАРАКТЕРЫ)
      .map(([ключ, х]) => пункт(БОТ + ключ, Т("Бот: {нрав}", { нрав: экранировать(Т(х.имя)) }))) : []),
  ].join("");
}

/**
 * Раздел «Жетоны со сцены» для диалога посадки. Выделенные на сцене
 * отмечены сразу: ведущий обвёл компанию у стойки — она и садится.
 *
 * @param {object} о
 * @param {boolean} о.ботРазрешён
 * @param {Set<string>} [о.занятые]  — ссылки жетонов, что уже за столом
 */
export function разметкаЖетонов({ ботРазрешён, занятые = new Set() }) {
  const жетоны = жетоныСцены().filter(ж => !занятые.has(ж.ссылка));
  const строки = жетоны.map(ж => `
      <div class="uo-zheton">
        <label class="uo-igrok">
          <input type="checkbox" name="жетон" value="${экранировать(ж.ссылка)}" ${ж.выделен ? "checked" : ""}>
          ${ж.образ ? `<img src="${экранировать(ж.образ)}" alt="">` : ""}
          ${экранировать(ж.имя)}
        </label>
        <select name="заЖетон" data-zheton="${экранировать(ж.ссылка)}">${выборИгрокаЖетона(ж, ботРазрешён)}</select>
      </div>`).join("");
  return `
    <fieldset>
      <legend>${Т("Жетоны со сцены")}</legend>
      ${строки || `<p class="uo-podskazka">${Т("На сцене нет жетонов с листом.")}</p>`}
      ${строки ? `<p class="uo-podskazka">${Т("Выделенные на сцене уже отмечены. Справа — кто за жетон играет: его игрок, вы сами или бот. Ставка снимается с листа жетона.")}</p>` : ""}
    </fieldset>`;
}

/**
 * Места из отмеченных жетонов.
 *
 * @param {HTMLElement} э         — корень диалога
 * @param {object[]} уже          — кто уже сидит: тёзок и двойных мест быть не должно
 * @param {boolean} ботРазрешён
 */
export function местаИзЖетонов(э, уже, ботРазрешён) {
  const поСсылке = new Map(жетоныСцены().map(ж => [ж.ссылка, ж]));
  const места = [];
  for (const в of э.querySelectorAll(`[name="жетон"]:checked`)) {
    const ж = поСсылке.get(в.value);
    if (!ж || !листПоСсылке(ж.ссылка)) continue;
    const сидят = [...уже, ...места];
    let кем = э.querySelector(`[name="заЖетон"][data-zheton="${в.value}"]`)?.value ?? кемПоУмолчанию(ж, ботРазрешён);
    if (кем === ИГРОК && !ж.игрок) кем = ВЕДУЩИЙ;
    if (кем.startsWith(БОТ) && !ботРазрешён) кем = ВЕДУЩИЙ;
    if (кем === ИГРОК && сидят.some(м => м.кто === ж.игрок.id)) continue;   // у человека одно место
    const нрав = кем.slice(БОТ.length);
    места.push({
      кто: кем === ИГРОК ? ж.игрок.id : null,
      бот: кем.startsWith(БОТ) ? { характер: ХАРАКТЕРЫ[нрав] ? нрав : ХАРАКТЕР_ПО_УМОЛЧАНИЮ } : null,
      имя: свободноеИмя(ж.имя, сидят),
      актёр: ж.ссылка,
      образ: ж.образ,
    });
  }
  return места;
}

