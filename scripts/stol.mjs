// Подпись по умолчанию переводится в миг объявления: параметр по умолчанию считается при вызове.
export async function объявить(содержимое, alias = Т("Загадка")) {
  if (!game.user.isGM) return;
  await ChatMessage.create({ content: содержимое, speaker: { alias } });
}

/**
 * Событие наружу: за него цепляются тайлы Monk's Active Tiles и макросы.
 *
 * Имя даётся дважды — по-русски и латиницей. Русское читается в своих
 * макросах, латинское спокойно вписывается в чужие поля, где кириллица
 * выглядит подозрительно.
 */
const ЛАТИНИЦЕЙ = { решено: "solved" };

export function событие(имя, стол) {
  Hooks.callAll(`${MODULE_ID}.${имя}`, стол);
  const латинское = ЛАТИНИЦЕЙ[имя];
  if (латинское) Hooks.callAll(`${MODULE_ID}.${латинское}`, стол);
}

export async function запуститьМакрос(имя, стол) {
  if (!имя) return;
  const макрос = game.macros.getName(имя);
  if (!макрос) return ui.notifications.warn(Т("Макрос «{имя}» не найден", { имя }));
  try {
    await макрос.execute({ стол });
  } catch (e) {
    console.error(`${MODULE_ID} | макрос «${имя}» упал`, e);
  }
}

