/**
 * UO · Игры и загадки — общий стол
 *
 * Одно устройство на все загадки и игры семьи. Отвечает за три вещи:
 * состояние (что лежит на столе), права (кому можно ходить) и связь
 * (как ход игрока доходит до ведущего, а картинка — до всех разом).
 *
 * Главное правило: **считает всегда ведущий.** Игрок шлёт намерение
 * «покрутить диск», «проверить» — применяет его клиент ведущего, он же
 * держит ответ. Иначе разгадка уехала бы в браузер игрока, а там её читают
 * через F12, и загадка перестаёт быть загадкой.
 *
 * Второе правило: в базу мира пишутся только события, а не каждое движение
 * пальца. Диски крутятся по сокету, а запись случается на проверке, разгадке
 * и закрытии — иначе от одной партии база пухнет.
 */

import { Т, М } from "./yazyk.mjs";

export const MODULE_ID = "uo-igry";
export const КАНАЛ = `module.${MODULE_ID}`;

/**
 * Оформление, общее для всех загадок: механика от облика отделена, и один
 * и тот же замок или мозаика выглядят храмовой печатью либо наростом тьмы
 * без единой новой строки кода.
 */
export const ТЕМЫ = {
  kamen: М("Камень"),
  orden: М("Цитадель"),
  bezdna: М("Бездна"),
};

/** Виды загадок и игр: тип -> правила. Заполняют файлы вроде zamok.mjs. */
export const ВИДЫ = new Map();

/* ────────────────────────── состояние ────────────────────────── */

export const всеСтолы = () => foundry.utils.deepClone(game.settings.get(MODULE_ID, "stoly") ?? {});
export const столПоId = id => всеСтолы()[id] ?? null;

/* ─────────────────────── выкладка в памяти ─────────────────────── */
/*
 * Окно настроек показывает загадку глазами игрока, пока ведущий её только
 * настраивает. Для этого загадку выкладывают её же выкладкой, но стол не
 * уходит в мир, а перехватывается здесь. Перехват касается только нового
 * стола — того, которого в мире ещё нет: ходы игроков по уже выложенным
 * столам, если придутся на эти миллисекунды, пишутся как обычно.
 */
let перехват = null;

export async function составить(тип, конфиг) {
  const вид = ВИДЫ.get(тип);
  if (!вид?.выложить) return { стол: null, тайна: null, заметки: [] };

  // Предупреждения выкладки («код пустой») — в окно настроек, а не всплывающими.
  const заметки = [];
  const уведомления = ui.notifications;
  const ловить = уровень => сообщение => { заметки.push({ уровень, текст: String(сообщение?.message ?? сообщение ?? "") }); return null; };
  const было = { warn: уведомления.warn, error: уведомления.error, info: уведомления.info };
  уведомления.warn = ловить("warn");
  уведомления.error = ловить("error");
  уведомления.info = ловить("info");

  перехват = { стол: null, тайна: null };
  let итог;
  try {
    await вид.выложить(foundry.utils.deepClone(конфиг));
  } catch (e) {
    заметки.push({ уровень: "error", текст: e.message });
  } finally {
    итог = перехват;
    перехват = null;
    Object.assign(уведомления, было);
  }
  return { стол: итог.стол, тайна: итог.тайна, заметки };
}

const новыйСтол = id => перехват && !(id in (game.settings.get(MODULE_ID, "stoly") ?? {}));

/** Записать стол в мир. Мировые настройки пишет только ведущий — так задумано. */
export async function записать(стол) {
  if (!game.user.isGM) return;
  if (новыйСтол(стол.id)) { перехват.стол = foundry.utils.deepClone(стол); return; }
  живые.delete(стол.id);                  // записанное больше не «на весу»
  const все = всеСтолы();
  все[стол.id] = стол;
  await game.settings.set(MODULE_ID, "stoly", все);
}

export async function убрать(id) {
  if (!game.user.isGM) return;
  if (перехват) return;                    // выкладка в памяти ничего со стола не убирает
  живые.delete(id);
  const все = всеСтолы();
  delete все[id];
  await game.settings.set(MODULE_ID, "stoly", все);
  await тайнуЗабыть(id);
}

/* ─────────────────────────── тайны ─────────────────────────── */
/*
 * Ответ живёт в клиентской настройке ведущего: она лежит в его браузере
 * и не уезжает ни к игрокам, ни в базу мира. Цена этому — ответ знает тот
 * ведущий, который загадку выложил; другому придётся засчитать вручную
 * или выложить заново. Для стола на одного ведущего это верный размен.
 */

const тайны = () => game.settings.get(MODULE_ID, "tajny") ?? {};
export const тайна = id => тайны()[id] ?? null;

export async function тайнуЗапомнить(id, значение) {
  if (новыйСтол(id)) { перехват.тайна = foundry.utils.deepClone(значение); return; }
  await game.settings.set(MODULE_ID, "tajny", { ...тайны(), [id]: значение });
}

export async function тайнуЗабыть(id) {
  const все = { ...тайны() };
  delete все[id];
  await game.settings.set(MODULE_ID, "tajny", все);
}

/* ──────────────────────── кто считает ──────────────────────── */

export const ведущийЗдесь = () => game.users.activeGM === game.user;

/* ─────────────────── живое поверх записанного ─────────────────── */
/*
 * Диски крутятся чаще, чем стоит писать в базу, поэтому текущее положение
 * живёт накладкой в памяти каждого клиента и ложится поверх записанного.
 * Опоздавший увидит положение на момент последней записи — не беда,
 * следующий же поворот его догонит.
 */

const живые = new Map();

export function живое(id, поле) {
  живые.set(id, { ...(живые.get(id) ?? {}), ...поле });
  освежить();
}

export const собрать = стол => ({ ...стол, ...(живые.get(стол.id) ?? {}) });

/* ─────────────────────────── связь ─────────────────────────── */

/** Игрок просит ход. Если мы и есть ведущий — считаем сами, иначе шлём ему. */
export function просить(запрос) {
  const полный = { ...запрос, кто: game.user.id };
  if (ведущийЗдесь()) return применить(полный);
  if (!game.users.activeGM) {
    ui.notifications.warn(Т("Ведущего нет за столом — ход не принят."));
    return;
  }
  game.socket.emit(КАНАЛ, { дело: "ход", запрос: полный });
}

/** Ведущий двинул что-то лёгкое: показываем всем, в базу не пишем. */
export function разослать(id, поле) {
  game.socket.emit(КАНАЛ, { дело: "живое", id, поле });
  живое(id, поле);
}

function применить(запрос) {
  const стол = столПоId(запрос.id);
  if (!стол) return;
  ВИДЫ.get(стол.тип)?.ход?.(собрать(стол), запрос);
}

export function принять(данные) {
  if (данные?.дело === "ход") {
    if (ведущийЗдесь()) применить(данные.запрос);
    return;
  }
  if (данные?.дело === "живое") { живое(данные.id, данные.поле); return; }

  // Ведущий вернул окно тем, кто его закрыл.
  if (данные?.дело === "вернуть") { скрытыеУМеня.delete(данные.id); освежить(); return; }

  // Словечко одному человеку. Сервер доставляет такое только адресату —
  // остальным за столом слышать незачем.
  if (данные?.дело === "шёпот") { ui.notifications.warn(данные.текст); return; }

  // Личные сведения по игре: то, что знает один игрок и не знают прочие.
  if (данные?.дело === "личное") {
    ВИДЫ.get(данные.тип)?.личное?.(данные.что);
    освежить();
  }
}

/**
 * Письмо одному человеку.
 *
 * Сервер Foundry рассылает сообщения модуля всем, **если** не назвать
 * получателей: тогда доставка идёт только им. Это единственный способ дать
 * игроку знать то, чего не знает сосед, — подглядеть через F12 не выйдет,
 * потому что чужому клиенту сообщение попросту не отправят.
 */
export function личноеПисьмо(комуId, тип, что) {
  if (!комуId) return;
  if (комуId === game.user.id) {
    ВИДЫ.get(тип)?.личное?.(что);
    освежить();
    return;
  }
  game.socket.emit(КАНАЛ, { дело: "личное", тип, что }, { recipients: [комуId] });
}

/* ─────────────────────────── таймер ─────────────────────────── */
/*
 * Загадка на время. Срок лежит на столе как миг окончания по часам сервера
 * Foundry (`game.time.serverTime`): часы у игроков врут по-разному, а сервер
 * у всех один. Отсчёт на экране — дело каждого клиента, а вот «время вышло»
 * решает только ведущий: он и объявляет, и клинит механизм.
 */

export const сейчас = () => game.time?.serverTime ?? Date.now();

/** Поле `таймер` для нового стола: минуты из диалога, 0 — без таймера. */
export function завестиТаймер(минут) {
  const мс = Math.round(Math.max(0, Number(минут) || 0) * 60_000);
  return мс ? { мс, до: сейчас() + мс } : null;
}

/** Тот же таймер, запущенный заново — для «Сбросить». */
export const перезавести = таймер => (таймер?.мс ? { мс: таймер.мс, до: сейчас() + таймер.мс } : null);

/*
 * Часы стоят — остаток лежит прямо в таймере (`пауза`), и срок `до` на это
 * время теряет силу. Так пауза переживает и перезаход в мир, и закрытое
 * окно: она на столе, а не в чьём-то браузере.
 */
export const наПаузе = стол => Number.isFinite(стол?.таймер?.пауза);

export const осталось = стол => (наПаузе(стол)
  ? Math.max(0, стол.таймер.пауза)
  : (стол?.таймер?.до ? Math.max(0, стол.таймер.до - сейчас()) : null));

/** Остановить часы или пустить их снова. */
export async function переключитьПаузу(id) {
  if (!game.user.isGM) return;
  const стол = столПоId(id);
  if (!стол?.таймер) return;
  const таймер = наПаузе(стол)
    ? { мс: стол.таймер.мс, до: сейчас() + Math.max(0, стол.таймер.пауза) }
    : { мс: стол.таймер.мс, до: стол.таймер.до, пауза: осталось(стол) };
  await записать({ ...стол, таймер });
}

/**
 * Прибавить или отнять время.
 *
 * Стол на паузе — правим остаток, идущий — двигаем срок. Меньше нуля не
 * уходим: отнятое до дна значит «время вышло», и пусть это решит ведущий
 * отдельно, а не случайный лишний щелчок.
 *
 * Считаем в секундах: на кнопке «−1» не видно, минута это или секунда,
 * а «−30 с» читается само.
 */
export async function подкрутитьВремя(id, секунд) {
  if (!game.user.isGM) return;
  const стол = столПоId(id);
  if (!стол?.таймер) return;
  const дельта = Math.round(Number(секунд) * 1000) || 0;
  const таймер = наПаузе(стол)
    ? { ...стол.таймер, пауза: Math.max(0, стол.таймер.пауза + дельта) }
    : { ...стол.таймер, до: Math.max(сейчас(), стол.таймер.до + дельта) };
  await записать({ ...стол, таймер });
}

const мм_сс = мс => {
  const с = Math.ceil(мс / 1000);
  return `${Math.floor(с / 60)}:${String(с % 60).padStart(2, "0")}`;
};

/** Строка с часами для окна; обновляет её завестиЧасы, без перерисовки окна. */
export function часы(стол) {
  const ост = осталось(стол);
  if (ост === null) return "";
  const стоят = стол.завершён || наПаузе(стол) ? " uo-stojat" : "";
  const значок = наПаузе(стол) ? "⏸" : "⏳";
  return `<span class="uo-tajmer${ост <= 30_000 ? " uo-malo" : ""}${стоят}" data-do="${стол.таймер.до}">${значок} ${мм_сс(ост)}</span>`;
}

/**
 * Отдел времени у ведущего — один на все столы с таймером.
 *
 * Стоит отдельной строкой, а не в общем ряду кнопок: там уже теснятся
 * «Засчитать», «Сбросить» и «Убрать со стола», и на узком окне ряд лопался.
 * Окну остаётся завести действие «время».
 */
export function кнопкиВремени(стол) {
  if (!game.user.isGM || !стол?.таймер) return "";
  const идут = !наПаузе(стол);
  return `
    <div class="uo-gm-vremya">
      <span class="uo-gm-podpis">${Т("Время")}</span>
      <button type="button" data-action="время" data-delo="-30"
        data-tooltip="${Т("Отнять полминуты")}">−30 ${Т("с")}</button>
      <button type="button" data-action="время" data-delo="пауза"
        data-tooltip="${идут ? Т("Остановить часы у всех") : Т("Пустить часы снова")}">${
        идут ? `<i class="fa-solid fa-pause"></i> ${Т("Пауза")}` : `<i class="fa-solid fa-play"></i> ${Т("Пуск")}`}</button>
      <button type="button" data-action="время" data-delo="+30"
        data-tooltip="${Т("Прибавить полминуты")}">+30 ${Т("с")}</button>
    </div>`;
}

/** Что делать по нажатию на эти кнопки: зовут окна из своего действия «время». */
export async function распорядитьсяВременем(id, дело) {
  if (дело === "пауза") return переключитьПаузу(id);
  return подкрутитьВремя(id, Number(дело));
}

/** Запустить отсчёт в открытом окне. Окно зовёт это в _onRender, а останавливает в _onClose. */
export function завестиЧасы(окно) {
  остановитьЧасы(окно);
  окно.часыТик = setInterval(() => {
    const м = окно.element?.querySelector?.(".uo-tajmer");
    if (!м || м.classList.contains("uo-stojat")) return;
    const ост = Math.max(0, Number(м.dataset.do) - сейчас());
    м.textContent = `⏳ ${мм_сс(ост)}`;
    м.classList.toggle("uo-malo", ост <= 30_000);
  }, 250);
}

export function остановитьЧасы(окно) {
  if (окно.часыТик) clearInterval(окно.часыТик);
  окно.часыТик = null;
}

/**
 * Ведущий следит за сроками всех столов, открыты окна или нет: загадку могли
 * спрятать, а время всё равно идёт. Истёкшее отдаётся правилам вида —
 * `времяВышло(стол)`; тот решает, что это значит для его механизма.
 */
const ужеИстекли = new Set();
export function следитьЗаВременем() {
  setInterval(() => {
    if (!ведущийЗдесь()) return;
    for (const сырой of Object.values(всеСтолы())) {
      // Часы стоят — срок не наступает: пауза для того и нужна.
      if (!сырой.таймер?.до || сырой.завершён || наПаузе(сырой)) { ужеИстекли.delete(сырой.id); continue; }
      if (сырой.таймер.до > сейчас() || ужеИстекли.has(сырой.id)) continue;
      ужеИстекли.add(сырой.id);
      ВИДЫ.get(сырой.тип)?.времяВышло?.(собрать(сырой));
    }
  }, 1000);
}

/* ─────────────────────────── окна ─────────────────────────── */

const окна = new Map();

/*
 * Крестик у игрока закрывает окно только ему: чужой стол ему не принадлежит.
 * Чтобы закрытое не выскакивало обратно от первого же поворота диска, помним
 * закрытое локально — и забываем, когда ведущий покажет загадку заново.
 */
const скрытыеУМеня = new Set();
const прежнийПоказан = new Map();

export const спрятатьУСебя = id => { скрытыеУМеня.add(id); };

/**
 * Игрок закрыл окно крестиком, а загадка на столе и открыта у прочих.
 *
 * Прежде вернуть его можно было только через «Спрятать» и снова «Показать» —
 * и тогда окно на миг закрывалось у всех, кто ничего не закрывал. Здесь
 * ведущий просто просит клиентов забыть их «спасибо, не надо»: у кого окно
 * открыто, тот лишь перерисует его, у кого закрыто — увидит снова.
 */
export function вернутьОкно(id) {
  if (!game.user.isGM) return;
  game.socket.emit(КАНАЛ, { дело: "вернуть", id });
  скрытыеУМеня.delete(id);
  освежить();
}

/**
 * Второе окно не должно лечь ровно на первое.
 *
 * Foundry ставит окна по середине, и два стола сливаются в один — нижнего
 * попросту не видно. Раскладываем лесенкой; первое остаётся там, где Foundry
 * его и задумала.
 */
function лесенка() {
  const n = окна.size;
  return n ? { left: 140 + n * 34, top: 110 + n * 34 } : {};
}

/** Свести окна с тем, что лежит на столе: чего нет — закрыть, что есть — освежить. */
export function освежить() {
  const все = всеСтолы();

  for (const [id, сырой] of Object.entries(все)) {
    const вид = ВИДЫ.get(сырой.тип);
    if (!вид?.Окно) continue;

    const стол = собрать(сырой);

    // Ведущий показал загадку заново — снимаем своё локальное «спасибо, не надо».
    if (прежнийПоказан.get(id) === false && стол.показан) скрытыеУМеня.delete(id);
    прежнийПоказан.set(id, стол.показан);
    if (скрытыеУМеня.has(id)) { закрытьОкно(id); continue; }

    // Завершённое само не всплывает. Окно, открытое сейчас, доживёт до конца
    // сцены — пусть все увидят, что замок поддался. Но при следующем входе
    // в мир разгаданное вчера не полезет из-под новой загадки.
    const ужеОткрыто = окна.has(id);
    if (!стол.показан || (стол.завершён && !ужеОткрыто)) { закрытьОкно(id); continue; }

    let окно = окна.get(id);
    if (!окно) {
      окно = new вид.Окно({ id: `${MODULE_ID}-${id}`, стол, position: лесенка() });
      окна.set(id, окно);
    }
    окно.стол = стол;
    окно.render({ force: true });
  }

  for (const id of [...окна.keys()]) if (!все[id]) закрытьОкно(id);
}

/** Закрыть окно самим: пометка нужна, чтобы окно не приняло это за волю человека. */
export function закрытьОкно(id) {
  const окно = окна.get(id);
  окна.delete(id);
  if (!окно) return;
  окно.закрываемСами = true;
  окно.close();
}

export const забытьОкно = id => окна.delete(id);

/** Спрятать загадку у всех, не убирая со стола: её можно показать снова. */
export async function спрятать(id) {
  if (!game.user.isGM) return;
  const стол = столПоId(id);
  if (!стол || !стол.показан) return;
  await записать({ ...стол, показан: false });
}

export async function показать(id) {
  if (!game.user.isGM) return;
  const стол = столПоId(id);
  if (!стол) return;
  await записать({ ...стол, показан: true });
}

