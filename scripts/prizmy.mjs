/** Чистые цвета по порядку граней разделителя. */
const ЧИСТЫЕ = [1, 2, 4];

/**
 * Куда выходит чистый цвет из разделителя, повёрнутого на `поворот` четвертей:
 * красный — в сторону поворота, зелёный — на следующую грань по часовой,
 * синий — на третью; четвёртая грань глухая.
 */
export const выходРазделителя = (поворот, и) => (Number(поворот) + и) % 4;

/* ─────────────────────────── палитра зала ─────────────────────────── */
/*
 * Как цвета смешиваются и раскладываются, решает палитра зала. Обычная —
 * свет: красный, зелёный и синий, сложение — «или» по битам, разделитель
 * раскладывает по битам же. Ведущий может завести свою (`зал.палитра`):
 * цвета с именами и красками, правила смешения «оранжевый + зелёный =
 * синий» и распада «синий → оранжевый, зелёный». Смеси без правила нет —
 * в смесителе такой свет гаснет. Цвет без распада проходит разделитель
 * через первую грань. Порядок цветов в распаде — порядок граней.
 */

const ОБЫЧНАЯ = {
  своя: false,
  смешать: список => (список.length ? список.reduce((с, ц) => с | ц, 0) : null),
  разложить: цвет => ЧИСТЫЕ.map((ц, и) => ((цвет & ц) ? { цвет: ц, грань: и } : null)).filter(Boolean),
  имя: маска => имяЦвета(маска),
  краска: маска => краска(маска),
  грани: () => ЧИСТЫЕ.map(краска),
  равны: (а, б) => а === б,
};

const ключСмеси = список => [...new Set(список.map(String))].sort().join("+");

export function палитраЗала(зал) {
  const п = зал?.палитра;
  if (!п?.цвета?.length) return ОБЫЧНАЯ;
  const цвета = new Map(п.цвета.map(ц => [String(ц.id), ц]));
  const смешения = new Map((п.смешения ?? []).filter(с => с.из?.length).map(с => [ключСмеси(с.из), String(с.в)]));
  const распады = new Map((п.распады ?? []).filter(р => р.в?.length).map(р => [String(р.из), р.в.map(String)]));
  return {
    своя: true,
    смешать: список => {
      const все = [...new Set(список.map(String))];
      if (!все.length) return null;
      return все.length === 1 ? все[0] : (смешения.get(ключСмеси(все)) ?? null);
    },
    разложить: цвет => (распады.get(String(цвет)) ?? [String(цвет)]).map((ц, и) => ({ цвет: ц, грань: и })),
    имя: цвет => цвета.get(String(цвет))?.имя ?? Т("тьма"),
    краска: цвет => цвета.get(String(цвет))?.краска ?? "#3a3a3a",
    // Грани разделителя на поле — красками первого распада, если он есть.
    грани: () => [...(распады.values().next().value ?? [])].map(ц => цвета.get(ц)?.краска ?? "#aaa"),
    равны: (а, б) => а !== null && а !== undefined && String(а) === String(б),
  };
}

const ШАГИ = [[1, 0], [0, 1], [-1, 0], [0, -1]];
const КОСАЯ = { "/": [3, 2, 1, 0], "\\": [1, 0, 3, 2] };
const наизнанку = куда => (куда + 2) % 4;

/**
 * Пустить все лучи и посмотреть, что куда пришло.
 *
 * Волнами: сперва идут лучи от источников, потом — от смесителей, которым
 * что-то принесли, и так пока свет не перестанет меняться. Волн немного,
 * иначе кольцо из зеркал крутило бы луч вечно.
 */
export function провести(зал) {
  const { ширина, высота, зеркала = {}, смесители = {}, приёмники = {}, разделители = {} } = зал;
  const пал = палитраЗала(зал);
  // Каждая клетка копит, что через неё прошло; смешивает палитра.
  const вРазделитель = new Map();  // клетка -> что в разделитель пришло
  const разослано = new Map();     // клетка -> что он уже разложил
  const свет = new Map();          // клетка -> какие цвета через неё прошли
  const вСмеситель = new Map();    // клетка -> что в неё пришло
  const испущено = new Map();      // клетка -> что она уже выпустила
  const приход = new Map();        // клетка приёмника -> что дошло

  const добавить = (карта, клетка, цвет) => {
    const было = карта.get(клетка);
    if (было) { if (!было.some(ц => String(ц) === String(цвет))) было.push(цвет); } else карта.set(клетка, [цвет]);
  };
  const подсветить = (клетка, цвет) => добавить(свет, клетка, цвет);

  const пустить = ({ x, y, куда, цвет, откуда }) => {
    let [сx, сy] = [x, y];
    for (let шаг = 0; шаг < ширина * высота * 4; шаг++) {
      if (сx < 0 || сy < 0 || сx >= ширина || сy >= высота) return;
      const клетка = сy * ширина + сx;

      if (клетка !== откуда && смесители[клетка] !== undefined) {
        добавить(вСмеситель, клетка, цвет);
        return;
      }
      if (клетка !== откуда && разделители[клетка] !== undefined) {
        добавить(вРазделитель, клетка, цвет);
        return;
      }
      if (приёмники[клетка] !== undefined) {
        добавить(приход, клетка, цвет);
        подсветить(клетка, цвет);
        return;
      }

      подсветить(клетка, цвет);
      const зеркало = зеркала[клетка];
      if (зеркало) куда = КОСАЯ[зеркало][куда];
      сx += ШАГИ[куда][0];
      сy += ШАГИ[куда][1];
    }
  };

  let волна = (зал.источники ?? []).map(и => ({ ...и, откуда: -1 }));
  for (let н = 0; н < 8 && волна.length; н++) {
    for (const луч of волна) пустить(луч);

    волна = [];
    for (const [клетка, пришло] of вСмеситель) {
      const цвет = пал.смешать(пришло);
      const отпечаток = String(цвет);
      if (испущено.get(клетка) === отпечаток) continue;
      испущено.set(клетка, отпечаток);
      if (цвет === null) continue;          // смеси без правила нет — свет гаснет
      волна.push({
        x: клетка % ширина,
        y: Math.floor(клетка / ширина),
        куда: смесители[клетка],
        цвет,
        откуда: клетка,
      });
    }
    // Разделитель: каждая часть распада — через свою грань.
    for (const [клетка, пришло] of вРазделитель) {
      const отпечаток = ключСмеси(пришло);
      if (разослано.get(клетка) === отпечаток) continue;
      разослано.set(клетка, отпечаток);
      for (const ц of пришло) {
        for (const { цвет, грань } of пал.разложить(ц)) {
          волна.push({
            x: клетка % ширина, y: Math.floor(клетка / ширина),
            куда: выходРазделителя(разделители[клетка], грань), цвет, откуда: клетка,
          });
        }
      }
    }
  }

  // Что в итоге в клетке: смесь пришедшего; у кристалла — только смесь.
  const светИтог = new Map([...свет].map(([к, с]) => [к, пал.смешать(с) ?? с[0]]));
  const приходИтог = new Map([...приход].map(([к, с]) => [к, пал.смешать(с)]));
  const решено = Object.entries(приёмники)
    .every(([клетка, нужно]) => пал.равны(приходИтог.get(Number(клетка)) ?? null, нужно));

  return { свет: светИтог, приход: приходИтог, вСмеситель: испущено, вРазделитель: разослано, решено, палитра: пал };
}

/* ─────────────────────────── постройка зала ─────────────────────────── */

const наугад = н => Math.floor(Math.random() * н);

/**
 * Самый длинный отрезок между изломами. При немногих изломах тропа гуляет
 * по всему залу; при многих длинные отрезки упираются в стены и в соседние
 * тропы раньше, чем изломы кончатся, — такой тропе велим петлять плотнее.
 */
const шагНаИзлом = изломов => (изломов > 6 ? 2 : изломов > 3 ? 4 : 99);

/**
 * Ломаная от смесителя к краю: пятимся против хода луча, ставя зеркала на изломах.
 *
 * Задом наперёд — потому что отражение симметрично: зеркало, поворачивающее луч
 * из А в Б, точно так же поворачивает из Б в А. Значит тропу можно прокладывать
 * от смесителя наружу, а луч потом пойдёт по ней в обратную сторону.
 */
function проложитьНазад(ширина, высота, откуда, входит, занято, зеркала, изломов) {
  let x = откуда % ширина;
  let y = Math.floor(откуда / ширина);
  let куда = наизнанку(входит);
  const свои = [];

  const впереди = () => {
    let [пx, пy] = [x, y], сколько = 0;
    while (true) {
      const нx = пx + ШАГИ[куда][0], нy = пy + ШАГИ[куда][1];
      if (нx < 0 || нy < 0 || нx >= ширина || нy >= высота) break;
      if (занято.has(нy * ширина + нx) || свои.includes(нy * ширина + нx)) break;
      пx = нx; пy = нy; сколько++;
    }
    return сколько;
  };

  for (let и = 0; и < изломов; и++) {
    const свободно = впереди();
    if (свободно < 1) return null;
    const длина = 1 + наугад(Math.min(свободно, шагНаИзлом(изломов)));
    for (let ш = 0; ш < длина; ш++) {
      x += ШАГИ[куда][0]; y += ШАГИ[куда][1];
      свои.push(y * ширина + x);
    }
    const клетка = y * ширина + x;
    const новое = (куда === 0 || куда === 2) ? (наугад(2) ? 1 : 3) : (наугад(2) ? 0 : 2);
    зеркала[клетка] = Object.entries(КОСАЯ).find(([, к]) => к[наизнанку(новое)] === наизнанку(куда))?.[0] ?? "/";
    куда = новое;
  }

  const добежать = впереди();
  if (добежать < 1) return null;
  for (let ш = 0; ш < добежать; ш++) {
    x += ШАГИ[куда][0]; y += ШАГИ[куда][1];
    свои.push(y * ширина + x);
  }
  return { источник: { x, y, куда: наизнанку(куда) }, свои };
}

/** Ломаная вперёд от смесителя до кристалла. */
function проложитьВперёд(ширина, высота, откуда, куда, занято, зеркала, изломов) {
  let x = откуда % ширина;
  let y = Math.floor(откуда / ширина);
  const свои = [];

  const впереди = () => {
    let [пx, пy] = [x, y], сколько = 0;
    while (true) {
      const нx = пx + ШАГИ[куда][0], нy = пy + ШАГИ[куда][1];
      if (нx < 0 || нy < 0 || нx >= ширина || нy >= высота) break;
      if (занято.has(нy * ширина + нx) || свои.includes(нy * ширина + нx)) break;
      пx = нx; пy = нy; сколько++;
    }
    return сколько;
  };

  for (let и = 0; и < изломов; и++) {
    const свободно = впереди();
    if (свободно < 1) return null;
    const длина = 1 + наугад(Math.min(свободно, шагНаИзлом(изломов)));
    for (let ш = 0; ш < длина; ш++) {
      x += ШАГИ[куда][0]; y += ШАГИ[куда][1];
      свои.push(y * ширина + x);
    }
    const клетка = y * ширина + x;
    const новое = (куда === 0 || куда === 2) ? (наугад(2) ? 1 : 3) : (наугад(2) ? 0 : 2);
    зеркала[клетка] = Object.entries(КОСАЯ).find(([, к]) => к[куда] === новое)?.[0] ?? "/";
    куда = новое;
  }

  const добежать = впереди();
  if (добежать < 1) return null;
  for (let ш = 0; ш < добежать; ш++) {
    x += ШАГИ[куда][0]; y += ШАГИ[куда][1];
    свои.push(y * ширина + x);
  }
  return { приёмник: y * ширина + x, свои };
}

/** Разложить заказанные повороты по отрезкам тропы, каждому хотя бы один. */
function поделить(сколько, частей = 3) {
  const доли = Array(частей).fill(1);
  for (let и = частей; и < сколько; и++) доли[наугад(частей)]++;
  return доли;
}

/**
 * Виды зала. «Сложение, 2 луча» — как было: два цвета сходятся в смесителе.
 * «Сложение, 3 луча»: красный, зелёный и синий входят в смеситель с трёх
 * сторон, кристалл ждёт белый. Третий луч добавляет отрезок тропы, так что
 * поворотов самое малое четыре.
 */
export const ВИДЫ_ЗАЛА = {
  // меньше/больше — сколько поворотов вид умеет: четыре тропы на поле 12×12
  // надёжно ложатся не длиннее четырнадцати поворотов.
  два: { имя: М("Сложение: 2 луча"), лучей: 2, меньше: 3, больше: 16 },
  три: { имя: М("Сложение: 3 луча → белый"), лучей: 3, меньше: 4, больше: 14 },
  // Разложение: один составной луч, разделитель, по кристаллу на чистый цвет.
  раз2: { имя: М("Разложение: 2 цвета"), разделитель: 2, меньше: 3, больше: 16 },
  раз3: { имя: М("Разложение: белый → 3 цвета"), разделитель: 3, меньше: 4, больше: 13 },
  // Белый раскладывается, два цвета сходятся в смесителе снова, третий идёт сам.
  разсл: { имя: М("Разложение и сложение"), смешанный: true, меньше: 5, больше: 13 },
};

export const выборВида = (выбрано = "два") => Object.entries(ВИДЫ_ЗАЛА)
  .map(([к, в]) => `<option value="${к}" ${к === выбрано ? "selected" : ""}>${Т(в.имя)}</option>`).join("");

/**
 * Пары входящих цветов на выбор ведущего: ключ — сложение, которое ждёт
 * кристалл. «Случайно» — пусто: пара выпадает как придётся.
 */
export const ПАРЫ = {
  жёлтый: [КРАСНЫЙ, ЗЕЛЁНЫЙ],
  пурпур: [КРАСНЫЙ, СИНИЙ],
  лазурь: [ЗЕЛЁНЫЙ, СИНИЙ],
};

/**
 * Зал на разложение: составной луч входит в разделитель, чистые цвета уходят
 * каждый к своему кристаллу. Клетка под разделитель уже выбрана и занята —
 * это то место, где в сложении стоял бы смеситель.
 */
function построитьРазложение(ширина, высота, лишних, изломов, пара, вид, клетка, зеркала, занято) {
  const цветов = ВИДЫ_ЗАЛА[вид].разделитель;
  const пары = Object.values(ПАРЫ);
  const составные = цветов === 3 ? [...ЧИСТЫЕ] : (ПАРЫ[пара] ?? пары[наугад(пары.length)]);
  const поворот = наугад(4);
  const выходы = составные.map(ц => выходРазделителя(поворот, ЧИСТЫЕ.indexOf(ц)));

  // Вход — через грань, из которой ничего не выходит; луч идёт с неё внутрь.
  const стороны = [0, 1, 2, 3].filter(с => !выходы.includes(с));
  const входит = наизнанку(стороны[наугад(стороны.length)]);

  const доли = поделить(изломов, 1 + цветов);
  const вход = проложитьНазад(ширина, высота, клетка, входит, занято, зеркала, доли[0]);
  if (!вход) return null;
  вход.свои.forEach(к => занято.add(к));

  const приёмники = {};
  for (let и = 0; и < цветов; и++) {
    const в = проложитьВперёд(ширина, высота, клетка, выходы[и], занято, зеркала, доли[и + 1]);
    if (!в) return null;
    в.свои.forEach(к => занято.add(к));
    приёмники[в.приёмник] = составные[и];
  }

  const зал = {
    ширина, высота, зеркала,
    источники: [{ ...вход.источник, цвет: составные.reduce((с, ц) => с | ц, 0) }],
    смесители: {},
    разделители: { [клетка]: поворот },
    приёмники,
  };

  const тропа = new Set([...занято, ...провести(зал).свет.keys()]);
  for (let и = 0; и < лишних; и++) {
    const к = наугад(ширина * высота);
    if (зеркала[к] || тропа.has(к)) continue;
    зеркала[к] = наугад(2) ? "/" : "\\";
  }
  return зал;
}

/**
 * Тропа между двумя деталями: выйти из `откуда` в сторону `куда` и войти в
 * `цель`, идя в сторону `входит`, ровно с `изломов` зеркалами по пути.
 *
 * Проложить к краю зала просто — иди, пока не упрёшься. Между двумя деталями
 * так не выйдет, и тропу ищем перебором вглубь с случайным порядком: прямо
 * или излом налево/направо на каждой клетке. Перебор ограничен, чтобы
 * неудачное расположение не держало сборку: не нашлось — попытка
 * выбрасывается целиком, как и прочие.
 */
function соединить(ширина, высота, откуда, куда, цель, входит, изломов, занято) {
  const путь = [];
  const зеркала = {};
  const видели = new Set();
  let узлов = 0;

  const шаг = (x, y, к, осталось) => {
    if (++узлов > 6000) return false;
    const нx = x + ШАГИ[к][0], нy = y + ШАГИ[к][1];
    if (нx < 0 || нy < 0 || нx >= ширина || нy >= высота) return false;
    const клетка = нy * ширина + нx;
    if (клетка === цель) return осталось === 0 && к === входит;
    if (занято.has(клетка) || видели.has(клетка)) return false;

    видели.add(клетка);
    путь.push(клетка);
    const пути = [[к, false]];
    if (осталось > 0) пути.push([(к + 1) % 4, true], [(к + 3) % 4, true]);
    for (let i = пути.length - 1; i > 0; i--) { const j = наугад(i + 1); [пути[i], пути[j]] = [пути[j], пути[i]]; }
    for (const [новое, излом] of пути) {
      if (излом) зеркала[клетка] = Object.entries(КОСАЯ).find(([, м]) => м[к] === новое)?.[0] ?? "/";
      if (шаг(нx, нy, новое, осталось - (излом ? 1 : 0))) return true;
      if (излом) delete зеркала[клетка];
    }
    видели.delete(клетка);
    путь.pop();
    return false;
  };

  return шаг(откуда % ширина, Math.floor(откуда / ширина), куда, изломов) ? { свои: путь, зеркала } : null;
}

/**
 * Зал «разложение и сложение»: белый входит в разделитель, два его цвета
 * тропами идут в смеситель и сходятся снова, третий цвет уходит к своему
 * кристаллу. Кристаллов два: один ждёт сложения пары, другой — чистый цвет.
 * `пара` — какие два цвета сойдутся; не задана — как выпадет.
 */
function построитьСмешанный(ширина, высота, лишних, изломов, пара, клетка, зеркала, занято) {
  const пары = Object.values(ПАРЫ);
  const сойдутся = ПАРЫ[пара] ?? пары[наугад(пары.length)];
  const один = ЧИСТЫЕ.find(ц => !сойдутся.includes(ц));
  const поворот = наугад(4);
  const выход = ц => выходРазделителя(поворот, ЧИСТЫЕ.indexOf(ц));

  // Пять отрезков: вход, две тропы к смесителю, выход смесителя, одинокий цвет.
  const доли = поделить(изломов, 5);

  // Вход — через глухую грань разделителя.
  const вход = проложитьНазад(ширина, высота, клетка, наизнанку((поворот + 3) % 4), занято, зеркала, доли[0]);
  if (!вход) return null;
  вход.свои.forEach(к => занято.add(к));

  // Смеситель — в свободной клетке не у края. Не подошло место — пробуем
  // другое: тропам к смесителю нужен простор с двух сторон.
  const свободные = [];
  for (let y = 1; y < высота - 1; y++) for (let x = 1; x < ширина - 1; x++) {
    const к = y * ширина + x;
    if (!занято.has(к)) свободные.push(к);
  }

  /*
   * Тропе к смесителю даём заказанное число изломов, а если геометрия так
   * не пускает — соседнее: одним изломом больше или меньше, а то и прямо.
   * Глубину всё равно меряет поиск, и неудачный зал отбросится там.
   */
  const тропаКСмесителю = (цвет, смеситель, входит, доля) => {
    for (const изл of [...new Set([доля, доля + 1, доля - 1, доля + 2, 0])].filter(н => н >= 0)) {
      const т = соединить(ширина, высота, клетка, выход(цвет), смеситель, входит, изл, занято);
      if (т) return т;
    }
    return null;
  };

  let смеситель = null, выходСмесителя = null;
  for (let попытка = 0; попытка < 8 && смеситель === null && свободные.length; попытка++) {
    const место = свободные.splice(наугад(свободные.length), 1)[0];
    const выходМ = наугад(4);
    const бока = [0, 1, 2, 3].filter(к => к !== выходМ && к !== наизнанку(выходМ));
    if (наугад(2)) бока.reverse();

    занято.add(место);
    const первая = тропаКСмесителю(сойдутся[0], место, бока[0], доли[1]);
    if (первая) первая.свои.forEach(к => занято.add(к));
    const вторая = первая && тропаКСмесителю(сойдутся[1], место, бока[1], доли[2]);
    if (первая && вторая) {
      вторая.свои.forEach(к => занято.add(к));
      Object.assign(зеркала, первая.зеркала, вторая.зеркала);
      смеситель = место;
      выходСмесителя = выходМ;
    } else {
      занято.delete(место);
      первая?.свои.forEach(к => занято.delete(к));
    }
  }
  if (смеситель === null) return null;

  const кСложению = проложитьВперёд(ширина, высота, смеситель, выходСмесителя, занято, зеркала, доли[3]);
  if (!кСложению) return null;
  кСложению.свои.forEach(к => занято.add(к));

  const кОдному = проложитьВперёд(ширина, высота, клетка, выход(один), занято, зеркала, доли[4]);
  if (!кОдному) return null;
  кОдному.свои.forEach(к => занято.add(к));

  const зал = {
    ширина, высота, зеркала,
    источники: [{ ...вход.источник, цвет: 7 }],
    смесители: { [смеситель]: выходСмесителя },
    разделители: { [клетка]: поворот },
    приёмники: { [кСложению.приёмник]: сойдутся[0] | сойдутся[1], [кОдному.приёмник]: один },
  };

  const тропа = new Set([...занято, ...провести(зал).свет.keys()]);
  for (let и = 0; и < лишних; и++) {
    const к = наугад(ширина * высота);
    if (зеркала[к] || тропа.has(к)) continue;
    зеркала[к] = наугад(2) ? "/" : "\\";
  }
  return зал;
}

