/**
 * Зал и кристаллы разметкой — для окна на столе и для подготовки устройства.
 *
 * `действие(к)` — что делает щелчок по зеркалу (имя действия окна или null);
 * `номер(к)` — номер рычага над зеркалом и тусклый ли он: `{ н, тускло }`.
 */
export function рисоватьЗал(с, { действие = () => null, номер = () => null, класс = () => "", всеКлетки = false, подробно = false } = {}) {
  const { свет, приход, палитра: пал } = провести(с);
  const начала = new Map((с.источники ?? []).map(и => [и.y * с.ширина + и.x, и.цвет]));
  // Подробно (в редакторе): куда светит источник и куда выпускает смеситель.
  const куда = new Map((с.источники ?? []).map(и => [и.y * с.ширина + и.x, и.куда]));
  const СТРЕЛКИ = ["→", "↓", "←", "↑"];
  const гранные = пал.грани();

  const клетки = Array.from({ length: с.ширина * с.высота }, (_, к) => {
    const зеркало = с.зеркала[к];
    const нужно = с.приёмники[к];
    const смеситель = с.смесители[к];
    const разделитель = с.разделители?.[к];
    const прошло = свет.get(к);
    // Деталь, которую крутят: зеркало под своей клеткой, вращающийся разделитель — «р» + клетка.
    const деталь = зеркало ? к : (разделитель !== undefined && с.вращаются ? `р${к}` : null);
    const доволен = нужно !== undefined && пал.равны(приход.get(к) ?? null, нужно);

    const классы = [
      "uo-prizma-kletka",
      зеркало ? "uo-est-zerkalo" : "",
      нужно !== undefined ? "uo-priemnik" : "",
      смеситель !== undefined ? "uo-smesitel" : "",
      разделитель !== undefined ? "uo-razdelitel" : "",
      деталь !== null ? "uo-est-zerkalo" : "",
      начала.has(к) ? "uo-istochnik" : "",
      доволен ? "uo-dovolen" : "",
      деталь !== null ? класс(деталь) : "",
    ].filter(Boolean).join(" ");

    const знак = нужно !== undefined ? "◈"
      : смеситель !== undefined ? (подробно ? `◉<span class="uo-strelka">${СТРЕЛКИ[смеситель]}</span>` : "◉")
        : разделитель !== undefined ? "◇"
          : зеркало ? (зеркало === "/" ? "╱" : "╲")
            : начала.has(к) ? (подробно ? СТРЕЛКИ[куда.get(к)] : "●") : "";
    const н = деталь !== null ? номер(деталь) : null;
    // В редакторе щёлкается любая клетка, и в data-kletka — сама клетка.
    const д = всеКлетки ? действие(к) : (деталь !== null ? действие(деталь) : null);
    const ключ = всеКлетки ? к : деталь;

    // Грани разделителя — полосками своих цветов: видно, куда какой уйдёт.
    const грани = разделитель !== undefined
      ? гранные.map((цвет, и) => `border-${["right", "bottom", "left", "top"][выходРазделителя(разделитель, и)]}: 3px solid ${цвет};`).join(" ")
      : "";

    const цветРамки = нужно !== undefined ? пал.краска(нужно)
      : начала.has(к) ? пал.краска(начала.get(к)) : null;

    const стиль = [
      прошло !== undefined ? `background: ${пал.краска(прошло)}22; box-shadow: inset 0 0 10px ${пал.краска(прошло)}66;` : "",
      цветРамки ? `border-color: ${цветРамки}; color: ${цветРамки};` : "",
      грани,
    ].join(" ");

    return `<button type="button" class="${классы}" style="${стиль}" ${
      д ? `data-action="${д}" data-kletka="${ключ}"` : "disabled"}>${знак}${
      н ? `<span class="uo-nomer-rychaga${н.тускло ? " uo-tusklo" : ""}">${н.н}</span>` : ""}</button>`;
  }).join("");

  const кристаллы = Object.entries(с.приёмники).map(([к, нужно]) => {
    const дошло = приход.get(Number(к)) ?? null;
    return `<span class="uo-krisstall" style="color: ${пал.краска(нужно)}">${Т("◈ нужен {цвет}", { цвет: экранировать(пал.имя(нужно)) })}${
      пал.равны(дошло, нужно) ? Т(" — есть") : дошло !== null ? Т(" (сейчас {цвет})", { цвет: экранировать(пал.имя(дошло)) }) : Т(" — не горит")}</span>`;
  }).join("");

  return `<div class="uo-prizmy" style="--shirina: ${с.ширина}">${клетки}</div>
    <div class="uo-kristally">${кристаллы}</div>`;
}

