/* ─────────────────────────── ход лучей ─────────────────────────── */

const ШАГИ = [[1, 0], [0, 1], [-1, 0], [0, -1]];
const КОСАЯ = { "/": [3, 2, 1, 0], "\\": [1, 0, 3, 2] };
const наизнанку = куда => (куда + 2) % 4;

/**
 * Пустить все лучи и посмотреть, что куда пришло.
 *
 * Волнами: сперва идут лучи от источников, потом — от смесителей, которым
 * что-то принесли, и так пока свет не перестанет меняться. Волн немного,
 * иначе кольцо из зеркал крутило бы луч вечно.
 */
export function провести(зал) {
  const { ширина, высота, зеркала = {}, смесители = {}, приёмники = {} } = зал;
  const свет = new Map();          // клетка -> какие цвета через неё прошли
  const вСмеситель = new Map();    // клетка -> что в неё пришло
  const испущено = new Map();      // клетка -> что она уже выпустила
  const приход = new Map();        // клетка приёмника -> что дошло

  const подсветить = (клетка, цвет) => свет.set(клетка, (свет.get(клетка) ?? 0) | цвет);

  const пустить = ({ x, y, куда, цвет, откуда }) => {
    let [сx, сy] = [x, y];
    for (let шаг = 0; шаг < ширина * высота * 4; шаг++) {
      if (сx < 0 || сy < 0 || сx >= ширина || сy >= высота) return;
      const клетка = сy * ширина + сx;

      if (клетка !== откуда && смесители[клетка] !== undefined) {
        вСмеситель.set(клетка, (вСмеситель.get(клетка) ?? 0) | цвет);
        return;
      }
      if (приёмники[клетка] !== undefined) {
        приход.set(клетка, (приход.get(клетка) ?? 0) | цвет);
        подсветить(клетка, цвет);
        return;
      }

      подсветить(клетка, цвет);
      const зеркало = зеркала[клетка];
      if (зеркало) куда = КОСАЯ[зеркало][куда];
      сx += ШАГИ[куда][0];
      сy += ШАГИ[куда][1];
    }
  };

  let волна = (зал.источники ?? []).map(и => ({ ...и, откуда: -1 }));
  for (let н = 0; н < 8 && волна.length; н++) {
    for (const луч of волна) пустить(луч);

    волна = [];
    for (const [клетка, цвет] of вСмеситель) {
      if (испущено.get(клетка) === цвет) continue;
      испущено.set(клетка, цвет);
      волна.push({
        x: клетка % ширина,
        y: Math.floor(клетка / ширина),
        куда: смесители[клетка],
        цвет,
        откуда: клетка,
      });
    }
  }

  const решено = Object.entries(приёмники)
    .every(([клетка, нужно]) => (приход.get(Number(клетка)) ?? 0) === нужно);

  return { свет, приход, вСмеситель: испущено, решено };
}

/* ─────────────────────────── постройка зала ─────────────────────────── */

const наугад = н => Math.floor(Math.random() * н);

/**
 * Ломаная от смесителя к краю: пятимся против хода луча, ставя зеркала на изломах.
 *
 * Задом наперёд — потому что отражение симметрично: зеркало, поворачивающее луч
 * из А в Б, точно так же поворачивает из Б в А. Значит тропу можно прокладывать
 * от смесителя наружу, а луч потом пойдёт по ней в обратную сторону.
 */
function проложитьНазад(ширина, высота, откуда, входит, занято, зеркала, изломов) {
  let x = откуда % ширина;
  let y = Math.floor(откуда / ширина);
  let куда = наизнанку(входит);
  const свои = [];

  const впереди = () => {
    let [пx, пy] = [x, y], сколько = 0;
    while (true) {
      const нx = пx + ШАГИ[куда][0], нy = пy + ШАГИ[куда][1];
      if (нx < 0 || нy < 0 || нx >= ширина || нy >= высота) break;
      if (занято.has(нy * ширина + нx) || свои.includes(нy * ширина + нx)) break;
      пx = нx; пy = нy; сколько++;
    }
    return сколько;
  };

  for (let и = 0; и < изломов; и++) {
    const свободно = впереди();
    if (свободно < 1) return null;
    const длина = 1 + наугад(свободно);
    for (let ш = 0; ш < длина; ш++) {
      x += ШАГИ[куда][0]; y += ШАГИ[куда][1];
      свои.push(y * ширина + x);
    }
    const клетка = y * ширина + x;
    const новое = (куда === 0 || куда === 2) ? (наугад(2) ? 1 : 3) : (наугад(2) ? 0 : 2);
    зеркала[клетка] = Object.entries(КОСАЯ).find(([, к]) => к[наизнанку(новое)] === наизнанку(куда))?.[0] ?? "/";
    куда = новое;
  }

  const добежать = впереди();
  if (добежать < 1) return null;
  for (let ш = 0; ш < добежать; ш++) {
    x += ШАГИ[куда][0]; y += ШАГИ[куда][1];
    свои.push(y * ширина + x);
  }
  return { источник: { x, y, куда: наизнанку(куда) }, свои };
}

/** Ломаная вперёд от смесителя до кристалла. */
function проложитьВперёд(ширина, высота, откуда, куда, занято, зеркала, изломов) {
  let x = откуда % ширина;
  let y = Math.floor(откуда / ширина);
  const свои = [];

  const впереди = () => {
    let [пx, пy] = [x, y], сколько = 0;
    while (true) {
      const нx = пx + ШАГИ[куда][0], нy = пy + ШАГИ[куда][1];
      if (нx < 0 || нy < 0 || нx >= ширина || нy >= высота) break;
      if (занято.has(нy * ширина + нx) || свои.includes(нy * ширина + нx)) break;
      пx = нx; пy = нy; сколько++;
    }
    return сколько;
  };

  for (let и = 0; и < изломов; и++) {
    const свободно = впереди();
    if (свободно < 1) return null;
    const длина = 1 + наугад(свободно);
    for (let ш = 0; ш < длина; ш++) {
      x += ШАГИ[куда][0]; y += ШАГИ[куда][1];
      свои.push(y * ширина + x);
    }
    const клетка = y * ширина + x;
    const новое = (куда === 0 || куда === 2) ? (наугад(2) ? 1 : 3) : (наугад(2) ? 0 : 2);
    зеркала[клетка] = Object.entries(КОСАЯ).find(([, к]) => к[куда] === новое)?.[0] ?? "/";
    куда = новое;
  }

  const добежать = впереди();
  if (добежать < 1) return null;
  for (let ш = 0; ш < добежать; ш++) {
    x += ШАГИ[куда][0]; y += ШАГИ[куда][1];
    свои.push(y * ширина + x);
  }
  return { приёмник: y * ширина + x, свои };
}

/** Разложить заказанные повороты по трём отрезкам тропы, каждому хотя бы один. */
function поделить(сколько) {
  const доли = [1, 1, 1];
  for (let и = 3; и < сколько; и++) доли[наугад(3)]++;
  return доли;
}

function построить(ширина, высота, лишних, изломов) {
  const зеркала = {};
  const занято = new Set();

  const смеситель = (1 + наугад(высота - 2)) * ширина + (1 + наугад(ширина - 2));
  занято.add(смеситель);

  const выход = наугад(4);
  const входы = [0, 1, 2, 3].filter(к => к !== выход && к !== наизнанку(выход));
  const первый = входы[наугад(входы.length)];
  const второй = входы.find(к => к !== первый) ?? наизнанку(первый);

  const цвета = [КРАСНЫЙ, ЗЕЛЁНЫЙ, СИНИЙ];
  const цвет1 = цвета[наугад(3)];
  const цвет2 = цвета.filter(ц => ц !== цвет1)[наугад(2)];

  const [долиА, долиБ, долиВ] = поделить(изломов);

  const а = проложитьНазад(ширина, высота, смеситель, первый, занято, зеркала, долиА);
  if (!а) return null;
  а.свои.forEach(к => занято.add(к));

  const б = проложитьНазад(ширина, высота, смеситель, второй, занято, зеркала, долиБ);
  if (!б) return null;
  б.свои.forEach(к => занято.add(к));

  const в = проложитьВперёд(ширина, высота, смеситель, выход, занято, зеркала, долиВ);
  if (!в) return null;
  в.свои.forEach(к => занято.add(к));

  const зал = {
    ширина, высота, зеркала,
    источники: [
      { ...а.источник, цвет: цвет1 },
      { ...б.источник, цвет: цвет2 },
    ],
    смесители: { [смеситель]: выход },
    приёмники: { [в.приёмник]: цвет1 | цвет2 },
  };

  // Лишние зеркала — только там, где свет не ходит.
  const тропа = new Set([...занято, ...провести(зал).свет.keys()]);
  for (let и = 0; и < лишних; и++) {
    const клетка = наугад(ширина * высота);
    if (зеркала[клетка] || тропа.has(клетка)) continue;
    зеркала[клетка] = наугад(2) ? "/" : "\\";
  }

  return зал;
}

/**
 * Разложить все развороты зеркал по глубине: сколько щелчков до ближайшего
 * решения. Считает razvoroty.mjs, здесь только подставляется ход лучей.
 */
export function разложить(зал) {
  return разбор(Object.keys(зал.зеркала ?? {}),
    где => провести({ ...зал, зеркала: где }).решено);
}

/** Решается ли зал вообще. */
export function решается(зал) {
  return (разложить(зал)?.решающих ?? 0) > 0;
}

/* ─────────────────────────── выложить на стол ─────────────────────────── */

export async function выложить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const ширина = Math.min(12, Math.max(5, Number(конфиг.ширина) || 9));
  const высота = Math.min(12, Math.max(5, Number(конфиг.высота) || 9));
  const лишних = Math.max(0, Math.min(6, Number(конфиг.лишних ?? 1)));
  const ходов = Math.max(3, Math.min(9, Number(конфиг.ходов) || 5));

  // Как и в зеркальном зале: строим, пока до решения не окажется не меньше
  // заказанного числа поворотов. Перебор говорит это точно, а не примерно.
  let зал = null, старт = null;
  for (let попытка = 0; попытка < 400 && !зал; попытка++) {
    const пробный = построить(ширина, высота, лишних, ходов);
    if (!пробный) continue;
    const разложенный = разложить(пробный);
    if (!разложенный?.решающих) continue;
    const начальное = начало(разложенный, ходов);
    if (!начальное || начальное.глубина < ходов) continue;
    зал = пробный;
    старт = начальное;
  }

  if (!зал) {
    for (let попытка = 0; попытка < 400 && !зал; попытка++) {
      const пробный = построить(ширина, высота, лишних, ходов);
      if (!пробный) continue;
      const разложенный = разложить(пробный);
      if (!разложенный?.решающих) continue;
      const начальное = начало(разложенный, 1);
      if (!начальное) continue;
      зал = пробный;
      старт = начальное;
    }
    if (зал) ui.notifications.warn(
      Т("Зал вышел на {глубина} поворот(ов) вместо {ходов} — на таком поле длиннее не легло.", { глубина: старт.глубина, ходов }));
  }
  if (!зал) { ui.notifications.error(Т("Не вышло сложить зал призм — попробуйте поле побольше.")); return null; }

  const перепутанные = старт.зеркала;

  await прибрать();

  const стол = {
    id: foundry.utils.randomID(),
    тип: "prizmy",
    название: конфиг.название?.trim() || Т("Зал призм"),
    подпись: конфиг.подпись?.trim() || "",
    тема: (конфиг.тема in ТЕМЫ) ? конфиг.тема : "bezdna",
    ширина: зал.ширина,
    высота: зал.высота,
    источники: зал.источники,
    смесители: зал.смесители,
    приёмники: зал.приёмники,
    зеркала: перепутанные,
    поворотов: 0,
    глубина: старт.глубина,
    предел: Math.max(0, Number(конфиг.предел) || 0),
    крутят: конфиг.крутят?.length ? конфиг.крутят : "все",
    макрос: конфиг.макрос?.trim() || null,
    зажжён: false,
    заклинило: false,
    завершён: false,
    показан: true,
  };

  if (стол.предел && стол.предел < старт.глубина) ui.notifications.warn(
    Т("Предел {предел} меньше, чем нужно поворотов ({глубина}) — зал не открыть.", { предел: стол.предел, глубина: старт.глубина }));

  await записать(стол);
  return стол;
}

export async function прибрать() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "prizmy" && с.завершён) await убрать(id);
  }
}

/* ─────────────────────────────── правила ─────────────────────────────── */

const можетКрутить = (стол, пользователь) =>
  !!пользователь && !стол.зажжён && !стол.заклинило &&
  (пользователь.isGM || стол.крутят === "все" || (стол.крутят ?? []).includes(пользователь.id));

const отложитьЗапись = foundry.utils.debounce(async id => {
  const сырой = столПоId(id);
  if (!сырой) return;
  const живой = собрать(сырой);
  await записать({ ...сырой, зеркала: живой.зеркала, поворотов: живой.поворотов });
}, 3000);

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!можетКрутить(стол, пользователь)) return;
  if (запрос.что !== "повернуть") return;

  const клетка = String(Number(запрос.клетка));
  if (!стол.зеркала[клетка]) return;

  const зеркала = { ...стол.зеркала, [клетка]: стол.зеркала[клетка] === "/" ? "\\" : "/" };
  const поворотов = стол.поворотов + 1;
  const { решено } = провести({ ...стол, зеркала });

  if (решено) return зажглось(стол, зеркала, поворотов, запрос.кто);

  if (стол.предел && поворотов >= стол.предел) {
    await записать({ ...столПоId(стол.id), зеркала, поворотов, заклинило: true, завершён: true });
    await объявить(Т(`<p><strong>{название}</strong> — призмы застыли.</p>`, { название: экранировать(стол.название) }), стол.название);
    return;
  }

  разослать(стол.id, { зеркала, поворотов });
  отложитьЗапись(стол.id);
}

async function зажглось(стол, зеркала, поворотов, ктоId) {
  const свежий = { ...столПоId(стол.id), зеркала, поворотов, зажжён: true, завершён: true };
  await записать(свежий);
  const цвета = Object.values(свежий.приёмники).map(имяЦвета).join(", ");
  await объявить(
    Т(`<p><strong>{название}</strong> — кристаллы взяли свой свет: {цвета}.</p>
     <p><em>{ктоId} довернул последнюю призму; поворотов {поворотов}.</em></p>`, { название: экранировать(свежий.название), цвета: 
      экранировать(цвета), ктоId: экранировать(имяИгрока(ктоId)), поворотов: поворотов }),
    свежий.название);
  событие("решено", свежий);
  await запуститьМакрос(свежий.макрос, свежий);
}

/* ─────────────────── рычаги ведущего ─────────────────── */

export async function засчитать(id) {
  const стол = столПоId(id);
  if (!стол) return;
  const полный = { ...собрать(стол), зажжён: true, заклинило: false, завершён: true };
  await записать(полный);
  await объявить(Т(`<p><strong>{название}</strong> — зажжён волей ведущего.</p>`, { название: экранировать(полный.название) }), полный.название);
  событие("решено", полный);
  await запуститьМакрос(полный.макрос, полный);
}

export async function сбросить(id) {
  const стол = столПоId(id);
  if (!стол) return;
  await записать({ ...стол, поворотов: 0, зажжён: false, заклинило: false, завершён: false });
}

