/**
 * Собрать зал, ничего не выкладывая: окно подготовки устройства показывает его
 * ведущему, а выкладывается потом ровно он — через `конфиг.готовый`.
 */
export const ХОДОВ_НАИБОЛЬШЕ = 16;
export const ЛИШНИХ_НАИБОЛЬШЕ = 12;

/*
 * Положение зала для поиска глубины — одним словарём: зеркала под своими
 * клетками, разделители под «р» + клетка (их четыре положения, а не два).
 */
const вПоложение = (зеркала, разделители = {}, вращаются = false) => ({
  ...зеркала,
  ...(вращаются ? Object.fromEntries(Object.entries(разделители).map(([к, п]) => [`р${к}`, п])) : {}),
});
const изПоложения = (где, разделители = {}) => {
  const з = {}, р = { ...разделители };
  for (const [к, v] of Object.entries(где)) if (к[0] === "р") р[к.slice(1)] = v; else з[к] = v;
  return { зеркала: з, разделители: р };
};
const повернутьДеталь = (к, v) => (к[0] === "р" ? (Number(v) + 1) % 4 : (v === "/" ? "\\" : "/"));

/** Что горит и решён ли зал — для поиска глубины по освещённым деталям. */
const оценка = зал => где => {
  const { зеркала, разделители } = изПоложения(где, зал.разделители);
  const { свет, решено, вРазделитель } = провести({ ...зал, зеркала, разделители });
  return {
    решено,
    горят: Object.keys(где).filter(к => (к[0] === "р" ? вРазделитель.has(Number(к.slice(1))) : свет.has(Number(к)))),
  };
};

/**
 * Сколько поворотов нужно залу из его нынешнего положения: число, 0 — уже
 * решён, Infinity — не решается никак, null — слишком сложно посчитать.
 * Для редактора: ведущий собирает зал руками и видит это вживую.
 */
export function глубинаЗала(зал) {
  const вращаются = !!зал.вращаются && Object.keys(зал.разделители ?? {}).length > 0;
  return глубинаОт(вПоложение(зал.зеркала ?? {}, зал.разделители ?? {}, вращаются), оценка(зал),
    { предел: 40, бюджет: 200_000, повернуть: повернутьДеталь });
}

/** Сбить зал: зеркала и вращающиеся разделители — как выпадет, лишь бы не решён. */
export function сбитьЗал(зал) {
  for (let попытка = 0; попытка < 60; попытка++) {
    const зеркала = Object.fromEntries(Object.keys(зал.зеркала ?? {}).map(к => [к, наугад(2) ? "/" : "\\"]));
    const разделители = { ...(зал.разделители ?? {}) };
    if (зал.вращаются) for (const к of Object.keys(разделители)) разделители[к] = наугад(4);
    const сбитый = { ...зал, зеркала, разделители };
    if (!провести(сбитый).решено) return сбитый;
  }
  return зал;
}

export function собратьЗал(конфиг = {}) {
  const ширина = Math.min(12, Math.max(5, Number(конфиг.ширина) || 9));
  const высота = Math.min(12, Math.max(5, Number(конфиг.высота) || 9));
  const лишних = Math.max(0, Math.min(ЛИШНИХ_НАИБОЛЬШЕ, Number(конфиг.лишних ?? 1)));
  const вид = ВИДЫ_ЗАЛА[конфиг.вид] ? конфиг.вид : "два";
  const ходов = Math.max(ВИДЫ_ЗАЛА[вид].меньше, Math.min(ВИДЫ_ЗАЛА[вид].больше, Number(конфиг.ходов) || 5));

  /*
   * Строим от решения: построить() прокладывает тропы, и зал в этом виде
   * горит. Потом переворачиваем каждое зеркало на тропе — их ровно столько,
   * сколько заказано поворотов, — а лишние, что лежат в темноте, кидаем как
   * выпадет. Глубину меряет поиск по освещённым зеркалам (razvoroty.mjs):
   * бывает, что свет находит обходной путь короче, — такой зал отбрасываем.
   * Лучший из неудачных остаётся запасным: пусть ведущий видит, что вышло.
   */
  const вращаются = конфиг.вращается !== false;

  let лучший = null;
  for (let попытка = 0; попытка < 250; попытка++) {
    const зал = построить(ширина, высота, лишних, ходов, конфиг.пара, вид);
    if (!зал) continue;
    const { свет, решено } = провести(зал);
    if (!решено) continue;

    const зеркала = {};
    for (const [к, з] of Object.entries(зал.зеркала)) {
      const наТропе = свет.has(Number(к));
      const перевернуть = наТропе || Math.random() < .5;
      зеркала[к] = перевернуть ? (з === "/" ? "\\" : "/") : з;
    }
    // Вращающийся разделитель тоже сбиваем: встаёт как выпадет, кроме верного.
    const разделители = { ...(зал.разделители ?? {}) };
    if (вращаются) for (const к of Object.keys(разделители)) разделители[к] = (разделители[к] + 1 + наугад(3)) % 4;

    const глубина = глубинаОт(вПоложение(зеркала, разделители, вращаются), оценка(зал),
      { предел: ходов + 2, повернуть: повернутьДеталь });
    if (!Number.isFinite(глубина) || глубина < 1) continue;

    const готовый = {
      ширина: зал.ширина, высота: зал.высота,
      источники: зал.источники, смесители: зал.смесители, приёмники: зал.приёмники,
      зеркала, разделители, вращаются: вращаются && Object.keys(разделители).length > 0, глубина,
    };
    if (глубина >= ходов) return готовый;
    if (!лучший || глубина > лучший.глубина) лучший = готовый;
  }

  if (лучший) {
    ui.notifications.warn(
      Т("Зал вышел на {глубина} поворот(ов) вместо {ходов} — на таком поле длиннее не легло.", { глубина: лучший.глубина, ходов }));
    return лучший;
  }
  ui.notifications.error(Т("Не вышло сложить зал призм — попробуйте поле побольше."));
  return null;
}

/** Что крутится в зале: зеркала и, если вращаются, разделители («р» + клетка). */
export const деталиЗала = зал => [
  ...Object.keys(зал.зеркала ?? {}),
  ...(зал.вращаются ? Object.keys(зал.разделители ?? {}).map(к => `р${к}`) : []),
];

