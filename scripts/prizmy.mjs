function построить(ширина, высота, лишних, изломов, пара = null, вид = "два") {
  const зеркала = {};
  const занято = new Set();

  const смеситель = (1 + наугад(высота - 2)) * ширина + (1 + наугад(ширина - 2));
  занято.add(смеситель);

  /*
   * Входы — направления, в которых лучи идут, входя в смеситель. Два луча
   * входят сбоку от выхода; третий — сзади, по ходу выхода: навстречу выходу
   * луч не пустить, там тропа к кристаллу.
   */
  if (ВИДЫ_ЗАЛА[вид]?.смешанный) return построитьСмешанный(ширина, высота, лишних, изломов, пара, смеситель, зеркала, занято);
  if (ВИДЫ_ЗАЛА[вид]?.разделитель) return построитьРазложение(ширина, высота, лишних, изломов, пара, вид, смеситель, зеркала, занято);

  const выход = наугад(4);
  const бока = [0, 1, 2, 3].filter(к => к !== выход && к !== наизнанку(выход));
  if (наугад(2)) бока.reverse();
  const лучей = ВИДЫ_ЗАЛА[вид]?.лучей ?? 2;
  const входы = лучей === 3 ? [...бока, выход] : бока;

  const цвета = [КРАСНЫЙ, ЗЕЛЁНЫЙ, СИНИЙ];
  let краски;
  if (лучей === 3) краски = [...цвета].sort(() => Math.random() - .5);
  else {
    // Заказанная пара — в случайном порядке по входам; иначе как выпадет.
    const заказ = ПАРЫ[пара];
    const цвет1 = заказ ? заказ[наугад(2)] : цвета[наугад(3)];
    краски = [цвет1, заказ ? заказ.find(ц => ц !== цвет1) : цвета.filter(ц => ц !== цвет1)[наугад(2)]];
  }

  const доли = поделить(изломов, входы.length + 1);
  const источники = [];
  for (let и = 0; и < входы.length; и++) {
    const тропа = проложитьНазад(ширина, высота, смеситель, входы[и], занято, зеркала, доли[и]);
    if (!тропа) return null;
    тропа.свои.forEach(к => занято.add(к));
    источники.push({ ...тропа.источник, цвет: краски[и] });
  }

  const в = проложитьВперёд(ширина, высота, смеситель, выход, занято, зеркала, доли.at(-1));
  if (!в) return null;
  в.свои.forEach(к => занято.add(к));

  const зал = {
    ширина, высота, зеркала, источники,
    смесители: { [смеситель]: выход },
    приёмники: { [в.приёмник]: краски.reduce((с, ц) => с | ц, 0) },
  };

  // Лишние зеркала — только там, где свет не ходит.
  const тропа = new Set([...занято, ...провести(зал).свет.keys()]);
  for (let и = 0; и < лишних; и++) {
    const клетка = наугад(ширина * высота);
    if (зеркала[клетка] || тропа.has(клетка)) continue;
    зеркала[клетка] = наугад(2) ? "/" : "\\";
  }

  return зал;
}

