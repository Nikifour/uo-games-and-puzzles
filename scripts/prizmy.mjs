/**
 * Зал призм — цветной свет и смесители.
 *
 * То же, что зал зеркал, но лучей несколько и они цветные. Смеситель — клетка,
 * которая гасит вошедшие лучи и выпускает один, цвета их сложения. Приёмнику
 * нужен свой цвет: красному кристаллу красный, жёлтому — сложение красного
 * с зелёным.
 *
 * Цвета складываются как свет, а не как краска: красный и зелёный дают жёлтый,
 * красный и синий — пурпур, зелёный и синий — лазурь, все три — белый. Это
 * стоит сказать игрокам вслух: половина стола помнит смешение красок из школы
 * и будет ждать от красного с зелёным бурого.
 *
 * Зал, как и одноцветный, строится от решения и **проверяется перебором**:
 * с двумя источниками и смесителем запутаться в собственном генераторе проще
 * простого, а игроки потом будут ковырять невозможное.
 *
 * Разделитель ◇ — обратное смесителю: всё, что в него вошло, он раскладывает
 * на чистые цвета и выпускает каждый в свою сторону — красный, зелёный и
 * синий через три грани, четвёртая глухая. Грани видны на поле цветными
 * полосками. Если зал так выложен, разделитель вращается щелчком на четверть
 * оборота — и все три выхода поворачиваются разом.
 *
 * Зал — механизм устройства «Зал призм (У)» (shturman.mjs): лучи видит один
 * штурман, а зеркала поворачивают остальные рычагами с пульта (vslepuju.mjs),
 * и на время — таймер общий, лежит в stol.mjs. Окно выкладки самой загадки
 * этих полей не показывает: их задаёт устройство.
 */

