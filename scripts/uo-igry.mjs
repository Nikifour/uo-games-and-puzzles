/* ─────────────── кнопка ведущего в панели заметок ─────────────── */

Hooks.on("getSceneControlButtons", controls => {
  if (!game.user.isGM) return;
  const группа = controls.notes ?? controls.journal;
  if (!группа?.tools) return;

  группа.tools["uo-igry"] = {
    name: "uo-igry",
    order: 90,
    title: Т("Игры и загадки"),
    icon: "fa-solid fa-puzzle-piece",
    button: true,
    visible: true,
    onChange: () => панель(),
  };
});

/* ─────────────── связь и обновление окон ─────────────── */

Hooks.once("ready", () => {
  game.socket.on(КАНАЛ, принять);

  // Стол переменился у ведущего — окна у всех перерисовываются сами.
  Hooks.on("updateSetting", setting => {
    if (setting?.key === `${MODULE_ID}.stoly`) освежить();
  });

  склад.переехать();          // заготовки замка из браузера — в журнал склада
  замок.починитьСтарые();     // столы от прежних версий: пометить и прибрать
  кости.починитьИмена();      // партии, выложенные под прежним именем игры
  освежить();                 // зашли в мир, а на столе уже что-то лежит
  кости.подхватитьБотов();    // партия осталась на ходу бота — пусть доиграет
  очко.подхватитьБотов();

  const счёт = Object.keys(всеСтолы()).length;
  if (счёт) console.log(`${MODULE_ID} | на столе: ${счёт}`);
});

/* ─────────────────────────── панель ведущего ─────────────────────────── */

export async function панель() {
  if (!game.user.isGM) return;

  const наСтоле = Object.values(всеСтолы());
  const состояние = с => {
    if (с.тип === "kosti") return с.победитель !== null ? Т(" — партия сыграна") : с.показан ? "" : Т(" — спрятан");
    if (с.тип === "mozaika") return с.собрана ? Т(" — сложена") : с.заклинило ? Т(" — ходы кончились") : с.показан ? "" : Т(" — спрятана");
    if (с.тип === "shifr") return с.прочтена ? Т(" — прочитана") : с.показан ? "" : Т(" — спрятана");
    if (с.тип === "vrata") return с.открыта !== null ? Т(" — открыты") : с.провал ? Т(" — не отзываются") : с.показан ? "" : Т(" — спрятаны");
    if (с.тип === "sozvezdie") return с.сложено ? Т(" — сошлось") : с.заклинило ? Т(" — небо погасло") : с.показан ? "" : Т(" — спрятано");
    if (с.тип === "puti") return с.пройден ? Т(" — пройдена") : с.заклинило ? Т(" — порталы погасли") : с.показан ? "" : Т(" — спрятана");
    if (с.тип === "prizmy") return с.зажжён ? Т(" — зажжён") : с.заклинило ? Т(" — призмы застыли") : с.показан ? "" : Т(" — спрятан");
    if (с.тип === "zerkala") return с.зажжён ? Т(" — зажжён") : с.заклинило ? Т(" — зеркала застыли") : с.показан ? "" : Т(" — спрятан");
    if (с.тип === "dzho") return с.узы?.length ? Т(" — узы Джо") : с.победитель !== null ? Т(" — спор решён") : с.показан ? "" : Т(" — спрятан");
    if (с.тип === "plity") return с.пройден ? Т(" — пройден") : с.заклинило ? Т(" — закрылся") : с.показан ? "" : Т(" — спрятан");
    if (с.тип === "ustrojstvo") return с.решено ? Т(" — открыт") : с.заклинило ? Т(" — заклинило") : с.показан ? "" : Т(" — спрятан");
    if (с.тип === "porjadok") return с.сложена ? Т(" — сошлась") : с.заклинило ? Т(" — попытки кончились") : с.показан ? "" : Т(" — спрятана");
    return с.открыт ? Т(" — открыт") : с.заклинило ? Т(" — заклинило") : с.показан ? "" : Т(" — спрятан");
  };

  const столы = наСтоле.length
    ? `<div class="uo-zagotovki">${наСтоле.map(с => `
        <div class="uo-zagotovka">
          <span>${экранировать(с.название)}${состояние(с)}</span>
          <button type="button" class="uo-vid" data-id="${с.id}">${с.показан ? Т("Спрятать") : Т("Показать")}</button>
          <button type="button" class="uo-ubrat" data-id="${с.id}">${Т("Убрать")}</button>
        </div>`).join("")}</div>`
    : `<p class="uo-podskazka">${Т("Стол пуст.")}</p>`;

  await DialogV2.wait({
    window: { title: Т("Игры и загадки"), icon: "fa-solid fa-puzzle-piece" },
    position: { width: 520 },
    content: `<div class="uo-forma">
      <h2>${Т("Сейчас на столе")}</h2>${столы}
      <h2>${Т("Заготовки загадок")}</h2>${склад.разметка()}
    </div>`,
    buttons: [
      { action: "замок", label: Т("Кодовый замок"), default: true, callback: () => замок.диалогЗамка() },
      { action: "мозаика", label: Т("Мозаика"), callback: () => мозаика.диалогМозаики() },
      { action: "шифр", label: Т("Надпись"), callback: () => шифр.диалогШифра() },
      { action: "порядок", label: Т("Череда"), callback: () => порядок.диалогПорядка() },
      { action: "устройство", label: Т("Устройство"), callback: () => устройство.диалогУстройства() },
      { action: "плиты", label: Т("Зал плит"), callback: () => плиты.диалогПлит() },
      { action: "врата", label: Т("Врата"), callback: () => врата.диалогВрат() },
      { action: "созвездие", label: Т("Созвездие"), callback: () => созвездие.диалогСозвездия() },
      { action: "пути", label: Т("Карта путей"), callback: () => пути.диалогПутей() },
      { action: "зеркала", label: Т("Зал зеркал"), callback: () => зеркала.диалогЗеркал() },
      { action: "призмы", label: Т("Зал призм"), callback: () => призмы.диалогПризм() },
      { action: "кости", label: Т("Кости"), callback: () => кости.диалогКостей() },
      { action: "джо", label: Т("Счастливчик Джо"), callback: () => джо.диалогДжо() },
      { action: "очко", label: Т("Двадцать одно"), callback: () => очко.диалогОчка() },
      { action: "закрыть", label: Т("Закрыть") },
    ],
    render: (event, диалог) => {
      const корень = диалог.element;
      const заново = async дело => { await дело(); диалог.close(); панель(); };

      корень.querySelectorAll(".uo-vid").forEach(к =>
        к.addEventListener("click", () => заново(() => {
          const с = столПоId(к.dataset.id);
          return с?.показан ? спрятать(к.dataset.id) : показать(к.dataset.id);
        })));
      корень.querySelectorAll(".uo-ubrat").forEach(к =>
        к.addEventListener("click", () => заново(() => убрать(к.dataset.id))));

      // Кнопки склада привязывает сам склад: панель показывает его разметку,
      // а не свою, и повторять здесь его правила было бы лишним.
      склад.привязать(корень, {
        закрыть: () => диалог.close(),
        обновить: () => { диалог.close(); панель(); },
      });
    },
  });
}

/* ─────────────── ручное управление из консоли и макросов ─────────────── */

globalThis.UOIgry = {
  /** Панель ведущего — то же, что кнопка в панели заметок. */
  panel: () => панель(),

  /**
   * Склад заготовок — то, что ведущий приготовил заранее.
   *
   * `put("plity", "Зал под усыпальницей", { скрытно: true })` кладёт загадку
   * в мир, не показывая её игрокам: этим и открывается сцена — из макроса
   * на тайле Monk's Active Tiles, а не руками посреди игры.
   */
  presets: {
    window: () => склад.окноСклада(),
    get all() { return склад.всё(); },
    list: тип => склад.список(тип),
    put: (тип, имя, как) => склад.выложить(тип, имя, как),
    save: (тип, имя, настройки) => склад.запомнить(тип, имя, настройки),
    rename: (тип, имя, новое) => склад.переименовать(тип, имя, новое),
    forget: (тип, имя) => склад.забыть(тип, имя),
  },

  gates: { create: () => врата.диалогВрат(), put: к => врата.выложить(к), solve: id => врата.засчитать(id), reset: id => врата.сбросить(id) },
  stars: { create: () => созвездие.диалогСозвездия(), put: к => созвездие.выложить(к), solve: id => созвездие.засчитать(id), reset: id => созвездие.сбросить(id) },
  paths: { create: () => пути.диалогПутей(), put: к => пути.выложить(к), solve: id => пути.засчитать(id), reset: id => пути.сбросить(id) },
  prisms: { create: () => призмы.диалогПризм(), put: к => призмы.выложить(к), solve: id => призмы.засчитать(id), reset: id => призмы.сбросить(id) },

  mirrors: { create: () => зеркала.диалогЗеркал(), put: к => зеркала.выложить(к), solve: id => зеркала.засчитать(id), reset: id => зеркала.сбросить(id) },

  joe: {
    create: () => джо.диалогДжо(),
    seat: конфиг => джо.посадить(конфиг),
    /** Ведущему: назначить местам число. Судьба кладёт кость под руку, берёт её человек. */
    fate: (id, места, номинал) => джо.судьба(id, места, номинал),
    win: (id, индекс) => джо.засчитать(id, индекс),
    reset: id => джо.сбросить(id),
  },

  slabs: {
    create: () => плиты.диалогПлит(),
    put: конфиг => плиты.выложить(конфиг),
    solve: id => плиты.засчитать(id),
    reset: id => плиты.сбросить(id),
    reroute: id => плиты.переложить(id),
  },

  device: {
    create: () => устройство.диалогУстройства(),
    put: конфиг => устройство.выложить(конфиг),
    solve: id => устройство.засчитать(id),
    reset: id => устройство.сбросить(id),
    resend: id => устройство.разослатьОбрывки(id),
    get presets() { return устройство.пул(); },
  },

  order: {
    create: () => порядок.диалогПорядка(),
    put: конфиг => порядок.выложить(конфиг),
    solve: id => порядок.засчитать(id),
    reset: id => порядок.сбросить(id),
    get sets() { return наборы.пул(); },
  },

  cipher: {
    create: () => шифр.диалогШифра(),
    put: конфиг => шифр.выложить(конфиг),
    solve: id => шифр.засчитать(id),
    reset: id => шифр.сбросить(id),
  },

  mosaic: {
    create: () => мозаика.диалогМозаики(),
    put: конфиг => мозаика.выложить(конфиг),
    solve: id => мозаика.засчитать(id),
    reset: id => мозаика.сбросить(id),
  },

  lock: {
    create: () => замок.диалогЗамка(),
    start: имя => замок.выложитьЗаготовку(имя),
    put: конфиг => замок.выложить(конфиг),
    get presets() { return замок.списокЗаготовок(); },
    forget: имя => замок.забытьЗаготовку(имя),
    solve: id => замок.засчитать(id),
    reset: id => замок.сбросить(id),
  },

  ochko: {
    create: () => очко.диалогОчка(),
    /** Посадить за стол из кода: {название, предел, побед, места:[{кто|бот, имя}]}. */
    seat: конфиг => очко.посадить(конфиг),
  },

  kosti: {
    create: () => кости.диалогКостей(),
    /** Правка пула соперников. */
    opponents: () => боты.редактор(),
    /** Посадить за стол из кода: {название, цель, места:[{кто|бот, имя}]}. */
    seat: конфиг => кости.посадить(конфиг),
  },

  /** Что сейчас на столе. */
  get tables() { return всеСтолы(); },

  /** Убрать стол по id, без аргумента — все. */
  clear: async id => {
    if (id) return убрать(id);
    for (const ключ of Object.keys(всеСтолы())) await убрать(ключ);
  },
};
