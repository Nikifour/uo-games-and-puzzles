/**
 * Подписи настроек — на выбранный язык.
 *
 * Настройки заводятся в init, а словарь читается позже, в i18nInit: в init
 * Т ещё не знает языка и отдаёт русское. Русская подпись и есть ключ словаря,
 * поэтому, когда словарь на месте, переводим уже заведённые подписи.
 * Повторный перевод безвреден: английской фразы в словаре нет, она вернётся как есть.
 */
function перевестиНастройки() {
  const перевести = (запись, поля) => {
    for (const поле of поля) if (typeof запись?.[поле] === "string") запись[поле] = Т(запись[поле]);
  };
  const свои = карта => [...(карта ?? new Map())].filter(([ключ]) => ключ.startsWith(`${MODULE_ID}.`));
  try {
    for (const [, меню] of свои(game.settings.menus)) перевести(меню, ["name", "label", "hint"]);
    for (const [, настройка] of свои(game.settings.settings)) {
      перевести(настройка, ["name", "hint"]);
      if (настройка.choices) перевести(настройка.choices, Object.keys(настройка.choices));
    }
  } catch (е) {
    console.warn(`${MODULE_ID} | подписи настроек не переведены`, е);
  }
}

