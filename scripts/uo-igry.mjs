/**
 * UO · Игры и загадки
 *
 * Стол, за которым ведущий выкладывает интерактивные загадки и настольные
 * игры, а игроки в них играют — все видят одно и то же в один и тот же миг.
 *
 * Устройство одно на всё: общий стол (stol.mjs) держит состояние, права
 * и связь, а правила каждой затеи живут отдельным файлом — кодовый замок
 * в zamok.mjs, Кости в kosti.mjs. Правила Костей и соперника вынесены ещё
 * дальше, в kosti-pravila.mjs и kosti-bot.mjs: они не знают о Foundry вовсе,
 * и потому проверяются тысячей партий без запуска мира.
 *
 * Отделено от общего модуля UO: у каждого инструмента своя ссылка,
 * своя установка и своя судьба.
 */

