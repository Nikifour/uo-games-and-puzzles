Hooks.once("ready", () => {
  game.socket.on(КАНАЛ, принять);

  // Стол переменился у ведущего — окна у всех перерисовываются сами.
  Hooks.on("updateSetting", setting => {
    if (setting?.key !== `${MODULE_ID}.stoly`) return;
    сверитьСЗаписью();          // переписанный стол снимает устаревшее «на лету»
    освежить();
    // Стол мог посадить или двинуть другой ведущий: ботов ходит только
    // ведущий за главным креслом, и узнаёт он о новом ходе бота отсюда.
    кости.подхватитьБотов();
    очко.подхватитьБотов();
    джо.подхватитьБотов();
  });

  склад.переехать();          // заготовки замка из браузера — в журнал склада
  замок.починитьСтарые();     // столы от прежних версий: пометить и прибрать
  кости.починитьИмена();      // партии, выложенные под прежним именем игры
  сверитьСЗаписью();          // запомнить, что лежит, — чтобы узнать перемену
  освежить();                 // зашли в мир, а на столе уже что-то лежит
  следитьЗаВременем();        // загадки на время: истёкшее закрывает ведущий
  кости.подхватитьБотов();    // партия осталась на ходу бота — пусть доиграет
  очко.подхватитьБотов();
  джо.подхватитьБотов();

  const счёт = Object.keys(всеСтолы()).length;
  if (счёт) console.log(`${MODULE_ID} | на столе: ${счёт}`);
});

