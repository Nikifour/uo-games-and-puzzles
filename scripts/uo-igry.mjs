/** Что лежит на столе — одной строкой, словами самой затеи. */
function состояниеСтола(с) {
  if (с.тип === "kosti") return с.победитель !== null ? Т(" — партия сыграна") : с.показан ? "" : Т(" — спрятан");
  if (с.тип === "mozaika") return с.собрана ? Т(" — сложена") : с.заклинило ? Т(" — ходы кончились") : с.показан ? "" : Т(" — спрятана");
  if (с.тип === "shifr") return с.прочтена ? Т(" — прочитана") : с.показан ? "" : Т(" — спрятана");
  if (с.тип === "vrata") return с.открыта !== null ? Т(" — открыты") : с.провал ? Т(" — не отзываются") : с.показан ? "" : Т(" — спрятаны");
  if (с.тип === "sozvezdie") return с.сложено ? Т(" — сошлось") : с.заклинило ? Т(" — небо погасло") : с.показан ? "" : Т(" — спрятано");
  if (с.тип === "puti") return с.пройден ? Т(" — пройдена") : с.заклинило ? Т(" — порталы погасли") : с.показан ? "" : Т(" — спрятана");
  if (с.тип === "prizmy") return с.зажжён ? Т(" — зажжён") : с.заклинило ? Т(" — призмы застыли") : с.показан ? "" : Т(" — спрятан");
  if (с.тип === "zerkala") return с.зажжён ? Т(" — зажжён") : с.заклинило ? Т(" — зеркала застыли") : с.показан ? "" : Т(" — спрятан");
  if (с.тип === "dzho") return с.узы?.length ? Т(" — узы Джо") : с.победитель !== null ? Т(" — спор решён") : с.показан ? "" : Т(" — спрятан");
  if (с.тип === "plity") return с.пройден ? Т(" — пройден") : с.заклинило ? Т(" — закрылся") : с.показан ? "" : Т(" — спрятан");
  if (с.тип === "ustrojstvo") return с.решено ? Т(" — открыт") : с.заклинило ? Т(" — заклинило") : с.показан ? "" : Т(" — спрятан");
  if (с.тип === "porjadok") return с.сложена ? Т(" — сошлась") : с.заклинило ? Т(" — попытки кончились") : с.показан ? "" : Т(" — спрятан");
  return с.открыт ? Т(" — открыт") : с.заклинило ? Т(" — заклинило") : с.показан ? "" : Т(" — спрятан");
}

/**
 * Панель ведущего.
 *
 * Прежде это был ряд из четырнадцати кнопок: по названию не видно ни того,
 * загадка это или игра, ни того, что вообще случится на столе, а нажатие
 * сразу открывало настройки. Теперь затеи разведены по роду, а щелчок
 * раскрывает описание с примером — подготовка открывается уже из него.
 */
class ОкноПанели extends ApplicationV2 {
  constructor(options = {}) {
    super(options);
    this.раскрыта = null;
  }

  static DEFAULT_OPTIONS = {
    classes: ["uo-igry", "uo-panel-okno"],
    tag: "div",
    window: { title: М("Игры и загадки"), icon: "fa-solid fa-puzzle-piece", resizable: true },
    position: { width: 640, height: "auto" },
    actions: {
      затея: ОкноПанели.#затея,
      подготовить: ОкноПанели.#подготовить,
      склад: ОкноПанели.#открытьСклад,
      вид: ОкноПанели.#вид,
      вернуть: ОкноПанели.#вернуть,
      убрать: ОкноПанели.#убрать,
      закрыть: ОкноПанели.#закрыть,
    },
  };

  get title() { return Т("Игры и загадки"); }

  static #затея(event, target) {
    const ключ = target.dataset.zateja;
    this.раскрыта = this.раскрыта === ключ ? null : ключ;
    this.render();
  }

  static async #подготовить(event, target) {
    const затея = ЗАТЕИ.find(з => з.ключ === target.dataset.zateja);
    if (!затея) return;
    await this.close();
    затея.открыть();
  }

  static #открытьСклад() { склад.окноСклада(); }

  static async #вид(event, target) {
    const с = столПоId(target.dataset.id);
    await (с?.показан ? спрятать(target.dataset.id) : показать(target.dataset.id));
    this.render();
  }

  /* Окно закрыл сам игрок — возвращаем, не тревожа остальных. */
  static #вернуть(event, target) {
    вернутьОкно(target.dataset.id);
    ui.notifications.info(Т("Окно возвращено тем, кто его закрыл"));
  }

  static async #убрать(event, target) {
    await убрать(target.dataset.id);
    this.render();
  }

  static #закрыть() { this.close(); }

  /** Описание раскрытой затеи: пример, слова и кнопка подготовки. */
  #описание(з) {
    const снимок = з.снимок ? `<img class="uo-zateja-snimok" src="modules/${MODULE_ID}/obzor/${з.ключ}.webp" alt="">` : "";
    return `<div class="uo-zateja-opisanie">
      ${снимок}
      <div class="uo-zateja-slova">
        <p>${Т(з.текст)}</p>
        <button type="button" data-action="подготовить" data-zateja="${з.ключ}">
          <i class="fa-solid fa-table-cells"></i> ${Т("Подготовить и выложить")}
        </button>
      </div>
    </div>`;
  }

  #раздел(род, заголовок) {
    const свои = ЗАТЕИ.filter(з => з.род === род);
    const раскрытая = свои.find(з => з.ключ === this.раскрыта);
    const кнопки = свои.map(з => `
      <button type="button" class="uo-zateja${this.раскрыта === з.ключ ? " uo-vybrana" : ""}"
              data-action="затея" data-zateja="${з.ключ}">${Т(з.имя)}</button>`).join("");
    return `<h2>${заголовок}</h2>
      <div class="uo-zatei">${кнопки}</div>
      ${раскрытая ? this.#описание(раскрытая) : ""}`;
  }

  /**
   * Склад — сводкой и кнопкой.
   *
   * Перечень заготовок с папками и поиском живёт в своём окне: к сороковой
   * заготовке он длиннее самой панели, а искать в нём глазами нечем.
   */
  #склад() {
    const заготовок = склад.счёт();
    const папок = склад.папки().length;
    const слова = заготовок
      ? (папок
        ? Т("Заготовлено: {сколько}, папок: {папок}", { сколько: заготовок, папок })
        : Т("Заготовлено: {сколько}", { сколько: заготовок }))
      : Т("Заготовок пока нет: они появятся, когда впишете имя в поле «Запомнить как заготовку» в диалоге любой загадки.");

    return `<div class="uo-sklad-svodka">
      <span class="uo-podskazka">${слова}</span>
      <button type="button" data-action="склад">
        <i class="fa-solid fa-box-archive"></i> ${Т("Открыть склад")}
      </button>
    </div>`;
  }

  async _renderHTML() {
    const наСтоле = Object.values(всеСтолы());
    const столы = наСтоле.length
      ? `<div class="uo-zagotovki">${наСтоле.map(с => `
          <div class="uo-zagotovka">
            <span>${экранировать(с.название)}${состояниеСтола(с)}</span>
            <button type="button" data-action="вид" data-id="${с.id}">${с.показан ? Т("Спрятать") : Т("Показать")}</button>
            ${с.показан ? `<button type="button" data-action="вернуть" data-id="${с.id}"
              data-tooltip="${Т("Если игрок закрыл окно крестиком")}">${Т("Вернуть окно")}</button>` : ""}
            <button type="button" data-action="убрать" data-id="${с.id}">${Т("Убрать")}</button>
          </div>`).join("")}</div>`
      : `<p class="uo-podskazka">${Т("Стол пуст.")}</p>`;

    return `<div class="uo-forma">
      <h2>${Т("Сейчас на столе")}</h2>${столы}
      ${this.#раздел("загадка", Т("Загадки"))}
      ${this.#раздел("игра", Т("Игры"))}
      ${this.#раздел("устройство", Т("Устройства"))}
      <h2>${Т("Заготовки загадок")}</h2>${this.#склад()}
      <div class="uo-panel-niz">
        <button type="button" data-action="закрыть">${Т("Закрыть")}</button>
      </div>
    </div>`;
  }

  _onRender(context, options) {
    super._onRender?.(context, options);
    // Снимка может не быть — тогда остаются одни слова, а не пустая рамка.
    for (const и of this.element.querySelectorAll(".uo-zateja-snimok")) {
      и.addEventListener("error", () => и.closest(".uo-zateja-opisanie")?.classList.add("uo-bez-snimka"), { once: true });
    }
  }

  _replaceHTML(result, content) { content.innerHTML = result; }

  _onClose(options) {
    super._onClose?.(options);
    if (окно === this) окно = null;
  }
}

/** Панель одна: вторая кнопка поднимает открытую, а не плодит окна. */
let окно = null;

export async function панель() {
  if (!game.user.isGM) return;
  if (окно?.rendered) { окно.bringToFront(); return окно; }
  окно = new ОкноПанели();
  return окно.render({ force: true });
}

