/**
 * Созвездие — соединить звёзды в верную фигуру.
 *
 * Звёзды с именами стоят на небе, а игроки протягивают между ними линии.
 * Какие именно линии верны, сказано не в правилах, а в подсказке из хроники:
 * «старшая звезда Короны держит три младших, и ни одна из них не связана
 * между собой». Разгадка тут — знание о мире, а не ловкость.
 *
 * Звёзды раскладываются по кругу сами: заставлять ведущего расставлять точки
 * мышью — работа на полчаса ради того, что читается и так. Зато имена и связи
 * он пишет текстом, а это и есть содержание.
 */

