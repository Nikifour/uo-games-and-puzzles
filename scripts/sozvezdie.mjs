/** Связь хранится как «меньший-больший», чтобы А-Б и Б-А были одним и тем же. */
export const ключСвязи = (a, b) => (a < b ? `${a}-${b}` : `${b}-${a}`);

/** Разбор строк вида «Ладонь - Око»: имена звёзд ищутся в списке. */
export function разобратьСвязи(текст, звёзды) {
  const имена = звёзды.map(з => з.toLowerCase());
  const связи = [];
  const беда = [];

  for (const строка of String(текст ?? "").split(/\r?\n/)) {
    const голая = строка.trim();
    if (!голая) continue;
    const части = голая.split(/\s*[-—–]\s*/).map(ч => ч.trim()).filter(Boolean);
    if (части.length !== 2) { беда.push(голая); continue; }
    const [a, b] = части.map(ч => имена.indexOf(ч.toLowerCase()));
    if (a < 0 || b < 0 || a === b) { беда.push(голая); continue; }
    связи.push(ключСвязи(a, b));
  }

  return { связи: [...new Set(связи)], беда };
}

/* ─────────────────────────── выложить на стол ─────────────────────────── */

export async function выложить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const звёзды = String(конфиг.звёзды ?? "").split(/\r?\n/).map(с => с.trim()).filter(Boolean);
  if (звёзды.length < 3) { ui.notifications.error(Т("Нужно хотя бы три звезды.")); return null; }

  const { связи, беда } = разобратьСвязи(конфиг.связи, звёзды);
  if (беда.length) {
    ui.notifications.error(Т("Не разобрал связи: {строки}. Пишите «Звезда - Звезда».", { строки: беда.slice(0, 3).join("; ") }));
    return null;
  }
  if (!связи.length) { ui.notifications.error(Т("Нужна хотя бы одна связь.")); return null; }

  await прибрать();

  const id = foundry.utils.randomID();
  const стол = {
    id,
    тип: "sozvezdie",
    название: конфиг.название?.trim() || Т("Созвездие"),
    подпись: конфиг.подпись?.trim() || "",
    тема: (конфиг.тема in ТЕМЫ) ? конфиг.тема : "bezdna",
    звёзды,
    связи: [],                       // что протянули игроки
    выбор: null,                     // какая звезда взята в руку
    попытки: { сделано: 0, предел: Math.max(0, Number(конфиг.предел) || 0) },
    подсказка: конфиг.подсказка === "сколько" ? "сколько" : "нет",
    тянут: конфиг.тянут?.length ? конфиг.тянут : "все",
    макрос: конфиг.макрос?.trim() || null,
    журнал: [],
    сложено: false,
    заклинило: false,
    завершён: false,
    показан: true,
  };

  await тайнуЗапомнить(id, { верные: связи });
  await записать(стол);
  return стол;
}

export async function прибрать() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "sozvezdie" && с.завершён) await убрать(id);
  }
}

/* ─────────────────────────────── правила ─────────────────────────────── */

const можетТянуть = (стол, пользователь) =>
  !!пользователь && !стол.сложено && !стол.заклинило &&
  (пользователь.isGM || стол.тянут === "все" || (стол.тянут ?? []).includes(пользователь.id));

const осталось = стол =>
  стол.попытки.предел ? стол.попытки.предел - стол.попытки.сделано : Infinity;

const отложитьЗапись = foundry.utils.debounce(async id => {
  const сырой = столПоId(id);
  if (!сырой) return;
  const живой = собрать(сырой);
  await записать({ ...сырой, связи: живой.связи, выбор: null });
}, 3000);

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!можетТянуть(стол, пользователь)) return;

  if (запрос.что === "звезда") {
    const какая = Number(запрос.звезда);
    if (!Number.isInteger(какая) || какая < 0 || какая >= стол.звёзды.length) return;

    if (стол.выбор === null || стол.выбор === undefined) return разослать(стол.id, { выбор: какая });
    if (стол.выбор === какая) return разослать(стол.id, { выбор: null });

    // Вторая звезда: тянем линию или снимаем, если она уже есть.
    const ключ = ключСвязи(стол.выбор, какая);
    const связи = стол.связи.includes(ключ)
      ? стол.связи.filter(с => с !== ключ)
      : [...стол.связи, ключ];
    разослать(стол.id, { связи, выбор: null });
    отложитьЗапись(стол.id);
    return;
  }

  if (запрос.что === "сверить") await сверить(стол, запрос.кто);
}

async function сверить(стол, ктоId) {
  if (осталось(стол) <= 0) return;

  const верные = тайна(стол.id)?.верные;
  if (!верные) {
    ui.notifications.error(
      Т("Верная фигура «{название}» не найдена в этом браузере. Засчитайте вручную или выложите заново.", { название: стол.название }));
    return;
  }

  const наши = new Set(стол.связи);
  const надо = new Set(верные);
  const совпало = [...надо].filter(с => наши.has(с)).length;
  const лишние = [...наши].filter(с => !надо.has(с)).length;
  const сложено = совпало === надо.size && лишние === 0;

  const обновлённый = {
    ...столПоId(стол.id),
    связи: стол.связи,
    выбор: null,
    попытки: { ...стол.попытки, сделано: стол.попытки.сделано + 1 },
    журнал: [...(стол.журнал ?? []), {
      кто: имяИгрока(ктоId),
      совпало: стол.подсказка === "сколько" ? совпало : null,
      лишние: стол.подсказка === "сколько" ? лишние : null,
      удача: сложено,
    }].slice(-8),
    сложено,
    завершён: сложено,
  };

  if (!сложено && обновлённый.попытки.предел &&
      обновлённый.попытки.сделано >= обновлённый.попытки.предел) {
    обновлённый.заклинило = true;
    обновлённый.завершён = true;
  }

  await записать(обновлённый);

  if (сложено) {
    await объявить(
      Т(`<p><strong>{название}</strong> — фигура сошлась, звёзды отзываются.</p>
       <p><em>{ктоId} свёл её с попытки номер {сделано}.</em></p>`, { название: экранировать(обновлённый.название), ктоId: экранировать(имяИгрока(ктоId)), сделано: обновлённый.попытки.сделано }),
      обновлённый.название);
    событие("решено", обновлённый);
    await запуститьМакрос(обновлённый.макрос, обновлённый);
  } else if (обновлённый.заклинило) {
    await объявить(Т(`<p><strong>{название}</strong> — небо гаснет, попытки кончились.</p>`, { название: экранировать(стол.название) }),
      стол.название);
  }
}

/* ─────────────────── рычаги ведущего ─────────────────── */

export async function засчитать(id) {
  const стол = столПоId(id);
  if (!стол) return;
  const верные = тайна(id)?.верные ?? собрать(стол).связи;
  const полный = { ...собрать(стол), связи: верные, выбор: null, сложено: true, заклинило: false, завершён: true };
  await записать(полный);
  await объявить(Т(`<p><strong>{название}</strong> — сведено волей ведущего.</p>`, { название: экранировать(полный.название) }), полный.название);
  событие("решено", полный);
  await запуститьМакрос(полный.макрос, полный);
}

export async function сбросить(id) {
  const стол = столПоId(id);
  if (!стол) return;
  await записать({
    ...стол,
    связи: [],
    выбор: null,
    попытки: { ...стол.попытки, сделано: 0 },
    журнал: [],
    сложено: false,
    заклинило: false,
    завершён: false,
  });
}

