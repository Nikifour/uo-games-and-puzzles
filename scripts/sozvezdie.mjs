/** Звёзды по кругу: читается и не требует от ведущего возни с точками. */
export function положения(сколько) {
  return Array.from({ length: сколько }, (_, i) => {
    const угол = (i / сколько) * Math.PI * 2 - Math.PI / 2;
    return { x: 50 + 38 * Math.cos(угол), y: 50 + 38 * Math.sin(угол) };
  });
}

class ОкноСозвездия extends ApplicationV2 {
  constructor(options = {}) {
    super(options);
    this.стол = options.стол;
    this.фигураВидна = false;
  }

  static DEFAULT_OPTIONS = {
    classes: ["uo-igry", "uo-sozvezdie-okno"],
    tag: "div",
    window: { title: М("Созвездие"), icon: "fa-solid fa-star", resizable: false },
    position: { width: 520, height: "auto" },
    actions: {
      звезда: ОкноСозвездия.#звезда,
      сверить: ОкноСозвездия.#сверить,
      фигураВидна: ОкноСозвездия.#фигураВидна,
      засчитать: ОкноСозвездия.#засчитать,
      сброс: ОкноСозвездия.#сброс,
      снять: ОкноСозвездия.#снять,
    },
  };

  get title() { return this.стол?.название ?? Т("Созвездие"); }

  static #звезда(event, target) {
    просить({ id: this.стол.id, что: "звезда", звезда: target.dataset.zvezda });
  }

  static #сверить() { просить({ id: this.стол.id, что: "сверить" }); }
  static #фигураВидна() { this.фигураВидна = !this.фигураВидна; this.render(); }
  static #засчитать() { засчитать(this.стол.id); }
  static #сброс() { сбросить(this.стол.id); }
  static #снять() { убрать(this.стол.id); }

  _onClose() {
    забытьОкно(this.стол.id);
    if (this.закрываемСами) return;
    if (game.user.isGM) спрятать(this.стол.id);
    else спрятатьУСебя(this.стол.id);
  }

  async _renderHTML() {
    const с = this.стол;
    const тянет = можетТянуть(с, game.user);
    const точки = положения(с.звёзды.length);
    const верные = this.фигураВидна ? (тайна(с.id)?.верные ?? []) : [];

    const линия = (ключ, класс) => {
      const [a, b] = ключ.split("-").map(Number);
      return `<line x1="${точки[a].x}" y1="${точки[a].y}" x2="${точки[b].x}" y2="${точки[b].y}" class="${класс}"/>`;
    };

    const небо = `
      <svg class="uo-nebo" viewBox="0 0 100 100" role="img">
        ${верные.map(к => линия(к, "uo-podskazannaja")).join("")}
        ${с.связи.map(к => линия(к, "uo-linija")).join("")}
        ${точки.map((т, i) => `
          <circle cx="${т.x}" cy="${т.y}" r="${с.выбор === i ? 3.4 : 2.4}"
                  class="uo-zvezda ${с.выбор === i ? "uo-vzjata" : ""}"/>`).join("")}
      </svg>`;

    const имена = с.звёзды.map((имя, i) => `
      <button type="button" class="uo-zvezda-knopka ${с.выбор === i ? "uo-vzjata" : ""}"
              ${тянет ? `data-action="звезда" data-zvezda="${i}"` : "disabled"}>
        <span class="uo-nomer">${i + 1}</span>${экранировать(имя)}
      </button>`).join("");

    const счёт = с.попытки.предел
      ? Т("Попытка {номер} из {предел}", { номер: Math.min(с.попытки.сделано + 1, с.попытки.предел), предел: с.попытки.предел })
      : Т("Линий протянуто: {линий}", { линий: с.связи.length });

    const журнал = (с.журнал ?? []).length ? `
      <ol class="uo-zhurnal">
        ${[...с.журнал].reverse().map(з => `
          <li class="${з.удача ? "uo-udacha" : ""}">
            <span class="uo-kto">${экранировать(з.кто)}</span>
            ${з.удача ? Т("— сошлось") : (з.совпало ?? null) !== null
              ? `<span class="uo-podskazka">${Т(`верных {совпало}, лишних {лишние}`, { совпало: з.совпало, лишние: з.лишние })}</span>` : Т("— мимо")}
          </li>`).join("")}
      </ol>` : "";

    const итог = с.сложено
      ? `<p class="uo-itog uo-otkryt">${Т("Фигура сошлась.")}</p>`
      : с.заклинило
        ? `<p class="uo-itog uo-zaklinilo">${Т("Небо погасло. Ведущий может зажечь его снова.")}</p>`
        : "";

    const гм = game.user.isGM ? `
      <section class="uo-gm">
        <div class="uo-gm-kod">
          <button type="button" data-action="фигураВидна">${this.фигураВидна ? Т("Скрыть фигуру") : Т("Показать фигуру")}</button>
        </div>
        <div class="uo-gm-knopki">
          <button type="button" data-action="засчитать">${Т("Засчитать")}</button>
          <button type="button" data-action="сброс">${Т("Стереть линии")}</button>
          <button type="button" data-action="снять">${Т("Убрать со стола")}</button>
        </div>
      </section>` : "";

    return `
      <div class="uo-sozvezdie-telo uo-tema-${экранировать(с.тема)}">
        ${с.подпись ? `<p class="uo-podpis">${экранировать(с.подпись)}</p>` : ""}
        ${небо}
        <div class="uo-zvezdy">${имена}</div>
        <p class="uo-podskazka">${с.выбор !== null && с.выбор !== undefined
          ? Т("Взята звезда <strong>{звезда}</strong> — выберите вторую. Повторная линия стирается.", { звезда: экранировать(с.звёзды[с.выбор]) })
          : Т("Возьмите звезду, потом вторую — между ними ляжет линия.")}</p>
        <div class="uo-stroka">
          <span class="uo-schet">${счёт}</span>
          ${тянет && осталось(с) > 0
            ? `<button type="button" class="uo-proverit" data-action="сверить">${Т("Сверить с небом")}</button>` : ""}
        </div>
        ${итог}
        ${журнал}
        ${гм}
      </div>`;
  }

  _replaceHTML(result, content) { content.innerHTML = result; }
}

