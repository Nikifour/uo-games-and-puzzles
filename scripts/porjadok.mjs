/**
 * Порядок — расставить картинки в нужной череде.
 *
 * Шесть фресок в порядке событий, четыре герба по старшинству, пять ступеней
 * обряда. Набор ведущий готовит заранее (настройки модуля, «Наборы картинок»),
 * а загадка тасует его при выкладывании.
 *
 * Меняются картинки местами щелчками: ткнул одну, ткнул вторую — поменялись.
 * Перетаскивание было бы красивее, но щелчок переживает и чужой курсор,
 * и медленную сеть, а за столом важнее, чтобы у всех совпадало.
 *
 * Тайна тут настоящая, и хранится она хитрее, чем у замка: сам набор лежит
 * на столе **уже перетасованным**, а верная череда — у ведущего. Иначе
 * порядок строк в состоянии стола и был бы ответом.
 */

