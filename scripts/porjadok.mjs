const экранировать = s => foundry.utils.escapeHTML(String(s ?? ""));

/* ─────────────────────────── выложить на стол ─────────────────────────── */

/** Перестановка «как попало», но не совпадающая с исходной. */
function перетасовать(сколько) {
  const порядок = Array.from({ length: сколько }, (_, i) => i);
  for (let i = порядок.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [порядок[i], порядок[j]] = [порядок[j], порядок[i]];
  }
  if (порядок.every((к, i) => к === i)) [порядок[0], порядок[1]] = [порядок[1], порядок[0]];
  return порядок;
}

export async function выложить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const исходные = конфиг.картинки?.length
    ? конфиг.картинки
    : наборы.пул()[Number(конфиг.набор)]?.картинки;

  if (!исходные || исходные.length < 2) {
    ui.notifications.error(Т("Нужен набор хотя бы из двух картинок."));
    return null;
  }

  // На стол картинки ложатся вперемешку, и порядок этого списка ничего
  // не выдаёт: верную череду знает только ведущий.
  const тасовка = перетасовать(исходные.length);
  const картинки = тасовка.map(и => ({
    путь: исходные[и].путь,
    подпись: исходные[и].подпись ?? "",
  }));
  // Верная череда — обратная перестановка: на месте i должна стоять та картинка,
  // что была i-й в наборе, а лежит она теперь там, куда её отправила тасовка.
  const верный = исходные.map((_, i) => тасовка.indexOf(i));

  await прибрать();

  const id = foundry.utils.randomID();
  const стол = {
    id,
    тип: "porjadok",
    название: конфиг.название?.trim() || Т("Череда"),
    подпись: конфиг.подпись?.trim() || "",
    тема: (конфиг.тема in ТЕМЫ) ? конфиг.тема : "kamen",
    картинки,
    порядок: картинки.map((_, i) => i),          // как лежит сейчас
    выбор: null,                                  // какую картинку взяли в руку
    попытки: { сделано: 0, предел: Math.max(0, Number(конфиг.предел) || 0) },
    подсказка: конфиг.подсказка === "сколько" ? "сколько" : "нет",
    двигают: конфиг.двигают?.length ? конфиг.двигают : "все",
    макрос: конфиг.макрос?.trim() || null,
    журнал: [],
    сложена: false,
    заклинило: false,
    завершён: false,
    показан: true,
  };

  await тайнуЗапомнить(id, { верный });
  await записать(стол);
  return стол;
}

export async function прибрать() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "porjadok" && с.завершён) await убрать(id);
  }
}

/* ─────────────────────────────── правила ─────────────────────────────── */

const можетДвигать = (стол, пользователь) =>
  !!пользователь && !стол.сложена && !стол.заклинило &&
  (пользователь.isGM || стол.двигают === "все" || (стол.двигают ?? []).includes(пользователь.id));

const осталосьПопыток = стол =>
  стол.попытки.предел ? стол.попытки.предел - стол.попытки.сделано : Infinity;

// Перестановки идут чаще, чем стоит писать в базу.
const отложитьЗапись = foundry.utils.debounce(async id => {
  const сырой = столПоId(id);
  if (!сырой) return;
  const живой = собрать(сырой);
  await записать({ ...сырой, порядок: живой.порядок, выбор: null });
}, 4000);

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!можетДвигать(стол, пользователь)) return;

  if (запрос.что === "взять") {
    const место = Number(запрос.место);
    if (!Number.isInteger(место) || место < 0 || место >= стол.порядок.length) return;

    // Второй щелчок по той же картинке — передумали.
    if (стол.выбор === место) return разослать(стол.id, { выбор: null });

    // Первый щелчок — берём в руку, второй — меняем местами.
    if (стол.выбор === null || стол.выбор === undefined) return разослать(стол.id, { выбор: место });

    const порядок = [...стол.порядок];
    [порядок[стол.выбор], порядок[место]] = [порядок[место], порядок[стол.выбор]];
    разослать(стол.id, { порядок, выбор: null });
    отложитьЗапись(стол.id);
    return;
  }

  if (запрос.что === "проверить") await проверить(стол, запрос.кто);
}

async function проверить(стол, ктоId) {
  if (осталосьПопыток(стол) <= 0) return;

  const верный = тайна(стол.id)?.верный;
  if (!верный) {
    ui.notifications.error(
      `Верная череда для «${стол.название}» не найдена в этом браузере. Засчитайте вручную или выложите заново.`);
    return;
  }

  const наМестах = стол.порядок.reduce((n, к, i) => n + (к === верный[i] ? 1 : 0), 0);
  const сложена = наМестах === верный.length;

  const обновлённый = {
    ...стол,
    выбор: null,
    попытки: { ...стол.попытки, сделано: стол.попытки.сделано + 1 },
    журнал: [...стол.журнал, {
      кто: имяИгрока(ктоId),
      наМестах: стол.подсказка === "сколько" ? наМестах : null,
      удача: сложена,
    }].slice(-10),
    сложена,
    завершён: сложена,
  };

  if (!сложена && обновлённый.попытки.предел &&
      обновлённый.попытки.сделано >= обновлённый.попытки.предел) {
    обновлённый.заклинило = true;
    обновлённый.завершён = true;
  }

  await записать(обновлённый);

  if (сложена) {
    await объявить(
      Т(`<p><strong>{название}</strong> — череда сошлась.</p>
       <p><em>{ктоId} угадал с попытки номер {сделано}.</em></p>`, { название: экранировать(обновлённый.название), ктоId: экранировать(имяИгрока(ктоId)), сделано: обновлённый.попытки.сделано }),
      обновлённый.название);
    событие("решено", обновлённый);
    await запуститьМакрос(обновлённый.макрос, обновлённый);
  } else if (обновлённый.заклинило) {
    await объявить(
      Т(`<p><strong>{название}</strong> — попытки кончились.</p>`, { название: экранировать(обновлённый.название) }), обновлённый.название);
  }
}

/* ─────────────────── рычаги ведущего (нажимает он сам) ─────────────────── */

export async function засчитать(id) {
  const стол = столПоId(id);
  if (!стол) return;
  const верный = тайна(id)?.верный ?? собрать(стол).порядок;
  const полный = { ...собрать(стол), порядок: верный, выбор: null, сложена: true, заклинило: false, завершён: true };
  await записать(полный);
  await объявить(Т(`<p><strong>{название}</strong> — сложена волей ведущего.</p>`, { название: экранировать(полный.название) }), полный.название);
  событие("решено", полный);
  await запуститьМакрос(полный.макрос, полный);
}

export async function сбросить(id) {
  const стол = столПоId(id);
  if (!стол) return;
  await записать({
    ...стол,
    порядок: перетасовать(стол.картинки.length),
    выбор: null,
    попытки: { ...стол.попытки, сделано: 0 },
    журнал: [],
    сложена: false,
    заклинило: false,
    завершён: false,
  });
}

/* ──────────────────────────────── окно ──────────────────────────────── */

class ОкноПорядка extends ApplicationV2 {
  constructor(options = {}) {
    super(options);
    this.стол = options.стол;
    this.ответВидно = false;
  }

  static DEFAULT_OPTIONS = {
    classes: ["uo-igry", "uo-porjadok-okno"],
    tag: "div",
    window: { title: Т("Череда"), icon: "fa-solid fa-arrow-down-1-9", resizable: false },
    position: { width: 560, height: "auto" },
    actions: {
      взять: ОкноПорядка.#взять,
      проверить: ОкноПорядка.#проверить,
      крупно: ОкноПорядка.#крупно,
      ответВидно: ОкноПорядка.#ответВидно,
      засчитать: ОкноПорядка.#засчитать,
      сброс: ОкноПорядка.#сброс,
      снять: ОкноПорядка.#снять,
    },
  };

  get title() { return this.стол?.название ?? Т("Череда"); }

  static #взять(event, target) {
    просить({ id: this.стол.id, что: "взять", место: target.dataset.mesto });
  }

  static #проверить() { просить({ id: this.стол.id, что: "проверить" }); }

  static #крупно(event, target) {
    const к = this.стол.картинки[Number(target.dataset.kartinka)];
    if (!к) return;
    new foundry.applications.apps.ImagePopout({
      src: к.путь,
      window: { title: к.подпись || this.стол.название },
    }).render(true);
  }

  static #ответВидно() { this.ответВидно = !this.ответВидно; this.render(); }
  static #засчитать() { засчитать(this.стол.id); }
  static #сброс() { сбросить(this.стол.id); }
  static #снять() { убрать(this.стол.id); }

  _onClose() {
    забытьОкно(this.стол.id);
    if (this.закрываемСами) return;
    if (game.user.isGM) спрятать(this.стол.id);
    else спрятатьУСебя(this.стол.id);
  }

  async _renderHTML() {
    const с = this.стол;
    const двигает = можетДвигать(с, game.user);
    const выбор = с.выбор ?? null;

    const карточки = с.порядок.map((какая, место) => {
      const к = с.картинки[какая] ?? {};
      return `
        <figure class="uo-karta ${выбор === место ? "uo-vzjata" : ""}">
          <span class="uo-nomer">${место + 1}</span>
          <img src="${к.путь ?? ""}" alt="" data-action="крупно" data-kartinka="${какая}">
          ${к.подпись ? `<figcaption>${экранировать(к.подпись)}</figcaption>` : ""}
          ${двигает
            ? `<button type="button" class="uo-vzjat" data-action="взять" data-mesto="${место}">${
                выбор === место ? Т("в руке") : "взять"}</button>`
            : ""}
        </figure>`;
    }).join("");

    const остаток = осталосьПопыток(с);
    const счёт = с.попытки.предел
      ? `Попытка ${Math.min(с.попытки.сделано + 1, с.попытки.предел)} из ${с.попытки.предел}`
      : `Попыток сделано: ${с.попытки.сделано}`;

    const журнал = с.журнал.length ? `
      <ol class="uo-zhurnal">
        ${[...с.журнал].reverse().map(з => `
          <li class="${з.удача ? "uo-udacha" : ""}">
            <span class="uo-kto">${экранировать(з.кто)}</span>
            ${з.удача ? "— сошлось" : (з.наМестах ?? null) !== null
              ? `<span class="uo-podskazka">${Т(`на своих местах: {наМестах}`, { наМестах: з.наМестах })}</span>` : "— мимо"}
          </li>`).join("")}
      </ol>` : "";

    const итог = с.сложена
      ? `<p class="uo-itog uo-otkryt">${Т("Череда сошлась.")}</p>`
      : с.заклинило
        ? `<p class="uo-itog uo-zaklinilo">${Т("Попытки кончились. Ведущий может дать ещё.")}</p>`
        : "";

    const ответ = (тайна(с.id)?.верный ?? []).map(и => с.картинки[и]?.подпись || (и + 1)).join(" → ");
    const гм = game.user.isGM ? `
      <section class="uo-gm">
        <div class="uo-gm-kod">
          <button type="button" data-action="ответВидно">${this.ответВидно ? Т("Скрыть ответ") : Т("Показать ответ")}</button>
          ${this.ответВидно ? `<code>${экранировать(ответ) || Т("— в этом браузере неизвестен —")}</code>` : ""}
        </div>
        <div class="uo-gm-knopki">
          <button type="button" data-action="засчитать">${Т("Засчитать")}</button>
          <button type="button" data-action="сброс">${Т("Перетасовать")}</button>
          <button type="button" data-action="снять">${Т("Убрать со стола")}</button>
        </div>
      </section>` : "";

    return `
      <div class="uo-porjadok-telo uo-tema-${экранировать(с.тема)}">
        ${с.подпись ? `<p class="uo-podpis">${экранировать(с.подпись)}</p>` : ""}
        <div class="uo-karty">${карточки}</div>
        <div class="uo-stroka">
          <span class="uo-schet">${счёт}</span>
          ${двигает && остаток > 0
            ? `<button type="button" class="uo-proverit" data-action="проверить">${Т("Проверить")}</button>`
            : ""}
        </div>
        ${итог}
        ${журнал}
        ${гм}
      </div>`;
  }

  _replaceHTML(result, content) { content.innerHTML = result; }
}

/* ──────────────────────────── диалог создания ──────────────────────────── */

export async function диалогПорядка(заготовка = null, имяЗаготовки = "") {
  if (!game.user.isGM) return null;

  const склад = наборы.пул();
  if (!склад.length) {
    ui.notifications.warn(
      Т("Сперва заведите набор: Настройки → Настройки модулей → UO · Игры и загадки → Наборы картинок."));
    return null;
  }

  const темы = Object.entries(ТЕМЫ).map(([id, имя]) => `<option value="${id}">${имя}</option>`).join("");
  const выборНабора = склад
    .map((н, i) => `<option value="${i}">${Т(`{имя} — картинок {картинки}`, { имя: экранировать(н.имя), картинки: н.картинки.length })}</option>`).join("");
  const игроки = game.users.filter(u => !u.isGM).map(u =>
    `<label class="uo-igrok"><input type="checkbox" name="игрок" value="${u.id}"> ${экранировать(u.name)}</label>`).join("");

  return DialogV2.wait({
    window: { title: Т("Новая череда"), icon: "fa-solid fa-arrow-down-1-9" },
    position: { width: 480 },
    content: `
      <div class="uo-forma">
        <label>${Т("Название")} <input type="text" name="название" value="Череда"></label>
        <label>${Т("Задача")} <input type="text" name="подпись" placeholder="${Т("«разложите по порядку событий»")}"></label>
        <label>${Т("Набор")} <select name="набор">${выборНабора}</select></label>
        <label>${Т("Оформление")} <select name="тема">${темы}</select></label>
        <label>${Т("Предел попыток")} <input type="number" name="предел" value="0" min="0" step="1"></label>
        <label>${Т("Подсказка после неудачи")}
          <select name="подсказка">
            <option value="нет">${Т("никакой")}</option>
            <option value="сколько">${Т("сколько картинок на своих местах")}</option>
          </select>
        </label>
        <label>${Т("Макрос при разгадке")} <input type="text" name="макрос" placeholder="${Т("имя макроса, необязательно")}"></label>
        <fieldset>
          <legend>${Т("Кто двигает картинки")}</legend>
          <label class="uo-igrok"><input type="radio" name="кто" value="все" checked> ${Т("Все игроки")}</label>
          <label class="uo-igrok"><input type="radio" name="кто" value="отмеченные"> ${Т("Только отмеченные ниже")}</label>
          ${игроки || `<p class="uo-podskazka">${Т("Игроков в мире нет.")}</p>`}
        </fieldset>
        ${полеЗаготовки(имяЗаготовки)}
      </div>`,
    buttons: [
      {
        action: "выложить", label: Т("Выложить на стол"), default: true,
        callback: async (event, кнопка, диалог) => {
          const э = диалог.element;
          const зн = имя => э.querySelector(`[name="${имя}"]`)?.value?.trim() ?? "";
          const поимённо = э.querySelector(`[name="кто"][value="отмеченные"]`)?.checked;

          return выложить(await запомнитьИзДиалога("porjadok", э, {
            название: зн("название"), подпись: зн("подпись"), набор: зн("набор"),
            тема: зн("тема"), предел: зн("предел"), подсказка: зн("подсказка"), макрос: зн("макрос"),
            двигают: поимённо ? [...э.querySelectorAll(`[name="игрок"]:checked`)].map(и => и.value) : [],
          }));
        },
      },
      { action: "отмена", label: Т("Отмена") },
    ],
    render: (event, диалог) => заполнить(диалог.element, заготовка),
  });
}

