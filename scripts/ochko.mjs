const экранировать = s => foundry.utils.escapeHTML(String(s ?? ""));
const пауза = мс => new Promise(r => setTimeout(r, мс));

/* ────────────────────────────── посадка ────────────────────────────── */

const пустаяРука = () => ({ кубики: [], стоит: false, вышел: false });

export async function посадить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const места = (конфиг.места ?? []).map(м => ({
    кто: м.кто ?? null,
    имя: м.имя,
    бот: м.бот ?? null,
    победы: 0,
  }));

  if (места.length < 2) { ui.notifications.error(Т("За стол нужно посадить хотя бы двоих.")); return null; }

  const стол = {
    id: foundry.utils.randomID(),
    тип: "ochko",
    название: конфиг.название?.trim() || Т("Двадцать одно"),
    правила: {
      ...ПРАВИЛА,
      предел: Math.max(6, Number(конфиг.предел) || ПРАВИЛА.предел),
      побед: Math.max(1, Number(конфиг.побед) || ПРАВИЛА.побед),
    },
    места,
    ставка: {
      сколько: Math.max(0, Number(конфиг.ставка) || 0),
      монета: конфиг.монета in МОНЕТЫ ? конфиг.монета : "gp",
      слисты: конфиг.слисты !== false,
      банк: 0,
      внесли: [],
    },
    раунд: 1,
    чей: 0,
    руки: места.map(пустаяРука),
    журнал: [],
    победитель: null,
    завершён: false,
    показан: true,
  };

  await записать(стол);
  const собран = await собратьСтавки(столПоId(стол.id));

  await объявить(
    Т(`<p>Стол «{название}»: {кто}.</p><p>Играем до {побед} побед, перебор — больше {предел}.</p>`, {
      название: экранировать(собран.название),
      кто: места.map(м => экранировать(м.имя)).join(", "),
      побед: собран.правила.побед,
      предел: собран.правила.предел,
    }), собран.название);

  двинутьБота(стол.id);
  return столПоId(стол.id);
}

/* ─────────────────────────────── бросок ─────────────────────────────── */

/**
 * Бросок одного кубика на глазах у стола.
 *
 * Настройка «broski» общая для всех игр семьи: громко в чат, тихо одному
 * ведущему или вовсе молча — тогда число просто появится в окне.
 */
async function броситьВИгре(грань, чьё, название) {
  const бросок = await new Roll(`1d${грань}`).evaluate();
  const режим = game.settings.get(MODULE_ID, "broski");

  if (режим === "tikho" && game.dice3d) {
    await game.dice3d.showForRoll(бросок, game.user, true);
  } else if (режим !== "tikho") {
    await бросок.toMessage({
      speaker: { alias: `${название} · ${чьё}` },
      flavor: Т(`бросает к{грань}`, { грань }),
    }, { rollMode: режим === "gm" ? CONST.DICE_ROLL_MODES.PRIVATE : CONST.DICE_ROLL_MODES.PUBLIC });
  }

  return бросок.dice[0].results[0].result;
}

/* ────────────────────────────── ходы людей ────────────────────────────── */

const место = стол => стол.места[стол.чей];
const рука = стол => стол.руки[стол.чей] ?? пустаяРука();

function егоХод(стол, пользователь) {
  if (!стол || стол.завершён || стол.победитель !== null) return false;
  const м = место(стол);
  if (!м) return false;
  // Ведущий ходит за пустое место и за бота: за столом всегда кто-то отвечает.
  return м.кто === пользователь.id || (!!пользователь.isGM && (!м.кто || м.бот));
}

function вЖурнал(стол, строка) {
  const журнал = [...(стол.журнал ?? []), строка].slice(-14);
  return { ...стол, журнал };
}

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!пользователь) return;

  if (запрос.что === "встать") {
    const индекс = стол.места.findIndex(м => м.кто === пользователь.id);
    if (индекс >= 0) await выгнать(стол.id, индекс, false, "сам");
    return;
  }

  if (!егоХод(стол, пользователь)) return;

  if (запрос.что === "взять") return взять(стол, Number(запрос.грань));
  if (запрос.что === "хватит") return хватит(стол);
  if (запрос.что === "пропустить" && пользователь.isGM) return дальше(стол);
}

/** Бросить кубик выбранного вида и прибавить к сумме. */
async function взять(стол, грань) {
  const моя = рука(стол);
  if (!КУБИКИ.includes(грань) || !доступные(моя).includes(грань)) return;
  if (закончил(моя, стол.правила)) return;

  const имя = место(стол).имя;
  const значение = await броситьВИгре(грань, имя, стол.название);

  const свежийСтол = столПоId(стол.id);
  if (!свежийСтол) return;

  const руки = свежийСтол.руки.map((р, i) => i === свежийСтол.чей
    ? { ...р, кубики: [...р.кубики, { грань, значение }] }
    : р);

  const стало = сумма(руки[свежийСтол.чей]);
  let свежий = вЖурнал({ ...свежийСтол, руки },
    Т(`{имя}: к{грань} → {значение}, всего {всего}`, { имя, грань, значение, всего: стало }));

  if (перебор(руки[свежийСтол.чей], свежийСтол.правила)) {
    await записать(свежий);
    await объявить(
      Т(`<p><strong>{имя}</strong> перебрал: {всего} при пределе {предел}.</p>`,
        { имя: экранировать(имя), всего: стало, предел: свежийСтол.правила.предел }), свежийСтол.название);
    await пауза(700);
    return дальше(столПоId(стол.id));
  }

  await записать(свежий);

  // Кубики кончились — рука доиграна сама собой, тянуть нечего.
  if (!доступные(руки[свежийСтол.чей]).length) {
    await пауза(500);
    return дальше(столПоId(стол.id));
  }
}

/** «Хватит»: рука закрывается с тем, что набрано. */
async function хватит(стол) {
  const свежийСтол = столПоId(стол.id);
  if (!свежийСтол) return;

  const руки = свежийСтол.руки.map((р, i) => i === свежийСтол.чей ? { ...р, стоит: true } : р);
  const имя = место(свежийСтол).имя;
  const итог = сумма(руки[свежийСтол.чей]);

  await записать(вЖурнал({ ...свежийСтол, руки }, Т(`{имя} остановился на {итог}`, { имя, итог })));
  await пауза(400);
  return дальше(столПоId(стол.id));
}

/**
 * Передать ход дальше. Если доиграли все — подвести раунд.
 *
 * Ищем следующего, кто ещё не закончил, начиная от текущего. Пустых мест
 * не бывает: вышедшего из-за стола убирают вместе с рукой.
 */
async function дальше(стол) {
  if (!стол || стол.завершён) return;

  const всего = стол.места.length;
  for (let шаг = 1; шаг <= всего; шаг++) {
    const i = (стол.чей + шаг) % всего;
    if (!закончил(стол.руки[i], стол.правила)) {
      await записать({ ...стол, чей: i });
      двинутьБота(стол.id);
      return;
    }
  }

  return подвестиРаунд(стол);
}

/** Раунд доигран: сравнить суммы, начислить победу, начать новый или закончить партию. */
async function подвестиРаунд(стол) {
  const { победители, лучшая, всеПеребрали } = итогРаунда(стол.руки, стол.правила);

  const строки = стол.места.map((м, i) => {
    const с = сумма(стол.руки[i]);
    const бит = перебор(стол.руки[i], стол.правила);
    return `<li>${экранировать(м.имя)} — ${бит ? Т(`перебор ({сумма})`, { сумма: с }) : с}</li>`;
  }).join("");

  let свежий = { ...стол };
  let итогом = "";

  if (всеПеребрали) {
    итогом = Т("<p>Перебрали все — раунд ничей.</p>");
    свежий = вЖурнал(свежий, Т(`Раунд {номер}: перебрали все`, { номер: стол.раунд }));
  } else if (победители.length > 1) {
    итогом = Т(`<p>Поровну — {сумма} у нескольких. Раунд ничей.</p>`, { сумма: лучшая });
    свежий = вЖурнал(свежий, Т(`Раунд {номер}: ничья на {сумма}`, { номер: стол.раунд, сумма: лучшая }));
  } else {
    const i = победители[0];
    const места = свежий.места.map((м, j) => j === i ? { ...м, победы: м.победы + 1 } : м);
    свежий = { ...свежий, места };
    итогом = Т(`<p><strong>{имя}</strong> берёт раунд: {сумма}.</p>`,
      { имя: экранировать(места[i].имя), сумма: лучшая });
    свежий = вЖурнал(свежий, Т(`Раунд {номер}: {имя} — {сумма}`,
      { номер: стол.раунд, имя: места[i].имя, сумма: лучшая }));
  }

  await объявить(`<p>${Т(`Раунд {номер}`, { номер: стол.раунд })}</p><ul>${строки}</ul>${итогом}`, стол.название);

  const чемпион = свежий.места.findIndex(м => м.победы >= свежий.правила.побед);
  if (чемпион >= 0) {
    свежий = { ...свежий, победитель: чемпион, завершён: true };
    await записать(свежий);
    await объявить(
      Т(`<p><strong>{имя}</strong> забирает партию: {побед} побед.</p>`,
        { имя: экранировать(свежий.места[чемпион].имя), побед: свежий.места[чемпион].победы }), свежий.название);
    await выдатьБанк(свежий, чемпион);
    событие("победа", свежий);
    return;
  }

  /*
   * Новый раунд начинает следующее место. Ходить последним выгодно — видно
   * чужие суммы, — поэтому право первого хода идёт по кругу, а не остаётся
   * у того, кому досталось при посадке.
   */
  const номер = стол.раунд + 1;
  await пауза(900);
  await записать({
    ...свежий,
    раунд: номер,
    чей: (номер - 1) % свежий.места.length,
    руки: свежий.места.map(пустаяРука),
  });
  двинутьБота(стол.id);
}

/* ─────────────────────────────── ход бота ─────────────────────────────── */

let ботЗанят = false;

/** Если на очереди бот и мы за ведущего — сыграть его руку целиком. */
export async function двинутьБота(id) {
  if (!ведущийЗдесь() || ботЗанят) return;

  const стол = столПоId(id);
  if (!стол || стол.завершён || стол.тип !== "ochko") return;
  const м = стол.места[стол.чей];
  if (!м?.бот) return;

  ботЗанят = true;
  try {
    const характер = ХАРАКТЕРЫ[м.бот.характер] ?? ХАРАКТЕРЫ[ХАРАКТЕР_ПО_УМОЛЧАНИЮ];

    // Страховка от бесконечности: кубиков всего шесть, но пусть петля знает предел.
    for (let шаг = 0; шаг < КУБИКИ.length + 1; шаг++) {
      const текущий = столПоId(id);
      if (!текущий || текущий.завершён || текущий.места[текущий.чей] !== м) break;

      const моя = текущий.руки[текущий.чей];
      if (закончил(моя, текущий.правила)) break;

      const реш = решение({
        рука: моя,
        лучшийЧужой: лучшийСредиДоигравших(текущий),
        чужиеДоиграли: остальныеДоиграли(текущий),
        правила: текущий.правила,
        характер,
      });

      await пауза(700);
      if (реш.грань === null) { await хватит(текущий); break; }
      await взять(текущий, реш.грань);
    }
  } finally {
    ботЗанят = false;
  }
}

/** Лучшая сумма среди тех, кто уже закончил и не перебрал. */
function лучшийСредиДоигравших(стол) {
  const суммы = стол.руки
    .map((р, i) => ({ р, i }))
    .filter(({ р, i }) => i !== стол.чей && закончил(р, стол.правила) && !перебор(р, стол.правила))
    .map(({ р }) => сумма(р));
  return суммы.length ? Math.max(...суммы) : 0;
}

const остальныеДоиграли = стол =>
  стол.руки.every((р, i) => i === стол.чей || закончил(р, стол.правила));

/* ──────────────────────────── выход из-за стола ──────────────────────────── */

export async function выгнать(id, индекс, вернутьСтавку = false, причина = "ведущий") {
  if (!game.user.isGM) return;
  const стол = столПоId(id);
  if (!стол || !стол.места[индекс]) return;

  const ушедший = стол.места[индекс];

  if (стол.места.length <= 2) {
    await объявить(
      Т(`<p><strong>{имя}</strong> встаёт из-за стола — играть больше не с кем.</p>`,
        { имя: экранировать(ушедший.имя) }), стол.название);
    if (вернутьСтавку) await вернутьСтавки(стол);
    await убрать(id);
    return;
  }

  const места = стол.места.filter((_, i) => i !== индекс);
  const руки = стол.руки.filter((_, i) => i !== индекс);
  const чей = стол.чей > индекс ? стол.чей - 1 : (стол.чей === индекс ? стол.чей % места.length : стол.чей);

  await записать(вЖурнал({ ...стол, места, руки, чей },
    Т(`{имя} встаёт из-за стола ({причина})`, { имя: ушедший.имя, причина })));

  await объявить(
    Т(`<p><strong>{имя}</strong> встаёт из-за стола.</p>`, { имя: экранировать(ушедший.имя) }), стол.название);

  const свежий = столПоId(id);
  if (свежий && закончил(свежий.руки[свежий.чей], свежий.правила)) return дальше(свежий);
  двинутьБота(id);
}

