/**
 * Двадцать одно за столом: места, раунды, сукно и соперник-бот.
 *
 * Правила и решение соперника живут отдельно и Foundry не знают
 * (ochko-pravila.mjs) — здесь только стол: кто сидит, чей ход, что набрано
 * и как это показать. Кубики бросает Foundry, поэтому Dice So Nice катает
 * их у всех на глазах, а не рисует числа.
 *
 * Ход устроен как в блэкджеке: игрок доигрывает свою руку до конца — берёт
 * кубики один за другим и говорит «хватит», — и только потом ход уходит
 * дальше. Так последний за столом видит чужие суммы, и это не изъян,
 * а суть игры: поэтому первый ход каждый раунд достаётся новому месту.
 */

