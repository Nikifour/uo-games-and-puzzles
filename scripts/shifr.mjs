/*
 * ─────────────────────────── надпись вслепую ───────────────────────────
 *
 * «Надпись (У)»: штурман видит шифр целиком, кольца крутят другие.
 *
 * Надпись шифруется подстановкой, как обычная, но подставляет не штурман:
 * у него нет органов ввода. Значения задают кольца, а кольца крутят с
 * пультов, где видно одни номера рычагов.
 *
 * Колец может быть меньше, чем разных букв в шифре. Тогда буквы без колец
 * так и остаются шифром — их не изменит никто, и надпись до конца не
 * сойдётся. Это сознательно: ведущий либо добивает кольца кнопкой в окне
 * подготовки, либо кладёт заведомо недочитываемую надпись и заканчивает её
 * «Засчитать».
 *
 * Кольцо — это шифр-буква, а не позиция: буква повторяется, и все её
 * вхождения ходят разом. Так и должно быть у подстановки.
 *
 * Победу по-прежнему объявляет штурман кнопкой «Прочесть», а не модуль.
 * Устройство меняет способ игры, но не нрав загадки.
 */

/** Детали для рычагов: «к0» — кольцо на шаг вперёд, «к0+»/«к0-» — в обе стороны. */
export const деталиНадписи = (колец, обеСтороны = false) => Array.from({ length: колец }, (_, i) =>
  (обеСтороны ? [`к${i}+`, `к${i}-`] : [`к${i}`])).flat();

/** Кольцо и шаг по детали рычага. */
const кольцоДетали = деталь => {
  const м = /^к(\d+)([+-]?)$/.exec(String(деталь ?? ""));
  return м ? { кольцо: Number(м[1]), шаг: м[2] === "-" ? -1 : 1 } : null;
};

/** Какие буквы азбуки встречаются в тексте: по разу и в порядке появления. */
export const буквыФразы = (текст, буквы) =>
  [...new Set([...String(текст ?? "")].filter(з => буквы.includes(з)))];

/**
 * Буквы текста по убыванию частоты.
 *
 * Частая буква меняется на глазах сразу в нескольких местах, и штурману есть
 * за что ухватиться: в знакомом месте проступает знакомое слово. Редкая
 * мелькнёт однажды, и пульт будет крутить без всякого отклика.
 */
export function частыеБуквы(текст, буквы, сколько) {
  const счёт = new Map();
  for (const з of String(текст ?? "")) if (буквы.includes(з)) счёт.set(з, (счёт.get(з) ?? 0) + 1);
  return [...счёт.entries()].sort((а, б) => б[1] - а[1]).slice(0, Math.max(0, сколько)).map(([б]) => б);
}

/**
 * Набор кандидатов на кольцо: верная буква и несколько чужих, вперемешку.
 *
 * Длина набора — это и есть трудность: рычаг двигает кольцо на шаг, и набор
 * из тридцати двух букв проходится тридцатью двумя нажатиями. Пять-шесть
 * кандидатов держат перебор человеческим.
 */
export function наборКольца(верная, буквы, сколько) {
  const размер = Math.max(2, Math.min(буквы.length, Number(сколько) || 2));
  const прочие = буквы.filter(б => б !== верная);
  const набор = [верная];
  while (набор.length < размер && прочие.length) {
    набор.push(прочие.splice(Math.floor(Math.random() * прочие.length), 1)[0]);
  }
  return перемешатьАзбуку(набор);
}

const прибрать_текст = т => String(т ?? "").toUpperCase().replace(/Ё/g, "Е");
const поКругу = (шаг, n) => ((Number(шаг) % n) + n) % n;

/** Сдвинуть буквы по кругу. Всё, что не буква, остаётся как было. */
function сдвинуть(текст, шаг, буквы) {
  const n = буквы.length;
  return [...прибрать_текст(текст)].map(з => {
    const i = буквы.indexOf(з);
    return i < 0 ? з : буквы[(i + поКругу(шаг, n)) % n];
  }).join("");
}

/** Случайная перестановка азбуки: ни одна буква не остаётся собой. */
export function перемешатьАзбуку(буквы) {
  const перемешанные = [...буквы];
  for (let i = перемешанные.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [перемешанные[i], перемешанные[j]] = [перемешанные[j], перемешанные[i]];
  }
  for (let i = 0; i < буквы.length; i++) {
    if (перемешанные[i] !== буквы[i]) continue;
    const сосед = (i + 1) % буквы.length;
    [перемешанные[i], перемешанные[сосед]] = [перемешанные[сосед], перемешанные[i]];
  }
  return перемешанные;
}

/* ─────────────────────────── выложить на стол ─────────────────────────── */

export async function выложить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const фраза = прибрать_текст(конфиг.фраза?.trim());
  if (!фраза) { ui.notifications.error(Т("Не вписана фраза.")); return null; }

  const азбука = АЗБУКИ[конфиг.азбука] ? конфиг.азбука : "ru";
  const буквы = АЗБУКИ[азбука].буквы;
  const n = буквы.length;
  // Вслепую бывает только подстановка: колесо вдвоём перебирается за минуту.
  const слепая = !!(конфиг.вслепую && конфиг.штурман && конфиг.кольца?.length && конфиг.ключ);
  const вид = слепая || конфиг.вид === "podstanovka" ? "podstanovka" : "sdvig";

  if (![...фраза].some(з => буквы.includes(з))) {
    ui.notifications.error(Т("В этой фразе нет ни одной буквы азбуки — шифровать нечего."));
    return null;
  }

  /*
   * Длинную надпись легко взять из журнала целиком — и получить страницу
   * шифра, которую за столом не разберут. Это не запрет, а предупреждение
   * в окне настроек: ведущий сам решит, обрезать или оставить.
   */
  if (фраза.length > ПРЕДЕЛ_ДЛИНЫ) {
    ui.notifications.warn(Т("Надпись очень длинная — {сколько} знаков. Подстановку такой длины за столом разбирают долго; обычно хватает двух-трёх строк.", { сколько: фраза.length }));
  }

  let шифртекст;
  let тайное;

  /*
   * Вслепую надпись шифруется целиком, а кольца даются не на все буквы.
   *
   * Отсюда важное следствие, и оно сознательное: буква без кольца не
   * изменится никогда — у штурмана нет органов ввода, у пультов только
   * рычаги. Пока колец меньше, чем разных букв, надпись до конца не
   * сходится и «Прочесть» не засчитается. Это не недосмотр: ведущий либо
   * добивает кольца кнопкой в окне подготовки, либо нарочно кладёт надпись,
   * которую стол не дочитает, и заканчивает её «Засчитать».
   *
   * Ключ приходит готовым из окна подготовки: там он уже показан ведущему,
   * и выкладывается ровно то, что он видел.
   */
  if (слепая) {
    const ключ = конфиг.ключ;
    шифртекст = [...фраза].map(з => ключ[з] ?? з).join("");
    тайное = { фраза, ключ: Object.fromEntries(Object.entries(ключ).map(([б, ш]) => [ш, б])) };
  } else if (вид === "sdvig") {
    const заданный = Number(конфиг.сдвиг);
    const сдвиг = Number.isInteger(заданный) && заданный % n !== 0
      ? поКругу(заданный, n)
      : 1 + Math.floor(Math.random() * (n - 1));
    шифртекст = сдвинуть(фраза, сдвиг, буквы);
    тайное = { фраза, сдвиг };
  } else {
    // ключ: буква азбуки -> та, которой её записали
    const перемешанные = перемешатьАзбуку(буквы);
    const ключ = Object.fromEntries(буквы.map((б, i) => [б, перемешанные[i]]));
    шифртекст = [...фраза].map(з => ключ[з] ?? з).join("");
    // разгадка читается наоборот: шифрбуква -> что она значит
    тайное = { фраза, ключ: Object.fromEntries(Object.entries(ключ).map(([б, ш]) => [ш, б])) };
  }

  /*
   * Кольца. Кольцо приходит готовым из окна подготовки: там ведущий видит,
   * на какие шифр-буквы они встали, и может добить остальные кнопкой.
   *
   * Кольцо держит ШИФР-букву, а набор на нём — кандидаты в настоящие. Буквы
   * без кольца догадки не получают вовсе: в надписи они так и стоят шифром,
   * тускло, как неразобранные у обычной подстановки.
   */
  const кольца = слепая
    ? конфиг.кольца.map(к => ({
      буква: к.буква,
      верная: к.верная,
      набор: [...к.набор],
      /*
       * `поз: null` — «не разгадано». Надпись начинается чистым шифром,
       * как и обычная: пока кольцо не тронули, на его месте стоит шифр-буква.
       *
       * Иначе выходила ложь: буква без кольца показана шифром, а буква с
       * кольцом — уже подставленным значением, и два соседних одинаковых
       * знака значили разное. Шифр казался сломанным, хотя был честным.
       */
      поз: null,
    }))
    : [];

  const открыто = {};
  const догадки = {};

  await прибрать();

  const id = foundry.utils.randomID();
  const стол = {
    id,
    тип: "shifr",
    вид,
    название: конфиг.название?.trim() || Т("Надпись"),
    подпись: конфиг.подпись?.trim() || "",
    тема: (конфиг.тема in ТЕМЫ) ? конфиг.тема : "kamen",
    азбука,
    шифртекст,
    колесо: 0,                 // для сдвига: какое положение примеряют
    догадки,                   // для подстановки: шифрбуква -> что подставили
    открыто,                   // открытые правдой: шифрбуква -> настоящая
    кольца,                    // вслепую: буква, набор кандидатов и положение
    отмечено: [],              // что отмечено к открытию сейчас
    /*
     * Открытий вслепую нет. Открывать буквы умеет тот, кто их видит, а
     * штурман за буквы не отвечает: его дело — прочесть, а не подставлять.
     * Милосердие у ведущего остаётся своё: «Засчитать».
     */
    открытие: {
      заРаз: слепая ? 0 : Math.max(0, Number(конфиг.буквЗаРаз) || 0),
      предел: слепая ? 0 : Math.max(0, Number(конфиг.открытий) || 0),
      сделано: 0,
    },
    выбор: null,               // какую шифрбукву взяли в руку
    попытки: { сделано: 0, предел: Math.max(0, Number(конфиг.предел) || 0) },
    крутят: конфиг.крутят?.length ? конфиг.крутят : "все",
    макрос: конфиг.макрос?.trim() || null,
    // Видит один, крутят другие: у кольца рычаг (или два — вперёд и назад).
    вслепую: слепая
      ? раздельно.разложить({
        штурман: конфиг.штурман, детали: деталиНадписи(кольца.length, конфиг.обеСтороны),
        рычаги: конфиг.рычаги, пометки: конфиг.пометки,
        подсказка: конфиг.подсказкаШтурману, пульты: конфиг.пульты,
      })
      : null,
    таймер: завестиТаймер(конфиг.таймер),
    журнал: [],
    прочтена: false,
    заклинило: false,
    завершён: false,
    показан: true,
  };

  await тайнуЗапомнить(id, тайное);
  await записать(стол);
  return стол;
}

export async function прибрать() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "shifr" && с.завершён) await убрать(id);
  }
}

/* ─────────────────────────────── правила ─────────────────────────────── */

/** Допущен ли к надписи по списку «кто разбирает». */
const вСписке = (стол, пользователь) =>
  !!пользователь && (стол.крутят === "все" || (стол.крутят ?? []).includes(пользователь.id));

/**
 * Кто трогает механизм. Вслепую это пульты: штурман смотрит и не крутит.
 */
/** Надпись ещё в деле: не прочитана, не заклинило, время не вышло. */
const идёт = стол => !стол.прочтена && !стол.заклинило && осталось(стол) !== 0;

const можетКрутить = (стол, пользователь) =>
  !!пользователь && идёт(стол) &&
  (пользователь.isGM || (стол.вслепую
    ? раздельно.пультыЧеловека(стол, пользователь, вСписке(стол, пользователь)).length > 0
    : вСписке(стол, пользователь)));

/**
 * Кто объявляет, что надпись заговорила.
 *
 * Вслепую это штурман: он один видит текст, и заявлять о прочтении может
 * только он. Пульты букв не видят вовсе.
 */
const можетЧитать = (стол, пользователь) =>
  !!пользователь && идёт(стол) &&
  (стол.вслепую
    ? (пользователь.isGM || пользователь.id === стол.вслепую.штурман)
    : можетКрутить(стол, пользователь));

const осталосьПопыток = стол =>
  стол.попытки?.предел ? стол.попытки.предел - стол.попытки.сделано : Infinity;

/*
 * Догадки и кольца меняются чаще, чем стоит писать в базу: рассылка показывает
 * их всем сразу, а запись идёт, когда рука отдохнёт.
 *
 * Без неё разобранное жило только в памяти клиентов до «Прочесть»: перезаход
 * посреди разгадки сбрасывал всё к началу. Для устройства это больнее, чем для
 * одиночной загадки, — там ещё и таймер идёт.
 */
const отложитьЗапись = foundry.utils.debounce(async id => {
  const сырой = столПоId(id);
  if (!сырой) return;
  const живой = собрать(сырой);
  await записать({ ...сырой, колесо: живой.колесо, догадки: живой.догадки, кольца: живой.кольца });
}, 3000);

/** Сколько открытий осталось. Ноль букв за раз — открытий нет вовсе. */
export const осталосьОткрытий = стол => {
  const о = стол.открытие ?? {};
  if (!о.заРаз) return 0;
  return о.предел ? о.предел - (о.сделано ?? 0) : Infinity;
};

/**
 * Как надпись читается сейчас.
 *
 * У подстановки неразгаданные буквы остаются собой: по ним и работают —
 * повтор буквы виден, длина слова видна, а смысла пока нет.
 */
export function прочтение(стол) {
  const буквы = АЗБУКИ[стол.азбука].буквы;
  if (стол.вид === "podstanovka") {
    return [...стол.шифртекст].map(з => (стол.догадки ?? {})[з] ?? з).join("");
  }
  return сдвинуть(стол.шифртекст, -Number(стол.колесо || 0), буквы);
}

/** Какие буквы шифра вообще встречаются в надписи. */
export const буквыНадписи = стол => буквыФразы(стол.шифртекст, АЗБУКИ[стол.азбука].буквы);

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);

  // «Прочесть» идёт своей дорогой: вслепую его жмёт штурман, а он не крутит.
  if (запрос.что === "прочесть") {
    if (можетЧитать(стол, пользователь)) await прочесть(стол, запрос.кто);
    return;
  }

  if (!можетКрутить(стол, пользователь)) return;

  /*
   * Вслепую за пультом только рычаги: буквы не берут и не подставляют —
   * пульт их не видит. Кольцо ходит по своему набору кандидатов.
   */
  if (стол.вслепую) {
    if (запрос.что !== "рычаг") return;
    if (!раздельно.можноТянуть(стол, пользователь, запрос.рычаг, вСписке(стол, пользователь))) return;
    const цель = кольцоДетали(раздельно.детальРычага(стол, запрос.рычаг));
    const к = цель && стол.кольца?.[цель.кольцо];
    if (!к) return;
    /*
     * Кольцо ходит по набору и возвращается в «не разгадано».
     *
     * Положений на одно больше, чем букв: кандидаты плюс пустое, где на
     * месте кольца снова стоит шифр-буква. Без него нельзя было бы снять
     * неверную догадку, и штурман навсегда остался бы с ложным знаком.
     */
    const n = к.набор.length;
    const было = Number.isInteger(к.поз) ? к.поз : -1;   // -1 — не разгадано
    const поз = поКругу(было + 1 + цель.шаг, n + 1) - 1;

    const кольца = стол.кольца.map((с, и) => и === цель.кольцо ? { ...с, поз: поз < 0 ? null : поз } : с);
    const догадки = { ...(стол.догадки ?? {}) };
    if (поз < 0) delete догадки[к.буква];
    else догадки[к.буква] = к.набор[поз];

    разослать(стол.id, { кольца, догадки });
    отложитьЗапись(стол.id);
    return;
  }

  if (запрос.что === "крутить" && стол.вид === "sdvig") {
    const буквы = АЗБУКИ[стол.азбука].буквы;
    разослать(стол.id, { колесо: поКругу(Number(стол.колесо || 0) + Number(запрос.шаг), буквы.length) });
    отложитьЗапись(стол.id);
    return;
  }

  // Отметить букву к открытию: столько, сколько ведущий дал за раз.
  if (запрос.что === "отметить" && стол.вид === "podstanovka") {
    const заРаз = стол.открытие?.заРаз ?? 0;
    if (!заРаз || осталосьОткрытий(стол) <= 0) return;
    const буква = String(запрос.буква ?? "");
    if (!буквыНадписи(стол).includes(буква) || (стол.открыто ?? {})[буква]) return;
    const отмечено = [...(стол.отмечено ?? [])];
    const и = отмечено.indexOf(буква);
    if (и >= 0) отмечено.splice(и, 1);
    else if (отмечено.length < заРаз) отмечено.push(буква);
    else return;
    разослать(стол.id, { отмечено });
    return;
  }

  if (запрос.что === "открыть" && стол.вид === "podstanovka") {
    await открыть(стол, запрос.кто);
    return;
  }

  if (запрос.что === "взять" && стол.вид === "podstanovka") {
    const буква = String(запрос.буква ?? "");
    if (!буквыНадписи(стол).includes(буква) || (стол.открыто ?? {})[буква]) return;
    // Щелчок по взятой букве стирает свою догадку и освобождает руку.
    if (стол.выбор === буква) {
      const догадки = { ...(стол.догадки ?? {}) };
      delete догадки[буква];
      разослать(стол.id, { догадки, выбор: null });
      отложитьЗапись(стол.id);
      return;
    }
    разослать(стол.id, { выбор: буква });
    return;
  }

  if (запрос.что === "подставить" && стол.вид === "podstanovka") {
    if (!стол.выбор) return;
    const буквы = АЗБУКИ[стол.азбука].буквы;
    const значит = String(запрос.буква ?? "");
    if (!буквы.includes(значит)) return;
    разослать(стол.id, { догадки: { ...(стол.догадки ?? {}), [стол.выбор]: значит }, выбор: null });
    отложитьЗапись(стол.id);
    return;
  }
}

/**
 * Открыть отмеченные буквы правдой.
 *
 * Это не догадка, а расход: открытий у стола столько, сколько дал ведущий.
 * Открытая буква встаёт в надпись намертво — её больше не меняют.
 */
async function открыть(стол, ктоId) {
  if (осталосьОткрытий(стол) <= 0) return;

  const ключ = тайна(стол.id)?.ключ;
  if (!ключ) {
    ui.notifications.error(
      Т("Разгадка надписи «{название}» не найдена в этом браузере. Засчитайте вручную или выложите заново.", { название: стол.название }));
    return;
  }

  const открытые = (стол.отмечено ?? []).filter(б => !(стол.открыто ?? {})[б] && ключ[б]);
  if (!открытые.length) return;

  const открыто = { ...(стол.открыто ?? {}) };
  const догадки = { ...(стол.догадки ?? {}) };
  for (const б of открытые) { открыто[б] = ключ[б]; догадки[б] = ключ[б]; }

  const открытие = { ...(стол.открытие ?? {}), сделано: (стол.открытие?.сделано ?? 0) + 1 };
  const свежий = { ...стол, открыто, догадки, отмечено: [], выбор: null, открытие };
  await записать(свежий);

  const осталось = осталосьОткрытий(свежий);
  await объявить(
    Т(`<p><strong>{название}</strong> — открыто: {буквы}.</p><p><em>{кто}; открытий осталось {осталось}.</em></p>`, {
      название: экранировать(свежий.название),
      буквы: экранировать(открытые.map(б => `${б}=${ключ[б]}`).join(", ")),
      кто: экранировать(имяИгрока(ктоId)),
      осталось: Number.isFinite(осталось) ? осталось : "∞",
    }), свежий.название);
}

/**
 * «Прочесть» — это заявка игрока, а не признание модуля.
 *
 * Разница видна за столом: пока признаёт модуль, колесо крутят вслепую,
 * пока заявляет игрок — читают.
 */
async function прочесть(стол, ктоId) {
  if (осталосьПопыток(стол) <= 0) return;

  const секрет = тайна(стол.id);
  if (!секрет) {
    ui.notifications.error(
      Т("Разгадка надписи «{название}» не найдена в этом браузере. Засчитайте вручную или выложите заново.", { название: стол.название }));
    return;
  }

  const читается = прочтение(стол);
  const верно = читается === секрет.фраза;

  const обновлённый = {
    ...стол,
    выбор: null,
    попытки: { ...стол.попытки, сделано: стол.попытки.сделано + 1 },
    журнал: [...(стол.журнал ?? []), { кто: имяИгрока(ктоId), чтение: читается, удача: верно }].slice(-8),
    прочтена: верно,
    завершён: верно,
  };

  if (!верно && обновлённый.попытки.предел &&
      обновлённый.попытки.сделано >= обновлённый.попытки.предел) {
    обновлённый.заклинило = true;
    обновлённый.завершён = true;
  }

  await записать(обновлённый);

  if (верно) {
    await объявить(
      Т(`<p><strong>{название}</strong> — надпись прочитана.</p>
       <p>«{читается}»</p>
       <p><em>{ктоId} прочёл с попытки номер {сделано}.</em></p>`, { название: экранировать(обновлённый.название), читается: экранировать(читается), ктоId: экранировать(имяИгрока(ктоId)), сделано: обновлённый.попытки.сделано }),
      обновлённый.название);
    событие("решено", обновлённый);
    await запуститьМакрос(обновлённый.макрос, обновлённый);
  } else if (обновлённый.заклинило) {
    await объявить(
      Т(`<p><strong>{название}</strong> — попытки кончились.</p>`, { название: экранировать(обновлённый.название) }), обновлённый.название);
  }
}

