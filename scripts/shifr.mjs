/** Время вышло — надпись замолкает, как от исчерпанных попыток. */
async function времяВышло(стол) {
  const свежий = столПоId(стол.id);
  if (!свежий || свежий.завершён) return;
  await записать({ ...свежий, заклинило: true, завершён: true });
  await объявить(`<p><strong>${экранировать(стол.название)}</strong> ${Т("— время вышло, механизм заклинило.")}</p>`, стол.название);
}

