/**
 * Надпись — то, что нужно прочесть.
 *
 * Два вида, и разница между ними принципиальная.
 *
 * **Колесо** (сдвиг): буквы сдвинуты по кругу азбуки, игроки крутят колесо
 * и смотрят, когда бессмыслица заговорит. Это не головоломка, а обряд
 * узнавания: положений всего три десятка, и перебрать их — минута. Ценность
 * тут в том мгновении, когда надпись читается вслух, а не в трудности.
 *
 * **Подстановка**: каждая буква заменена своей, без всякого порядка. Перебрать
 * нельзя — вариантов больше, чем звёзд. Играют иначе: смотрят на короткие
 * слова, на повторяющиеся буквы, на окончания, и подставляют по одной.
 * Вот это настоящая загадка на стол.
 *
 * И то и другое **признаёт разгадку не модуль, а игрок**: он жмёт «Прочесть»,
 * когда решил, что надпись заговорила. Иначе колесо превращается в счётчик:
 * дави стрелку, пока не объявят победу, — читать незачем.
 *
 * **Открытия.** Подстановку можно выложить с открытиями: ведущий задаёт,
 * сколько букв открывают за раз и сколько таких открытий даётся. Игроки
 * отмечают столько шифр-букв и жмут «Открыть» — модуль показывает их
 * настоящие значения, и эти буквы встают в надпись намертво. Остальное
 * по-прежнему додумывают подстановками. Без открытий (0) всё как было.
 */

