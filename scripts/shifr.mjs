/** Открыть одну букву: подсказка для подстановки, когда стол встал намертво. */
export async function подсказатьБукву(id) {
  const стол = столПоId(id);
  const ключ = тайна(id)?.ключ;
  if (!стол || стол.вид !== "podstanovka" || !ключ) return;

  const живой = собрать(стол);
  const неразгаданные = буквыНадписи(живой).filter(б => (живой.догадки ?? {})[б] !== ключ[б]);
  if (!неразгаданные.length) return;

  const буква = неразгаданные[Math.floor(Math.random() * неразгаданные.length)];
  const догадки = { ...(живой.догадки ?? {}), [буква]: ключ[буква] };

  /*
   * Вслепую подсказка должна двинуть и само кольцо, иначе оно останется
   * стоять на прежнем кандидате, и первый же поворот рычага сотрёт
   * подсказку. Верная буква в наборе кольца есть всегда — набор строится
   * вокруг неё.
   *
   * Буква без кольца так подсказкой и открывается: это единственный способ
   * её раскрыть, и ради него подсказка здесь и оставлена.
   */
  const кольца = (живой.кольца ?? []).map(к => {
    if (к.буква !== буква) return к;
    const поз = к.набор.indexOf(ключ[буква]);
    return поз < 0 ? к : { ...к, поз };
  });

  await записать({ ...живой, догадки, кольца, выбор: null });
  await объявить(
    Т(`<p><strong>{название}</strong>: ведущий подсказывает — <code>{буква}</code> значит <code>{буква3}</code>.</p>`, { название: экранировать(стол.название), буква: 
      экранировать(буква), буква3: экранировать(ключ[буква]) }), стол.название);
}

export async function засчитать(id) {
  const стол = столПоId(id);
  if (!стол) return;
  const секрет = тайна(id);
  const живой = собрать(стол);

  const полный = секрет?.ключ
    ? { ...живой, догадки: { ...секрет.ключ }, выбор: null, прочтена: true, заклинило: false, завершён: true }
    : { ...живой, колесо: секрет?.сдвиг ?? живой.колесо, прочтена: true, заклинило: false, завершён: true };

  await записать(полный);
  await объявить(
    Т(`<p><strong>{название}</strong> — прочитана волей ведущего.</p>
     <p>«{полный}»</p>`, { название: экранировать(полный.название), полный: экранировать(секрет?.фраза ?? прочтение(полный)) }), полный.название);
  событие("решено", полный);
  await запуститьМакрос(полный.макрос, полный);
}

export async function сбросить(id) {
  const стол = столПоId(id);
  if (!стол) return;

  // Вслепую сброс возвращает кольца в «не разгадано»: надпись снова чистый шифр.
  const догадки = {};
  const открыто = {};
  let кольца = стол.кольца ?? [];
  if (стол.вслепую) кольца = кольца.map(к => ({ ...к, поз: null }));

  await записать({
    ...стол,
    колесо: 0,
    догадки,
    открыто,
    кольца,
    отмечено: [],
    открытие: { ...(стол.открытие ?? {}), сделано: 0 },
    выбор: null,
    попытки: { ...стол.попытки, сделано: 0 },
    журнал: [],
    прочтена: false,
    заклинило: false,
    завершён: false,
    таймер: перезавести(стол.таймер),
  });
}

