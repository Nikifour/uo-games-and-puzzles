/**
 * «Счастливчик Джо» за столом.
 *
 * Ходят по очереди, по одному броску 2к6: бросил — оставил одну кость —
 * передал дальше. Так все шесть кругов бросков идут на глазах у всех, и видно,
 * как соперник строит ряд. Считает расклад — правила в dzho-pravila.mjs,
 * здесь только стол.
 *
 * Круг решает спор, если у кого-то перевес; при равенстве играют следующий,
 * и так до условленного числа кругов. Очки между кругами не копятся.
 * Если и круги кончились — развязка на сумму 2к6, где две однерки бьют всё.
 *
 * Джо (шесть одинаковых) — безусловная победа. Если Джо у двоих, спор
 * не решается вовсе: по воровскому поверью они связаны узами судьбы,
 * и спорить им больше не о чем.
 */

