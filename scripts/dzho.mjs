/**
 * Подсадить посреди спора. Пока круг не начат или в перерыве перед новым
 * кругом — сразу; в разгар круга новенький ждёт следующего: ряд из шести
 * костей у всех должен складываться одновременно. В развязку не садятся.
 */
export async function подсадить(id, новые) {
  if (!game.user.isGM || !новые?.length) return;
  let стол = столПоId(id);
  if (!стол || стол.победитель !== null || стол.узы.length) return;

  const кругНеНачат = !стол.развязка && !стол.бросок.length && стол.места.every(м => !м.кости.length);
  const сразу = кругНеНачат && !["развязка", "переброс"].includes(стол.перерыв?.что);
  for (const н of новые) {
    const место = { кто: н.кто, имя: н.имя, бот: н.бот, кости: [], очки: 0 };
    if (сразу) стол = { ...стол, места: [...стол.места, место] };
    else стол = { ...стол, ждут: [...(стол.ждут ?? []), место] };
    const все = [...стол.места, ...(стол.ждут ?? [])];
    стол = { ...стол, ставка: await сбор.ставкаСНового({ ...стол, места: все }, все.length - 1) };
    стол = вЖурнал(стол, сразу
      ? Т("{имя} подсаживается за стол", { имя: н.имя })
      : Т("{имя} ждёт следующего круга", { имя: н.имя }));
  }
  await записать(стол);
  await сбор.объявитьПодсадку(стол, новые.map(н => н.имя), сразу);
  двинутьБота(id);
}

/** Стол на ходу бота — пусть доиграет. Зовётся при входе в мир и при каждой перемене столов. */
export function подхватитьБотов() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "dzho" && с.победитель === null && !с.узы?.length && с.места[с.чей]?.бот) двинутьБота(id);
  }
}

