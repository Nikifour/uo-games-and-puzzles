/* ────────────────────────────── посадка ────────────────────────────── */

export async function посадить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const места = (конфиг.места ?? []).map(м => ({
    кто: м.кто ?? null,
    имя: м.имя,
    бот: м.бот ?? null,
    кости: [],
    очки: 0,
  }));

  if (места.length < 2) { ui.notifications.error(Т("За стол нужно посадить хотя бы двоих.")); return null; }

  await прибрать();

  const стол = {
    id: foundry.utils.randomID(),
    тип: "dzho",
    название: конфиг.название?.trim() || Т("Счастливчик Джо"),
    подпись: конфиг.подпись?.trim() || "",
    тема: (конфиг.тема in ТЕМЫ) ? конфиг.тема : "kamen",
    места,
    чей: 0,
    бросок: [],
    круг: 1,
    кругов: Math.max(1, Math.min(9, Number(конфиг.кругов) || 3)),
    ставка: {
      сколько: Math.max(0, Number(конфиг.ставка) || 0),
      монета: конфиг.монета in МОНЕТЫ ? конфиг.монета : "gp",
      слисты: конфиг.слисты !== false,
      банк: 0,
      внесли: [],
    },
    развязка: null,
    журнал: [],
    победитель: null,
    узы: [],
    завершён: false,
    показан: true,
    макрос: конфиг.макрос?.trim() || null,
  };

  await записать(стол);
  await объявить(
    Т(`<p><strong>{название}</strong> — за стол сели: {имя}.</p>
     <p>Спор решают {кругов} {кругов4}.</p>`, { название: экранировать(стол.название), имя: 
      места.map(м => экранировать(м.имя)).join(", "), кругов: стол.кругов, кругов4: числом(стол.кругов, М("круг"), М("круга"), М("кругов")) }),
    стол.название);

  const сСтавкой = await собратьСтавки(стол);
  двинутьБота(стол.id);
  return сСтавкой;
}

export async function прибрать() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "dzho" && с.завершён) await убрать(id);
  }
}

/* ─────────────────────────────── правила стола ─────────────────────────────── */

const место = стол => стол.места[стол.чей];

function егоХод(стол, пользователь) {
  if (!пользователь || стол.победитель !== null || стол.узы.length) return false;
  const м = место(стол);
  if (м.бот) return пользователь.isGM;
  return пользователь.isGM || м.кто === пользователь.id;
}

const вЖурнал = (стол, строка) => ({ ...стол, журнал: [...(стол.журнал ?? []), строка].slice(-14) });

/**
 * Бросок 2к6.
 *
 * Здесь же живёт рука судьбы: если этому месту назначено число, одна кость
 * его показывает, а вторая честная. Судьба кладёт кость под руку — берёт её
 * человек сам, и может не взять.
 */
async function броситьВИгре(стол, индекс) {
  const бросок = await new Roll("2d6").evaluate();
  const кости = бросок.dice[0].results;

  const назначено = тайна(стол.id)?.судьба?.[индекс];
  if (назначено && !кости.some(р => р.result === назначено)) {
    кости[Math.floor(Math.random() * кости.length)].result = назначено;
    try { бросок._total = кости.reduce((с, р) => с + р.result, 0); } catch { /* итог не нужен */ }
  }

  const режим = game.settings.get(MODULE_ID, "broski");
  if (режим === "tikho" && game.dice3d) {
    await game.dice3d.showForRoll(бросок, game.user, true);
  } else if (режим !== "tikho") {
    await бросок.toMessage({
      speaker: { alias: `${стол.название} · ${стол.места[индекс].имя}` },
      flavor: стол.развязка ? Т("развязка") : Т("круг {круг}", { круг: стол.круг }),
    }, { rollMode: режим === "gm" ? CONST.DICE_ROLL_MODES.PRIVATE : CONST.DICE_ROLL_MODES.PUBLIC });
  }

  return кости.map(р => р.result);
}

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!егоХод(стол, пользователь)) return;

  if (запрос.что === "бросить") {
    if (стол.бросок.length) return;
    const кости = await броситьВИгре(стол, стол.чей);
    await записать({ ...столПоId(стол.id), бросок: кости });
    if (стол.развязка) await принятьРазвязку(столПоId(стол.id), кости);
    return;
  }

  if (запрос.что === "оставить") {
    if (стол.развязка) return;
    const какая = Number(запрос.кость);
    const кость = стол.бросок[какая];
    if (!кость) return;
    return оставить(стол, кость);
  }

  if (запрос.что === "пропустить" && пользователь.isGM) return дальше(стол);
}

async function оставить(стол, кость) {
  const места = стол.места.map((м, i) => {
    if (i !== стол.чей) return м;
    const кости = [...м.кости, кость];
    return { ...м, кости, очки: очкиРяда(кости) };
  });

  const свежий = вЖурнал({ ...столПоId(стол.id), места, бросок: [] },
    Т("{имя} оставляет {кость}", { имя: место(стол).имя, кость: ГРАНИ[кость] }));
  await записать(свежий);
  await дальше(столПоId(стол.id));
}

/** Ход переходит дальше; когда у всех по шесть костей — круг кончился. */
async function дальше(стол) {
  if (!стол || стол.победитель !== null || стол.узы.length) return;

  if (стол.места.every(м => м.кости.length >= БРОСКОВ)) return концаКруга(стол);

  const чей = (стол.чей + 1) % стол.места.length;
  await записать({ ...стол, чей, бросок: [] });
  двинутьБота(стол.id);
}

async function концаКруга(стол) {
  const джоцы = стол.места.map((м, i) => (джо(м.кости) ? i : -1)).filter(i => i >= 0);

  // Двое с Джо — спор снимается совсем: по поверью они связаны.
  if (джоцы.length >= 2) return узыДжо(стол, джоцы);
  if (джоцы.length === 1) return победа(стол, джоцы[0], Т("Джо"));

  const наибольшие = Math.max(...стол.места.map(м => м.очки));
  const лучшие = стол.места
    .map((м, i) => (м.очки === наибольшие ? i : -1))
    .filter(i => i >= 0);

  if (лучшие.length === 1) return победа(стол, лучшие[0], 
    `${стол.места[лучшие[0]].очки} ${числом(стол.места[лучшие[0]].очки, М("очко"), М("очка"), М("очков"))}`);

  await объявить(
    Т(`<p><strong>{название}</strong>: круг {круг} — поровну, по {очки}.</p>`, { название: экранировать(стол.название), круг: стол.круг, очки: 
      стол.места[лучшие[0]].очки }), стол.название);

  if (стол.круг < стол.кругов) return новыйКруг(стол);
  return начатьРазвязку(стол);
}

async function новыйКруг(стол) {
  await записать(вЖурнал({
    ...стол,
    круг: стол.круг + 1,
    чей: 0,
    бросок: [],
    места: стол.места.map(м => ({ ...м, кости: [], очки: 0 })),
  }, Т("круг {круг} — поровну, играем ещё", { круг: стол.круг })));
  двинутьБота(стол.id);
}

/* ─────────────────────────────── развязка ─────────────────────────────── */

async function начатьРазвязку(стол) {
  await объявить(
    Т(`<p><strong>{название}</strong>: круги кончились — развязка на сумму.</p>
     <p><em>Две однерки бьют всё, даже две шестёрки.</em></p>`, { название: экранировать(стол.название) }), стол.название);
  await записать({
    ...стол,
    чей: 0,
    бросок: [],
    развязка: { суммы: стол.места.map(() => null) },
    места: стол.места.map(м => ({ ...м, кости: [], очки: 0 })),
  });
  двинутьБота(стол.id);
}

async function принятьРазвязку(стол, кости) {
  const суммы = [...стол.развязка.суммы];
  суммы[стол.чей] = {
    кости,
    сумма: кости[0] + кости[1],
    однерки: кости[0] === 1 && кости[1] === 1,
  };

  const свежий = вЖурнал({ ...стол, развязка: { суммы }, бросок: [] },
    `${место(стол).имя}: ${кости.map(к => ГРАНИ[к]).join(" ")}${суммы[стол.чей].однерки ? Т(" — однерки!") : ""}`);

  if (суммы.some(с => с === null)) {
    const чей = (стол.чей + 1) % стол.места.length;
    await записать({ ...свежий, чей });
    двинутьБота(стол.id);
    return;
  }

  // Все бросили. Однерки старше всего, дальше по сумме.
  const счастливцы = суммы.map((с, i) => (с.однерки ? i : -1)).filter(i => i >= 0);
  if (счастливцы.length === 1) return победа(свежий, счастливцы[0], Т("две однерки"));

  if (счастливцы.length === 0) {
    const лучший = суммы.reduce((л, с, i) => (с.сумма > суммы[л].сумма ? i : л), 0);
    const поровну = суммы.filter(с => с.сумма === суммы[лучший].сумма).length > 1;
    if (!поровну) return победа(свежий, лучший, Т("сумма {сумма}", { сумма: суммы[лучший].сумма }));
  }

  await объявить(Т(`<p><strong>{название}</strong>: и тут поровну — бросают заново.</p>`, { название: экранировать(стол.название) }),
    стол.название);
  await записать({ ...свежий, чей: 0, развязка: { суммы: стол.места.map(() => null) } });
  двинутьБота(стол.id);
}

/* ─────────────────────────────── итоги ─────────────────────────────── */

async function победа(стол, индекс, чем) {
  const свежий = { ...стол, победитель: индекс, завершён: true, бросок: [] };
  await записать(свежий);
  await объявить(
    Т(`<p><strong>{имя}</strong> берёт спор: {чем}.</p>`, { имя: экранировать(свежий.места[индекс].имя), чем: экранировать(чем) }),
    свежий.название);
  await выдатьБанк(свежий, индекс);
  событие("победа", свежий);
  await запуститьМакрос(свежий.макрос, свежий);
}

/**
 * Узы Джо.
 *
 * Спор не решается: по поверью воров двое, выбросивших Джо в один круг,
 * связаны судьбой, и спорить им больше не о чем. Ставки возвращаются,
 * а дальше — дело ведущего и сцены.
 */
async function узыДжо(стол, кто) {
  const свежий = { ...стол, узы: кто, завершён: true, бросок: [] };
  await вернутьСтавки(стол);
  await записать(свежий);
  await объявить(
    Т(`<p><strong>{имя}</strong> и <strong>{имя2}</strong> выбросили Джо в один круг.</p>
     <p>Спор снят: по поверью они связаны узами судьбы. Обычай велит пожать руки и поцеловаться —
     и держаться друг друга до конца.</p>`, { имя: экранировать(свежий.места[кто[0]].имя), имя2: 
      экранировать(свежий.места[кто[1]].имя) }), свежий.название);
  событие("узы", свежий);
  await запуститьМакрос(свежий.макрос, свежий);
}

/* ─────────────────────────────── ход бота ─────────────────────────────── */

let ботЗанят = false;

export async function двинутьБота(id) {
  if (!ведущийЗдесь() || ботЗанят) return;
  if (!game.settings.get(MODULE_ID, "bot")) return;

  const стол = столПоId(id);
  if (!стол || стол.тип !== "dzho" || стол.победитель !== null || стол.узы.length) return;
  const м = стол.места[стол.чей];
  if (!м?.бот) return;

  ботЗанят = true;
  try {
    const задержка = Number(game.settings.get(MODULE_ID, "botPauza")) || 0;
    const характер = ХАРАКТЕРЫ[м.бот.характер] ?? ХАРАКТЕРЫ.traktirshchik;

    await пауза(задержка);
    const кости = await броситьВИгре(стол, стол.чей);
    await записать({ ...столПоId(id), бросок: кости });

    const текущий = столПоId(id);
    if (текущий.развязка) { await принятьРазвязку(текущий, кости); return; }

    await пауза(задержка);
    await оставить(собрать(текущий), лучшая(м.кости, кости, характер.мастерство ?? 0.8));
  } catch (e) {
    console.error(`${MODULE_ID} | ход бота в Джо сорвался`, e);
    ui.notifications.error(Т("Ход бота сорвался — ход можно передать вручную."));
  } finally {
    ботЗанят = false;
  }

  const после = столПоId(id);
  if (после?.победитель === null && !после.узы.length && после.места[после.чей]?.бот) двинутьБота(id);
}

/* ─────────────────── рычаги ведущего ─────────────────── */

/**
 * Рука судьбы.
 *
 * Назначает местам число: в каждом их броске одна кость будет его показывать,
 * вторая честная. Хранится в тайнах ведущего — ни в состоянии стола, ни в чате,
 * ни в журнале следа нет, и назначенный расклад ничем не отличается от того,
 * что сложился сам.
 *
 *   UOIgry.joe.fate(id, [0, 1], 4)   — этим двоим сегодня идут четвёрки
 *   UOIgry.joe.fate(id)              — снять
 */
export async function судьба(id, места = [], номинал = 0) {
  if (!game.user.isGM) return;
  const назначение = {};
  for (const м of места) if (номинал >= 1 && номинал <= 6) назначение[м] = номинал;
  await тайнуЗапомнить(id, { ...(тайна(id) ?? {}), судьба: назначение });
}

export async function засчитать(id, индекс = 0) {
  const стол = столПоId(id);
  if (!стол) return;
  await победа(собрать(стол), индекс, Т("воля ведущего"));
}

export async function сбросить(id) {
  const стол = столПоId(id);
  if (!стол) return;
  await записать({
    ...стол,
    чей: 0,
    бросок: [],
    круг: 1,
    развязка: null,
    журнал: [],
    победитель: null,
    узы: [],
    завершён: false,
    места: стол.места.map(м => ({ ...м, кости: [], очки: 0 })),
  });
}

