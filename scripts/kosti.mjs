/** Сказать месту, что у него в рукаве. Ботам писать некому. */
function сообщитьМесту(id, индекс) {
  const кто = столПоId(id)?.места?.[индекс]?.кто;
  if (!кто) return;
  личноеПисьмо(кто, "kosti", {
    что: "шулер", id,
    есть: !!шулера(id)[индекс],
    вкл: !!подменяет(id)[индекс],
  });
}

/** Ведущий даёт или забирает подменные кости. */
export async function датьПодменные(id, индекс, есть) {
  if (!game.user.isGM) return;
  const ш = { ...шулера(id) };
  const в = { ...подменяет(id) };
  if (есть) ш[индекс] = true;
  else { delete ш[индекс]; delete в[индекс]; }
  await записатьТайну(id, { шулера: ш, вкл: в });
  сообщитьМесту(id, индекс);
}

async function переключитьПодмену(стол, индекс) {
  if (!шулера(стол.id)[индекс]) return;
  const в = { ...подменяет(стол.id) };
  в[индекс] = !в[индекс];
  await записатьТайну(стол.id, { вкл: в });
  сообщитьМесту(стол.id, индекс);
}

/** Кости уже брошены — подкручиваем до того, как их кто-то увидит. */
function подкрутить(бросок) {
  const результаты = бросок.dice[0].results;
  for (const р of результаты) {
    if (р.result === 1 || р.result === 5) continue;      // и так в цене
    if (Math.random() < СИЛА_ПОДМЕНЫ) р.result = Math.random() < 0.6 ? 1 : 5;
  }
  try { бросок._total = результаты.reduce((с, р) => с + р.result, 0); } catch { /* итог нам не нужен */ }
}

/**
 * Проверка подмены: Ловкость рук против пассивного внимания зрителей.
 *
 * Пассивное нарочно: иначе на каждый бросок пришлось бы гонять всех за столом
 * бросать Восприятие, а это шесть бросков на ход и мёртвая партия. Зато
 * проверка идёт на **каждый** подменённый бросок: чем чаще плутуешь, тем
 * вернее попадёшься.
 *
 * Итог знает только ведущий. Шулеру не говорят, заметили его или нет, —
 * это его тревога и сцена ведущего, а не строка в чате.
 */
async function проверитьПодмену(стол, индекс) {
  const шулер = стол.места[индекс];
  const актёр = актёрМеста(шулер);
  const мод = шулер.бот ? ЛОВКОСТЬ_БОТА : (актёр?.system?.skills?.slt?.total ?? 0);

  const бросок = await new Roll(`1d20 + ${мод}`).evaluate();
  const итог = бросок.total;

  const заметили = [];
  стол.места.forEach((м, i) => {
    if (i === индекс) return;
    const внимание = м.бот ? ВНИМАНИЕ_БОТА : (актёрМеста(м)?.system?.skills?.prc?.passive ?? 10);
    if (внимание >= итог) заметили.push(`${м.имя} (${внимание})`);
  });

  const кому = ChatMessage.getWhisperRecipients?.("GM")?.map(u => u.id) ?? [];
  await ChatMessage.create({
    whisper: кому,
    speaker: { alias: стол.название },
    content: `<p><strong>${экранировать(шулер.имя)}</strong> ${Т("подменяет кости.")}</p>
      <p>${Т("Ловкость рук:")} <strong>${итог}</strong> (d20${мод >= 0 ? "+" : ""}${мод}).</p>
      <p>${заметили.length
        ? Т(`Заметили: <strong>{кто}</strong>.`, { кто: заметили.map(экранировать).join(", ") })
        : Т("Никто не заметил.")}</p>`,
  });

  if (!шулер.бот) шепнуть(шулер.кто, Т("Кости подменены."));
}

