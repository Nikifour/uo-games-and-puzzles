/* ────────────────────────────── посадка ────────────────────────────── */

export async function посадить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const места = (конфиг.места ?? []).map(м => ({
    кто: м.кто ?? null,
    имя: м.имя,
    бот: м.бот ?? null,
    ...сбор.сЖетона(м),
    очки: 0,
  }));

  if (места.length < 2) { ui.notifications.error(Т("За стол нужно посадить хотя бы двоих.")); return null; }

  const стол = {
    id: foundry.utils.randomID(),
    тип: "kosti",
    название: конфиг.название?.trim() || Т("Кости"),
    правила: {
      ...ПРАВИЛА,
      цель: Math.max(500, Number(конфиг.цель) || ПРАВИЛА.цель),
      триПары: Number(конфиг.триПары) || 0,
      порогВхода: Math.max(0, Number(конфиг.порогВхода) || 0),
    },
    места,
    ставка: {
      сколько: Math.max(0, Number(конфиг.ставка) || 0),
      монета: конфиг.монета in МОНЕТЫ ? конфиг.монета : "gp",
      слисты: конфиг.слисты !== false,
      банк: 0,
      внесли: [],
    },
    чей: 0,
    бросок: [],
    выбор: [],
    вХоде: 0,
    костейВРуке: 6,
    отложены: [],
    реплика: null,
    пусто: false,
    журнал: [],
    победитель: null,
    завершён: false,
    показан: true,
  };

  await записать(стол);
  await объявить(
    Т(`<p><strong>{название}</strong> — за стол сели: {имя}.</p>
     <p>Играем до {цель}.</p>`, { название: экранировать(стол.название), имя: места.map(м => экранировать(м.имя)).join(", "), цель: стол.правила.цель }), стол.название);

  const сСтавкой = await собратьСтавки(стол);

  двинутьБота(стол.id);
  return сСтавкой;
}

/* ─────────────────────────────── правила стола ─────────────────────────────── */

const место = стол => стол.места[стол.чей];
const чужиеОчки = стол => Math.max(0, ...стол.места.filter((_, i) => i !== стол.чей).map(м => м.очки));

/** Может ли этот человек ходить прямо сейчас. Ведущий может за любого. */
function егоХод(стол, пользователь) {
  if (!пользователь || стол.победитель) return false;
  const м = место(стол);
  if (м.бот) return пользователь.isGM;          // за бота вмешивается только ведущий
  return пользователь.isGM || м.кто === пользователь.id;
}

function вЖурнал(стол, строка) {
  return { ...стол, журнал: [...стол.журнал, строка].slice(-14) };
}

/**
 * Бросок настоящими костями Foundry.
 *
 * За партию бросков набегают десятки, и в общем чате от них не остаётся
 * живого места. Поэтому по умолчанию кости **катятся, но не пишутся**:
 * Dice So Nice умеет показать бросок всем без сообщения в чат
 * (`showForRoll` с synchronize), а числа и так видны в окне игры.
 *
 * Кому чат дорог как летопись — настройка возвращает сообщения: всем
 * или шёпотом одному ведущему.
 */
async function броситьВИгре(сколько, чьё, название, подсунуто = 0) {
  const бросок = await new Roll(`${сколько}d6`).evaluate();
  if (подсунуто) подкрутить(бросок, подсунуто);   // до того, как кости кто-то увидит
  const режим = game.settings.get(MODULE_ID, "broski");

  if (режим === "tikho" && game.dice3d) {
    await game.dice3d.showForRoll(бросок, game.user, true);
  } else if (режим !== "tikho") {
    await бросок.toMessage({
      speaker: { alias: `${название} · ${чьё}` },
      flavor: Т("бросает {сколько} {кость}", { сколько, кость: числом(сколько, М("кость"), М("кости"), М("костей")) }),
    }, { rollMode: режим === "gm" ? CONST.DICE_ROLL_MODES.PRIVATE : CONST.DICE_ROLL_MODES.PUBLIC });
  }
  // Тихо и без Dice So Nice — кости просто появятся в окне: показывать нечем.

  return бросок.dice[0].results.map(р => р.result);
}

/* ─────────────────────────────── ходы людей ─────────────────────────────── */

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!пользователь) return;

  // Встать можно когда угодно, а не только в свой ход: за столом не держат.
  if (запрос.что === "встать") {
    const индекс = стол.места.findIndex(м => м.кто === пользователь.id);
    if (индекс >= 0) await выгнать(стол.id, индекс, false, "сам");
    return;
  }

  if (!егоХод(стол, пользователь)) return;

  if (запрос.что === "выбор") {
    разослать(стол.id, { выбор: Array.isArray(запрос.выбор) ? запрос.выбор : [] });
    return;
  }

  if (запрос.что === "подмена") return переключитьПодмену(стол, стол.чей, запрос.сколько);
  if (запрос.что === "бросить") return бросокЧеловека(стол);
  if (запрос.что === "отложить") return отложить(стол, !!запрос.банк, пользователь);
  if (запрос.что === "пропустить" && пользователь.isGM) return следующий(стол);
}

/**
 * Столы, где кости сейчас катятся. Пока Dice So Nice доигрывает бросок,
 * сукно пустое, и без этой пометки кнопка «Бросить» успела бы загореться
 * снова — а второй щелчок бросил бы ещё раз. Память, а не только запись:
 * два быстрых щелчка приходят раньше, чем запись успевает лечь.
 */
const катятся = new Set();

async function бросокЧеловека(стол) {
  if (стол.бросок.length || катятся.has(стол.id)) return;   // кости уже на сукне или летят
  катятся.add(стол.id);
  try {
    if (!стол.катит) await записать({ ...столПоId(стол.id), катит: true });
    await броситьИЛечь(стол);
  } finally {
    катятся.delete(стол.id);
  }
}

async function броситьИЛечь(стол) {
  const имя = место(стол).имя;
  const подсунуто = Math.min(подсовывает(стол.id, стол.чей), стол.костейВРуке);
  const кости = await броситьВИгре(стол.костейВРуке, имя, стол.название, подсунуто);
  if (подсунуто) await проверитьПодмену(стол, стол.чей, подсунуто);

  const свежий = { ...столПоId(стол.id), бросок: кости, выбор: [], реплика: null, пусто: false, катит: false };

  if (!естьХод(кости, стол.правила)) {
    await записать(вЖурнал({ ...свежий, вХоде: 0, пусто: true, реплика: { место: стол.чей, текст: Т("Пусто!") } },
      Т(`{имя} — пусто, ход сгорел`, { имя })));
    await объявить(Т(`<p><strong>{имя}</strong> — пусто. Всё, что набрано за ход, сгорело.</p>`, { имя: экранировать(имя) }), стол.название);
    await пауза(1400);
    return следующий(столПоId(стол.id));
  }

  await записать(свежий);
}

async function отложить(стол, банк, пользователь) {
  const выбраны = (стол.выбор ?? []).map(i => стол.бросок[i]).filter(Boolean);
  const { очки, годен } = оценить(выбраны, стол.правила);

  if (!выбраны.length || !годен || !очки) {
    шепнуть(пользователь.id, Т("Так отложить нельзя: в отборе должна считаться каждая кость."));
    return;
  }

  const осталось = стол.бросок.filter((_, i) => !(стол.выбор ?? []).includes(i));
  const вХоде = стол.вХоде + очки;
  const имя = место(стол).имя;

  let свежий = {
    ...столПоId(стол.id),
    вХоде,
    бросок: [],
    выбор: [],
    костейВРуке: осталось.length === 0 ? 6 : осталось.length,
    // Отложил все шесть — они возвращаются в руку, на краю сукна пусто.
    отложены: осталось.length === 0 ? [] : [...(стол.отложены ?? []), ...выбраны],
    // «Отложить и бросить»: кнопка «Бросить» не должна мелькнуть, пока кости летят.
    катит: !банк,
  };
  свежий = вЖурнал(свежий, Т(`{имя} откладывает {кости} — {очки}`, { имя, кости: выбраны.map(к => ГРАНИ[к]).join(" "), очки }));

  if (банк) {
    await записать(свежий);
    return вБанк(столПоId(стол.id));
  }

  await записать(свежий);
  if (осталось.length === 0) {
    await объявить(Т(`<p><strong>{имя}</strong> отложил все кости — бросает шесть заново.</p>`, { имя: экранировать(имя) }), стол.название);
  }

  // «Отложить и бросить» — одно движение: отложенное ушло на край, оставшиеся
  // кости сразу летят на сукно. Короткая пауза — чтобы стол успел увидеть,
  // что именно отложено.
  await пауза(500);
  return бросокЧеловека(столПоId(стол.id));
}

async function вБанк(стол) {
  const м = место(стол);
  const правила = стол.правила;

  // Пока счёт не открыт, мелочь в банк не кладётся: очки сгорают.
  if (м.очки === 0 && правила.порогВхода && стол.вХоде < правила.порогВхода) {
    const свежий = вЖурнал({ ...стол, вХоде: 0 },
      Т(`{имя} не набрал {порог} для входа — очки сгорели`, { имя: м.имя, порог: правила.порогВхода }));
    await записать(свежий);
    return следующий(столПоId(стол.id));
  }

  const набрано = стол.вХоде;
  const места = стол.места.map((x, i) => i === стол.чей ? { ...x, очки: x.очки + набрано } : x);
  const итог = места[стол.чей].очки;

  let свежий = вЖурнал({ ...стол, места }, Т(`{имя} записывает {набрано} — всего {итог}`, { имя: м.имя, набрано, итог }));

  if (итог >= правила.цель) {
    свежий = { ...свежий, победитель: стол.чей, завершён: true, вХоде: 0, бросок: [], выбор: [] };
    await записать(свежий);
    await объявить(
      Т(`<p><strong>{имя}</strong> выигрывает: {итог} при цели {цель}.</p>`, { имя: экранировать(м.имя), итог: итог, цель: правила.цель }), стол.название);
    await выдатьБанк(свежий, стол.чей);
    событие("победа", свежий);
    return;
  }

  await записать(свежий);
  return следующий(столПоId(стол.id));
}

/** Что лежит перед местом в начале хода: ничего. */
const ЧИСТЫЙ_ХОД = { вХоде: 0, бросок: [], выбор: [], костейВРуке: 6, отложены: [], реплика: null, пусто: false, катит: false };

/** Передать ход дальше по кругу. */
async function следующий(стол) {
  if (!стол || стол.победитель !== null) return;
  const чей = (стол.чей + 1) % стол.места.length;
  await записать({ ...стол, чей, ...ЧИСТЫЙ_ХОД });
  сообщитьМесту(стол.id, чей);        // вдруг игрок перезагрузил страницу и забыл про рукав
  двинутьБота(стол.id);
}

/* ─────────────────────────────── ход бота ─────────────────────────────── */

let ботЗанят = false;

/** Сигнал «стол ушёл из-под бота»: ход обрывается молча, это не поломка. */
const СТОЛ_УШЁЛ = Symbol("стол ушёл");

/** Если на очереди бот и мы за ведущего — сыграть его ход целиком. */
export async function двинутьБота(id) {
  if (!ведущийЗдесь() || ботЗанят) return;
  if (!game.settings.get(MODULE_ID, "bot")) return;

  const стол = столПоId(id);
  if (!стол || стол.тип !== "kosti" || стол.победитель !== null) return;
  const м = стол.места[стол.чей];
  if (!м?.бот) return;

  /*
   * Ход бота — цепочка пауз, и между ними стол могут снять, а бота выставить.
   * Перед каждым броском и записью проверяем, что стол на месте и ход всё ещё
   * его; иначе бот докатывал бы весь ход в пустоту — бросок за броском в чат.
   * Место сверяется по имени: стол читается копией, а имена за столом разные.
   */
  const наМесте = () => {
    const с = столПоId(id);
    if (!с || с.победитель !== null || с.места[с.чей]?.имя !== м.имя) throw СТОЛ_УШЁЛ;
    return с;
  };

  ботЗанят = true;
  try {
    const задержка = Number(game.settings.get(MODULE_ID, "botPauza")) || 0;
    const характер = ХАРАКТЕРЫ[м.бот.характер] ?? ХАРАКТЕРЫ.traktirshchik;
    const сказать = текст => ({ место: стол.чей, текст });

    // Ход перешёл к боту — дать столу заметить это прежде первого броска.
    await пауза(задержка / 2);
    наМесте();

    /*
     * Бот ходит так, чтобы за ним можно было следить глазами: бросил — кости
     * легли на сукно; подумал — выбранные засветились; сказал, что решил, —
     * и только тогда отложенные ушли к нему на край. Иначе стол видит лишь
     * итог: кости мелькнули и пропали, а куда делись — догадывайся.
     */
    const взял = await сыгратьХод(
      { мои: м.очки, чужие: чужиеОчки(стол), правила: стол.правила, характер },
      {
        бросать: async сколько => {
          await записать({ ...наМесте(), катит: true });
          // Бот с краплёными подсовывает весь рукав на каждый бросок
          const подсунуто = Math.min(вРукаве(id, стол.чей), сколько);
          const кости = await броситьВИгре(сколько, м.имя, стол.название, подсунуто);
          if (подсунуто) await проверитьПодмену(столПоId(id) ?? стол, стол.чей, подсунуто);
          await записать({ ...наМесте(), бросок: кости, выбор: [], костейВРуке: сколько, реплика: null, пусто: false, катит: false });
          await пауза(задержка);
          return кости;
        },
        событие: async е => {
          const текущий = наМесте();
          if (е.что === "отложил") {
            // Сначала показать, какие кости он берёт…
            await записать({
              ...текущий,
              выбор: индексыКостей(текущий.бросок, е.берём),
              реплика: сказать(Т("Откладывает на {очки}", { очки: е.очки })),
            });
            await пауза(задержка);
            // …потом убрать их с сукна и сказать, что дальше.
            await записать(вЖурнал({
              ...наМесте(),
              вХоде: е.вХоде, бросок: [], выбор: [], костейВРуке: е.костей,
              отложены: е.костей === 6 ? [] : [...(текущий.отложены ?? []), ...е.берём],
              реплика: сказать(е.банк
                ? Т("Записывает {очки}", { очки: е.вХоде })
                : Т("Бросает ещё {сколько}", { сколько: е.костей })),
            }, Т(`{имя} откладывает {кости} — {очки}`, { имя: м.имя, кости: е.берём.map(к => ГРАНИ[к]).join(" "), очки: е.очки })));
            await пауза(задержка * 0.8);
          }
          if (е.что === "пусто") {
            await записать(вЖурнал({ ...текущий, вХоде: 0, пусто: true, реплика: сказать(Т("Пусто!")) },
              Т(`{имя} — пусто, ход сгорел`, { имя: м.имя })));
            await пауза(задержка * 1.2);
          }
        },
      });

    const текущий = столПоId(id);
    if (!текущий) return;
    if (взял > 0) await вБанк({ ...текущий, вХоде: взял });
    else await следующий(текущий);
  } catch (e) {
    if (e === СТОЛ_УШЁЛ) return;
    console.error(`${MODULE_ID} | ход бота сорвался`, e);
    ui.notifications.error(Т("Ход бота сорвался — посмотрите консоль. Ход можно передать вручную."));
  } finally {
    ботЗанят = false;
  }

  // Пока бот ходил, замок «занято» не давал двинуть следующего. Если за ним
  // сидит ещё один бот, партия иначе встала бы навсегда.
  const после = столПоId(id);
  if (после?.победитель === null && после.места[после.чей]?.бот) двинутьБота(id);
}

/** Какие по счёту кости на сукне бот берёт: те же значения, каждую кость один раз. */
function индексыКостей(бросок, берём) {
  const занято = new Set();
  return берём.map(значение => {
    const i = бросок.findIndex((к, j) => к === значение && !занято.has(j));
    занято.add(i);
    return i;
  }).filter(i => i >= 0);
}

/* ─────────────────────── личное словечко игроку ─────────────────────── */
/*
 * Сервер Foundry умеет доставлять сообщение модуля названным поимённо,
 * а не всем. Мелочь, но именно она позволяет объяснить игроку, почему
 * его отбор не принят, не объявляя об этом всему столу.
 */

function шепнуть(комуId, текст) {
  if (комуId === game.user.id) return void ui.notifications.warn(текст);
  game.socket.emit(`module.${MODULE_ID}`, { дело: "шёпот", текст }, { recipients: [комуId] });
}

/* ──────────────────────── кто встал из-за стола ──────────────────────── */

/**
 * Убрать место со стола: игрок вышел сам или ведущий его выставил.
 *
 * Тонкость здесь одна, зато злая: места пронумерованы, и по этим номерам
 * помнят и чей ход, и кто внёс ставку, и у кого краплёные в рукаве. Убрали
 * место в середине — все номера правее съехали, и если их не пересчитать,
 * подменные кости окажутся в рукаве у соседа.
 */
export async function выгнать(id, индекс, вернутьСтавку = false, причина = "ведущий") {
  const стол = столПоId(id);
  if (!стол || стол.победитель !== null) return;
  const ушедший = стол.места[индекс];
  if (!ушедший) return;

  const сдвинуть = набор => Object.fromEntries(Object.entries(набор ?? {})
    .filter(([i]) => Number(i) !== индекс)
    .map(([i, значение]) => [Number(i) > индекс ? Number(i) - 1 : Number(i), значение]));

  const ставка = { ...(стол.ставка ?? {}) };
  if (ставка.сколько) {
    const внёс = (ставка.внесли ?? []).includes(индекс);
    if (вернутьСтавку) {
      if (внёс) await изменитьКошелёк(актёрМеста(ушедший), ставка.монета, ставка.сколько);
      ставка.банк = Math.max(0, ставка.банк - ставка.сколько);
    }
    ставка.внесли = (ставка.внесли ?? [])
      .filter(i => i !== индекс)
      .map(i => (i > индекс ? i - 1 : i));
  }

  // Номера мест в тайнах ведущего тоже съезжают.
  if (game.user.isGM) {
    await записатьТайну(id, { шулера: сдвинуть(шулера(id)), вкл: сдвинуть(подменяет(id)) });
  }

  const места = стол.места.filter((_, i) => i !== индекс);
  const былЕгоХод = стол.чей === индекс;
  let чей = стол.чей > индекс ? стол.чей - 1 : стол.чей;
  if (чей >= места.length) чей = 0;

  let свежий = вЖурнал({
    ...стол, места, ставка, чей,
    ...(былЕгоХод ? ЧИСТЫЙ_ХОД : {}),
  }, причина === "сам"
    ? Т(`{имя} встаёт из-за стола`, { имя: ушедший.имя })
    : Т(`{имя} выставлен из-за стола`, { имя: ушедший.имя }));

  await объявить(
    причина === "сам"
      ? `<p><strong>${экранировать(ушедший.имя)}</strong> ${Т("встаёт из-за стола.")}</p>`
      : `<p><strong>${экранировать(ушедший.имя)}</strong> ${Т("покидает стол — так решил ведущий.")}</p>`,
    стол.название);

  // Остался один — забирает то, что на столе, и партия окончена.
  if (места.length < 2) {
    свежий = { ...свежий, победитель: места.length ? 0 : null, завершён: true, бросок: [], выбор: [], вХоде: 0 };
    await записать(свежий);
    if (места.length) {
      await объявить(Т(`<p>За столом остался один. <strong>{имя}</strong> забирает всё.</p>`, { имя: экранировать(места[0].имя) }),
        стол.название);
      await выдатьБанк(свежий, 0);
      событие("победа", свежий);
    }
    return;
  }

  await записать(свежий);
  if (былЕгоХод) сообщитьМесту(id, чей);
  двинутьБота(id);
}

/* ─────────────────────────────── подсадка ─────────────────────────────── */

/**
 * Посадить новых за стол посреди партии. В Костях раундов нет, поэтому
 * новенький садится сразу, в конец круга, со счётом с нуля: до него очередь
 * дойдёт, как до всех.
 */
export async function подсадить(id, новые) {
  if (!game.user.isGM || !новые?.length) return;
  let стол = столПоId(id);
  if (!стол || стол.победитель !== null) return;

  for (const н of новые) {
    стол = { ...стол, места: [...стол.места, { кто: н.кто, имя: н.имя, бот: н.бот, ...сбор.сЖетона(н), очки: 0 }] };
    стол = { ...стол, ставка: await сбор.ставкаСНового(стол, стол.места.length - 1) };
    стол = вЖурнал(стол, Т("{имя} подсаживается за стол", { имя: н.имя }));
  }
  await записать(стол);
  await сбор.объявитьПодсадку(стол, новые.map(н => н.имя), true);
  двинутьБота(id);
}

/* ─────────────────────────────── шулерство ─────────────────────────────── */
/*
 * Подменные кости — тайна, и хранится она там же, где ответ от замка:
 * в браузере ведущего. В состоянии стола её нет и быть не может — стол читают
 * все, и соседу хватило бы одного взгляда в консоль, чтобы «заметить» подмену
 * без всякой проверки внимания.
 *
 * Тому, у кого кости в рукаве, ведущий шлёт личное письмо: сервер доставляет
 * его только адресату. Так игрок видит свою кнопку, а сосед — нет.
 */

/** Как верно подсунутая краплёная ложится единицей или пятёркой. Иначе катится честно. */
const ВЕРНОСТЬ_КРАПЛЁНОЙ = 0.85;

/** Сколько краплёных может лежать в рукаве. Больше трёх в рукав не спрячешь. */
export const РУКАВ_ДО = 3;

/** Штраф к Ловкости рук за каждую подсунутую кость: две подменить труднее, чем одну. */
const ШТРАФ_ЗА_КОСТЬ = 2;

/** Ловкость рук трактирного бота, если нрав её не задал: он это делал тысячу раз. */
const ЛОВКОСТЬ_БОТА = 3;

/** Внимание бота за столом, если нрав его не задал: обычный завсегдатай, не следопыт. */
const ВНИМАНИЕ_БОТА = 12;

/**
 * Что знает наш клиент про свои подменные кости. Ключ — стол и место:
 * у игрока место одно, а у ведущего их может быть несколько — каждое
 * «Играет ведущий» со своим рукавом.
 */
const ПОДМЕНА = new Map();
const ключПодмены = (id, индекс) => `${id}:${индекс}`;

/** Пришло личное письмо от ведущего. */
function личное(что) {
  if (что?.что !== "шулер") return;
  ПОДМЕНА.set(ключПодмены(что.id, что.индекс), { есть: костейВПределах(что.есть, РУКАВ_ДО), вкл: костейВПределах(что.вкл, РУКАВ_ДО) });
}

/** Рукав места, чей сейчас ход. Кнопку видит только тот, кто за это место ходит. */
const мояПодмена = стол => ПОДМЕНА.get(ключПодмены(стол.id, стол.чей)) ?? { есть: 0, вкл: 0 };

/* — сторона ведущего — */

/*
 * В тайне ведущего два списка по местам: `шулера` — сколько краплёных
 * в рукаве, `вкл` — сколько шулер решил подсовывать. Прежде там лежали
 * true/false — «рукав есть» и «подмена включена»; true читается как одна кость.
 */
const шулера = id => тайна(id)?.шулера ?? {};
const подменяет = id => тайна(id)?.вкл ?? {};
const костейВПределах = (значение, до) => Math.max(0, Math.min(до, значение === true ? 1 : Number(значение) || 0));

/** Сколько краплёных в рукаве у места. */
const вРукаве = (id, индекс) => костейВПределах(шулера(id)[индекс], РУКАВ_ДО);

/** Сколько из них место подсовывает в бросок — не больше, чем в рукаве. */
const подсовывает = (id, индекс) => костейВПределах(подменяет(id)[индекс], вРукаве(id, индекс));

async function записатьТайну(id, поле) {
  await тайнуЗапомнить(id, { ...(тайна(id) ?? {}), ...поле });
}

/**
 * Сказать месту, что у него в рукаве. Ботам писать некому, а место
 * «Играет ведущий» читают ведущие — любой из них может за него бросать.
 */
function сообщитьМесту(id, индекс) {
  const м = столПоId(id)?.места?.[индекс];
  if (!м || м.бот) return;
  const кому = м.кто ? [м.кто] : game.users.filter(u => u.isGM && (u.active || u === game.user)).map(u => u.id);
  for (const адресат of кому) {
    личноеПисьмо(адресат, "kosti", {
      что: "шулер", id, индекс,
      есть: вРукаве(id, индекс),
      вкл: подсовывает(id, индекс),
    });
  }
}

/**
 * Ведущий кладёт краплёные в рукав или забирает. `сколько` — число костей,
 * 0 — забрать; true по старой памяти — одна.
 */
export async function датьПодменные(id, индекс, сколько) {
  if (!game.user.isGM) return;
  const ш = { ...шулера(id) };
  const в = { ...подменяет(id) };
  const n = костейВПределах(сколько, РУКАВ_ДО);
  if (n) {
    ш[индекс] = n;
    if (в[индекс]) в[индекс] = костейВПределах(в[индекс], n);       // подсовывать больше, чем в рукаве, нечего
  } else { delete ш[индекс]; delete в[индекс]; }
  await записатьТайну(id, { шулера: ш, вкл: в });
  сообщитьМесту(id, индекс);
}

/**
 * Шулер решил, сколько подсовывать. Выбор держится и на следующие броски,
 * пока его не сменят. Без числа (старое окно) — щелчок «всё или ничего».
 */
async function переключитьПодмену(стол, индекс, сколько) {
  const есть = вРукаве(стол.id, индекс);
  if (!есть) return;
  const в = { ...подменяет(стол.id) };
  в[индекс] = сколько === undefined ? (подсовывает(стол.id, индекс) ? 0 : есть) : костейВПределах(сколько, есть);
  await записатьТайну(стол.id, { вкл: в });
  сообщитьМесту(стол.id, индекс);
}

/**
 * Кости уже брошены — подкручиваем до того, как их кто-то увидит.
 * Краплёными становятся `подсунуто` костей наугад: какая из шести
 * подменная, по месту на сукне не угадать. Остальные легли честно.
 */
function подкрутить(бросок, подсунуто) {
  const результаты = бросок.dice[0].results;
  const места = результаты.map((р, i) => i);
  for (let i = места.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [места[i], места[j]] = [места[j], места[i]];
  }
  for (const i of места.slice(0, подсунуто)) {
    const р = результаты[i];
    if (р.result === 1 || р.result === 5) continue;      // и так в цене
    if (Math.random() < ВЕРНОСТЬ_КРАПЛЁНОЙ) р.result = Math.random() < 0.6 ? 1 : 5;
  }
  try { бросок._total = результаты.reduce((с, р) => с + р.result, 0); } catch { /* итог нам не нужен */ }
}

/**
 * Проверка подмены: Ловкость рук против пассивного внимания зрителей.
 *
 * Пассивное нарочно: иначе на каждый бросок пришлось бы гонять всех за столом
 * бросать Восприятие, а это шесть бросков на ход и мёртвая партия. Зато
 * проверка идёт на **каждый** подменённый бросок: чем чаще плутуешь, тем
 * вернее попадёшься.
 *
 * Итог знает только ведущий. Шулеру не говорят, заметили его или нет, —
 * это его тревога и сцена ведущего, а не строка в чате.
 */
async function проверитьПодмену(стол, индекс, подсунуто = 1) {
  const шулер = стол.места[индекс];
  const актёр = актёрМеста(шулер);
  const ловкость = шулер.бот ? (ХАРАКТЕРЫ[шулер.бот.характер]?.ловкость ?? ЛОВКОСТЬ_БОТА) : (актёр?.system?.skills?.slt?.total ?? 0);
  const штраф = ШТРАФ_ЗА_КОСТЬ * подсунуто;
  const мод = ловкость - штраф;

  const бросок = await new Roll(`1d20 + ${мод}`).evaluate();
  const итог = бросок.total;

  const заметили = [];
  const игрокиЗаметили = [];
  стол.места.forEach((м, i) => {
    if (i === индекс) return;
    const внимание = м.бот ? (ХАРАКТЕРЫ[м.бот.характер]?.внимание ?? ВНИМАНИЕ_БОТА) : (актёрМеста(м)?.system?.skills?.prc?.passive ?? 10);
    if (внимание < итог) return;
    заметили.push(`${м.имя} (${внимание})`);
    if (м.кто && !game.users.get(м.кто)?.isGM) игрокиЗаметили.push(м.кто);
  });

  const кому = ChatMessage.getWhisperRecipients?.("GM")?.map(u => u.id) ?? [];
  await ChatMessage.create({
    whisper: кому,
    speaker: { alias: стол.название },
    content: `<p><strong>${экранировать(шулер.имя)}</strong> ${Т("подсовывает краплёных: {сколько}.", { сколько: подсунуто })}</p>
      <p>${Т("Ловкость рук:")} <strong>${итог}</strong> (d20${ловкость >= 0 ? "+" : ""}${ловкость}${штраф ? ` −${штраф}` : ""}).</p>
      <p>${заметили.length
        ? Т(`Заметили: <strong>{кто}</strong>.`, { кто: заметили.map(экранировать).join(", ") })
        : Т("Никто не заметил.")}</p>`,
  });

  /*
   * Заметивший игрок узнаёт об этом сам, шёпотом: что делать с замеченным —
   * сказать вслух, промолчать или потребовать кости на проверку — решает он.
   * Цифр ему не показывают: сколько выбросил шулер, знает только ведущий.
   * Шулеру не говорят, что его заметили.
   */
  for (const кто of игрокиЗаметили) {
    await ChatMessage.create({
      whisper: [кто],
      speaker: { alias: стол.название },
      content: `<p>${Т("Вы замечаете, как <strong>{имя}</strong> подменяет кости.", { имя: экранировать(шулер.имя) })}</p>`,
    });
  }

  if (!шулер.бот) шепнуть(шулер.кто, Т("Кости подменены."));
}

