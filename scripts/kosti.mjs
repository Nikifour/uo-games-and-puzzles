/* ────────────────────────────── посадка ────────────────────────────── */

export async function посадить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const места = (конфиг.места ?? []).map(м => ({
    кто: м.кто ?? null,
    имя: м.имя,
    бот: м.бот ?? null,
    очки: 0,
  }));

  if (места.length < 2) { ui.notifications.error(Т("За стол нужно посадить хотя бы двоих.")); return null; }

  const стол = {
    id: foundry.utils.randomID(),
    тип: "kosti",
    название: конфиг.название?.trim() || Т("Кости"),
    правила: {
      ...ПРАВИЛА,
      цель: Math.max(500, Number(конфиг.цель) || ПРАВИЛА.цель),
      триПары: Number(конфиг.триПары) || 0,
      порогВхода: Math.max(0, Number(конфиг.порогВхода) || 0),
    },
    места,
    ставка: {
      сколько: Math.max(0, Number(конфиг.ставка) || 0),
      монета: конфиг.монета in МОНЕТЫ ? конфиг.монета : "gp",
      слисты: конфиг.слисты !== false,
      банк: 0,
      внесли: [],
    },
    чей: 0,
    бросок: [],
    выбор: [],
    вХоде: 0,
    костейВРуке: 6,
    журнал: [],
    победитель: null,
    завершён: false,
    показан: true,
  };

  await записать(стол);
  await объявить(
    Т(`<p><strong>{название}</strong> — за стол сели: {имя}.</p>
     <p>Играем до {цель}.</p>`, { название: экранировать(стол.название), имя: места.map(м => экранировать(м.имя)).join(", "), цель: стол.правила.цель }), стол.название);

  const сСтавкой = await собратьСтавки(стол);

  двинутьБота(стол.id);
  return сСтавкой;
}

/* ─────────────────────────────── правила стола ─────────────────────────────── */

const место = стол => стол.места[стол.чей];
const чужиеОчки = стол => Math.max(0, ...стол.места.filter((_, i) => i !== стол.чей).map(м => м.очки));

/** Может ли этот человек ходить прямо сейчас. Ведущий может за любого. */
function егоХод(стол, пользователь) {
  if (!пользователь || стол.победитель) return false;
  const м = место(стол);
  if (м.бот) return пользователь.isGM;          // за бота вмешивается только ведущий
  return пользователь.isGM || м.кто === пользователь.id;
}

function вЖурнал(стол, строка) {
  return { ...стол, журнал: [...стол.журнал, строка].slice(-14) };
}

/**
 * Бросок настоящими костями Foundry.
 *
 * За партию бросков набегают десятки, и в общем чате от них не остаётся
 * живого места. Поэтому по умолчанию кости **катятся, но не пишутся**:
 * Dice So Nice умеет показать бросок всем без сообщения в чат
 * (`showForRoll` с synchronize), а числа и так видны в окне игры.
 *
 * Кому чат дорог как летопись — настройка возвращает сообщения: всем
 * или шёпотом одному ведущему.
 */
async function броситьВИгре(сколько, чьё, название, подменять = false) {
  const бросок = await new Roll(`${сколько}d6`).evaluate();
  if (подменять) подкрутить(бросок);              // до того, как кости кто-то увидит
  const режим = game.settings.get(MODULE_ID, "broski");

  if (режим === "tikho" && game.dice3d) {
    await game.dice3d.showForRoll(бросок, game.user, true);
  } else if (режим !== "tikho") {
    await бросок.toMessage({
      speaker: { alias: `${название} · ${чьё}` },
      flavor: Т("бросает {сколько} {кость}", { сколько, кость: числом(сколько, М("кость"), М("кости"), М("костей")) }),
    }, { rollMode: режим === "gm" ? CONST.DICE_ROLL_MODES.PRIVATE : CONST.DICE_ROLL_MODES.PUBLIC });
  }
  // Тихо и без Dice So Nice — кости просто появятся в окне: показывать нечем.

  return бросок.dice[0].results.map(р => р.result);
}

/* ─────────────────────────────── ходы людей ─────────────────────────────── */

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!пользователь) return;

  // Встать можно когда угодно, а не только в свой ход: за столом не держат.
  if (запрос.что === "встать") {
    const индекс = стол.места.findIndex(м => м.кто === пользователь.id);
    if (индекс >= 0) await выгнать(стол.id, индекс, false, "сам");
    return;
  }

  if (!егоХод(стол, пользователь)) return;

  if (запрос.что === "выбор") {
    разослать(стол.id, { выбор: Array.isArray(запрос.выбор) ? запрос.выбор : [] });
    return;
  }

  if (запрос.что === "подмена") return переключитьПодмену(стол, стол.чей);
  if (запрос.что === "бросить") return бросокЧеловека(стол);
  if (запрос.что === "отложить") return отложить(стол, !!запрос.банк, пользователь);
  if (запрос.что === "пропустить" && пользователь.isGM) return следующий(стол);
}

async function бросокЧеловека(стол) {
  if (стол.бросок.length) return;                      // кости уже на сукне
  const имя = место(стол).имя;
  const плутует = !!шулера(стол.id)[стол.чей] && !!подменяет(стол.id)[стол.чей];
  const кости = await броситьВИгре(стол.костейВРуке, имя, стол.название, плутует);
  if (плутует) await проверитьПодмену(стол, стол.чей);

  const свежий = { ...столПоId(стол.id), бросок: кости, выбор: [] };

  if (!естьХод(кости, стол.правила)) {
    await записать(вЖурнал({ ...свежий, вХоде: 0 }, Т(`{имя} — пусто, ход сгорел`, { имя })));
    await объявить(Т(`<p><strong>{имя}</strong> — пусто. Всё, что набрано за ход, сгорело.</p>`, { имя: экранировать(имя) }), стол.название);
    await пауза(900);
    return следующий(столПоId(стол.id));
  }

  await записать(свежий);
}

async function отложить(стол, банк, пользователь) {
  const выбраны = (стол.выбор ?? []).map(i => стол.бросок[i]).filter(Boolean);
  const { очки, годен } = оценить(выбраны, стол.правила);

  if (!выбраны.length || !годен || !очки) {
    шепнуть(пользователь.id, Т("Так отложить нельзя: в отборе должна считаться каждая кость."));
    return;
  }

  const осталось = стол.бросок.filter((_, i) => !(стол.выбор ?? []).includes(i));
  const вХоде = стол.вХоде + очки;
  const имя = место(стол).имя;

  let свежий = {
    ...столПоId(стол.id),
    вХоде,
    бросок: [],
    выбор: [],
    костейВРуке: осталось.length === 0 ? 6 : осталось.length,
  };
  свежий = вЖурнал(свежий, Т(`{имя} откладывает {кости} — {очки}`, { имя, кости: выбраны.map(к => ГРАНИ[к]).join(" "), очки }));

  if (банк) {
    await записать(свежий);
    return вБанк(столПоId(стол.id));
  }

  await записать(свежий);
  if (осталось.length === 0) {
    await объявить(Т(`<p><strong>{имя}</strong> отложил все кости — бросает шесть заново.</p>`, { имя: экранировать(имя) }), стол.название);
  }
}

async function вБанк(стол) {
  const м = место(стол);
  const правила = стол.правила;

  // Пока счёт не открыт, мелочь в банк не кладётся: очки сгорают.
  if (м.очки === 0 && правила.порогВхода && стол.вХоде < правила.порогВхода) {
    const свежий = вЖурнал({ ...стол, вХоде: 0 },
      Т(`{имя} не набрал {порог} для входа — очки сгорели`, { имя: м.имя, порог: правила.порогВхода }));
    await записать(свежий);
    return следующий(столПоId(стол.id));
  }

  const набрано = стол.вХоде;
  const места = стол.места.map((x, i) => i === стол.чей ? { ...x, очки: x.очки + набрано } : x);
  const итог = места[стол.чей].очки;

  let свежий = вЖурнал({ ...стол, места }, Т(`{имя} записывает {набрано} — всего {итог}`, { имя: м.имя, набрано, итог }));

  if (итог >= правила.цель) {
    свежий = { ...свежий, победитель: стол.чей, завершён: true, вХоде: 0, бросок: [], выбор: [] };
    await записать(свежий);
    await объявить(
      Т(`<p><strong>{имя}</strong> выигрывает: {итог} при цели {цель}.</p>`, { имя: экранировать(м.имя), итог: итог, цель: правила.цель }), стол.название);
    await выдатьБанк(свежий, стол.чей);
    событие("победа", свежий);
    return;
  }

  await записать(свежий);
  return следующий(столПоId(стол.id));
}

/** Передать ход дальше по кругу. */
async function следующий(стол) {
  if (!стол || стол.победитель !== null) return;
  const чей = (стол.чей + 1) % стол.места.length;
  await записать({ ...стол, чей, вХоде: 0, бросок: [], выбор: [], костейВРуке: 6 });
  сообщитьМесту(стол.id, чей);        // вдруг игрок перезагрузил страницу и забыл про рукав
  двинутьБота(стол.id);
}

/* ─────────────────────────────── ход бота ─────────────────────────────── */

let ботЗанят = false;

/** Если на очереди бот и мы за ведущего — сыграть его ход целиком. */
export async function двинутьБота(id) {
  if (!ведущийЗдесь() || ботЗанят) return;
  if (!game.settings.get(MODULE_ID, "bot")) return;

  const стол = столПоId(id);
  if (!стол || стол.тип !== "kosti" || стол.победитель !== null) return;
  const м = стол.места[стол.чей];
  if (!м?.бот) return;

  ботЗанят = true;
  try {
    const задержка = Number(game.settings.get(MODULE_ID, "botPauza")) || 0;
    const характер = ХАРАКТЕРЫ[м.бот.характер] ?? ХАРАКТЕРЫ.traktirshchik;

    const взял = await сыгратьХод(
      { мои: м.очки, чужие: чужиеОчки(стол), правила: стол.правила, характер },
      {
        бросать: async сколько => {
          const плутует = !!шулера(id)[стол.чей];       // помеченный бот играет краплёными всегда
          const кости = await броситьВИгре(сколько, м.имя, стол.название, плутует);
          if (плутует) await проверитьПодмену(столПоId(id) ?? стол, стол.чей);
          await записать({ ...столПоId(id), бросок: кости, выбор: [], костейВРуке: сколько });
          await пауза(задержка);
          return кости;
        },
        событие: async е => {
          const текущий = столПоId(id);
          if (!текущий) return;
          if (е.что === "отложил") {
            await записать(вЖурнал(
              { ...текущий, вХоде: е.вХоде, бросок: [], выбор: [], костейВРуке: е.костей },
              Т(`{имя} откладывает {кости} — {очки}`, { имя: м.имя, кости: е.берём.map(к => ГРАНИ[к]).join(" "), очки: е.очки })));
            await пауза(задержка);
          }
          if (е.что === "пусто") {
            await записать(вЖурнал({ ...текущий, вХоде: 0 }, Т(`{имя} — пусто, ход сгорел`, { имя: м.имя })));
            await пауза(задержка);
          }
        },
      });

    const текущий = столПоId(id);
    if (!текущий) return;
    if (взял > 0) await вБанк({ ...текущий, вХоде: взял });
    else await следующий(текущий);
  } catch (e) {
    console.error(`${MODULE_ID} | ход бота сорвался`, e);
    ui.notifications.error(Т("Ход бота сорвался — посмотрите консоль. Ход можно передать вручную."));
  } finally {
    ботЗанят = false;
  }

  // Пока бот ходил, замок «занято» не давал двинуть следующего. Если за ним
  // сидит ещё один бот, партия иначе встала бы навсегда.
  const после = столПоId(id);
  if (после?.победитель === null && после.места[после.чей]?.бот) двинутьБота(id);
}

/* ─────────────────────── личное словечко игроку ─────────────────────── */
/*
 * Сервер Foundry умеет доставлять сообщение модуля названным поимённо,
 * а не всем. Мелочь, но именно она позволяет объяснить игроку, почему
 * его отбор не принят, не объявляя об этом всему столу.
 */

function шепнуть(комуId, текст) {
  if (комуId === game.user.id) return void ui.notifications.warn(текст);
  game.socket.emit(`module.${MODULE_ID}`, { дело: "шёпот", текст }, { recipients: [комуId] });
}

/* ──────────────────────── кто встал из-за стола ──────────────────────── */

/**
 * Убрать место со стола: игрок вышел сам или ведущий его выставил.
 *
 * Тонкость здесь одна, зато злая: места пронумерованы, и по этим номерам
 * помнят и чей ход, и кто внёс ставку, и у кого краплёные в рукаве. Убрали
 * место в середине — все номера правее съехали, и если их не пересчитать,
 * подменные кости окажутся в рукаве у соседа.
 */
export async function выгнать(id, индекс, вернутьСтавку = false, причина = "ведущий") {
  const стол = столПоId(id);
  if (!стол || стол.победитель !== null) return;
  const ушедший = стол.места[индекс];
  if (!ушедший) return;

  const сдвинуть = набор => Object.fromEntries(Object.entries(набор ?? {})
    .filter(([i]) => Number(i) !== индекс)
    .map(([i, значение]) => [Number(i) > индекс ? Number(i) - 1 : Number(i), значение]));

  const ставка = { ...(стол.ставка ?? {}) };
  if (ставка.сколько) {
    const внёс = (ставка.внесли ?? []).includes(индекс);
    if (вернутьСтавку) {
      if (внёс) await изменитьКошелёк(актёрМеста(ушедший), ставка.монета, ставка.сколько);
      ставка.банк = Math.max(0, ставка.банк - ставка.сколько);
    }
    ставка.внесли = (ставка.внесли ?? [])
      .filter(i => i !== индекс)
      .map(i => (i > индекс ? i - 1 : i));
  }

  // Номера мест в тайнах ведущего тоже съезжают.
  if (game.user.isGM) {
    await записатьТайну(id, { шулера: сдвинуть(шулера(id)), вкл: сдвинуть(подменяет(id)) });
  }

  const места = стол.места.filter((_, i) => i !== индекс);
  const былЕгоХод = стол.чей === индекс;
  let чей = стол.чей > индекс ? стол.чей - 1 : стол.чей;
  if (чей >= места.length) чей = 0;

  let свежий = вЖурнал({
    ...стол, места, ставка, чей,
    ...(былЕгоХод ? { вХоде: 0, бросок: [], выбор: [], костейВРуке: 6 } : {}),
  }, причина === "сам"
    ? Т(`{имя} встаёт из-за стола`, { имя: ушедший.имя })
    : Т(`{имя} выставлен из-за стола`, { имя: ушедший.имя }));

  await объявить(
    причина === "сам"
      ? `<p><strong>${экранировать(ушедший.имя)}</strong> ${Т("встаёт из-за стола.")}</p>`
      : `<p><strong>${экранировать(ушедший.имя)}</strong> ${Т("покидает стол — так решил ведущий.")}</p>`,
    стол.название);

  // Остался один — забирает то, что на столе, и партия окончена.
  if (места.length < 2) {
    свежий = { ...свежий, победитель: места.length ? 0 : null, завершён: true, бросок: [], выбор: [], вХоде: 0 };
    await записать(свежий);
    if (места.length) {
      await объявить(Т(`<p>За столом остался один. <strong>{имя}</strong> забирает всё.</p>`, { имя: экранировать(места[0].имя) }),
        стол.название);
      await выдатьБанк(свежий, 0);
      событие("победа", свежий);
    }
    return;
  }

  await записать(свежий);
  if (былЕгоХод) сообщитьМесту(id, чей);
  двинутьБота(id);
}

/* ─────────────────────────────── шулерство ─────────────────────────────── */
/*
 * Подменные кости — тайна, и хранится она там же, где ответ от замка:
 * в браузере ведущего. В состоянии стола её нет и быть не может — стол читают
 * все, и соседу хватило бы одного взгляда в консоль, чтобы «заметить» подмену
 * без всякой проверки внимания.
 *
 * Тому, у кого кости в рукаве, ведущий шлёт личное письмо: сервер доставляет
 * его только адресату. Так игрок видит свою кнопку, а сосед — нет.
 */

/** Насколько охотно подменная кость ложится на единицу или пятёрку. */
const СИЛА_ПОДМЕНЫ = 0.45;

/** Ловкость рук трактирного бота: он это делал тысячу раз. */
const ЛОВКОСТЬ_БОТА = 3;

/** Внимание бота за столом: обычный завсегдатай, не следопыт. */
const ВНИМАНИЕ_БОТА = 12;

/** Что знает наш клиент про свои подменные кости. Ключ — стол. */
const ПОДМЕНА = new Map();

/** Пришло личное письмо от ведущего. */
function личное(что) {
  if (что?.что !== "шулер") return;
  ПОДМЕНА.set(что.id, { есть: !!что.есть, вкл: !!что.вкл });
}

const мояПодмена = стол => ПОДМЕНА.get(стол.id) ?? { есть: false, вкл: false };

/* — сторона ведущего — */

const шулера = id => тайна(id)?.шулера ?? {};
