/**
 * Развороты зеркал: перебор и глубина.
 *
 * Общее для зала зеркал и зала призм. Каждое зеркало стоит одной из двух косых,
 * значит все положения зала — это двоичные числа: бит на зеркало. Щелчок по
 * зеркалу переворачивает один бит, то есть переводит зал в соседнюю вершину
 * двоичного куба.
 *
 * Отсюда честная мера сложности: **глубина** — сколько щелчков нужно от
 * нынешнего положения до ближайшего решающего. Считается поиском в ширину
 * из всех решающих положений разом: сперва они (глубина 0), потом их соседи
 * (глубина 1) и так далее, пока куб не заполнится.
 *
 * Это заменяет прежнее «развернём зеркала как попало». Случайный разворот
 * сплошь и рядом оказывался в одном щелчке от ответа — зал решался с первого
 * тычка. Теперь начальное положение берётся из тех, что стоят от решения не
 * ближе заказанного числа ходов.
 */

/** Положение зеркал по двоичной маске: бит выставлен — косая «/». */
export const набор = (ключи, маска) => {
  const где = {};
  ключи.forEach((к, и) => { где[к] = (маска >> и) & 1 ? "/" : "\\"; });
  return где;
};

/** Маска по положению зеркал — обратное преобразование. */
export const маска = (ключи, где) =>
  ключи.reduce((м, к, и) => (где[к] === "/" ? м | (1 << и) : м), 0);

/**
 * Перебрать все положения и посчитать глубину каждого.
 *
 * `решает` получает готовое положение зеркал и отвечает, зажигается ли зал.
 * Перебор экспоненциальный, поэтому есть предел: шестнадцать зеркал — это
 * 65 536 прогонов луча, за глаза; больше в зале и не бывает.
 */
export function разбор(ключи, решает, предел = 16) {
  if (!ключи.length || ключи.length > предел) return null;

  const всего = 1 << ключи.length;
  const глубина = new Int16Array(всего).fill(-1);
  const очередь = [];

  for (let м = 0; м < всего; м++) {
    if (!решает(набор(ключи, м))) continue;
    глубина[м] = 0;
    очередь.push(м);
  }
  if (!очередь.length) return { ключи, всего, решающих: 0, глубина, глубже: 0 };

  const решающих = очередь.length;
  let глубже = 0;
  for (let г = 0; г < очередь.length; г++) {
    const м = очередь[г];
    for (let б = 0; б < ключи.length; б++) {
      const сосед = м ^ (1 << б);
      if (глубина[сосед] !== -1) continue;
      глубина[сосед] = глубина[м] + 1;
      глубже = Math.max(глубже, глубина[сосед]);
      очередь.push(сосед);
    }
  }

  return { ключи, всего, решающих, глубина, глубже };
}

/**
 * Выбрать начальное положение: не решённое и не ближе `хочу` ходов к ответу.
 *
 * Если такого нет — берём самое дальнее, какое есть, и честно возвращаем его
 * глубину: пусть выкладывающий видит, что зал вышел проще заказанного, вместо
 * молчаливой подмены.
 */
export function начало(разобранный, хочу = 1) {
  if (!разобранный || !разобранный.решающих) return null;

  const { ключи, всего, глубина, глубже } = разобранный;
  const цель = Math.min(Math.max(1, хочу), глубже);
  if (!цель) return null;                       // решается при любом развороте — не загадка

  const годные = [];
  for (let м = 0; м < всего; м++) if (глубина[м] >= цель) годные.push(м);
  if (!годные.length) return null;

  const выбор = годные[Math.floor(Math.random() * годные.length)];
  return { зеркала: набор(ключи, выбор), глубина: глубина[выбор] };
}
