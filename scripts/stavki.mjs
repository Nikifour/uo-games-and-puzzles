/**
 * Ставки за столом: монеты, банк и кошельки на листах.
 *
 * Общее для всех игр семьи. Правило одно и то же, играют ли в Кости или
 * в Джо: ставку кладут все, банк считается по числу мест, а с листа
 * снимается там, где лист есть и монет хватает. Остальное — на ведущем.
 *
 * Вынесено сюда, когда игр стало две: дублировать деньги — последнее дело,
 * ошибка в копии дороже любой другой.
 */

import { записать, объявить } from "./stol.mjs";
import { Т, М } from "./yazyk.mjs";

const экранировать = s => foundry.utils.escapeHTML(String(s ?? ""));

/** Лист персонажа, если он у места есть. У бота листа нет. */
export const актёрМеста = м => (м?.кто ? game.users.get(м.кто)?.character : null) ?? null;

export const МОНЕТЫ = {
  pp: { имя: М("платиновых"), кратко: М("пм") },
  gp: { имя: М("золотых"), кратко: М("зм") },
  ep: { имя: М("электрумовых"), кратко: М("эм") },
  sp: { имя: М("серебряных"), кратко: М("см") },
  cp: { имя: М("медных"), кратко: М("мм") },
};

export const монетами = (сколько, монета) => `${сколько} ${МОНЕТЫ[монета] ? Т(МОНЕТЫ[монета].кратко) : монета}`;
export const вКошельке = (актёр, монета) => Number(актёр?.system?.currency?.[монета] ?? 0);

export async function изменитьКошелёк(актёр, монета, насколько) {
  if (!актёр) return false;
  const было = вКошельке(актёр, монета);
  if (было + насколько < 0) return false;
  await актёр.update({ [`system.currency.${монета}`]: было + насколько });
  return true;
}

/**
 * Собрать ставки.
 *
 * Ставку кладут все, и банк считается по числу мест — даже если чьи-то монеты
 * двигает ведущий руками: у бота листа нет, у игрока может не быть персонажа.
 * С листа снимается только там, где лист есть и монет хватает. Отказывать
 * в игре из-за пустого кошелька модуль не берётся: это разговор за столом,
 * а не дело программы.
 */
export async function собратьСтавки(стол) {
  const { сколько, монета, слисты } = стол.ставка ?? {};
  if (!сколько) return стол;

  const внесли = [];
  const мимо = [];

  for (const [i, м] of стол.места.entries()) {
    const актёр = слисты ? актёрМеста(м) : null;
    if (!актёр) { мимо.push(м.имя); continue; }
    if (await изменитьКошелёк(актёр, монета, -сколько)) внесли.push(i);
    else мимо.push(Т(`{имя} — не хватило`, { имя: м.имя }));
  }

  const обновлённый = {
    ...стол,
    ставка: { ...стол.ставка, внесли, банк: сколько * стол.места.length },
  };
  await записать(обновлённый);

  await объявить(
    Т(`<p>Ставка — {монета} с каждого, в банке {монета2}.</p>`, { монета: монетами(сколько, монета), монета2: монетами(обновлённый.ставка.банк, монета) }) +
    (мимо.length ? `<p>${Т(`С листа не снято у: {мимо} — эти ставки на ведущем.`, { мимо: мимо.map(экранировать).join(", ") })}</p>` : ""),
    стол.название);

  return обновлённый;
}

export async function выдатьБанк(стол, индекс) {
  const { сколько, банк, монета, слисты } = стол.ставка ?? {};
  if (!сколько || !банк) return;

  const м = стол.места[индекс];
  const актёр = слисты ? актёрМеста(м) : null;
  if (актёр) await изменитьКошелёк(актёр, монета, банк);

  await объявить(
    Т(`<p><strong>{имя}</strong> забирает банк: {монета}.</p>`, { имя: экранировать(м.имя), монета: монетами(банк, монета) }) +
    (актёр ? "" : `<p>${Т("На лист не начислено — банк отдаёт ведущий.")}</p>`),
    стол.название);
}

/** Партию бросили на середине — вернуть тем, с кого успели снять. */
export async function вернутьСтавки(стол) {
  const { сколько, монета, внесли = [] } = стол.ставка ?? {};
  if (!сколько || !внесли.length) return;
  for (const i of внесли) await изменитьКошелёк(актёрМеста(стол.места[i]), монета, сколько);
  await объявить(Т(`<p>Партия не доиграна — ставки возвращены.</p>`), стол.название);
}
