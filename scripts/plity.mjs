/**
 * Плиты — зал, который переходят по одной.
 *
 * Через зал ведёт единственная безопасная тропа, и её никто не знает. Шагнул
 * верно — плита держит; шагнул мимо — она уходит из-под ноги, и всё начинается
 * от порога. Но найденные ловушки остаются помеченными, поэтому со второго
 * захода идут увереннее: зал не столько загадка, сколько общая память стола.
 *
 * Дальше начинается работа ведущего. Модуль объявляет, что плита подвела,
 * и вызывает макрос ловушки, если он назначен, — а что именно случилось,
 * решает ведущий: дротик, яма, вой, тревога. Тут нарочно не сделано никакого
 * урона: цена ошибки — дело стола, а не модуля.
 */

