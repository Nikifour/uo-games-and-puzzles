class ОкноПлит extends ApplicationV2 {
  constructor(options = {}) {
    super(options);
    this.стол = options.стол;
    this.тропаВидна = false;
  }

  static DEFAULT_OPTIONS = {
    classes: ["uo-igry", "uo-plity-okno"],
    tag: "div",
    window: { title: М("Зал плит"), icon: "fa-solid fa-shoe-prints", resizable: false },
    position: { width: 480, height: "auto" },
    actions: {
      шагнуть: ОкноПлит.#шагнуть,
      тропаВидна: ОкноПлит.#тропаВидна,
      переложить: ОкноПлит.#переложить,
      засчитать: ОкноПлит.#засчитать,
      сброс: ОкноПлит.#сброс,
      снять: ОкноПлит.#снять,
    },
  };

  get title() { return this.стол?.название ?? Т("Зал плит"); }

  static #шагнуть(event, target) {
    просить({ id: this.стол.id, что: "шагнуть", плита: target.dataset.plita });
  }

  static #тропаВидна() { this.тропаВидна = !this.тропаВидна; this.render(); }
  static #переложить() { переложить(this.стол.id); }
  static #засчитать() { засчитать(this.стол.id); }
  static #сброс() { сбросить(this.стол.id); }
  static #снять() { убрать(this.стол.id); }

  _onClose() {
    забытьОкно(this.стол.id);
    if (this.закрываемСами) return;
    if (game.user.isGM) спрятать(this.стол.id);
    else спрятатьУСебя(this.стол.id);
  }

  async _renderHTML() {
    const с = this.стол;
    const шагает = можетШагать(с, game.user);
    const можно = шагает ? доступные(с) : [];
    const тропа = this.тропаВидна ? (тайна(с.id)?.путь ?? []) : [];
    const где = с.пройдено[с.пройдено.length - 1];

    const плиты = Array.from({ length: с.ширина * с.высота }, (_, к) => {
      const пройдена = с.пройдено.includes(к);
      const ловушка = с.ловушки.includes(к);
      const доступна = можно.includes(к);
      const подсмотр = тропа.includes(к) && !пройдена;

      const классы = [
        "uo-plita",
        пройдена ? "uo-projdena" : "",
        к === где ? "uo-tut" : "",
        ловушка ? "uo-lovushka" : "",
        доступна ? "uo-mozhno" : "",
        подсмотр ? "uo-tropa" : "",
      ].filter(Boolean).join(" ");

      return `<button type="button" class="${классы}" ${
        доступна ? `data-action="шагнуть" data-plita="${к}"` : "disabled"}>${
        ловушка ? "✕" : пройдена ? "•" : ""}</button>`;
    }).join("");

    const счёт = с.ловушек.предел
      ? Т("Ловушек сработало {сработало} из {предел}", { сработало: с.ловушек.сработало, предел: с.ловушек.предел })
      : Т("Ловушек сработало: {сработало}", { сработало: с.ловушек.сработало });

    const итог = с.пройден
      ? `<p class="uo-itog uo-otkryt">${Т("Зал пройден.")}</p>`
      : с.заклинило
        ? `<p class="uo-itog uo-zaklinilo">${Т("Зал больше не пускает. Ведущий может открыть его заново.")}</p>`
        : "";

    const журнал = (с.журнал ?? []).length ? `
      <ol class="uo-zhurnal">
        ${[...с.журнал].reverse().map(з => `
          <li><span class="uo-kto">${экранировать(з.кто)}</span>
              <span class="uo-podskazka">${Т(`плита {ширина}:{ширина2}`, { ширина: Math.floor(з.плита / с.ширина) + 1, ширина2: 
                (з.плита % с.ширина) + 1 })}</span></li>`).join("")}
      </ol>` : "";

    const гм = game.user.isGM ? `
      <section class="uo-gm">
        <div class="uo-gm-kod">
          <button type="button" data-action="тропаВидна">${this.тропаВидна ? Т("Скрыть тропу") : Т("Показать тропу")}</button>
        </div>
        <div class="uo-gm-knopki">
          <button type="button" data-action="переложить">${Т("Переложить тропу")}</button>
          <button type="button" data-action="засчитать">${Т("Засчитать")}</button>
          <button type="button" data-action="сброс">${Т("Сбросить")}</button>
          <button type="button" data-action="снять">${Т("Убрать со стола")}</button>
        </div>
      </section>` : "";

    return `
      <div class="uo-plity-telo uo-tema-${экранировать(с.тема)}">
        ${с.подпись ? `<p class="uo-podpis">${экранировать(с.подпись)}</p>` : ""}
        <p class="uo-podskazka">${Т("Тот берег — верхний ряд. Идут снизу, по одной плите за шаг.")}</p>
        <div class="uo-plity" style="--shirina: ${с.ширина}">${плиты}</div>
        <div class="uo-stroka"><span class="uo-schet">${счёт}</span></div>
        ${итог}
        ${журнал}
        ${гм}
      </div>`;
  }

  _replaceHTML(result, content) { content.innerHTML = result; }
}

