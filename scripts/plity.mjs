/* ─────────────────────────── прокладка тропы ─────────────────────────── */

const наугад = сколько => Math.floor(Math.random() * сколько);

/**
 * Тропа кладётся рядами снизу вверх: в каждом ряду немного вбок, потом шаг
 * вперёд. Так она не пересекает саму себя и не петляет через весь зал —
 * а значит, соседняя клетка всегда одна из немногих, и выбор осмыслен.
 */
function проложить(ширина, высота) {
  const путь = [];
  let столбец = наугад(ширина);

  for (let ряд = высота - 1; ряд >= 0; ряд--) {
    const разброс = Math.min(2, ширина - 1);
    const цель = ряд === 0
      ? столбец
      : Math.max(0, Math.min(ширина - 1, столбец + наугад(разброс * 2 + 1) - разброс));

    путь.push(ряд * ширина + столбец);
    const шаг = цель > столбец ? 1 : -1;
    while (столбец !== цель) {
      столбец += шаг;
      путь.push(ряд * ширина + столбец);
    }
  }
  return путь;
}

const рядом = (a, b, ширина) => {
  const [ра, ка] = [Math.floor(a / ширина), a % ширина];
  const [рб, кб] = [Math.floor(b / ширина), b % ширина];
  return Math.abs(ра - рб) + Math.abs(ка - кб) === 1;
};

/* ─────────────────────────── выложить на стол ─────────────────────────── */

export async function выложить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const ширина = Math.min(9, Math.max(3, Number(конфиг.ширина) || 5));
  const высота = Math.min(9, Math.max(3, Number(конфиг.высота) || 5));
  const путь = проложить(ширина, высота);

  await прибрать();

  const id = foundry.utils.randomID();
  const стол = {
    id,
    тип: "plity",
    название: конфиг.название?.trim() || Т("Зал плит"),
    подпись: конфиг.подпись?.trim() || "",
    тема: (конфиг.тема in ТЕМЫ) ? конфиг.тема : "kamen",
    ширина,
    высота,
    пройдено: [],
    ловушки: [],
    помнитьЛовушки: конфиг.помнитьЛовушки !== false,
    откат: конфиг.откат === "шаг" ? "шаг" : "порог",
    ловушек: { сработало: 0, предел: Math.max(0, Number(конфиг.предел) || 0) },
    шагают: конфиг.шагают?.length ? конфиг.шагают : "все",
    макрос: конфиг.макрос?.trim() || null,
    макросЛовушки: конфиг.макросЛовушки?.trim() || null,
    журнал: [],
    пройден: false,
    заклинило: false,
    завершён: false,
    показан: true,
  };

  await тайнуЗапомнить(id, { путь });
  await записать(стол);
  return стол;
}

export async function прибрать() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "plity" && с.завершён) await убрать(id);
  }
}

/* ─────────────────────────────── правила ─────────────────────────────── */

const можетШагать = (стол, пользователь) =>
  !!пользователь && !стол.пройден && !стол.заклинило &&
  (пользователь.isGM || стол.шагают === "все" || (стол.шагают ?? []).includes(пользователь.id));

/** Куда можно ступить с того места, где стоим. */
export function доступные(стол) {
  const { ширина, высота, пройдено } = стол;
  if (!пройдено.length) {
    return Array.from({ length: ширина }, (_, к) => (высота - 1) * ширина + к);
  }
  const где = пройдено[пройдено.length - 1];
  return Array.from({ length: ширина * высота }, (_, к) => к)
    .filter(к => рядом(к, где, ширина) && !пройдено.includes(к));
}

async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!можетШагать(стол, пользователь)) return;
  if (запрос.что !== "шагнуть") return;

  const плита = Number(запрос.плита);
  if (!доступные(стол).includes(плита)) return;

  const путь = тайна(стол.id)?.путь;
  if (!путь) {
    ui.notifications.error(
      Т("Тропа зала «{название}» не найдена в этом браузере. Засчитайте вручную или выложите заново.", { название: стол.название }));
    return;
  }

  if (плита === путь[стол.пройдено.length]) {
    const пройдено = [...стол.пройдено, плита];
    if (пройдено.length === путь.length) return перешли(стол, пройдено, запрос.кто);
    разослать(стол.id, { пройдено });
    await записать({ ...столПоId(стол.id), пройдено });
    return;
  }

  return подвела(стол, плита, запрос.кто);
}

async function подвела(стол, плита, ктоId) {
  const ловушки = стол.помнитьЛовушки && !стол.ловушки.includes(плита)
    ? [...стол.ловушки, плита]
    : стол.ловушки;

  const пройдено = стол.откат === "шаг" ? стол.пройдено.slice(0, -1) : [];

  const обновлённый = {
    ...столПоId(стол.id),
    пройдено,
    ловушки,
    ловушек: { ...стол.ловушек, сработало: стол.ловушек.сработало + 1 },
    журнал: [...(стол.журнал ?? []), { кто: имяИгрока(ктоId), плита }].slice(-8),
  };

  if (обновлённый.ловушек.предел && обновлённый.ловушек.сработало >= обновлённый.ловушек.предел) {
    обновлённый.заклинило = true;
    обновлённый.завершён = true;
  }

  await записать(обновлённый);

  await объявить(
    Т(`<p><strong>{название}</strong>: плита под {ктоId} уходит вниз.</p>`, { название: экранировать(стол.название), ктоId: 
      экранировать(имяИгрока(ктоId)) }) +
    (обновлённый.заклинило
      ? `<p>${Т("Зал больше не пускает.")}</p>`
      : стол.откат === "шаг" ? `<p>${Т("Шаг назад.")}</p>` : `<p>${Т("Всё сначала, от порога.")}</p>`),
    стол.название);

  событие("ловушка", обновлённый);
  await запуститьМакрос(стол.макросЛовушки, обновлённый);
}

async function перешли(стол, пройдено, ктоId) {
  const свежий = { ...столПоId(стол.id), пройдено, пройден: true, завершён: true };
  await записать(свежий);
  await объявить(
    Т(`<p><strong>{название}</strong> — зал пройден.</p>
     <p><em>Последний шаг сделал {ктоId}; ловушек сработало {сработало}.</em></p>`, { название: экранировать(свежий.название), ктоId: экранировать(имяИгрока(ктоId)), сработало: 
       свежий.ловушек.сработало }),
    свежий.название);
  событие("решено", свежий);
  await запуститьМакрос(свежий.макрос, свежий);
}

/* ─────────────────── рычаги ведущего (нажимает он сам) ─────────────────── */

export async function засчитать(id) {
  const стол = столПоId(id);
  if (!стол) return;
  const путь = тайна(id)?.путь ?? [];
  const полный = { ...собрать(стол), пройдено: путь, пройден: true, заклинило: false, завершён: true };
  await записать(полный);
  await объявить(Т(`<p><strong>{название}</strong> — пройден волей ведущего.</p>`, { название: экранировать(полный.название) }), полный.название);
  событие("решено", полный);
  await запуститьМакрос(полный.макрос, полный);
}

export async function сбросить(id) {
  const стол = столПоId(id);
  if (!стол) return;
  await записать({
    ...стол,
    пройдено: [],
    ловушки: [],
    ловушек: { ...стол.ловушек, сработало: 0 },
    журнал: [],
    пройден: false,
    заклинило: false,
    завершён: false,
  });
}

/** Проложить тропу заново: та же комната, другой путь. */
export async function переложить(id) {
  const стол = столПоId(id);
  if (!стол) return;
  await тайнуЗапомнить(id, { путь: проложить(стол.ширина, стол.высота) });
  await сбросить(id);
  await объявить(Т(`<p><strong>{название}</strong> — плиты перещёлкнулись, тропа другая.</p>`, { название: экранировать(стол.название) }),
    стол.название);
}

