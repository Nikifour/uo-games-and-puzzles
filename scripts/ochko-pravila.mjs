/**
 * Двадцать одно — правила, счёт и решение соперника. Ни одной связи с Foundry.
 *
 * Отделено по той же причине, что и в Костях: здесь живёт вся арифметика,
 * из-за которой за столом спорят, и её можно прогнать тысячей партий,
 * не поднимая мир.
 *
 * Игра в двух словах. У каждого шесть кубиков — от к4 до к20, — и каждый
 * берётся один раз за раунд. Бросил, прибавил к сумме; перевалило за 21 —
 * раунд проигран. Остановиться можно когда угодно. Раунд берёт тот, у кого
 * сумма больше, но не больше 21.
 *
 * Отсюда вся соль: к20 в начале почти безопасен и почти бесполезен,
 * а в конце решает — но чаще губит. Порядок кубиков и есть игра.
 */

/** Что лежит перед каждым: по одному кубику каждого вида. */
export const КУБИКИ = [4, 6, 8, 10, 12, 20];

export const ПРАВИЛА = {
  предел: 21,       // больше — перебор
  побед: 3,         // столько раундов нужно взять, чтобы забрать партию
};

/** Кубики, которые ещё не брошены в этом раунде. */
export const доступные = рука => КУБИКИ.filter(г => !(рука?.кубики ?? []).some(к => к.грань === г));

export const сумма = рука => (рука?.кубики ?? []).reduce((с, к) => с + к.значение, 0);

export const перебор = (рука, п = ПРАВИЛА) => сумма(рука) > п.предел;

/** Рука доиграна: перебрал, сказал «хватит» или бросать больше нечем. */
export const закончил = (рука, п = ПРАВИЛА) =>
  !!рука?.стоит || перебор(рука, п) || доступные(рука).length === 0;

/**
 * Доля граней, которые дают перебор.
 *
 * Считается в лоб и потому честно: у к20 при сумме 15 губительны
 * четырнадцать граней из двадцати, и это ровно 0.7 — никаких прикидок.
 */
export function рискПеребора(сейчас, грань, п = ПРАВИЛА) {
  const запас = п.предел - сейчас;          // сколько ещё можно принять
  if (запас <= 0) return 1;
  const хорошие = Math.min(грань, запас);   // грани от 1 до запаса включительно
  return (грань - хорошие) / грань;
}

/** Среднее приращение от кубика — половина граней плюс половина. */
export const ожидание = грань => (грань + 1) / 2;

/**
 * Кто взял раунд.
 *
 * Перебравшие выбывают: у них не «плохая сумма», у них нет суммы вовсе.
 * Равные суммы делят раунд ничьёй — победы не получает никто, и следующий
 * раунд играется как обычно.
 *
 * @returns {{победители: number[], лучшая: number, всеПеребрали: boolean}}
 */
export function итогРаунда(руки, п = ПРАВИЛА) {
  const живые = руки
    .map((р, i) => ({ i, сумма: сумма(р), вне: перебор(р, п) || р?.вышел }))
    .filter(р => !р.вне);

  if (!живые.length) return { победители: [], лучшая: 0, всеПеребрали: true };

  const лучшая = Math.max(...живые.map(р => р.сумма));
  return {
    победители: живые.filter(р => р.сумма === лучшая).map(р => р.i),
    лучшая,
    всеПеребрали: false,
  };
}

/* ────────────────────────────── соперник ────────────────────────────── */

/**
 * Насколько бот готов рисковать. Ручки те же, что в Костях, и не случайно:
 * пул соперников общий, трактирщик за обоими столами один и тот же человек.
 *
 *   жадность   — во сколько раз охотнее обычного он тянет ещё один кубик;
 *   мастерство — как часто он вообще считает верно.
 */
const ПОРОГ_РИСКА = 0.42;   // выше этой доли перебора кубик не берётся

/**
 * Брать ещё или хватит.
 *
 * Решение опирается на три вещи: свою сумму, лучшую открытую чужую и то,
 * доиграли ли остальные. Догонять приходится всегда — вторая по величине
 * сумма не стоит ничего, поэтому отстающий рискует, а ведущий бережётся.
 *
 * @returns {{грань: number}|{грань: null}} какой кубик бросить; null — хватит.
 */
export function решение(положение, случай = Math.random) {
  const {
    рука, лучшийЧужой = 0, чужиеДоиграли = false,
    правила = ПРАВИЛА, характер = {},
  } = положение;

  const п = { ...ПРАВИЛА, ...правила };
  const свои = сумма(рука);
  const можно = доступные(рука);
  if (!можно.length) return { грань: null };

  const жадность = характер.жадность ?? 1;
  const умно = случай() < (характер.мастерство ?? 0.8);

  // Уже впереди и соперники доиграли — брать нечего, риск чистый убыток.
  if (чужиеДоиграли && свои > лучшийЧужой && умно) return { грань: null };

  // Отстаём безнадёжно: без броска раунд всё равно проигран, берём даже плохое.
  const надоДогонять = чужиеДоиграли && свои <= лучшийЧужой;

  let порог = ПОРОГ_РИСКА * жадность;
  if (надоДогонять) порог = 1;                 // хуже проигрыша уже не будет
  else if (лучшийЧужой > свои) порог *= 1.35;  // отстаём, но ещё не всё решено

  /*
   * Из подходящих берём тот кубик, что даёт больше всего пользы: ближе
   * подводит к пределу, но не за него. Крупный кубик, отложенный на потом,
   * почти наверняка станет негодным — поэтому при равном риске берётся
   * крупный, а мелкие остаются про запас.
   */
  const годные = можно
    .map(грань => ({ грань, риск: рискПеребора(свои, грань, п) }))
    .filter(к => к.риск <= порог);

  if (!годные.length) return { грань: null };

  годные.sort((a, b) => (ожидание(b.грань) - b.риск * 12) - (ожидание(a.грань) - a.риск * 12));
  const выбор = умно ? годные[0] : годные[Math.floor(случай() * годные.length)];

  // Рука дрогнула: иногда останавливается там, где стоило брать, и наоборот.
  if (!умно && случай() < 0.3) return { грань: null };

  return { грань: выбор.грань };
}
