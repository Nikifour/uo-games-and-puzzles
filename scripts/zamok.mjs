/**
 * Заготовка помнит готовый набор символов, а в диалоге на его месте поле
 * «свои»: остальные ключи в имена полей попадают сами, а этот — единственный,
 * где имена разошлись.
 */
const ОСОБЫЕ = {
  набор: (э, значение) => {
    const поле = э.querySelector(`[name="свои"]`);
    if (поле) поле.value = Array.isArray(значение) ? значение.join(" ") : (значение ?? "");
  },
};

