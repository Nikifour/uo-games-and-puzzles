/* ─────────────────────────── выложить на стол ─────────────────────────── */

export async function выложить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const набор = конфиг.набор?.length ? конфиг.набор : НАБОРЫ.cifry.символы;
  const код = [...String(конфиг.код ?? "")].map(с => набор.indexOf(с));

  if (!код.length) { ui.notifications.error(Т("Код пустой.")); return null; }
  if (код.some(i => i < 0)) { ui.notifications.error(Т("В коде есть символ, которого нет на дисках.")); return null; }

  // Прибираем стол: разгаданное вчера не должно всплывать под новой загадкой.
  await прибрать();

  const id = foundry.utils.randomID();
  const стол = {
    id,
    тип: "zamok",
    название: конфиг.название?.trim() || Т("Кодовый замок"),
    подпись: конфиг.подпись?.trim() || "",
    тема: (конфиг.тема in ТЕМЫ) ? конфиг.тема : "kamen",
    набор,
    позиции: код.map(() => 0),
    крутят: конфиг.крутят?.length ? конфиг.крутят : "все",
    попытки: {
      сделано: 0,
      предел: Math.max(0, Number(конфиг.предел) || 0),
      наКаждого: !!конфиг.наКаждого,
      поИгрокам: {},
    },
    подсказка: конфиг.подсказка === "сколько" ? "сколько" : "нет",
    макрос: конфиг.макрос?.trim() || null,
    журнал: [],
    открыт: false,
    заклинило: false,
    завершён: false,
    показан: true,
  };

  // Ответ уходит отдельно от стола и только к ведущему.
  await тайнуЗапомнить(id, { код });
  await записать(стол);
  return стол;
}

/* ─────────────────────────────── правила ─────────────────────────────── */

const можетКрутить = (стол, пользователь) =>
  !!пользователь && !стол.открыт && !стол.заклинило &&
  (пользователь.isGM || стол.крутят === "все" || (стол.крутят ?? []).includes(пользователь.id));

/**
 * Сколько попыток осталось лично этому человеку.
 *
 * Предел бывает двух родов, и разница за столом заметная: общий — «пять
 * попыток на всю партию, тратьте как хотите»; на каждого — «по попытке
 * каждому, и никто не сожжёт чужую». Второй родился из простого желания:
 * пусть каждый попытает удачу сам.
 */
export function остатокПопыток(стол, пользователь) {
  const п = стол.попытки ?? {};
  if (!п.предел) return Infinity;
  return п.наКаждого
    ? п.предел - (п.поИгрокам?.[пользователь.id] ?? 0)
    : п.предел - п.сделано;
}

const можетПроверить = (стол, пользователь) =>
  можетКрутить(стол, пользователь) && остатокПопыток(стол, пользователь) > 0;

/** Убрать со стола всё завершённое. */
export async function прибрать() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "zamok" && с.завершён) await убрать(id);
  }
}

/**
 * Разобраться со столами, оставшимися от прежних версий модуля.
 *
 * У них нет пометки «завершён», поэтому разгаданный вчера замок всплывал
 * из-под сегодняшней загадки. Проставляем пометку по состоянию и прибираем.
 * Делает это только тот ведущий, который сейчас за столом, — чтобы двое
 * не чинили одно и то же наперегонки.
 */
export async function починитьСтарые() {
  if (!ведущийЗдесь()) return;
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип !== "zamok" || с.завершён !== undefined) continue;
    await записать({ ...с, завершён: !!(с.открыт || с.заклинило) });
  }
  await прибрать();
}

// Положение дисков пишется в базу не на каждый щелчок, а когда рука отдохнёт.
const отложитьЗапись = foundry.utils.debounce(async id => {
  const сырой = столПоId(id);
  if (!сырой) return;
  await записать({ ...сырой, позиции: собрать(сырой).позиции });
}, 4000);

/** Ход игрока. Выполняется на клиенте ведущего — здесь и только здесь. */
async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);
  if (!можетКрутить(стол, пользователь)) return;

  // Диски крутит и тот, у кого попытки кончились: подсказать соседу можно
  // всегда, а вот жать «Проверить» — уже нет.
  if (запрос.что === "проверить" && !можетПроверить(стол, пользователь)) return;

  if (запрос.что === "крутить") {
    const диск = Number(запрос.диск);
    if (!Number.isInteger(диск) || диск < 0 || диск >= стол.позиции.length) return;
    const длина = стол.набор.length;
    const позиции = [...стол.позиции];
    позиции[диск] = (позиции[диск] + Number(запрос.шаг) + длина) % длина;
    разослать(стол.id, { позиции });
    отложитьЗапись(стол.id);
    return;
  }

  if (запрос.что === "проверить") await проверить(стол, запрос.кто);
}

async function проверить(стол, ктоId) {
  const код = тайна(стол.id)?.код;
  if (!код) {
    ui.notifications.error(
      `Ответ замка «${стол.название}» не найден в этом браузере. Засчитайте вручную или выложите замок заново.`);
    return;
  }

  const верно = стол.позиции.reduce((n, p, i) => n + (p === код[i] ? 1 : 0), 0);
  const разгадан = верно === код.length;
  const набрано = стол.позиции.map(p => стол.набор[p]).join("");

  const поИгрокам = { ...(стол.попытки.поИгрокам ?? {}) };
  поИгрокам[ктоId] = (поИгрокам[ктоId] ?? 0) + 1;

  const обновлённый = {
    ...стол,
    попытки: { ...стол.попытки, сделано: стол.попытки.сделано + 1, поИгрокам },
    журнал: [...стол.журнал, {
      кто: имяИгрока(ктоId),
      набор: набрано,
      верно: стол.подсказка === "сколько" ? верно : null,
      удача: разгадан,
    }].slice(-12),
    открыт: разгадан,
    завершён: разгадан,
  };

  // Заклинивает только общий предел: когда попытки у каждого свои, кончаются
  // они поодиночке, и замок ждёт остальных.
  if (!разгадан && обновлённый.попытки.предел && !обновлённый.попытки.наКаждого &&
      обновлённый.попытки.сделано >= обновлённый.попытки.предел) {
    обновлённый.заклинило = true;
    обновлённый.завершён = true;
  }

  await записать(обновлённый);

  if (разгадан) await разгадано(обновлённый, набрано, имяИгрока(ктоId));
  else if (обновлённый.заклинило) {
    await объявить(
      Т(`<p><strong>{название}</strong> — попытки кончились, механизм заклинило.</p>`, { название: экранировать(обновлённый.название) }),
      обновлённый.название);
  }
}

async function разгадано(стол, набрано, кто) {
  await объявить(
    Т(`<p><strong>{название}</strong> — открыт.</p>
     <p>{кто} набрал <code>{набрано}</code> с попытки номер {сделано}.</p>`, { название: экранировать(стол.название), кто: экранировать(кто), набрано: экранировать(набрано), сделано: стол.попытки.сделано }),
    стол.название);
  событие("решено", стол);
  await запуститьМакрос(стол.макрос, стол);
}

/* ─────────────────── рычаги ведущего (нажимает он сам) ─────────────────── */

export async function засчитать(id) {
  const стол = столПоId(id);
  if (!стол) return;
  const полный = { ...собрать(стол), открыт: true, заклинило: false, завершён: true };
  await записать(полный);
  await объявить(Т(`<p><strong>{название}</strong> — открыт волей ведущего.</p>`, { название: экранировать(полный.название) }), полный.название);
  событие("решено", полный);
  await запуститьМакрос(полный.макрос, полный);
}

export async function сбросить(id) {
  const стол = столПоId(id);
  if (!стол) return;
  await записать({
    ...стол,
    позиции: стол.позиции.map(() => 0),
    попытки: { ...стол.попытки, сделано: 0, поИгрокам: {} },
    журнал: [],
    открыт: false,
    заклинило: false,
    завершён: false,
  });
}

