/**
 * Детали замка для рычагов: «д0», «д1»… — диск на шаг вперёд; в обе стороны —
 * «д0+» (вперёд) и «д0-» (назад) на каждый диск.
 */
export const деталиЗамка = (дисков, обеСтороны = false) => Array.from({ length: дисков }, (_, i) =>
  (обеСтороны ? [`д${i}+`, `д${i}-`] : [`д${i}`])).flat();

/** Диск и шаг по детали рычага. */
const поДетали = деталь => {
  const м = /^д(\d+)([+-]?)$/.exec(String(деталь ?? ""));
  return м ? { диск: Number(м[1]), шаг: м[2] === "-" ? -1 : 1 } : null;
};

/** Символы диска: у каждого свой набор; старые столы — один на все. */
export const наборДиска = (стол, i) => стол.наборы?.[i] ?? стол.набор;

/** Код или набранное строкой — через пробел, если на дисках не одиночные значки. */
function набранное(стол, позиции) {
  const знаки = позиции.map((п, i) => наборДиска(стол, i)[п] ?? "?");
  return знаки.some(з => [...з].length > 1) ? знаки.join(" ") : знаки.join("");
}

/* ─────────────────────────── выложить на стол ─────────────────────────── */

export async function выложить(конфиг = {}) {
  if (!game.user.isGM) return null;

  const набор = конфиг.набор?.length ? конфиг.набор : НАБОРЫ.cifry.символы;
  // Код — список символов по дискам; старые заготовки хранят его строкой.
  const символы = Array.isArray(конфиг.код) ? конфиг.код : [...String(конфиг.код ?? "")];
  // У каждого диска свой набор; старые заготовки — один на все.
  const наборы = символы.map((_, i) => (конфиг.наборы?.[i]?.length ? конфиг.наборы[i] : набор));
  const код = символы.map((с, i) => наборы[i].indexOf(с));

  if (!код.length) { ui.notifications.error(Т("Код пустой.")); return null; }
  if (код.some(i => i < 0)) { ui.notifications.error(Т("В коде есть символ, которого нет на дисках.")); return null; }

  // С чего диски начинают: как задал ведущий, иначе с первого символа.
  const начальные = символы.map((_, i) => Math.max(0, наборы[i].indexOf(конфиг.начальные?.[i])));
  if (начальные.every((п, i) => п === код[i])) {
    ui.notifications.warn(Т("Диски в начале стоят ровно на коде — замок откроется первой же проверкой."));
  }

  // Прибираем стол: разгаданное вчера не должно всплывать под новой загадкой.
  await прибрать();

  const id = foundry.utils.randomID();
  const стол = {
    id,
    тип: "zamok",
    название: конфиг.название?.trim() || Т("Кодовый замок"),
    подпись: конфиг.подпись?.trim() || "",
    тема: (конфиг.тема in ТЕМЫ) ? конфиг.тема : "kamen",
    набор: наборы[0],
    наборы,
    начальные,
    позиции: [...начальные],
    крутят: конфиг.крутят?.length ? конфиг.крутят : "все",
    попытки: {
      сделано: 0,
      предел: Math.max(0, Number(конфиг.предел) || 0),
      наКаждого: !!конфиг.наКаждого,
      поИгрокам: {},
    },
    подсказка: конфиг.подсказка === "сколько" ? "сколько" : "нет",
    макрос: конфиг.макрос?.trim() || null,
    // Видит один, крутят другие: у диска рычаг (или два — вперёд и назад).
    вслепую: конфиг.вслепую && конфиг.штурман
      ? раздельно.разложить({
        штурман: конфиг.штурман, детали: деталиЗамка(код.length, конфиг.обеСтороны),
        рычаги: конфиг.рычаги, пометки: конфиг.пометки, подсказка: конфиг.подсказкаШтурману, пульты: конфиг.пульты,
      })
      : null,
    таймер: завестиТаймер(конфиг.таймер),
    журнал: [],
    открыт: false,
    заклинило: false,
    завершён: false,
    показан: true,
  };

  // Ответ уходит отдельно от стола и только к ведущему.
  await тайнуЗапомнить(id, { код });
  await записать(стол);
  return стол;
}

/* ─────────────────────────────── правила ─────────────────────────────── */

/** Допущен ли к дискам по списку «кто крутит». */
const вСписке = (стол, пользователь) =>
  !!пользователь && (стол.крутят === "все" || (стол.крутят ?? []).includes(пользователь.id));

/** Может ли крутить: вслепую — только со своего пульта; штурман не крутит. */
const допущен = (стол, пользователь) =>
  !!пользователь && (пользователь.isGM || (стол.вслепую
    ? раздельно.пультыЧеловека(стол, пользователь, вСписке(стол, пользователь)).length > 0
    : вСписке(стол, пользователь)));

const идёт = стол => !стол.открыт && !стол.заклинило && осталось(стол) !== 0;

const можетКрутить = (стол, пользователь) => идёт(стол) && допущен(стол, пользователь);

/**
 * Сколько попыток осталось лично этому человеку.
 *
 * Предел бывает двух родов, и разница за столом заметная: общий — «пять
 * попыток на всю партию, тратьте как хотите»; на каждого — «по попытке
 * каждому, и никто не сожжёт чужую». Второй — чтобы каждый мог попытать
 * удачу сам.
 */
export function остатокПопыток(стол, пользователь) {
  const п = стол.попытки ?? {};
  if (!п.предел) return Infinity;
  return п.наКаждого
    ? п.предел - (п.поИгрокам?.[пользователь.id] ?? 0)
    : п.предел - п.сделано;
}

/** Проверяет тот, кто крутит; вслепую — штурман: он один видит диски. */
const можетПроверить = (стол, пользователь) => идёт(стол) && !!пользователь &&
  (стол.вслепую ? (пользователь.isGM || пользователь.id === стол.вслепую.штурман) : допущен(стол, пользователь)) &&
  остатокПопыток(стол, пользователь) > 0;

/** Убрать со стола всё завершённое. */
export async function прибрать() {
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип === "zamok" && с.завершён) await убрать(id);
  }
}

/**
 * Разобраться со столами, оставшимися от прежних версий модуля.
 *
 * У них нет пометки «завершён», поэтому разгаданный вчера замок всплывал
 * из-под сегодняшней загадки. Проставляем пометку по состоянию и прибираем.
 * Делает это только тот ведущий, который сейчас за столом, — чтобы двое
 * не чинили одно и то же наперегонки.
 */
export async function починитьСтарые() {
  if (!ведущийЗдесь()) return;
  for (const [id, с] of Object.entries(всеСтолы())) {
    if (с.тип !== "zamok" || с.завершён !== undefined) continue;
    await записать({ ...с, завершён: !!(с.открыт || с.заклинило) });
  }
  await прибрать();
}

// Положение дисков пишется в базу не на каждый щелчок, а когда рука отдохнёт.
const отложитьЗапись = foundry.utils.debounce(async id => {
  const сырой = столПоId(id);
  if (!сырой) return;
  await записать({ ...сырой, позиции: собрать(сырой).позиции });
}, 4000);

/** Ход игрока. Выполняется на клиенте ведущего — здесь и только здесь. */
async function ход(стол, запрос) {
  const пользователь = game.users.get(запрос.кто);

  // Диски крутит и тот, у кого попытки кончились: подсказать соседу можно
  // всегда, а вот жать «Проверить» — уже нет.
  if (запрос.что === "проверить") {
    if (!можетПроверить(стол, пользователь)) return;
    return проверить(стол, запрос.кто);
  }
  if (!можетКрутить(стол, пользователь)) return;

  // Вслепую крутят рычагом с пульта; прямо по диску — ведущий и обычный замок.
  let диск, шаг;
  if (запрос.что === "рычаг") {
    if (!раздельно.можноТянуть(стол, пользователь, запрос.рычаг, вСписке(стол, пользователь))) return;
    const д = поДетали(раздельно.детальРычага(стол, запрос.рычаг));
    if (!д) return;
    ({ диск, шаг } = д);
  } else if (запрос.что === "крутить" && (!стол.вслепую || пользователь.isGM)) {
    диск = Number(запрос.диск);
    шаг = Number(запрос.шаг);
  } else return;

  {
    if (!Number.isInteger(диск) || диск < 0 || диск >= стол.позиции.length) return;
    const длина = наборДиска(стол, диск).length;
    const позиции = [...стол.позиции];
    позиции[диск] = (позиции[диск] + шаг + длина) % длина;
    разослать(стол.id, { позиции });
    отложитьЗапись(стол.id);
  }
}

/** Время вышло — механизм клинит, как от исчерпанных попыток. */
async function времяВышло(стол) {
  const свежий = столПоId(стол.id);
  if (!свежий || свежий.завершён) return;
  await записать({ ...свежий, позиции: стол.позиции, заклинило: true, завершён: true });
  await объявить(`<p><strong>${экранировать(стол.название)}</strong> ${Т("— время вышло, механизм заклинило.")}</p>`, стол.название);
}

async function проверить(стол, ктоId) {
  const код = тайна(стол.id)?.код;
  if (!код) {
    ui.notifications.error(
      Т("Ответ замка «{название}» не найден в этом браузере. Засчитайте вручную или выложите замок заново.", { название: стол.название }));
    return;
  }

  const верно = стол.позиции.reduce((n, p, i) => n + (p === код[i] ? 1 : 0), 0);
  const разгадан = верно === код.length;
  const набрано = набранное(стол, стол.позиции);

  const поИгрокам = { ...(стол.попытки.поИгрокам ?? {}) };
  поИгрокам[ктоId] = (поИгрокам[ктоId] ?? 0) + 1;

  const обновлённый = {
    ...стол,
    попытки: { ...стол.попытки, сделано: стол.попытки.сделано + 1, поИгрокам },
    журнал: [...стол.журнал, {
      кто: имяИгрока(ктоId),
      набор: набрано,
      верно: стол.подсказка === "сколько" ? верно : null,
      удача: разгадан,
    }].slice(-12),
    открыт: разгадан,
    завершён: разгадан,
  };

  // Заклинивает только общий предел: когда попытки у каждого свои, кончаются
  // они поодиночке, и замок ждёт остальных.
  if (!разгадан && обновлённый.попытки.предел && !обновлённый.попытки.наКаждого &&
      обновлённый.попытки.сделано >= обновлённый.попытки.предел) {
    обновлённый.заклинило = true;
    обновлённый.завершён = true;
  }

  await записать(обновлённый);

  if (разгадан) await разгадано(обновлённый, набрано, имяИгрока(ктоId));
  else if (обновлённый.заклинило) {
    await объявить(
      Т(`<p><strong>{название}</strong> — попытки кончились, механизм заклинило.</p>`, { название: экранировать(обновлённый.название) }),
      обновлённый.название);
  }
}

async function разгадано(стол, набрано, кто) {
  await объявить(
    Т(`<p><strong>{название}</strong> — открыт.</p>
     <p>{кто} набрал <code>{набрано}</code> с попытки номер {сделано}.</p>`, { название: экранировать(стол.название), кто: экранировать(кто), набрано: экранировать(набрано), сделано: стол.попытки.сделано }),
    стол.название);
  событие("решено", стол);
  await запуститьМакрос(стол.макрос, стол);
}

/* ─────────────────── рычаги ведущего (нажимает он сам) ─────────────────── */

export async function засчитать(id) {
  const стол = столПоId(id);
  if (!стол) return;
  const полный = { ...собрать(стол), открыт: true, заклинило: false, завершён: true };
  await записать(полный);
  await объявить(Т(`<p><strong>{название}</strong> — открыт волей ведущего.</p>`, { название: экранировать(полный.название) }), полный.название);
  событие("решено", полный);
  await запуститьМакрос(полный.макрос, полный);
}

export async function сбросить(id) {
  const стол = столПоId(id);
  if (!стол) return;
  await записать({
    ...стол,
    позиции: стол.начальные ? [...стол.начальные] : стол.позиции.map(() => 0),
    попытки: { ...стол.попытки, сделано: 0, поИгрокам: {} },
    журнал: [],
    открыт: false,
    заклинило: false,
    завершён: false,
    таймер: перезавести(стол.таймер),
  });
}

