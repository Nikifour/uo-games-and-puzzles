class ОкноЗамка extends ApplicationV2 {
  constructor(options = {}) {
    super(options);
    this.стол = options.стол;
    this.кодВидно = false;
  }

  static DEFAULT_OPTIONS = {
    classes: ["uo-igry", "uo-zamok"],
    tag: "div",
    window: { title: Т("Кодовый замок"), icon: "fa-solid fa-lock", resizable: false },
    position: { width: 460, height: "auto" },
    actions: {
      крутить: ОкноЗамка.#вручную,
      проверить: ОкноЗамка.#нажатьПроверить,
      засчитать: ОкноЗамка.#нажатьЗасчитать,
      сброс: ОкноЗамка.#нажатьСброс,
      кодВидно: ОкноЗамка.#нажатьКод,
      снять: ОкноЗамка.#нажатьСнять,
    },
  };

  get title() { return this.стол?.название ?? Т("Кодовый замок"); }

  static #вручную(event, target) {
    просить({
      id: this.стол.id, что: "крутить",
      диск: target.dataset.disk, шаг: Number(target.dataset.step),
    });
  }

  static #нажатьПроверить() { просить({ id: this.стол.id, что: "проверить" }); }
  static #нажатьЗасчитать() { засчитать(this.стол.id); }
  static #нажатьСброс() { сбросить(this.стол.id); }
  static #нажатьСнять() { убрать(this.стол.id); }
  static #нажатьКод() { this.кодВидно = !this.кодВидно; this.render(); }

  /**
   * Крестик. Закрыли мы сами (стол убрали, загадку спрятали) — молчим.
   * Закрыл человек: ведущий прячет загадку у всех, игрок — только у себя.
   * Иначе брошенная проба остаётся лежать на столе и всплывает завтра.
   */
  _onClose() {
    забытьОкно(this.стол.id);
    if (this.закрываемСами) return;
    if (game.user.isGM) спрятать(this.стол.id);
    else спрятатьУСебя(this.стол.id);
  }

  async _renderHTML() {
    const с = this.стол;
    const крутит = можетКрутить(с, game.user);
    const набор = с.набор;
    const длина = набор.length;

    const диски = с.позиции.map((поз, i) => {
      const выше = набор[(поз - 1 + длина) % длина];
      const ниже = набор[(поз + 1) % длина];
      return `
        <div class="uo-disk">
          ${крутит ? `<button type="button" class="uo-krut" data-action="крутить" data-disk="${i}" data-step="-1" aria-label="выше">▲</button>` : ""}
          <div class="uo-okoshko">
            <span class="uo-sosed">${экранировать(выше)}</span>
            <span class="uo-simvol">${экранировать(набор[поз])}</span>
            <span class="uo-sosed">${экранировать(ниже)}</span>
          </div>
          ${крутит ? `<button type="button" class="uo-krut" data-action="крутить" data-disk="${i}" data-step="1" aria-label="ниже">▼</button>` : ""}
        </div>`;
    }).join("");

    const проверяет = можетПроверить(с, game.user);
    const остаток = остатокПопыток(с, game.user);
    const счёт = !с.попытки.предел
      ? `Попыток сделано: ${с.попытки.сделано}`
      : с.попытки.наКаждого
        ? `Ваших попыток осталось: ${Math.max(0, остаток)} из ${с.попытки.предел} · всего сделано ${с.попытки.сделано}`
        : `Попытка ${Math.min(с.попытки.сделано + 1, с.попытки.предел)} из ${с.попытки.предел}`;

    const журнал = с.журнал.length ? `
      <ol class="uo-zhurnal">
        ${[...с.журнал].reverse().map(з => `
          <li class="${з.удача ? "uo-udacha" : ""}">
            <code>${экранировать(з.набор)}</code>
            <span class="uo-kto">${экранировать(з.кто)}</span>
            ${(з.верно ?? null) !== null && !з.удача
              ? `<span class="uo-podskazka">${Т(`верных дисков: {верно}`, { верно: з.верно })}</span>` : ""}
          </li>`).join("")}
      </ol>` : "";

    const состояние = с.открыт
      ? `<p class="uo-itog uo-otkryt">${Т("Замок открыт.")}</p>`
      : с.заклинило
        ? `<p class="uo-itog uo-zaklinilo">${Т("Механизм заклинило. Ведущий может дать ещё попытку.")}</p>`
        : "";

    const кодСтрокой = (тайна(с.id)?.код ?? []).map(i => набор[i]).join("");
    const гм = game.user.isGM ? `
      <section class="uo-gm">
        <div class="uo-gm-kod">
          <button type="button" data-action="кодВидно">${this.кодВидно ? Т("Скрыть код") : Т("Показать код")}</button>
          ${this.кодВидно ? `<code>${экранировать(кодСтрокой) || Т("— в этом браузере неизвестен —")}</code>` : ""}
        </div>
        <div class="uo-gm-knopki">
          <button type="button" data-action="засчитать">${Т("Засчитать")}</button>
          <button type="button" data-action="сброс">${Т("Сбросить")}</button>
          <button type="button" data-action="снять">${Т("Убрать со стола")}</button>
        </div>
      </section>` : "";

    return `
      <div class="uo-zamok-telo uo-tema-${экранировать(с.тема)}">
        ${с.подпись ? `<p class="uo-podpis">${экранировать(с.подпись)}</p>` : ""}
        <div class="uo-diski">${диски}</div>
        <div class="uo-stroka">
          <span class="uo-schet">${счёт}</span>
          ${проверяет
            ? `<button type="button" class="uo-proverit" data-action="проверить">${Т("Проверить")}</button>`
            : крутит ? `<span class="uo-podskazka">${Т("Ваши попытки кончились — крутить можно, проверять нет.")}</span>` : ""}
        </div>
        ${состояние}
        ${журнал}
        ${гм}
      </div>`;
  }

  _replaceHTML(result, content) { content.innerHTML = result; }
}

