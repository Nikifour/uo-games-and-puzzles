/**
 * Склад заготовок: всё, что ведущий приготовил до партии.
 *
 * Зачем склад один на все загадки. Готовятся не к загадке, а к вечеру: замок
 * на двери, зал плит за ней, устройство в мастерской, череда фресок в
 * усыпальнице. Собирать это посреди сцены — значит выпасть из игры на пять
 * минут, а сцену держит ведущий один. Значит настройки должны лежать готовыми
 * и выкладываться одним нажатием.
 *
 * Почему в журнале, а не в настройках.
 *
 * Настройка мира читается любым игроком из консоли — а в заготовке лежит
 * ответ: код замка, верный порядок рычагов, правдивые надписи на вратах.
 * Настройка клиента ответ прячет, но живёт в браузере: не уезжает с миром,
 * не достаётся второму ведущему и пропадает от чистки данных браузера.
 *
 * Журнал, у которого нет прав ни у кого кроме ведущего, — единственное место,
 * где данные разом и общие, и закрытые. Он уезжает в резервной копии мира
 * вместе со всем прочим, переживает смену браузера и машины, а игрок его
 * не видит даже в списке журналов: документ без прав ему попросту не шлют.
 *
 * Сами заготовки лежат во флаге журнала, а не текстом на странице: флаг —
 * готовая запись, её не надо разбирать из текста и нельзя испортить,
 * случайно открыв журнал и нажав пробел.
 *
 * Что заготовка НЕ помнит: разгадку с прошлой партии, ходы, кто крутил диски.
 * Она помнит настройки. Выложенная дважды, она даёт два разных стола с одним
 * и тем же кодом — это и нужно, когда партия переносится на неделю.
 */

import { MODULE_ID, ВИДЫ, спрятать } from "./stol.mjs";
import { Т, М } from "./yazyk.mjs";

const { DialogV2 } = foundry.applications.api;
const экранировать = s => foundry.utils.escapeHTML(String(s ?? ""));

// Имя переводится при создании журнала; искать его по имени не будем — только по флагу.
const ИМЯ_ЖУРНАЛА = М("UO · Заготовки загадок");
const ФЛАГ = "zagotovki";

/**
 * Название вида по-человечески. Берётся из того же списка ВИДЫ, куда каждая
 * загадка себя записывает: отдельной таблицы имён не держим, иначе она
 * разойдётся с настоящей при первой же новой загадке.
 */
export const названиеВида = тип => Т(ВИДЫ.get(тип)?.имя ?? тип);

/** Умеет ли этот вид выкладываться из заготовки. */
export const заготовимый = тип => typeof ВИДЫ.get(тип)?.выложить === "function";

/* ─────────────────────────── хранилище ─────────────────────────── */

/** Журнал склада. Ищем по флагу, а не по имени: имя ведущий вправе переменить. */
const найтиЖурнал = () => game.journal?.find(ж => ж.getFlag(MODULE_ID, ФЛАГ) !== undefined) ?? null;

/** Тот же журнал, но при надобности созданный. Только ведущим. */
async function журнал() {
  const свой = найтиЖурнал();
  if (свой || !game.user.isGM) return свой;

  return JournalEntry.create({
    name: Т(ИМЯ_ЖУРНАЛА),
    // Ни у кого, кроме ведущего: игроку такой документ не пересылают вовсе,
    // и в списке журналов его у него нет.
    ownership: { default: CONST.DOCUMENT_OWNERSHIP_LEVELS.NONE },
    flags: { [MODULE_ID]: { [ФЛАГ]: [] } },
  });
}

/**
 * Склад, как он лежит в журнале: список записей { тип, имя, настройки }.
 *
 * Списком, а не деревом «тип → имя → настройки», хотя читать удобнее второе.
 * Причина в том, как Foundry пишет флаги: объекты она **сливает** с тем, что
 * там лежало. Записать дерево без забытой заготовки — значит не убрать её:
 * слияние вернёт ключ на место. Список же заменяется целиком.
 *
 * Дерево собирается на чтении, в `всё()`. Так удобство осталось, а забытое
 * забывается по-настоящему.
 */
const записи = () => {
  const склад = найтиЖурнал()?.getFlag(MODULE_ID, ФЛАГ);
  return Array.isArray(склад) ? foundry.utils.deepClone(склад) : [];
};

/**
 * Весь склад привычным видом: { тип: { имя: настройки } }.
 *
 * Каждый раз собирается заново, а значит отдаётся копией: правка полученного
 * не заденет ни журнал, ни следующего читателя.
 */
export function всё() {
  const дерево = {};
  for (const з of записи()) {
    if (!з?.тип || !з?.имя) continue;
    (дерево[з.тип] ??= {})[з.имя] = з.настройки ?? {};
  }
  return дерево;
}

/** Заготовки одного вида: { имя: настройки }. */
export const пул = тип => всё()[тип] ?? {};

/** Имена заготовок одного вида. */
export const список = тип => Object.keys(пул(тип));

/** Сколько всего заготовлено — для панели, чтобы не считать её же руками. */
export const счёт = () => Object.values(всё()).reduce((с, п) => с + Object.keys(п).length, 0);

/** Записать список записей. Список Foundry заменяет целиком — того и надо. */
async function записать(список) {
  const ж = await журнал();
  if (!ж) return false;
  await ж.setFlag(MODULE_ID, ФЛАГ, список);
  return true;
}

export async function запомнить(тип, имя, настройки) {
  if (!game.user.isGM) return false;
  const чистое = String(имя ?? "").trim();
  if (!чистое) return false;

  const свежая = { тип, имя: чистое, настройки: foundry.utils.deepClone(настройки) };
  const было = записи();
  const место = было.findIndex(з => з.тип === тип && з.имя === чистое);
  if (место >= 0) было[место] = свежая;
  else было.push(свежая);

  if (!(await записать(было))) return false;

  ui.notifications.info(место >= 0
    ? Т("Заготовка «{имя}» перезаписана", { имя: чистое })
    : Т("Заготовка «{имя}» запомнена", { имя: чистое }));
  return true;
}

export async function забыть(тип, имя) {
  if (!game.user.isGM || !пул(тип)[имя]) return;
  await записать(записи().filter(з => !(з.тип === тип && з.имя === имя)));
}

export async function переименовать(тип, имя, новое) {
  const чистое = String(новое ?? "").trim();
  if (!game.user.isGM || !чистое || чистое === имя || !пул(тип)[имя]) return false;

  // Занятое имя не перебиваем: две записи с одним именем — это молча
  // потерянная заготовка, а не переименование.
  if (чистое in пул(тип)) {
    ui.notifications.warn(Т("Заготовка «{имя}» уже есть", { имя: чистое }));
    return false;
  }

  return записать(записи().map(з =>
    (з.тип === тип && з.имя === имя) ? { ...з, имя: чистое } : з));
}

/**
 * Выложить заготовку на стол.
 *
 * `скрытно` — то самое «приготовить заранее»: стол ложится в мир, но игроки
 * его не видят, пока ведущий не покажет его из панели. Прячем после выкладки,
 * а не при ней: тогда не нужно править одиннадцать `выложить`, и каждая
 * загадка остаётся хозяйкой своего стола.
 */
export async function выложить(тип, имя, { скрытно = false } = {}) {
  const настройки = пул(тип)[имя];
  if (!настройки) {
    ui.notifications.warn(Т("Заготовки «{имя}» нет", { имя }));
    return null;
  }
  const вид = ВИДЫ.get(тип);
  if (typeof вид?.выложить !== "function") {
    ui.notifications.warn(Т("Не знаю, как выкладывать «{тип}»", { тип }));
    return null;
  }

  const стол = await вид.выложить(настройки);   // «пул» уже отдал копию
  if (стол && скрытно) await спрятать(стол.id);
  return стол;
}

/* ───────────────── поле «запомнить» для диалогов загадок ───────────────── */

/**
 * Строка «запомнить как заготовку» для диалога любой загадки.
 *
 * Одной вставкой, а не своей разметкой в каждом файле: одиннадцать копий —
 * одиннадцать мест, где подпись и поведение со временем разойдутся.
 */
export const полеЗаготовки = (значение = "") => `
  <label>${Т("Запомнить как заготовку")}
    <input type="text" name="заготовка" value="${экранировать(значение)}" placeholder="${Т("имя, необязательно")}">
  </label>
  <p class="uo-podskazka">${Т("С именем настройки лягут в склад ведущего, и загадку можно будет выложить снова одним нажатием. Склад уезжает вместе с миром, игрокам он не виден.")}</p>`;

/**
 * Отметить в диалоге список игроков.
 *
 * Имя поля у каждой загадки своё — «крутят», «двигают», «выбирают»,
 * «участники», — а разметка одна и та же: галочки на игроков и, где это
 * к месту, переключатель «все / отмеченные». Поэтому список узнаётся
 * по разметке, а не по имени поля, и новая загадка получает это даром.
 *
 * Пустой список значит «все» — так же, как при выкладке.
 */
function отметитьИгроков(элемент, кто) {
  const галочки = элемент.querySelectorAll(`[name="игрок"], [name="участник"]`);
  if (!галочки.length) return;

  const поимённо = Array.isArray(кто) && кто.length > 0;
  const переключатель = элемент.querySelector(`[name="кто"][value="${поимённо ? "отмеченные" : "все"}"]`);
  if (переключатель) переключатель.checked = true;

  for (const галка of галочки) галка.checked = поимённо && кто.includes(галка.value);
}

/**
 * Разложить настройки заготовки по полям диалога.
 *
 * Работает по совпадению имён: ключ настроек — имя поля. Это не совпадение,
 * а замысел: диалоги собирают настройки тем же путём наоборот, через
 * `зн("название")`. Пока правило держится, новая загадка получает правку
 * заготовок, ничего для этого не написав.
 *
 * `особые` — для тех немногих ключей, где имена разошлись: у замка настройки
 * помнят готовый набор символов, а в диалоге на его месте поле «свои».
 */
export function заполнить(элемент, настройки, особые = {}) {
  if (!элемент || !настройки) return;

  for (const [ключ, значение] of Object.entries(настройки)) {
    if (особые[ключ]) { особые[ключ](элемент, значение); continue; }

    const поле = элемент.querySelector(`[name="${CSS.escape(ключ)}"]`);
    if (!поле) {
      if (Array.isArray(значение)) отметитьИгроков(элемент, значение);
      continue;
    }
    if (поле.type === "checkbox") поле.checked = !!значение;
    else if (значение !== null && значение !== undefined) поле.value = значение;
  }
}

/**
 * Снять имя из поля и запомнить настройки, если имя вписано.
 *
 * Зовётся до выкладки: настройки бывают отвергнуты проверкой (пустой код,
 * нет картинки), но заготовка нужна и тогда — ведущий как раз собирает её
 * впрок и правит по частям.
 */
export async function запомнитьИзДиалога(тип, элемент, настройки) {
  const имя = элемент.querySelector(`[name="заготовка"]`)?.value?.trim();
  if (имя) await запомнить(тип, имя, настройки);
  return настройки;
}

/* ─────────────────────── переезд со старого места ─────────────────────── */

/**
 * Заготовки замка прежде лежали в настройке клиента. Переносим их в журнал
 * один раз и старое место чистим: иначе на двух машинах будет два разных
 * склада, и ведущий не поймёт, почему на одной заготовки есть, а на другой
 * нет. Уже занятое имя не перебиваем — своё новее переехавшего.
 */
export async function переехать() {
  if (!game.user.isGM) return;

  const старое = game.settings.get(MODULE_ID, "zagotovki");
  const имена = (старое && typeof старое === "object") ? Object.keys(старое) : [];
  if (!имена.length) return;

  const свои = пул("zamok");
  const список = записи();
  for (const имя of имена) {
    if (имя in свои) continue;
    список.push({ тип: "zamok", имя, настройки: старое[имя] });
  }
  if (!(await записать(список))) return;

  await game.settings.set(MODULE_ID, "zagotovki", {});
  console.log(`${MODULE_ID} | заготовки замка переехали в журнал: ${имена.length}`);
}

/* ─────────────────────────── окно склада ─────────────────────────── */

/**
 * Разметка склада: разделы по видам.
 *
 * Отдана наружу, потому что склад виден из двух мест — своим окном и разделом
 * в панели ведущего. Две разметки одного склада разошлись бы уже к третьей
 * правке, а привязка кнопок ниже — та же самая.
 *
 * Порядок — как в списке видов, а не как в складе: в панели загадки идут
 * своим заведённым чередом, и склад должен читаться так же. Виды, чьих
 * заготовок нет, пропускаем — пустой заголовок ничего не сообщает.
 *
 * Отдельно идут заготовки вида, которого больше нет в списке: показываем их,
 * чтобы человек мог забыть их сам, а не гадать, куда они девались.
 */
export function разметка() {
  const склад = всё();
  const свои = [...ВИДЫ.keys()].filter(т => Object.keys(склад[т] ?? {}).length);
  const чужие = Object.keys(склад).filter(т => !ВИДЫ.has(т));

  if (!свои.length && !чужие.length) {
    return `<p class="uo-podskazka">${Т("Заготовок пока нет: они появятся, когда впишете имя в поле «Запомнить как заготовку» в диалоге любой загадки.")}</p>`;
  }

  const разделы = [...свои, ...чужие].map(тип => {
    const живой = заготовимый(тип);
    const правится = typeof ВИДЫ.get(тип)?.диалог === "function";
    const метка = имя => `data-vid="${экранировать(тип)}" data-imya="${экранировать(имя)}"`;

    const строки = Object.keys(склад[тип]).sort((а, б) => а.localeCompare(б, "ru")).map(имя => `
      <div class="uo-zagotovka">
        <span>${экранировать(имя)}</span>
        ${живой ? `
          <button type="button" class="uo-vylozhit" ${метка(имя)}>${Т("Выложить")}</button>
          <button type="button" class="uo-skrytno" ${метка(имя)}>${Т("Скрытно")}</button>` : ""}
        ${правится ? `<button type="button" class="uo-pravit-zagotovku" ${метка(имя)}>${Т("Править")}</button>` : ""}
        <button type="button" class="uo-zabyt-zagotovku" ${метка(имя)}>${Т("Забыть")}</button>
      </div>`).join("");

    return `<h3>${экранировать(названиеВида(тип))}${живой ? "" : Т(" — вид неизвестен")}</h3>
      <div class="uo-zagotovki">${строки}</div>`;
  }).join("");

  return разделы + `<p class="uo-podskazka">${Т("«Скрытно» кладёт загадку в мир, не показывая её игрокам: приготовьте всё до партии, а откроете каждую в свой миг — кнопкой «Показать». «Править» открывает диалог с настройками заготовки: сохраните под тем же именем — заготовка перепишется.")}</p>`;
}

/**
 * Привязать кнопки склада.
 *
 * `закрыть` зовётся там, где действие уводит человека дальше — на стол или
 * в диалог загадки; `обновить` — где он остаётся на месте и должен увидеть
 * перемену. Оба даёт хозяин окна: своё окно склада перерисовывает себя,
 * панель ведущего — себя.
 */
export function привязать(корень, { закрыть = () => {}, обновить = () => {} } = {}) {
  const данные = к => [к.dataset.vid, к.dataset.imya];

  корень.querySelectorAll(".uo-vylozhit").forEach(к =>
    к.addEventListener("click", () => { закрыть(); выложить(...данные(к)); }));

  корень.querySelectorAll(".uo-skrytno").forEach(к =>
    к.addEventListener("click", () => { закрыть(); выложить(...данные(к), { скрытно: true }); }));

  корень.querySelectorAll(".uo-pravit-zagotovku").forEach(к =>
    к.addEventListener("click", () => {
      const [тип, имя] = данные(к);
      const диалог = ВИДЫ.get(тип)?.диалог;
      if (!диалог) return;
      закрыть();
      // Имя передаётся в поле «запомнить»: сохранение под ним и есть правка.
      диалог(пул(тип)[имя] ?? null, имя);
    }));

  корень.querySelectorAll(".uo-zabyt-zagotovku").forEach(к =>
    к.addEventListener("click", async () => {
      const [тип, имя] = данные(к);
      const точно = await DialogV2.confirm({
        window: { title: Т("Забыть заготовку") },
        content: `<p>${Т("Забыть заготовку «{имя}»? Выложенные из неё загадки останутся на столе.", { имя: экранировать(имя) })}</p>`,
        rejectClose: false,
      });
      if (!точно) return;
      await забыть(тип, имя);
      обновить();
    }));
}

export async function окноСклада() {
  if (!game.user.isGM) return;

  await DialogV2.wait({
    window: { title: Т("Склад заготовок"), icon: "fa-solid fa-box-archive" },
    position: { width: 540 },
    content: `<div class="uo-forma">${разметка()}</div>`,
    buttons: [{ action: "закрыть", label: Т("Закрыть"), default: true }],
    render: (event, диалог) => привязать(диалог.element, {
      закрыть: () => диалог.close(),
      обновить: () => { диалог.close(); окноСклада(); },
    }),
  });
}

/** Пункт в настройках модуля: то же окно, но из общего списка настроек. */
export class МенюСклада extends foundry.applications.api.ApplicationV2 {
  async render() {
    await окноСклада();
    return this;
  }
}
