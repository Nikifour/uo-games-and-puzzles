/**
 * Склад заготовок: всё, что ведущий приготовил до партии.
 *
 * Зачем склад один на все загадки. Готовятся не к загадке, а к вечеру: замок
 * на двери, зал плит за ней, устройство в мастерской, череда фресок в
 * усыпальнице. Собирать это посреди сцены — значит выпасть из игры на пять
 * минут, а сцену держит ведущий один. Значит настройки должны лежать готовыми
 * и выкладываться одним нажатием.
 *
 * Почему в журнале, а не в настройках.
 *
 * Настройка мира читается любым игроком из консоли — а в заготовке лежит
 * ответ: код замка, верный порядок рычагов, правдивые надписи на вратах.
 * Настройка клиента ответ прячет, но живёт в браузере: не уезжает с миром,
 * не достаётся второму ведущему и пропадает от чистки данных браузера.
 *
 * Журнал, у которого нет прав ни у кого кроме ведущего, — единственное место,
 * где данные разом и общие, и закрытые. Он уезжает в резервной копии мира
 * вместе со всем прочим, переживает смену браузера и машины, а игрок его
 * не видит даже в списке журналов: документ без прав ему попросту не шлют.
 *
 * Сами заготовки лежат во флаге журнала, а не текстом на странице: флаг —
 * готовая запись, её не надо разбирать из текста и нельзя испортить,
 * случайно открыв журнал и нажав пробел.
 *
 * Что заготовка НЕ помнит: разгадку с прошлой партии, ходы, кто крутил диски.
 * Она помнит настройки. Выложенная дважды, она даёт два разных стола с одним
 * и тем же кодом — это и нужно, когда партия переносится на неделю.
 */

import { MODULE_ID, ВИДЫ, спрятать } from "./stol.mjs";
import { Т, М } from "./yazyk.mjs";

const { ApplicationV2, DialogV2 } = foundry.applications.api;
const экранировать = s => foundry.utils.escapeHTML(String(s ?? ""));

// Имя переводится при создании журнала; искать его по имени не будем — только по флагу.
const ИМЯ_ЖУРНАЛА = М("UO · Заготовки загадок");
const ФЛАГ = "zagotovki";

/**
 * Название вида по-человечески. Берётся из того же списка ВИДЫ, куда каждая
 * загадка себя записывает: отдельной таблицы имён не держим, иначе она
 * разойдётся с настоящей при первой же новой загадке.
 */
export const названиеВида = тип => Т(ВИДЫ.get(тип)?.имя ?? тип);

/** Умеет ли этот вид выкладываться из заготовки. */
export const заготовимый = тип => typeof ВИДЫ.get(тип)?.выложить === "function";

/* ─────────────────────────── хранилище ─────────────────────────── */

/** Журнал склада. Ищем по флагу, а не по имени: имя ведущий вправе переменить. */
const найтиЖурнал = () => game.journal?.find(ж => ж.getFlag(MODULE_ID, ФЛАГ) !== undefined) ?? null;

/** Тот же журнал, но при надобности созданный. Только ведущим. */
async function журнал() {
  const свой = найтиЖурнал();
  if (свой || !game.user.isGM) return свой;

  return JournalEntry.create({
    name: Т(ИМЯ_ЖУРНАЛА),
    // Ни у кого, кроме ведущего: игроку такой документ не пересылают вовсе,
    // и в списке журналов его у него нет.
    ownership: { default: CONST.DOCUMENT_OWNERSHIP_LEVELS.NONE },
    flags: { [MODULE_ID]: { [ФЛАГ]: [] } },
  });
}

/**
 * Склад, как он лежит в журнале: список записей { тип, имя, настройки }.
 *
 * Списком, а не деревом «тип → имя → настройки», хотя читать удобнее второе.
 * Причина в том, как Foundry пишет флаги: объекты она **сливает** с тем, что
 * там лежало. Записать дерево без забытой заготовки — значит не убрать её:
 * слияние вернёт ключ на место. Список же заменяется целиком.
 *
 * Дерево собирается на чтении, в `всё()`. Так удобство осталось, а забытое
 * забывается по-настоящему.
 */
const записи = () => {
  const склад = найтиЖурнал()?.getFlag(MODULE_ID, ФЛАГ);
  return Array.isArray(склад) ? foundry.utils.deepClone(склад) : [];
};

/**
 * Весь склад привычным видом: { тип: { имя: настройки } }.
 *
 * Каждый раз собирается заново, а значит отдаётся копией: правка полученного
 * не заденет ни журнал, ни следующего читателя.
 */
export function всё() {
  const дерево = {};
  for (const з of записи()) {
    if (!з?.тип || !з?.имя) continue;
    (дерево[з.тип] ??= {})[з.имя] = з.настройки ?? {};
  }
  return дерево;
}

/** Заготовки одного вида: { имя: настройки }. */
export const пул = тип => всё()[тип] ?? {};

/** Имена заготовок одного вида. */
export const список = тип => Object.keys(пул(тип));

/** Сколько всего заготовлено — для панели, чтобы не считать её же руками. */
export const счёт = () => Object.values(всё()).reduce((с, п) => с + Object.keys(п).length, 0);

/** Записать список записей. Список Foundry заменяет целиком — того и надо. */
async function записать(список) {
  const ж = await журнал();
  if (!ж) return false;
  await ж.setFlag(MODULE_ID, ФЛАГ, список);
  return true;
}

export async function запомнить(тип, имя, настройки, { папка } = {}) {
  if (!game.user.isGM) return false;
  const чистое = String(имя ?? "").trim();
  if (!чистое) return false;

  const было = записи();
  const место = было.findIndex(з => з.тип === тип && з.имя === чистое);
  // Полку заготовка сохраняет: правка настроек не должна снимать её с места,
  // а перекладывают заготовку отдельно, в окне склада.
  const полка = чистыйПуть(папка ?? было[место]?.папка);
  const свежая = { тип, имя: чистое, настройки: foundry.utils.deepClone(настройки), папка: полка };
  if (место >= 0) было[место] = свежая;
  else было.push(свежая);

  if (!(await записать(было))) return false;

  ui.notifications.info(место >= 0
    ? Т("Заготовка «{имя}» перезаписана", { имя: чистое })
    : Т("Заготовка «{имя}» запомнена", { имя: чистое }));
  return true;
}

export async function забыть(тип, имя) {
  if (!game.user.isGM || !пул(тип)[имя]) return;
  await записать(записи().filter(з => !(з.тип === тип && з.имя === имя)));
}

export async function переименовать(тип, имя, новое) {
  const чистое = String(новое ?? "").trim();
  if (!game.user.isGM || !чистое || чистое === имя || !пул(тип)[имя]) return false;

  // Занятое имя не перебиваем: две записи с одним именем — это молча
  // потерянная заготовка, а не переименование.
  if (чистое in пул(тип)) {
    ui.notifications.warn(Т("Заготовка «{имя}» уже есть", { имя: чистое }));
    return false;
  }

  return записать(записи().map(з =>
    (з.тип === тип && з.имя === имя) ? { ...з, имя: чистое } : з));
}

/* ─────────────────────────── папки ─────────────────────────── */

/**
 * Папки склада.
 *
 * К десятой партии заготовок набирается сорок, и плоский список перестаёт
 * читаться: ведущий помнит не вид загадки, а сцену — «поместье, подвал».
 * Поэтому у записи есть путь `папка` вида «Поместье/Подвал», а сами папки
 * лежат отдельным флагом: пустая папка тоже должна жить, иначе её нельзя
 * завести заранее и положить в неё заготовку потом.
 *
 * Имя заготовки остаётся единственным на вид, как и было. Выкладывают её по
 * паре «вид + имя» — из панели, из макроса, из тайла, — и папка на это не
 * влияет: она полка, а не часть имени. Переложить заготовку можно в любой
 * миг, ни один макрос от этого не сломается.
 */
const ФЛАГ_ПАПОК = "papki";
export const РАЗДЕЛИТЕЛЬ = "/";

/** Путь без пустых и обрубленных звеньев: «/Поместье// Подвал/» → «Поместье/Подвал». */
export const чистыйПуть = путь =>
  String(путь ?? "").split(РАЗДЕЛИТЕЛЬ).map(з => з.trim()).filter(Boolean).join(РАЗДЕЛИТЕЛЬ);

const родитель = путь => чистыйПуть(путь).split(РАЗДЕЛИТЕЛЬ).slice(0, -1).join(РАЗДЕЛИТЕЛЬ);

/** Последнее звено пути — то, что написано на корешке. */
export const имяПапки = путь => чистыйПуть(путь).split(РАЗДЕЛИТЕЛЬ).at(-1) ?? "";

const записанныеПапки = () => {
  const свои = найтиЖурнал()?.getFlag(MODULE_ID, ФЛАГ_ПАПОК);
  return Array.isArray(свои) ? свои.map(чистыйПуть).filter(Boolean) : [];
};

/**
 * Все папки склада: заведённые руками и те, в которых лежат заготовки.
 *
 * Второе — ради целости. Путь у заготовки может уцелеть от папки, убранной
 * на другой машине, и заготовка из-за этого не должна исчезнуть из виду.
 * Промежуточные звенья добавляются сами: есть «Поместье/Подвал» — значит
 * есть и «Поместье», даже если её никто не заводил.
 */
export function папки() {
  const все = new Set();
  const добавить = путь => {
    const звенья = чистыйПуть(путь).split(РАЗДЕЛИТЕЛЬ).filter(Boolean);
    for (let и = 1; и <= звенья.length; и++) все.add(звенья.slice(0, и).join(РАЗДЕЛИТЕЛЬ));
  };
  for (const п of записанныеПапки()) добавить(п);
  for (const з of записи()) добавить(з?.папка);
  return [...все].sort((а, б) => а.localeCompare(б, "ru"));
}

/** Папки прямо внутри этой — то, что видно, когда в неё зашли. */
export function подпапки(путь = "") {
  const свой = чистыйПуть(путь);
  return папки().filter(п => родитель(п) === свой);
}

/** Заготовки, лежащие прямо в этой папке. */
export function вПапке(путь = "") {
  const свой = чистыйПуть(путь);
  return записи().filter(з => з?.тип && з?.имя && чистыйПуть(з.папка) === свой);
}

/** Сколько заготовок в папке со всем вложенным — число на корешке. */
export function счётВПапке(путь) {
  const свой = чистыйПуть(путь);
  if (!свой) return счёт();
  return записи().filter(з => {
    if (!з?.тип || !з?.имя) return false;
    const п = чистыйПуть(з.папка);
    return п === свой || п.startsWith(свой + РАЗДЕЛИТЕЛЬ);
  }).length;
}

/** Где лежит эта заготовка. Пустая строка — нигде, прямо в складе. */
export const папкаЗаготовки = (тип, имя) =>
  чистыйПуть(записи().find(з => з.тип === тип && з.имя === имя)?.папка);

/** Для поиска: ни регистр, ни ё роли не играют. */
const сложить = с => String(с ?? "").toLowerCase().replace(/ё/g, "е");

/**
 * Поиск по названию поверх папок.
 *
 * Второй путь к заготовке и главный, когда папок стало много: ведущий помнит
 * имя, а не полку. Ищем по имени заготовки, а заодно по пути — «подвал»
 * найдёт и всё, что лежит в одноимённой папке.
 */
export function найти(слово) {
  const что = сложить(слово).trim();
  if (!что) return [];
  return записи()
    .filter(з => з?.тип && з?.имя && (сложить(з.имя).includes(что) || сложить(з.папка).includes(что)))
    .sort((а, б) => а.имя.localeCompare(б.имя, "ru"));
}

/** Завести папку. Внутри `внутри`, если оттуда её и заводят. */
export async function создатьПапку(имя, внутри = "") {
  if (!game.user.isGM) return null;
  // «/» в имени человек написать может — разбираем его как путь, а не браним.
  const звено = чистыйПуть(имя);
  if (!звено) return null;

  const путь = [чистыйПуть(внутри), звено].filter(Boolean).join(РАЗДЕЛИТЕЛЬ);
  if (папки().includes(путь)) {
    ui.notifications.warn(Т("Папка «{имя}» уже есть", { имя: путь }));
    return путь;
  }
  const ж = await журнал();
  if (!ж) return null;
  await ж.setFlag(MODULE_ID, ФЛАГ_ПАПОК, [...записанныеПапки(), путь]);
  return путь;
}

/**
 * Переименовать папку вместе со вложенными и со всем, что в ней лежит:
 * путь заготовки — её же поле, и переписать его надо в тот же приём.
 */
export async function переименоватьПапку(путь, новое) {
  if (!game.user.isGM) return false;
  const старый = чистыйПуть(путь);
  const звено = чистыйПуть(новое);
  if (!старый || !звено) return false;

  const свежий = [родитель(старый), звено].filter(Boolean).join(РАЗДЕЛИТЕЛЬ);
  if (свежий === старый) return false;
  if (папки().includes(свежий)) {
    ui.notifications.warn(Т("Папка «{имя}» уже есть", { имя: свежий }));
    return false;
  }

  const внутри = п => п === старый || п.startsWith(старый + РАЗДЕЛИТЕЛЬ);
  const переписать = п => (внутри(п) ? свежий + п.slice(старый.length) : п);

  const ж = await журнал();
  if (!ж) return false;
  await ж.setFlag(MODULE_ID, ФЛАГ_ПАПОК, [...new Set(папки().map(переписать))]);
  await записать(записи().map(з =>
    (внутри(чистыйПуть(з?.папка)) ? { ...з, папка: переписать(чистыйПуть(з.папка)) } : з)));
  return true;
}

/**
 * Убрать папку.
 *
 * Содержимое переезжает к родителю, а не исчезает вместе с полкой: заготовки
 * собирали руками, и убрать папку — не то же самое, что забыть заготовку.
 * Вложенные папки переезжают так же: «Поместье/Подвал/Галерея» при уборке
 * «Подвала» станет «Поместье/Галерея».
 */
export async function убратьПапку(путь) {
  if (!game.user.isGM) return false;
  const свой = чистыйПуть(путь);
  if (!свой) return false;

  const выше = родитель(свой);
  const внутри = п => п === свой || п.startsWith(свой + РАЗДЕЛИТЕЛЬ);
  const наверх = п => {
    const хвост = п.slice(свой.length).split(РАЗДЕЛИТЕЛЬ).filter(Boolean).join(РАЗДЕЛИТЕЛЬ);
    return [выше, хвост].filter(Boolean).join(РАЗДЕЛИТЕЛЬ);
  };

  const остались = new Set();
  for (const п of папки()) {
    if (!внутри(п)) { остались.add(п); continue; }
    if (п === свой) continue;                        // сама полка и уходит
    остались.add(наверх(п));
  }

  const ж = await журнал();
  if (!ж) return false;
  await ж.setFlag(MODULE_ID, ФЛАГ_ПАПОК, [...остались]);
  await записать(записи().map(з =>
    (внутри(чистыйПуть(з?.папка)) ? { ...з, папка: наверх(чистыйПуть(з.папка)) } : з)));
  return true;
}

/** Переложить заготовку на другую полку. */
export async function переложить(тип, имя, папка) {
  if (!game.user.isGM) return false;
  const куда = чистыйПуть(папка);
  const было = записи();
  const место = было.findIndex(з => з.тип === тип && з.имя === имя);
  if (место < 0) return false;
  if (чистыйПуть(было[место].папка) === куда) return true;

  было[место] = { ...было[место], папка: куда };
  return записать(было);
}

/**
 * Выложить заготовку на стол.
 *
 * `скрытно` — то самое «приготовить заранее»: стол ложится в мир, но игроки
 * его не видят, пока ведущий не покажет его из панели. Прячем после выкладки,
 * а не при ней: тогда не нужно править одиннадцать `выложить`, и каждая
 * загадка остаётся хозяйкой своего стола.
 */
export async function выложить(тип, имя, { скрытно = false } = {}) {
  const настройки = пул(тип)[имя];
  if (!настройки) {
    ui.notifications.warn(Т("Заготовки «{имя}» нет", { имя }));
    return null;
  }
  const вид = ВИДЫ.get(тип);
  if (typeof вид?.выложить !== "function") {
    ui.notifications.warn(Т("Не знаю, как выкладывать «{тип}»", { тип }));
    return null;
  }

  const стол = await вид.выложить(настройки);   // «пул» уже отдал копию
  if (стол && скрытно) await спрятать(стол.id);
  return стол;
}

