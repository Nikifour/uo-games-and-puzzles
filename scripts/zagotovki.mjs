/**
 * Строка «запомнить как заготовку» для диалога любой загадки.
 *
 * Одной вставкой, а не своей разметкой в каждом файле: одиннадцать копий —
 * одиннадцать мест, где подпись и поведение со временем разойдутся.
 */
export const полеЗаготовки = (значение = "") => `
  <label>${Т("Запомнить как заготовку")}
    <input type="text" name="заготовка" value="${экранировать(значение)}" placeholder="${Т("имя, необязательно")}">
  </label>
  <p class="uo-podskazka">${Т("С именем настройки лягут в склад ведущего, и загадку можно будет выложить снова одним нажатием. Склад уезжает вместе с миром, игрокам он не виден.")}</p>`;

/**
 * Отметить в диалоге список игроков.
 *
 * Имя поля у каждой загадки своё — «крутят», «двигают», «выбирают»,
 * «участники», — а разметка одна и та же: галочки на игроков и, где это
 * к месту, переключатель «все / отмеченные». Поэтому список узнаётся
 * по разметке, а не по имени поля, и новая загадка получает это даром.
 *
 * Пустой список значит «все» — так же, как при выкладке.
 */
function отметитьИгроков(элемент, кто) {
  const галочки = элемент.querySelectorAll(`[name="игрок"], [name="участник"]`);
  if (!галочки.length) return;

  const поимённо = Array.isArray(кто) && кто.length > 0;
  const переключатель = элемент.querySelector(`[name="кто"][value="${поимённо ? "отмеченные" : "все"}"]`);
  if (переключатель) переключатель.checked = true;

  for (const галка of галочки) галка.checked = поимённо && кто.includes(галка.value);
}

/**
 * Разложить настройки заготовки по полям диалога.
 *
 * Работает по совпадению имён: ключ настроек — имя поля. Это не совпадение,
 * а замысел: диалоги собирают настройки тем же путём наоборот, через
 * `зн("название")`. Пока правило держится, новая загадка получает правку
 * заготовок, ничего для этого не написав.
 *
 * `особые` — для тех немногих ключей, где имена разошлись: у замка настройки
 * помнят готовый набор символов, а в диалоге на его месте поле «свои».
 */
export function заполнить(элемент, настройки, особые = {}) {
  if (!элемент || !настройки) return;

  for (const [ключ, значение] of Object.entries(настройки)) {
    if (особые[ключ]) { особые[ключ](элемент, значение); continue; }

    const поле = элемент.querySelector(`[name="${CSS.escape(ключ)}"]`);
    if (!поле) {
      if (Array.isArray(значение)) отметитьИгроков(элемент, значение);
      continue;
    }
    if (поле.type === "checkbox") поле.checked = !!значение;
    else if (значение !== null && значение !== undefined) поле.value = значение;
  }
}

/**
 * Снять имя из поля и запомнить настройки, если имя вписано.
 *
 * Зовётся до выкладки: настройки бывают отвергнуты проверкой (пустой код,
 * нет картинки), но заготовка нужна и тогда — ведущий как раз собирает её
 * впрок и правит по частям.
 */
export async function запомнитьИзДиалога(тип, элемент, настройки) {
  const имя = элемент.querySelector(`[name="заготовка"]`)?.value?.trim();
  if (имя) await запомнить(тип, имя, настройки);
  return настройки;
}

/* ─────────────────────── переезд со старого места ─────────────────────── */

/**
 * Заготовки замка прежде лежали в настройке клиента. Переносим их в журнал
 * один раз и старое место чистим: иначе на двух машинах будет два разных
 * склада, и ведущий не поймёт, почему на одной заготовки есть, а на другой
 * нет. Уже занятое имя не перебиваем — своё новее переехавшего.
 */
export async function переехать() {
  if (!game.user.isGM) return;

  const старое = game.settings.get(MODULE_ID, "zagotovki");
  const имена = (старое && typeof старое === "object") ? Object.keys(старое) : [];
  if (!имена.length) return;

  const свои = пул("zamok");
  const список = записи();
  for (const имя of имена) {
    if (имя in свои) continue;
    список.push({ тип: "zamok", имя, настройки: старое[имя] });
  }
  if (!(await записать(список))) return;

  await game.settings.set(MODULE_ID, "zagotovki", {});
  console.log(`${MODULE_ID} | заготовки замка переехали в журнал: ${имена.length}`);
}

