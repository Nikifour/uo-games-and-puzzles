/**
 * Соперник в Костях. Тоже чистый: ни Foundry, ни окон — только решение.
 *
 * Две независимые ручки, и это важно.
 *
 *   жадность — когда останавливаться. Осторожный трактирщик кладёт в банк
 *              рано, безрассудный наёмник тянет до последней кости.
 *   мастерство — насколько часто бот вообще играет верно. Безупречный бот
 *              обыгрывает живых людей стабильно: математика на его стороне,
 *              и это скучно. Трактирщик, который ошибается, интереснее.
 *
 * Случайность всегда приходит снаружи. В игре её даст Foundry, в проверке —
 * свой генератор с зерном, иначе тысяча партий не повторится дважды.
 */

import { ПРАВИЛА, отборы } from "./kosti-pravila.mjs";
import { М } from "./yazyk.mjs";

/**
 * Когда пора в банк, смотря сколько костей останется в руке.
 *
 * Числа не с потолка: одной костью пусто выпадает в двух случаях из трёх,
 * двумя — почти в половине, шестью — в одном из сорока. Чем меньше костей,
 * тем дешевле остановиться.
 */
const ПОРОГ = { 0: Infinity, 1: 300, 2: 350, 3: 450, 4: 600, 5: 800, 6: Infinity };

export const ХАРАКТЕРЫ = {
  traktirshchik: { имя: М("Осторожный трактирщик"), жадность: 0.7, мастерство: 0.8 },
  naemnik: { имя: М("Безрассудный наёмник"), жадность: 1.6, мастерство: 0.65 },
  schetovod: { имя: М("Счетовод"), жадность: 1.0, мастерство: 0.95 },
  seliak: { имя: М("Селянин"), жадность: 1.1, мастерство: 0.45 },
};

export const ХАРАКТЕР_ПО_УМОЛЧАНИЮ = "traktirshchik";

/**
 * Насколько ценно продолжать с таким числом костей — грубая прикидка среднего
 * улова. Нужна не точность, а порядок величин: пятью костями бросать выгоднее,
 * чем одной, и бот должен это чувствовать при выборе, что отложить.
 */
const ОЖИДАНИЕ = { 0: 0, 1: 25, 2: 60, 3: 110, 4: 180, 5: 260, 6: 360 };

/**
 * Решение бота на один бросок.
 *
 * @returns {{берём: number[], очки: number, банк: boolean}|null}
 *          null — брать нечего, это кости.
 */
export function решение(положение, случай = Math.random) {
  const {
    бросок, вХоде = 0, мои = 0, чужие = 0,
    правила = ПРАВИЛА, характер = ХАРАКТЕРЫ[ХАРАКТЕР_ПО_УМОЛЧАНИЮ],
  } = положение;

  const п = { ...ПРАВИЛА, ...правила };
  const варианты = отборы(бросок, п);
  if (!варианты.length) return null;

  // Что отложить. Взвешиваем не только очки: оставленные кости — тоже ценность.
  const взвешенные = [...варианты].sort((a, b) =>
    (b.очки + ОЖИДАНИЕ[b.осталось]) - (a.очки + ОЖИДАНИЕ[a.осталось]));

  const умно = случай() < (характер.мастерство ?? 0.8);
  const выбор = умно ? взвешенные[0] : взвешенные[Math.floor(случай() * взвешенные.length)];

  const всегоЗаХод = вХоде + выбор.очки;
  const осталось = выбор.осталось === 0 ? 6 : выбор.осталось;   // все отложены — бросаем шесть заново

  // Победа в шаге: считать дальше незачем.
  if (мои + всегоЗаХод >= п.цель) return { берём: выбор.набор, очки: выбор.очки, банк: true };

  let порог = (ПОРОГ[осталось] ?? 400) * (характер.жадность ?? 1);

  // Соперник у самой цели — осторожничать больше нечем, надо догонять.
  if (чужие >= п.цель * 0.85) порог *= 1.6;

  // Счёт ещё не открыт: банк ниже порога входа бессмыслен, очки сгорят.
  if (мои === 0 && п.порогВхода && всегоЗаХод < п.порогВхода) порог = Infinity;

  let банк = всегоЗаХод >= порог;
  if (!умно && случай() < 0.35) банк = !банк;    // рука дрогнула и в решении тоже

  return { берём: выбор.набор, очки: выбор.очки, банк };
}

/**
 * Весь ход бота от первого броска до банка или пустого броска.
 *
 * Кости бот бросает не сам: их даёт снаружи `бросать`. За столом это будет
 * настоящий бросок Foundry — с показом Dice So Nice и паузой на подумать,
 * а в проверке правил тот же ход прогоняется мгновенно тысячу раз.
 * Так проверенное и сыгранное — один и тот же код, а не два похожих.
 *
 * @returns {Promise<number>} сколько очков ушло в банк; 0 — кости.
 */
export async function сыгратьХод(положение, { бросать, событие } = {}, случай = Math.random) {
  let вХоде = 0;
  let костей = 6;

  // Страховка от бесконечности: «горячие кости» теоретически позволяют
  // катать вечно, и одна кривая настройка жадности повесила бы стол.
  for (let шаг = 0; шаг < 40; шаг++) {
    const бросок = await бросать(костей);
    await событие?.({ что: "бросок", бросок, костей, вХоде });

    const реш = решение({ ...положение, бросок, вХоде }, случай);
    if (!реш) {
      await событие?.({ что: "пусто", бросок, вХоде });
      return 0;
    }

    вХоде += реш.очки;
    костей -= реш.берём.length;
    if (костей === 0) костей = 6;                  // отложил всё — бросает шесть заново
    await событие?.({ что: "отложил", берём: реш.берём, очки: реш.очки, вХоде, костей });

    if (реш.банк) {
      await событие?.({ что: "банк", вХоде });
      return вХоде;
    }
  }

  return вХоде;
}
